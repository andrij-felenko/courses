def _find(src, s):
    i = src.find(s)
    assert i >= 0, "нема в джерелі: " + s[:70]
    return i


def para(src, start):
    i = _find(src, start)
    j = src.find("\n\n", i)
    return src[i: j if j >= 0 else len(src)].strip()


def rng(src, start, stop):
    i = _find(src, start)
    j = src.find(stop, i)
    assert j > i, "кінець не знайдено: " + stop[:50]
    return src[i:j].strip()


def sent(src, s):
    _find(src, s)
    return s


def build(items, src=CANON):
    out, drop = [], []
    for it in items:
        kind = it[0]
        if kind == "P": out.append(para(src, it[1]))
        elif kind == "R": out.append(rng(src, it[1], it[2]))
        elif kind == "S": out.append(sent(src, it[1]))
        elif kind == "H": out.append("### " + it[1])
        elif kind == "X": drop.append(it[1])
        else: raise ValueError(kind)
    text = "\n\n".join(out)
    for d in drop:
        assert d in text, "нічого викидати: " + d[:60]
        text = text.replace(d, "")
    return re.sub(r"\n{3,}", "\n\n", text).strip()


