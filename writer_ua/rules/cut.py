# Єдина правка тексту: латинське «v» посеред українського слова — одруківка канону, не правило.
FIX = {"заvela": "завела"}

SQUEEZE_LINE = "    <ЩО ЗЖАТИ>що можна стиснути без втрати сенсу й на чому; немає — пустота</ЩО ЗЖАТИ>"


def fix(t):
    for a, b in FIX.items(): t = t.replace(a, b)
    return t


def shared_file(name, spec):
    body = build(spec["items"])
    if spec.get("readme"):
        body += "\n\n" + build(spec["readme"], src=README)
    todo = "\n".join("- " + t for t in spec["todo"]) or "- {порожньо}"
    own = ("\n\n" + spec["own"].strip() + "\n") if spec.get("own") else ""
    return (f"# {name}\n\n**Обсяг:** {spec['scope']}\n\n## Треба зробити\n\n"
            f"{MARK_A}\n{fix(body)}\n{MARK_B}{own}\n\n## Коментарі\n\n{todo}\n")


def type_file(path, items):
    s = io.open(path, encoding="utf-8").read()
    block = MARK_A + "\n" + fix(build(items)) + "\n" + MARK_B
    if MARK_A in s:
        s = s[: s.index(MARK_A)] + block + s[s.index(MARK_B) + len(MARK_B):]
    else:
        k = s.index("## Коментарі")
        s = s[:k].rstrip() + "\n\n" + block + "\n\n" + s[k:]
    # блок «що зжати» — у контракті письма кожного типу, один раз
    if path.endswith("-rules.md") and "<ЩО ЗЖАТИ>" not in s:
        s = s.replace("    <ЩО ДОДАТИ>", SQUEEZE_LINE + "\n    <ЩО ДОДАТИ>", 1)
    return s


def main(check_only):
    outputs = {}
    for name, spec in SHARED.items():
        outputs[os.path.join(HERE, name + ".md")] = shared_file(name, spec)
    for name, items in TYPES.items():
        p = os.path.join(HERE, "types", name + ".md")
        outputs[p] = type_file(p, items)
    if check_only:
        print("усі підрядки на місці:", len(outputs), "файлів")
        return
    for p, text in outputs.items():
        io.open(p, "w", encoding="utf-8", newline="").write(text)
        print("записано", os.path.relpath(p, ROOT), len(text), "симв.")


if __name__ == "__main__":
    main("--check" in sys.argv)
