#!/usr/bin/env node
/* ============================================================================
   delivery.js — ЧИ ЧУЄ АГЕНТ ТЕ, ЧОГО МИ ВІД НЬОГО ХОЧЕМО.

   Найдорожча вада конвеєра не в тому, що правило погане, а в тому, що воно НЕ ДОЇХАЛО
   до того, хто мусить його виконати. Її не видно ні в правилах, ні в коді: обидва
   правильні, а між ними діра. Ловили її щоразу руками й щоразу після того, як текст
   уже написано.

   Тут вона ловиться за секунду. Скрипт складає КОЖЕН справжній запит конвеєра й дивиться,
   чи є в ньому кожен клас вимог, який ми від цього кроку чекаємо.

   ЩО ВОНО ВЖЕ ЗНАЙШЛО (усе — справжні діри, не здогади):
     · ціль формулювалась як «що вивести» — і текст відкривався формулою;
     · дописувач і переписувач мали наказ лінкувати й не мали переліку адрес;
     · суддя міряв живу українську, не маючи правил мови.

   ⛔ ЧОГО НЕ РОБИТЬ: не судить, чи правило добре. Лише чи воно там, де має бути.

   Ужиток:  node writer_ua/checkers/delivery.js
   Вихід:   0 — дір немає · 1 — є
   ========================================================================== */
"use strict";
const P = require("../runners/prompt.js");
const L = require("../runners/local.js");
const A = require("../runners/algorithm.js");

const art = L.unitOf("cat-hw-controls", "estop-mushroom-button", "article", "ДЕТАЛЬНА");
const of = (t) => ({ ...art, type: t, version: "" });

const calls = {
  "ціль article": P.goal(art, { mentions: "", linkable: "Л" }),
  "обсяг article": P.scope(art, { goal: "ц", preknow: "П", books: "К" }),
  "ціль math": P.goal(of("math"), { mentions: "", linkable: "Л" }),
  "обсяг math": P.scope(of("math"), { goal: "ц", preknow: "П", books: "К" }),
  "каркас article": P.karkas(art, { goal: "ц", level: 2, preknow: "П", inserts: "В" }),
  "каркас math": P.karkas(of("math"), { goal: "ц", level: 2, preknow: "", inserts: "В" }),
  "каркас hist": P.karkas(of("hist"), { goal: "ц", level: 2, preknow: "", inserts: "В" }),
  "письмо article": P.write(art, { goal: "ц", level: 2, sections: "1", theses: "", inserts: "розділ 1: код Python — щось", passed: "П", linkable: "Л", opory: "О" }),
  "письмо math": P.write(of("math"), { goal: "ц", level: 2, sections: "1", theses: "", inserts: "", passed: "", linkable: "Л", opory: "" }),
  "письмо hist": P.write(of("hist"), { goal: "ц", level: 2, sections: "1", theses: "", inserts: "", passed: "", linkable: "Л", opory: "" }),
  "дописування": P.extend(art, { goal: "ц", level: 2, section: "1", text: "т", neighbours: "", add: "5 | щ", linkable: "Л" }),
  "стиснення": P.compress(art, { goal: "ц", level: 2, section: "1", text: "т", neighbours: "", squeeze: "щ" }),
  "викладка": P.layout(art, { goal: "ц", level: 2, text: "т", passed: "" }),
  "перепис": P.rewrite(art, { goal: "ц", paragraphs: "т", defect: "д", attempt: 1, maxAttempts: A.MAX_LAYOUT, linkable: "Л" }),
  "код: архітектура": P.karkas({ ...of("code"), lang: "c", carrier: "x" }, { goal: "ц", level: 2, preknow: "", inserts: "" }),
  "код: файли": P.codeWrite({ ...of("code"), lang: "c", carrier: "x" }, { goal: "ц", level: 2, files: "f", classes: "", structure: "" }),
  "фігура": P.figure(of("fig"), { goal: "ц", what: "щ", section: 1, file: "img/fig-1.svg", level: 2 }),
  "чи треба базова": P.basicNeeded(art, { goal: "ц", level: 2, text: "т", zone: "з" }),
};

/* Клас вимоги → як його впізнати в тексті завдання. */
const need = {
  "захід/порядок": /ЗАХІД|раніше за розв|ПОРЯДОК ПУНКТІВ|причинн|причинов|ЩО ЛАМАЄТЬСЯ/i,
  "обсяг ↑": /частка предмета не вичерпана|не менше \d+ слів/,
  "обсяг ↓": /МЕЖІ, а не цілі|надто великі статті|переросла стелю/,
  "справжні адреси": /КУДИ МОЖНА ЛІНКУВАТИ|Своїх адрес не складай/,
  "правила лінків": /жодних висячих згадок|root:/,
  "правила фігур": /Фігури\.|SVG/,
  "правила коду": /:::code|тека мови/,
  "жива українська": /Лише \*\*справжні слова\*\*|справжні слова/,
  "історія/атрибуція": /виміри ідентичності|статус доказовост|Розрізняти виміри/,
  "шкала рівня": /^\s{2}1[ —]/m,
  "означення вставок": /узагальнений клас пристрою|Від нуля до трьох/,
  "контракт": /<ПОВЕРНИ>/,
};

/* Що кому ПОТРІБНО: — не потрібно, + потрібно. */
const want = {
  "ціль article": ["захід/порядок", "справжні адреси", "контракт"],
  "обсяг article": ["шкала рівня", "означення вставок", "контракт"],
  "ціль math": ["захід/порядок", "справжні адреси", "контракт"],
  "обсяг math": ["шкала рівня", "означення вставок", "контракт"],
  "каркас article": ["захід/порядок", "правила фігур"],
  "каркас math": ["захід/порядок", "правила фігур"],
  "каркас hist": ["захід/порядок", "правила фігур", "історія/атрибуція"],
  "письмо article": ["захід/порядок", "обсяг ↑", "обсяг ↓", "справжні адреси", "правила лінків", "правила фігур", "правила коду", "жива українська", "контракт"],
  "письмо math": ["захід/порядок", "обсяг ↑", "обсяг ↓", "справжні адреси", "правила лінків", "правила фігур", "жива українська", "контракт"],
  "письмо hist": ["захід/порядок", "обсяг ↑", "обсяг ↓", "справжні адреси", "правила лінків", "жива українська", "історія/атрибуція", "контракт"],
  "дописування": ["обсяг ↑", "справжні адреси", "правила лінків", "жива українська", "контракт"],
  "стиснення": ["обсяг ↓", "жива українська", "контракт"],
  "викладка": ["захід/порядок", "обсяг ↓", "жива українська", "контракт"],
  "перепис": ["справжні адреси", "жива українська", "контракт"],
  "код: архітектура": ["правила коду", "контракт"],
  "код: файли": ["правила коду", "контракт"],
  "фігура": ["правила фігур", "контракт"],
  "чи треба базова": ["контракт"],
};

const keys = Object.keys(need);
const w = 18;
console.log("".padEnd(w) + keys.map((k) => k.slice(0, 9).padEnd(11)).join(""));
const gaps = [];
for (const [name, prompt] of Object.entries(calls)) {
  const wanted = want[name] || [];
  const row = keys.map((k) => {
    const has = need[k].test(prompt);
    const req = wanted.includes(k);
    if (req && !has) { gaps.push(`${name}: НЕМАЄ «${k}»`); return "⛔ немає  ".padEnd(11); }
    if (req && has) return "є        ".padEnd(11);
    return (has ? "· зайве  " : "         ").padEnd(11);
  });
  console.log(name.padEnd(w) + row.join(""));
}
console.log("\nдіри:");
gaps.length ? gaps.forEach((g) => console.log("  ⛔ " + g)) : console.log("  немає");
process.exit(gaps.length ? 1 : 0);
