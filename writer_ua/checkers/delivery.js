#!/usr/bin/env node
/* ============================================================================
   delivery.js — ЧИ ЧУЄ АГЕНТ ТЕ, ЧОГО МИ ВІД НЬОГО ХОЧЕМО.

   Найдорожча вада конвеєра не в тому, що правило погане, а в тому, що воно НЕ ДОЇХАЛО
   до того, хто мусить його виконати. Її не видно ні в правилах, ні в коді: обидва
   правильні, а між ними діра. Тут вона ловиться за секунду: скрипт складає КОЖЕН
   справжній запит конвеєра й дивиться, чи є в ньому кожен клас вимог, який ми від цього
   кроку чекаємо, — і чи не доїхало те, чого цьому кроку не треба.

   ⛔ ЧОГО НЕ РОБИТЬ: не судить, чи правило добре. Лише чи воно там, де має бути.

   Ужиток:  node writer_ua/checkers/delivery.js
   Вихід:   0 — дір немає · 1 — є
   ========================================================================== */
"use strict";
const P = require("../runners/prompt.js");
const L = require("../runners/local.js");
const MF = require("../lib/manifest.js");

const pick = (kind) => {
  for (const [slug, b] of MF.books()) {
    if (b.kind !== kind) continue;
    const bk = MF.loadBook(MF.bookDirOf(slug));
    const t = bk && MF.allTopics(bk).find((x) => x.own);
    if (t) return L.unitOf(slug, t.slug);
  }
  throw new Error(`немає книги виду ${kind}`);
};
const art = pick("sci");
const step = pick("course");
const ins = (t) => L.unitOf(art.book, art.slug, t, "", `${t}-probe`);
const basic = L.unitOf(art.book, art.slug, "basic", "базова");
const code = { ...L.unitOf(art.book, art.slug, "code", ""), lang: "c", carrier: "x", about: "щ" };
const fig = L.unitOf(art.book, art.slug, "fig", "");

const W = { goal: "ц", level: 2, depth: "г", sections: "1 | Назва | важливість: висока | п", theses: "", integrate: "і", preknow: "пк", passed: "П", linkable: "Л", code: "", words: { part: 1000, all: 2400, ceiling: 10000 } };
const calls = {
  "ціль article": P.goal(art, { mentions: "з", passed: "" }),
  "ціль крок курсу": P.goal(step, { mentions: "з", passed: "П" }),
  "ціль hist": P.goal(ins("hist"), { mentions: "", about: "о" }),
  "структура": P.structure(art, { goal: "ц", books: "к" }),
  "каркас article": P.karkas(art, { goal: "ц", passed: "П", known: "К", inserts: "В", detailed: "" }),
  "каркас hist": P.karkas(ins("hist"), { goal: "ц", passed: "", known: "К", inserts: "", detailed: "" }),
  "каркас proj": P.karkas(ins("proj"), { goal: "ц", passed: "", known: "К", inserts: "", detailed: "" }),
  "каркас basic": P.karkas(basic, { goal: "ц", passed: "", known: "", inserts: "", detailed: "Д" }),
  "письмо article": P.write(art, W),
  "письмо крок курсу": P.write(step, W),
  "письмо basic": P.write(basic, W),
  "письмо hist": P.write(ins("hist"), W),
  "письмо math": P.write(ins("math"), W),
  "письмо proj": P.write(ins("proj"), W),
  "письмо api": P.write(ins("api"), W),
  "письмо comp": P.write(ins("comp"), W),
  "дописування": P.extend(art, { ...W, section: "1", text: "т", paragraph: "п", how: "поглибити", add: "5 | щ" }),
  "стиснення": P.compress(art, { goal: "ц", level: 2, section: "1", text: "т", theses: "", squeeze: "щ", by: 100 }),
  "аналіз": P.analysis(art, { goal: "ц", level: 2, text: "т", theses: "", groups: "1", force: false }),
  "де дописати": P.analysis(art, { goal: "ц", level: 2, text: "т", theses: "", groups: "1", force: true }),
  "факти": P.facts(art, { lines: "р" }),
  "розставлення": P.place(art, { text: "т", figures: "ф", links: "л" }),
  "тема чи вставка": P.topicsInsert({ inserts: "в", topics: "т" }),
  "код: архітектура": P.codeKarkas(code, { goal: "ц" }),
  "код: файли": P.codeWrite(code, { goal: "ц", level: 2, files: "f", classes: "", structure: "" }),
  "фігура": P.figure(fig, { goal: "ц", what: "щ", section: 1, file: "img/fig-1.svg", level: 2 }),
  "тема куди": P.topicsCategory({ shelf: "ш", topics: "т" }),
  "тема чи є": P.topicsDedupe({ existing: "е", topics: "т", hints: "" }),
  "тема розвести": P.topicsRename({ pairs: "п" }),
};

/* Клас вимоги → як його впізнати в тексті завдання. */
const need = {
  "ціль читача": /що читач має (з неї )?винести|що читач має знати|навчиться робити|має вміти/,
  "вхід без стіни": /Спочатку — те, що зрозуміло без нічого/,
  "захід/порядок": /захід, а не початок апарату|Від потреби до розв|Порядок причинний|що ламається, поки цього немає/i,
  "обсяг — межа, не ціль": /верхня межа, не ціль|міра — верхня межа/i,
  "обсяг ↓": /стаття серед інших статей|Довший текст не глибший|компактніш/i,
  "справжні адреси": /КУДИ МОЖНА ЛІНКУВАТИ|лише на адресу з/,
  "лінк на нову тему": /root:new/,
  "правила фігур": /Фігуру ставиш|чи потрібна там картинка|Намалюй SVG|Постав фігуру в цей розділ/,
  "правила коду": /:::code|Тека мови — корінь/,
  "мова коду": /C і C\+\+ — два окремі питання/,
  "жива українська": /Жива українська/,
  "історія/атрибуція": /виміри ідентичності|Лише справжня історія/i,
  "шкала рівня": /^\s{2,}(1 — те, з чим|1 упізнати|1 — головна лінія|1 — що це за клас|1 — та частина)/m,
  "шкала 5→1": /5 — без цього розділ не зрозуміти/,
  "тези": /На кожен написаний розділ/,
  "вставки": /П'ять питань — по одному на тип вставки/,
  "форма вставок": /Вставки теми — не розділи/,
  "коротка вставка": /Коротка вставка зі списку/,
  "бали": /Бали нараховуються, а не знімаються/,
  "правила типу": /Повна версія — сісти й зрозуміти до кінця/,
  "де дописати": /Тексту бракує багато/,
  "послідовність курсу": /спирається на пройдене/,
  "самодостатність": /не спирається на «вже відоме»/,
  "контракт": /<ПОВЕРНИ>/,
};

const PROSE = ["вхід без стіни", "захід/порядок", "обсяг — межа, не ціль", "обсяг ↓", "справжні адреси", "лінк на нову тему",
  "правила фігур", "правила коду", "мова коду", "жива українська", "шкала 5→1", "коротка вставка", "тези", "контракт"];

/* Що кому ПОТРІБНО. Клас, якого тут нема, а в запиті є, — «зайве»: теж діра, лише дешевша. */
/* Проза їде каркасові, стисненню й аналізу цілком — план має дозволити її виконати,
   стискач не має рвати нитку, а суддя судить саме за нею. */
const CORE = ["вхід без стіни", "захід/порядок", "обсяг — межа, не ціль", "обсяг ↓"];
const want = {
  "ціль article": ["ціль читача", "самодостатність", "контракт"],
  "ціль крок курсу": ["ціль читача", "послідовність курсу", "контракт"],
  "ціль hist": ["ціль читача", "самодостатність", "контракт"],
  "структура": ["вставки", "самодостатність", "контракт"],
  "каркас article": [...CORE, "шкала рівня", "правила фігур", "форма вставок", "самодостатність", "контракт"],
  "каркас hist": [...CORE, "шкала рівня", "правила фігур", "форма вставок", "самодостатність", "контракт"],
  "каркас proj": [...CORE, "шкала рівня", "правила фігур", "форма вставок", "мова коду", "самодостатність", "контракт"],
  "каркас basic": [...CORE, "самодостатність", "контракт"],
  "письмо article": [...PROSE, "правила типу", "самодостатність"],
  "письмо крок курсу": [...PROSE, "правила типу", "послідовність курсу"],
  "письмо basic": [...PROSE, "самодостатність"],
  /* Історії файли про код не йдуть — їй код не потрібен. */
  "письмо hist": [...PROSE.filter((k) => !/коду/.test(k)), "історія/атрибуція", "самодостатність"],
  "письмо math": [...PROSE, "самодостатність"],
  "письмо proj": [...PROSE, "самодостатність"],
  "письмо api": [...PROSE, "самодостатність"],
  "письмо comp": [...PROSE, "самодостатність"],
  /* Дописування — один абзац: протокол свій (mode-extend), «коротка вставка» з mode-write не йде. */
  "дописування": [...PROSE.filter((k) => k !== "коротка вставка" && k !== "шкала 5→1"), "правила типу", "самодостатність"],
  "стиснення": [...CORE, "жива українська", "правила типу", "самодостатність", "контракт"],
  "аналіз": [...CORE, "бали", "правила типу", "контракт"],
  "де дописати": [...CORE, "бали", "правила типу", "де дописати", "контракт"],
  "факти": ["історія/атрибуція", "контракт"],
  "розставлення": ["правила фігур", "контракт"],
  "тема чи вставка": ["контракт"],
  "код: архітектура": ["мова коду", "шкала рівня", "контракт"],
  "код: файли": ["правила коду", "мова коду", "контракт"],
  "фігура": ["правила фігур", "контракт"],
  "тема куди": ["контракт"],
  "тема чи є": ["контракт"],
  "тема розвести": ["контракт"],
};

const keys = Object.keys(need);
const w = 18;
console.log("".padEnd(w) + keys.map((k) => k.slice(0, 8).padEnd(10)).join(""));
const gaps = [], extra = [];
for (const [name, prompt] of Object.entries(calls)) {
  const wanted = want[name] || [];
  const row = keys.map((k) => {
    const has = need[k].test(prompt);
    const req = wanted.includes(k);
    if (req && !has) { gaps.push(`${name}: НЕМАЄ «${k}»`); return "⛔ немає ".padEnd(10); }
    if (req && has) return "є".padEnd(10);
    if (has) { extra.push(`${name}: зайве «${k}»`); return "· зайве ".padEnd(10); }
    return "".padEnd(10);
  });
  console.log(name.padEnd(w) + row.join(""));
}
console.log("\nдіри:");
gaps.length ? gaps.forEach((g) => console.log("  ⛔ " + g)) : console.log("  немає");
console.log("зайве:");
extra.length ? extra.forEach((g) => console.log("  · " + g)) : console.log("  немає");
process.exit(gaps.length ? 1 : 0);
