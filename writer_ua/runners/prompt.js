#!/usr/bin/env node
/* ============================================================================
   prompt.js — СКЛАДАННЯ ЗАВДАННЯ З БЛОКІВ. Підстановка, а не зшивання.

   Кожен блок має ОДНЕ джерело: ціль зі стану, тези з попереднього кроку, правила з
   файла. Тому тут немає жодного «зліпити рядок» — є список блоків і один спосіб їх
   вивести. Вартість теж стає видимою: `weigh()` каже, скільки важить кожен блок, і
   видно, за що платиш.

   ДЕ ЖИВЕ ЩО. Кістяк завдання — тут, у коді: він однаковий для всіх типів. Те, що
   різниться від типу до типу, — «що просимо» і «що повертає» — лежить у
   `rules/types/<тип>-<goals|karkas|rules>.md` і читається звідти. Так тип тримає лише
   РІЗНИЦЮ, і вісім копій правил про код не розходяться.

   ⛔ АГЕНТОВІ НЕ ЙДЕ РОЗДІЛ «ЩО ТРЕБА ЗРОБИТИ». Це наші відкриті питання, не його
   робота: показати їх означало б попросити вгадати те, чого ми самі не вирішили.
   ========================================================================== */
"use strict";
const fs = require("fs");
const path = require("path");

const RULES = path.join(__dirname, "..", "rules");

/* ── читання правил типу ───────────────────────────────────────────────────── */

const readType = (type, kind) => {
  const p = path.join(RULES, "types", `${type}-${kind}.md`);
  if (!fs.existsSync(p)) throw new Error(`немає правил: ${path.relative(RULES, p)}`);
  return fs.readFileSync(p, "utf8");
};

/**
 * Секція markdown за заголовком другого рівня, без самого заголовка.
 * Ріжемо розбиттям, а не регуляркою з поглядом уперед: `(?=^## |\s*$)` збігається з
 * порожнім рядком одразу після заголовка, тож секція виходила порожня, і `<ЩО ЗРОБИТИ>`
 * тихо їхало без головного припису.
 */
function section(md, title) {
  for (const part of String(md).split(/^## /m).slice(1)) {
    const nl = part.indexOf("\n");
    if (part.slice(0, nl < 0 ? part.length : nl).trim() === title)
      return part.slice(nl + 1).trim();
  }
  return "";
}

/**
 * Те, що агент бачить у `<ПРАВИЛА>`: сама довідка, і більше нічого.
 *
 * ⛔ «ЩО ПРОСИМО» Й «ЩО ПОВЕРТАЄ» ЗВІДСИ ЗНЯТО — вони вже їдуть окремими блоками
 * `<ЩО ЗРОБИТИ>` і `<ПОВЕРНИ>`. Лишені тут, вони не просто дублювались: у викладки,
 * перепису й формул власний контракт ІНШИЙ, тож агент бачив у своїх правилах чужий
 * перелік тегів (`ТЕКСТ`, `ТЕЗИ`, `ЧИ ГЛИБШЕ`…) поруч зі своїм (`ОК`, `НЕ ТАК`) —
 * два контракти в одному завданні.
 *
 * «Що треба зробити» — наші відкриті питання, не його робота: показати їх означало б
 * попросити вгадати те, чого ми самі не вирішили.
 */
function forAgent(md) {
  return String(md)
    .split(/^## /m)
    .filter((part, i) => i === 0 || !/^(Треба отримати|Коментарі)\s*$/m.test(part.split("\n")[0]))
    .map((part, i) => (i === 0 ? part : "## " + part))
    .join("")
    .replace(/^<!--[^\n]*-->\s*$/gm, "")
    .trim();
}

/**
 * Спільні правила — по файлу на турботу, рівно ті, що потрібні цьому запиту.
 * Порожній файл нічого не додає: заглушка не має ставати блоком.
 */
function shared(names) {
  return names.map((n) => {
    const p = path.join(RULES, n + ".md");
    if (!fs.existsSync(p)) return "";
    const body = forAgent(section(fs.readFileSync(p, "utf8"), ASK));
    return body && !/^\{ще не нарізано/.test(body) ? body : "";
  }).filter(Boolean).join("\n\n");
}

/**
 * Правила самої книги — `_canon.md` в її теці: наскрізний приклад, єдині терміни, мова
 * прикладів. Де вони уточнюють загальне, перевага в них — тому стоять ПЕРШИМИ.
 */
function bookCanon(u) {
  const p = u && u.bookDir ? path.join(u.bookDir, "_canon.md") : "";
  return p && fs.existsSync(p) ? fs.readFileSync(p, "utf8").trim() : "";
}

/** Правила письма: канон книги → спільні → свій тип. Код — лише коли він прив'язаний. */
function writingRules(u, { code = false } = {}) {
  const names = ["prose", "language", "links", "formulas"];
  if (code) names.push("code");
  return [bookCanon(u), shared(names), forAgent(readType(u.type, "rules"))].filter(Boolean).join("\n\n");
}

/* ── блоки ─────────────────────────────────────────────────────────────────── */

/**
 * Блок із порожнім тілом НЕ друкується. Порожній `<ТЕЗИ ПОПЕРЕДНІХ РОЗДІЛІВ>` у
 * першого письменника — це не «нічого немає», це зайвий рядок, за який платять усі
 * наступні ходи.
 */
function render(blocks) {
  /* ⛔ ОДНАКОВІ ТЕГИ ЗЛИВАЮТЬСЯ В ОДИН БЛОК, у порядку появи. Так правила й конкретний
     припис стають ОДНИМ наказом `<ЩО ЗРОБИТИ>`, а не окремим фоном і окремим наказом.
     Фон агент гортає: заміряно — `<ПРАВИЛА>` важили 82% завдання проти 5% наказу, і
     правило, покладене туди, не діяло. Перевірено двічі: вкладки запрацювали від
     переносу в наказ, а шкала «що додати» не працювала, поки лежала у фоні. */
  const merged = [];
  for (const b of blocks) {
    if (!b || b.body === undefined || b.body === null || String(b.body).trim() === "") continue;
    const at = merged.find((x) => x.tag === b.tag);
    if (at) at.body += "\n\n" + String(b.body).trim();
    else merged.push({ tag: b.tag, body: String(b.body).trim() });
  }
  return merged.map((b) => `<${b.tag}>\n${b.body}\n</${b.tag}>`).join("\n\n");
}

/** Скільки важить кожен блок — щоб було видно, що різати. */
function weigh(blocks) {
  return blocks.filter((b) => b && String(b.body || "").trim())
    .map((b) => ({ tag: b.tag, chars: String(b.body).trim().length }))
    .sort((a, b) => b.chars - a.chars);
}

/* ── шапка завдання ────────────────────────────────────────────────────────── */

/**
 * ⚠️ ПОСИЛАННЯ НА СТАТТЮ ЗАВЖДИ НЕСЕ ПОВНИЙ ШЛЯХ МОВОЮ. Машинна адреса потрібна
 * скриптам, а не тому, хто читає: `sf-apps/model-building-blocks` не каже нічого, а
 * «Архітектура застосунку / Предметна модель / Цеглинки моделі» каже все одразу.
 */
const KIND_NAME = { course: "курс", cat: "каталог", sys: "довідник" };
const kindName = (k) => KIND_NAME[k] || "книга";

const head = (u) => [
  `${kindName(u.kind)}: ${u.bookTitle}`,
  `тема: ${u.title}`,
  `тип: ${u.type}${u.version ? ` — ${u.version} версія статті` : ""}`,
  u.groupTitle
    ? (u.kind === "course"
      ? `де лежить: том «${u.groupTitle}» / розділ «${u.chapterTitle}»`
      : `де лежить: група «${u.groupTitle}» / розділ «${u.chapterTitle}»`)
    : null,
  u.type === "code" && u.lang ? `мова: ${u.lang}${u.about ? `\nщо реалізує: ${u.about}` : ""}` : null,
].filter(Boolean).join("\n");

/* ── самі завдання ─────────────────────────────────────────────────────────── */

const ASK = "Треба зробити", RET = "Треба отримати";

/**
 * Хвіст наказу, спільний для всіх, хто пише прозу.
 *
 * ⛔ ЖИВЕ В ОДНОМУ МІСЦІ. Це не різниця типу — стаття, історія, порівняння й проєкт
 * просять тут те саме, — тож копія в кожному `types/*-rules.md` була б восьмим шансом
 * розійтися. Один раз так уже сталося: тут стояло «немає або неважливе — поверни
 * пустоту», а в типових файлах «порожнім не буває НІКОЛИ», і письменник діставав два
 * протилежні накази в одному блоці.
 *
 * ЧОМУ ШКАЛА, А НЕ «НАЗВИ, ЩО МОЖНА ДОДАТИ». Дозвіл повернути пустоту письменник
 * вибирає майже завжди — думати дорожче. Тоді етап розміру не має НАЗВАНОГО матеріалу
 * й дописувати нічим, а коротка стаття лишається короткою.
 */
const TAIL = `
Наприкінці:
— дай тези: ПРО ЩО реалізовано, а не звіт про зроблене;
— скажи, чи можеш написати ще глибше і чи повно виклав увесь матеріал;
— назви, що можна зжати без втрати сенсу й на чому; немає — поверни пустоту;
— назви нові теми, на які натрапив. Не заводь їх, тільки назви.

Назви, що ще можна додати, і став кожному пункту рівень важливості:

    5 — точно треба
    4 — треба для розуміння теми
    3 — добре для більш глибокого засвоєння
    2 — додавши, засвоїмо простіше
    1 — це доповнює тему

Іди згори вниз: немає чого назвати на 5 — переходь на 4, з 4 на 3, і так далі.
⛔ Порожнім цей перелік не буває НІКОЛИ: щонайменше один пункт рівня 1 є завжди.
⛔ Кількостей слів не називай ніде — ні підлоги, ні стелі, ні квоти на розділ.`;

const P = {
  /** Запит 1 · ЦІЛЬ. Лише цей текст і базові правила — більше нічого. */
  goal(u, { mentions }) {
    const rules = readType(u.type, "goals");
    return render([
      { tag: "ЗАВДАННЯ", body: head(u) },
      { tag: "ЗГАДКИ В КОРПУСІ", body: mentions },
      { tag: "ПРАВИЛА-DROP", body: forAgent(rules) },
      {
        tag: "ЩО ЗРОБИТИ", body: `${section(rules, ASK)}
Назва теми й місце, де вона лежить, важать більше за згадки: згадки лише доповнюють.`
      },
      {
        tag: "ПОВЕРНИ", body: u.type === "basic"
          ? "<ЦІЛЬ>речення або абзац</ЦІЛЬ>"
          : "<ЦІЛЬ>речення або абзац</ЦІЛЬ>\n<РІВЕНЬ>1 | 2 | 3</РІВЕНЬ>"
      },
    ]);
  },

  /** Запит 2 · КАРКАС. Єдиний, хто бачить preknowlist і перелік книг. */
  karkas(u, { goal, level, preknow, books }) {
    const rules = readType(u.type, "karkas");
    return render([
      { tag: "ЗАВДАННЯ", body: head(u) },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "РІВЕНЬ", body: level ? String(level) : "" },
      /* У курсі це не сусіди, а пройдене: крок спирається на нього як на відоме. */
      { tag: u.kind === "course" ? "ЩО ЧИТАЧ УЖЕ ПРОЙШОВ" : "ЩО ЧИТАЧ УЖЕ ЗНАЄ", body: u.type === "article" ? preknow : "" },
      { tag: "КНИГИ РЕПО", body: u.type === "article" ? books : "" },
      /* ⚠️ КАРКАС МУСИТЬ БАЧИТИ ПРАВИЛА ПРО ОБСЯГ І МЕЖУ ТЕМИ, бо саме він вирішує,
         скільки буде розділів і скільки проєктів коду. Без цього рядка правило «стаття
         серед інших статей» дійшло б аж до письменника — коли п'ятнадцять розділів і три
         проєкти вже замовлено, і різати нічого. Архітектурі коду з тієї ж причини йдуть
         спільні правила про код: тека мови — корінь, модулів стільки, скільки має річ. */
      { tag: "ПРАВИЛА-DROP", body: [bookCanon(u), shared([u.type === "code" ? "code" : "prose"]), forAgent(rules)].filter(Boolean).join("\n\n") },
      {
        tag: "ЩО ЗРОБИТИ", body: u.type === "code"
          ? `${section(rules, ASK)}
Шлях кожного файла — ВІД КОРЕНЯ ПРОЄКТУ, і корінь проєкту це вже сама тека мови «${u.lang}».
Отже шлях не повторює ні мови, ні імені носія: «app/main.${u.lang}», а не «${u.lang}/app/main.${u.lang}»
і не «${u.carrier || "<носій>"}/${u.lang}/app/main.${u.lang}». Довга форма з правил — про директиву
«:::code» у прозі, не про цю відповідь.`
          : section(rules, ASK)
      },
      { tag: "ПОВЕРНИ", body: section(rules, RET) },
    ]);
  },

  /** Запит 3 · ПИСЬМО. Групою — лише перший раз. */
  write(u, { goal, level, sections, theses, inserts, passed, linkable }) {
    const rules = readType(u.type, "rules");
    const hasCode = /\bкод\b/i.test(String(inserts || "")) || u.type === "code";
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nрівень: ${level || "—"}` },
      { tag: "ЦІЛЬ", body: goal },
      /* У курсі письменник мусить бачити, на що спирається: пройдене — відоме читачеві. */
      { tag: "ЩО ЧИТАЧ УЖЕ ПРОЙШОВ", body: u.kind === "course" ? passed : "" },
      { tag: "МОЇ РОЗДІЛИ", body: sections },
      { tag: "ТЕЗИ ПОПЕРЕДНІХ РОЗДІЛІВ", body: theses },
      { tag: "ВСТАВКИ Й КОД ЦИХ РОЗДІЛІВ", body: inserts },
      /* ⛔ ЄДИНИЙ ПЕРЕЛІК АДРЕС, ЯКІ СПРАВДІ Є. Правила описують форму лінка, і письменник
         її знає — саме тому й складає адреси сам, коли справжніх не дали. */
      { tag: "КУДИ МОЖНА ЛІНКУВАТИ", body: linkable },
      { tag: "ПРАВИЛА-DROP", body: writingRules(u, { code: hasCode }) },
      {
        tag: "ЩО ЗРОБИТИ", body: `${section(rules, ASK)}
⛔ Лінк став ЛИШЕ на адресу з «Куди можна лінкувати» або з «Вставки й код цих розділів» —
дослівно, як там написано. Своїх адрес не складай: форму ти знаєш, а слугів корпусу ні,
і складена адреса — битий лінк. Треба послатися на те, чого в переліку немає, — не лінкуй,
а назви це в «Нові теми».
${TAIL}`
      },
      {
        tag: "ПОВЕРНИ", body: section(rules, RET) || `<ТЕКСТ>готовий текст розділів із заголовками</ТЕКСТ>
<ТЕЗИ>по рядку на тезу</ТЕЗИ>
<ЧИ ГЛИБШЕ>так — і що саме додав би | ні</ЧИ ГЛИБШЕ>
<ЧИ ПОВНО>так | ні — і чого бракує</ЧИ ПОВНО>
<ЩО ЗЖАТИ>що можна стиснути без втрати сенсу й на чому; немає — пустота</ЩО ЗЖАТИ>
<ЩО ДОДАТИ>перелік або порожньо</ЩО ДОДАТИ>
<НОВІ ТЕМИ>назви або порожньо</НОВІ ТЕМИ>`
      },
    ]);
  },

  /** Запит 4 · ДОПИСУВАННЯ. Один розділ, не група. */
  extend(u, { goal, level, section: sec, text, neighbours, add }) {
    /* ⚠️ МІРА ДОПИСУВАННЯ — ЧИСЛОМ, І ЦЕ НЕ СУПЕРЕЧИТЬ ЗАБОРОНІ ЧИСЕЛ.
       Заборона стоїть на ОРІЄНТИРІ ДЛЯ ВСІЄЇ СТАТТІ: показане число стає ціллю, і
       письменник на ньому спиняється — заміряно, медіана 2970 при орієнтирі 2950 й
       розкид 300 слів на смузі 7700, тобто довжину задавала таблиця, а не предмет.
       Тут число інше за роллю: це ПІДЛОГА НА НАЗВАНИЙ ПУНКТ, який письменник обрав
       сам. Спинитися на ній нема на чому — пунктів кілька, і кожен має свою.
       «Принаймні абзац» було тим самим числом, лише розмитим: абзац тлумачать на
       свою користь, а 300 слів — ні. */
    const top = Number((String(add).match(/^\s*([1-5])\s*\|/m) || [])[1]) || 1;
    const WORDS = top >= 4 ? 300 : top === 3 ? 250 : 150;
    const much = `Кожен названий пункт розгорни НОВИМ текстом — не менше ${WORDS} слів на пункт.
І ще стільки ж (${WORDS} слів) додай, РОЗШИРИВШИ вже написане в цьому розділі: поглиб
наявні місця там, де вони сказані стисло, а не переказуй їх іншими словами.
Разом розділ має вирости приблизно на ${WORDS * 2} слів.`;
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nрівень: ${level || "—"}` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "ЦЕЙ РОЗДІЛ", body: `питання: ${sec}\nнаявний текст:\n${text}` },
      { tag: "ТЕЗИ СУСІДІВ", body: neighbours },
      { tag: "ЩО ЗРОБИТИ", body: writingRules(u) },
      {
        /* Дописувач теж вертає «що додати» — і його перелік іде в наступне коло. Без
           хвоста він міг би повернути пустоту, і коло обірвалось би на першому кроці. */
        tag: "ЩО ЗРОБИТИ", body: `Розшир цей розділ САМЕ ЦИМ:

${add}

${much}

⛔ Ці слова мусять бути ПРО НАЗВАНЕ. Набивати обсяг загальними реченнями, переказом
уже сказаного чи повторами — гірше, ніж не дописати зовсім: таке однаково знімуть
на перечитуванні, а стаття втратить нитку.
⛔ Чого в цьому переліку немає — того не додавай.
${TAIL}`
      },
      {
        tag: "ПОВЕРНИ", body: `<ТЕКСТ>новий текст ЦЬОГО розділу</ТЕКСТ>
<ТЕЗИ>перезібрані</ТЕЗИ>
<ЧИ ГЛИБШЕ>так — і що саме | ні</ЧИ ГЛИБШЕ>
<ЧИ ПОВНО>так | ні — і чого бракує</ЧИ ПОВНО>
<ЩО ЗЖАТИ>або порожньо</ЩО ЗЖАТИ>
<ЩО ДОДАТИ>або порожньо</ЩО ДОДАТИ>`
      },
    ]);
  },

  /**
   * Запит 12 · СТИСНЕННЯ. Дзеркало дописування: не «до числа», а НАЗВАНИМ матеріалом —
   * тим, що письменник сам назвав у «Що зжати». Сліпе обрубання по стелі думати не вміє
   * й рве нитку посередині.
   */
  compress(u, { goal, level, section: sec, text, neighbours, squeeze, howMuch }) {
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nрівень: ${level || "—"}\nнаскільки: ${howMuch}` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "ЦЕЙ РОЗДІЛ", body: `питання: ${sec}\nнаявний текст:\n${text}` },
      { tag: "ТЕЗИ СУСІДІВ", body: neighbours },
      { tag: "ЩО ЗЖАТИ", body: squeeze },
      { tag: "ПРАВИЛА-DROP", body: writingRules(u) },
      {
        tag: "ЩО ЗРОБИТИ", body: `Стисни цей розділ — ${howMuch}. Прибери саме те, що названо в «Що зжати»,
і лише його. Порядок думки й нитку не ламай: якщо скорочення робить пояснення
діркуватим, це місце не скорочуй. Решти тексту не чіпай.`
      },
      {
        tag: "ПОВЕРНИ", body: `<ТЕКСТ>новий текст ЦЬОГО розділу</ТЕКСТ>
<ТЕЗИ>перезібрані</ТЕЗИ>
<ЩО ЗЖАТИ>що ще можна, або порожньо</ЩО ЗЖАТИ>`
      },
    ]);
  },

  /** Запит 6 · ВИКЛАДКА. Єдине повне перечитування в конвеєрі. */
  layout(u, { goal, level, text }) {
    const rules = readType(u.type, "rules");
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nрівень: ${level || "—"}` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "ТЕКСТ", body: text },
      { tag: "ПРАВИЛА-DROP", body: [bookCanon(u), shared(["prose"]), forAgent(rules)].filter(Boolean).join("\n\n") },
      {
        tag: "ЩО ЗРОБИТИ", body: `Чи повно текст відповідає заявленій цілі на цьому рівні — і чи тримається
він правил викладу: нитка без пробілів, перехід між думками природний, а не
через порожні речення-зв'язки, текст не говорить про себе?
Якщо так — поверни лише «ок» і більше нічого.
Якщо ні — назви конкретно, ЩО не так і ДЕ, по абзацах. Нічого не переписуй.`
      },
      { tag: "ПОВЕРНИ", body: "<ОК>так | ні</ОК>\n<НЕ ТАК>абзац {який} :: {що саме не так}</НЕ ТАК>" },
    ]);
  },

  /** Запит 7 · ПЕРЕПИС. Тільки названі абзаци. */
  /**
   * ⛔ ТЕКСТ ІДЕ ЦІЛИЙ І ВЕРТАЄТЬСЯ ЦІЛИЙ. Доти сюди йшла вся стаття під тегом «АБЗАЦИ»
   * з приписом «перепиши саме ці абзаци», а назад просили «перероблені абзаци» — агент
   * чесно вертав самі лише перероблені шматки, і алгоритм клав їх НА МІСЦЕ ВСІЄЇ статті.
   * Заміряно на `proj`-вставці: 2080 слів прози до перепису, 616 після. Тому тег тепер
   * «ТЕКСТ», а припис каже прямо: віддай усе, ціле, з полагодженими місцями.
   */
  rewrite(u, { goal, paragraphs, defect, attempt }) {
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nспроба: ${attempt} з 7` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "ТЕКСТ", body: paragraphs },
      { tag: "ЩО НЕ ТАК", body: defect },
      { tag: "ПРАВИЛА-DROP", body: writingRules(u) },
      {
        tag: "ЩО ЗРОБИТИ", body: `Полагодь названі місця так, щоб зауважень не лишилось.
Решти не чіпай: там, де зауважень немає, текст має лишитися слово в слово.
⛔ Поверни текст ЦІЛИЙ — від першого рядка до останнього, а не самі лише виправлені
шматки. Те, що ти повернеш, стає статтею; чого не повернеш — зникне.`
      },
      { tag: "ПОВЕРНИ", body: "<ТЕКСТ>увесь текст, цілий, із полагодженими місцями</ТЕКСТ>" },
    ]);
  },

  /**
   * Запит 13 · КОД. Реалізувати архітектуру файлами. Прози не пише; правила — спільні
   * про код плюс свої, а «що просимо» й «що повертає» — з code-rules.md.
   */
  codeWrite(u, { goal, level, files, classes, structure }) {
    const rules = readType("code", "rules");
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nрівень: ${level || "—"}` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "ФАЙЛИ", body: files },
      { tag: "КЛАСИ", body: classes },
      { tag: "СТРУКТУРА", body: structure },
      { tag: "ПРАВИЛА-DROP", body: [bookCanon(u), shared(["code"]), forAgent(rules)].filter(Boolean).join("\n\n") },
      {
        tag: "ЩО ЗРОБИТИ", body: `${section(rules, ASK)}
Шлях кожного файла — ВІД КОРЕНЯ ПРОЄКТУ, і корінь проєкту це вже сама тека мови «${u.lang}».
Отже шлях не повторює ні мови, ні імені носія: «app/main.${u.lang}», а не «${u.lang}/app/main.${u.lang}»
і не «${u.carrier || "<носій>"}/${u.lang}/app/main.${u.lang}». Довга форма з правил — про директиву
«:::code» у прозі, не про цю відповідь.`
      },
      { tag: "ПОВЕРНИ", body: section(rules, RET) },
    ]);
  },

  /** Запит 8 · ФОРМУЛИ. Один раз; тексту статті не шлемо. */
  formulas(u, { lines }) {
    return render([
      { tag: "ЗАВДАННЯ", body: head(u) },
      { tag: "ФОРМУЛИ Й ОБРАХУНКИ", body: lines },
      { tag: "ПРАВИЛА-DROP", body: forAgent(fs.readFileSync(path.join(RULES, "formulas.md"), "utf8")) },
      {
        tag: "ЩО ЗРОБИТИ", body: `Перевір кожну формулу й кожен обрахунок.
Поверни ЛИШЕ пари: стара → на яку замінити. Правильні не згадуй узагалі.`
      },
      { tag: "ПОВЕРНИ", body: "<ЗАМІНИ>{рядок} :: {було} → {стало}</ЗАМІНИ>" },
    ]);
  },

  /** Запит 9 · КОД C і C++. Тексту не бачить і не потребує. */
  codeLangs(u, { dir, langs }) {
    return render([
      { tag: "ЗАВДАННЯ", body: `тема: ${u.title}\nде код: ${dir}\nмови, що вже є: ${langs || "жодної"}` },
      {
        tag: "ЩО ЗРОБИТИ", body: `Чи можна цей код написати на C? Чи можна на C++?
На кожне — «так» або «ні», і причину, якщо «ні».`
      },
      { tag: "ПОВЕРНИ", body: "<C>так | ні — причина</C>\n<CPP>так | ні — причина</CPP>" },
    ]);
  },

  /** Запит 11 · БАЗОВА. Лише коли локальна перевірка сказала «треба». */
  basicNeeded(u, { goal, level, text }) {
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nрівень детальної: ${level || "—"}` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "ТЕКСТ ДЕТАЛЬНОЇ", body: text },
      { tag: "ПРАВИЛА-DROP", body: forAgent(readType("basic", "goals")) },
      {
        tag: "ЩО ЗРОБИТИ", body: `Локальна перевірка каже, що базова версія потрібна.
Підтверди або спростуй — одним словом і одним реченням причини.`
      },
      { tag: "ПОВЕРНИ", body: "<ТРЕБА>так | ні</ТРЕБА>\n<ЧОМУ>одне речення</ЧОМУ>" },
    ]);
  },

  /** Запит 10 · НОВІ ТЕМИ. Один на БАТЧ, типу не має. */
  newTopics({ named, existing }) {
    return render([
      { tag: "НАЗВАНІ ТЕМИ", body: named },
      { tag: "ТЕМИ, ЩО Є", body: existing },
      {
        tag: "ЩО ЗРОБИТИ", body: `Для кожної названої теми скажи одне з двох: вона вже є серед наявних —
і котра саме, — або її треба заводити.`
      },
      { tag: "ПОВЕРНИ", body: "<Є>назване → наявна тема</Є>\n<ЗАВОДИТИ>назви</ЗАВОДИТИ>" },
    ]);
  },
};

module.exports = { ...P, render, weigh, section, forAgent, readType, head, shared, bookCanon, writingRules };
