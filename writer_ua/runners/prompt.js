#!/usr/bin/env node
/* ============================================================================
   prompt.js — СКЛАДАННЯ ЗАВДАННЯ З БЛОКІВ. Підстановка, а не зшивання.

   Кожен блок має ОДНЕ джерело: ціль зі стану, тези з попереднього кроку, правила з
   файла. Тому тут немає жодного «зліпити рядок» — є список блоків і один спосіб їх
   вивести. Вартість теж стає видимою: `weigh()` каже, скільки важить кожен блок, і
   видно, за що платиш.

   ДЕ ЖИВЕ ЩО. Кістяк завдання — тут, у коді: він однаковий для всіх типів. Те, що
   різниться від типу до типу, — «що просимо» і «що повертає» — лежить у
   `rules/types/<тип>-<goals|karkas|rules>.md` і читається звідти. Так тип тримає лише
   РІЗНИЦЮ, і вісім копій правил про код не розходяться.

   ⛔ АГЕНТОВІ НЕ ЙДЕ РОЗДІЛ «ЩО ТРЕБА ЗРОБИТИ». Це наші відкриті питання, не його
   робота: показати їх означало б попросити вгадати те, чого ми самі не вирішили.
   ========================================================================== */
"use strict";
const fs = require("fs");
const path = require("path");

const RULES = path.join(__dirname, "..", "rules");

/* ── читання правил типу ───────────────────────────────────────────────────── */

const readType = (type, kind) => {
  const p = path.join(RULES, "types", `${type}-${kind}.md`);
  if (!fs.existsSync(p)) throw new Error(`немає правил: ${path.relative(RULES, p)}`);
  return fs.readFileSync(p, "utf8");
};

/**
 * Секція markdown за заголовком другого рівня, без самого заголовка.
 * Ріжемо розбиттям, а не регуляркою з поглядом уперед: `(?=^## |\s*$)` збігається з
 * порожнім рядком одразу після заголовка, тож секція виходила порожня, і `<ЩО ЗРОБИТИ>`
 * тихо їхало без головного припису.
 */
function section(md, title) {
  for (const part of String(md).split(/^## /m).slice(1)) {
    const nl = part.indexOf("\n");
    if (part.slice(0, nl < 0 ? part.length : nl).trim() === title)
      return part.slice(nl + 1).trim();
  }
  return "";
}

/** Те, що агент справді бачить: усе, крім наших відкритих питань. */
function forAgent(md) {
  return md.replace(/^## Що треба зробити\s*$[\s\S]*$/m, "").trim();
}

/* ── блоки ─────────────────────────────────────────────────────────────────── */

/**
 * Блок із порожнім тілом НЕ друкується. Порожній `<ТЕЗИ ПОПЕРЕДНІХ РОЗДІЛІВ>` у
 * першого письменника — це не «нічого немає», це зайвий рядок, за який платять усі
 * наступні ходи.
 */
function render(blocks) {
  return blocks
    .filter((b) => b && b.body !== undefined && b.body !== null && String(b.body).trim() !== "")
    .map((b) => `<${b.tag}>\n${String(b.body).trim()}\n</${b.tag}>`)
    .join("\n\n");
}

/** Скільки важить кожен блок — щоб було видно, що різати. */
function weigh(blocks) {
  return blocks.filter((b) => b && String(b.body || "").trim())
    .map((b) => ({ tag: b.tag, chars: String(b.body).trim().length }))
    .sort((a, b) => b.chars - a.chars);
}

/* ── шапка завдання ────────────────────────────────────────────────────────── */

/**
 * ⚠️ ПОСИЛАННЯ НА СТАТТЮ ЗАВЖДИ НЕСЕ ПОВНИЙ ШЛЯХ МОВОЮ. Машинна адреса потрібна
 * скриптам, а не тому, хто читає: `sf-apps/model-building-blocks` не каже нічого, а
 * «Архітектура застосунку / Предметна модель / Цеглинки моделі» каже все одразу.
 */
const head = (u) => [
  `книга: ${u.bookTitle}`,
  `тема: ${u.title}`,
  `тип: ${u.type}${u.version ? ` — ${u.version} версія статті` : ""}`,
  u.groupTitle ? `де лежить: група «${u.groupTitle}» / розділ «${u.chapterTitle}»` : null,
].filter(Boolean).join("\n");

/* ── самі завдання ─────────────────────────────────────────────────────────── */

const ASK = "Що просимо", RET = "Що повертає";

const P = {
  /** Запит 1 · ЦІЛЬ. Лише цей текст і базові правила — більше нічого. */
  goal(u, { mentions }) {
    const rules = readType(u.type, "goals");
    return render([
      { tag: "ЗАВДАННЯ", body: head(u) },
      { tag: "ЗГАДКИ В КОРПУСІ", body: mentions },
      { tag: "ПРАВИЛА", body: forAgent(rules) },
      {
        tag: "ЩО ЗРОБИТИ", body: `${section(rules, ASK)}
Назва теми й місце, де вона лежить, важать більше за згадки: згадки лише доповнюють.`
      },
      {
        tag: "ПОВЕРНИ", body: u.type === "basic"
          ? "<ЦІЛЬ>речення або абзац</ЦІЛЬ>"
          : "<ЦІЛЬ>речення або абзац</ЦІЛЬ>\n<РІВЕНЬ>1 | 2 | 3</РІВЕНЬ>"
      },
    ]);
  },

  /** Запит 2 · КАРКАС. Єдиний, хто бачить preknowlist і перелік книг. */
  karkas(u, { goal, level, preknow, books }) {
    const rules = readType(u.type, "karkas");
    return render([
      { tag: "ЗАВДАННЯ", body: head(u) },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "РІВЕНЬ", body: level ? String(level) : "" },
      { tag: "ЩО ЧИТАЧ УЖЕ ЗНАЄ", body: u.type === "article" ? preknow : "" },
      { tag: "КНИГИ РЕПО", body: u.type === "article" ? books : "" },
      { tag: "ПРАВИЛА", body: forAgent(rules) },
      { tag: "ЩО ЗРОБИТИ", body: section(rules, ASK) },
      { tag: "ПОВЕРНИ", body: section(rules, RET) },
    ]);
  },

  /** Запит 3 · ПИСЬМО. Групою — лише перший раз. */
  write(u, { goal, level, sections, theses, inserts }) {
    const rules = readType(u.type, "rules");
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nрівень: ${level || "—"}` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "МОЇ РОЗДІЛИ", body: sections },
      { tag: "ТЕЗИ ПОПЕРЕДНІХ РОЗДІЛІВ", body: theses },
      { tag: "ВСТАВКИ Й КОД ЦИХ РОЗДІЛІВ", body: inserts },
      { tag: "ПРАВИЛА", body: forAgent(rules) },
      {
        tag: "ЩО ЗРОБИТИ", body: `${section(rules, ASK)}
Наприкінці:
— дай тези: ПРО ЩО реалізовано, а не звіт про зроблене;
— скажи, чи можеш написати ще глибше і чи повно виклав увесь матеріал;
— назви, що можна додати для кращого розуміння. Не перевантажуй і не пиши заради
  обсягу: немає або неважливе — поверни пустоту;
— назви нові теми, на які натрапив. Не заводь їх, тільки назви.`
      },
      {
        tag: "ПОВЕРНИ", body: section(rules, RET) || `<ТЕКСТ>готовий текст розділів із заголовками</ТЕКСТ>
<ТЕЗИ>по рядку на тезу</ТЕЗИ>
<ЧИ ГЛИБШЕ>так — і що саме додав би | ні</ЧИ ГЛИБШЕ>
<ЧИ ПОВНО>так | ні — і чого бракує</ЧИ ПОВНО>
<ЩО ДОДАТИ>перелік або порожньо</ЩО ДОДАТИ>
<НОВІ ТЕМИ>назви або порожньо</НОВІ ТЕМИ>`
      },
    ]);
  },

  /** Запит 4 · ДОПИСУВАННЯ. Один розділ, не група. */
  extend(u, { goal, level, section: sec, text, neighbours, add, howMuch }) {
    const rules = readType(u.type, "rules");
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nрівень: ${level || "—"}\nнаскільки: ${howMuch}` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "ЦЕЙ РОЗДІЛ", body: `питання: ${sec}\nнаявний текст:\n${text}` },
      { tag: "ТЕЗИ СУСІДІВ", body: neighbours },
      { tag: "ЩО ДОДАТИ", body: add },
      { tag: "ПРАВИЛА", body: forAgent(rules) },
      {
        tag: "ЩО ЗРОБИТИ", body: `Розшир цей розділ — ${howMuch}. Додай саме те, що названо в «Що додати».
Заради обсягу не вигадуй нічого. Решти тексту не чіпай.`
      },
      {
        tag: "ПОВЕРНИ", body: `<ТЕКСТ>новий текст ЦЬОГО розділу</ТЕКСТ>
<ТЕЗИ>перезібрані</ТЕЗИ>
<ЧИ ГЛИБШЕ>так — і що саме | ні</ЧИ ГЛИБШЕ>
<ЧИ ПОВНО>так | ні — і чого бракує</ЧИ ПОВНО>
<ЩО ДОДАТИ>або порожньо</ЩО ДОДАТИ>`
      },
    ]);
  },

  /** Запит 6 · ВИКЛАДКА. Єдине повне перечитування в конвеєрі. */
  layout(u, { goal, level, text }) {
    const rules = readType(u.type, "rules");
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nрівень: ${level || "—"}` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "ТЕКСТ", body: text },
      { tag: "ПРАВИЛА", body: forAgent(rules) },
      {
        tag: "ЩО ЗРОБИТИ", body: `Чи повно текст відповідає заявленій цілі на цьому рівні?
Якщо так — поверни лише «ок» і більше нічого.
Якщо ні — назви конкретно, ЩО не так і ДЕ, по абзацах. Нічого не переписуй.`
      },
      { tag: "ПОВЕРНИ", body: "<ОК>так | ні</ОК>\n<НЕ ТАК>абзац {який} :: {що саме не так}</НЕ ТАК>" },
    ]);
  },

  /** Запит 7 · ПЕРЕПИС. Тільки названі абзаци. */
  rewrite(u, { goal, paragraphs, defect, attempt }) {
    const rules = readType(u.type, "rules");
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nспроба: ${attempt} з 7` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "АБЗАЦИ", body: paragraphs },
      { tag: "ЩО НЕ ТАК", body: defect },
      { tag: "ПРАВИЛА", body: forAgent(rules) },
      {
        tag: "ЩО ЗРОБИТИ", body: `Перепиши саме ці абзаци так, щоб названого не лишилось.
Поза ними не чіпай нічого.`
      },
      { tag: "ПОВЕРНИ", body: "<ТЕКСТ>перероблені абзаци, у тому самому порядку</ТЕКСТ>" },
    ]);
  },

  /** Запит 8 · ФОРМУЛИ. Один раз; тексту статті не шлемо. */
  formulas(u, { lines }) {
    return render([
      { tag: "ЗАВДАННЯ", body: head(u) },
      { tag: "ФОРМУЛИ Й ОБРАХУНКИ", body: lines },
      { tag: "ПРАВИЛА", body: forAgent(fs.readFileSync(path.join(RULES, "formulas.md"), "utf8")) },
      {
        tag: "ЩО ЗРОБИТИ", body: `Перевір кожну формулу й кожен обрахунок.
Поверни ЛИШЕ пари: стара → на яку замінити. Правильні не згадуй узагалі.`
      },
      { tag: "ПОВЕРНИ", body: "<ЗАМІНИ>{рядок} :: {було} → {стало}</ЗАМІНИ>" },
    ]);
  },

  /** Запит 9 · КОД C і C++. Тексту не бачить і не потребує. */
  codeLangs(u, { dir, langs }) {
    return render([
      { tag: "ЗАВДАННЯ", body: `тема: ${u.title}\nде код: ${dir}\nмови, що вже є: ${langs || "жодної"}` },
      {
        tag: "ЩО ЗРОБИТИ", body: `Чи можна цей код написати на C? Чи можна на C++?
На кожне — «так» або «ні», і причину, якщо «ні».`
      },
      { tag: "ПОВЕРНИ", body: "<C>так | ні — причина</C>\n<CPP>так | ні — причина</CPP>" },
    ]);
  },

  /** Запит 11 · БАЗОВА. Лише коли локальна перевірка сказала «треба». */
  basicNeeded(u, { goal, level, text }) {
    return render([
      { tag: "ЗАВДАННЯ", body: `${head(u)}\nрівень детальної: ${level || "—"}` },
      { tag: "ЦІЛЬ", body: goal },
      { tag: "ТЕКСТ ДЕТАЛЬНОЇ", body: text },
      { tag: "ПРАВИЛА", body: forAgent(readType("basic", "goals")) },
      {
        tag: "ЩО ЗРОБИТИ", body: `Локальна перевірка каже, що базова версія потрібна.
Підтверди або спростуй — одним словом і одним реченням причини.`
      },
      { tag: "ПОВЕРНИ", body: "<ТРЕБА>так | ні</ТРЕБА>\n<ЧОМУ>одне речення</ЧОМУ>" },
    ]);
  },

  /** Запит 10 · НОВІ ТЕМИ. Один на БАТЧ, типу не має. */
  newTopics({ named, existing }) {
    return render([
      { tag: "НАЗВАНІ ТЕМИ", body: named },
      { tag: "ТЕМИ, ЩО Є", body: existing },
      {
        tag: "ЩО ЗРОБИТИ", body: `Для кожної названої теми скажи одне з двох: вона вже є серед наявних —
і котра саме, — або її треба заводити.`
      },
      { tag: "ПОВЕРНИ", body: "<Є>назване → наявна тема</Є>\n<ЗАВОДИТИ>назви</ЗАВОДИТИ>" },
    ]);
  },
};

module.exports = { ...P, render, weigh, section, forAgent, readType, head };
