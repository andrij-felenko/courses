#!/usr/bin/env node
/* ============================================================================
   prompt.js — СКЛАДАННЯ ЗАВДАННЯ З БЛОКІВ. Підстановка, а не зшивання.

   Кожен блок має ОДНЕ джерело: ціль зі стану, тези з попереднього кроку, правила з
   файла. Тому тут немає жодного «зліпити рядок» — є список блоків і один спосіб їх
   вивести. Вартість теж стає видимою: `weigh()` каже, скільки важить кожен блок, і
   видно, за що платиш.

   ДЕ ЖИВЕ ЩО. Кістяк завдання — тут, у коді: він однаковий для всіх типів. Те, що
   різниться від типу до типу, — «що просимо» і «що повертає» — лежить у
   `rules/types/<тип>-<goals|karkas|rules>.md` і читається звідти. Так тип тримає лише
   РІЗНИЦЮ, і вісім копій правил про код не розходяться.

   ⛔ АГЕНТОВІ НЕ ЙДЕ РОЗДІЛ «ЩО ТРЕБА ЗРОБИТИ». Це наші відкриті питання, не його
   робота: показати їх означало б попросити вгадати те, чого ми самі не вирішили.
   ========================================================================== */
"use strict";
const fs = require("fs");
const path = require("path");

const RULES = path.join(__dirname, "..", "rules");

/* ── читання правил типу ───────────────────────────────────────────────────── */

const readType = (type, kind) => {
  const p = path.join(RULES, "types", `${type}-${kind}.md`);
  if (!fs.existsSync(p)) throw new Error(`немає правил: ${path.relative(RULES, p)}`);
  return fs.readFileSync(p, "utf8");
};

/**
 * Секція markdown за заголовком другого рівня, без самого заголовка.
 * Ріжемо розбиттям, а не регуляркою з поглядом уперед: `(?=^## |\s*$)` збігається з
 * порожнім рядком одразу після заголовка, тож секція виходила порожня, і `<ЩО ЗРОБИТИ>`
 * тихо їхало без головного припису.
 */
function section(md, title) {
  for (const part of String(md).split(/^## /m).slice(1)) {
    const nl = part.indexOf("\n");
    if (part.slice(0, nl < 0 ? part.length : nl).trim() === title)
      return part.slice(nl + 1).trim();
  }
  return "";
}

/**
 * ⛔ АГЕНТ БАЧИТЬ РІВНО ОДНУ СЕКЦІЮ ФАЙЛА ПРАВИЛ — «Треба зробити». Це не спрощення
 * заради стислості, а спосіб УНЕМОЖЛИВИТИ клас вад, який ми вже двічі ловили руками.
 *
 * Раніше тут стояв `forAgent()`, що зрізав дві секції з кінця й лишав усе решта. Тоді
 * джерел ставало два — «весь файл, крім двох секцій» і «сама секція наказу», — і хто
 * підставляв обидва, слав правила двічі: у каркасі статті це було 7,5 КБ слово в слово.
 * Заразом до наказу їхала службова шапка («Іде в запит 5 (аналіз)» — запиту, якого в
 * конвеєрі немає) і маркери `<!-- канон -->`.
 *
 * Одне джерело — і ні дубля, ні службового тексту вже не буває за побудовою.
 */

/**
 * Спільні правила — по файлу на турботу, рівно ті, що потрібні цьому запиту.
 * Порожній файл нічого не додає: заглушка не має ставати блоком.
 */
function shared(names) {
  return names.map((n) => {
    const p = path.join(RULES, n + ".md");
    if (!fs.existsSync(p)) return "";
    const body = section(fs.readFileSync(p, "utf8"), ASK);
    return body && !/^\{ще не нарізано/.test(body) ? body : "";
  }).filter(Boolean).join("\n\n");
}

/**
 * Правила самої книги — `_canon.md` в її теці: наскрізний приклад, єдині терміни, мова
 * прикладів. Де вони уточнюють загальне, перевага в них — тому стоять ПЕРШИМИ.
 */
function bookCanon(u) {
  const p = u && u.bookDir ? path.join(u.bookDir, "_canon.md") : "";
  if (!p || !fs.existsSync(p)) return "";
  /* ⛔ ПЕРЕВАГУ ТРЕБА СКАЗАТИ ВГОЛОС. Доти вона жила в коментарі цього коду, тобто
     адресувалась нам, а не агентові: порядок блоків сам по собі сили не має, і при
     конфлікті наскрізного прикладу книги із загальним правилом вибір був навмання. */
  return "ПРАВИЛА ЦІЄЇ КНИГИ. Там, де вони уточнюють загальне, перевага в них.\n\n"
    + fs.readFileSync(p, "utf8").trim();
}

/** Правила письма: канон книги → спільні → свій тип. Код — лише коли він прив'язаний. */
function writingRules(u, { code = false } = {}) {
  const names = ["prose", "language", "links", "formulas", "figures"];
  if (code) names.push("code");
  return [bookCanon(u), shared(names), section(readType(u.type, "rules"), ASK)].filter(Boolean).join("\n\n");
}

/* ── блоки ─────────────────────────────────────────────────────────────────── */

/**
 * Блок із порожнім тілом НЕ друкується. Порожній `<ТЕЗИ ПОПЕРЕДНІХ РОЗДІЛІВ>` у
 * першого письменника — це не «нічого немає», це зайвий рядок, за який платять усі
 * наступні ходи.
 */
function render(blocks) {
  /* ⛔ ОДНАКОВІ ТЕГИ ЗЛИВАЮТЬСЯ В ОДИН БЛОК, у порядку появи. Так правила й конкретний
     припис стають ОДНИМ наказом `<ЩО ЗРОБИТИ>`, а не окремим фоном і окремим наказом.
     Фон агент гортає: заміряно — `<ПРАВИЛА>` важили 82% завдання проти 5% наказу, і
     правило, покладене туди, не діяло. Перевірено двічі: вкладки запрацювали від
     переносу в наказ, а шкала «що додати» не працювала, поки лежала у фоні. */
  const merged = [];
  for (const b of blocks) {
    if (!b || b.body === undefined || b.body === null || String(b.body).trim() === "") continue;
    const at = merged.find((x) => x.tag === b.tag);
    if (at) at.body += "\n\n" + String(b.body).trim();
    else merged.push({ tag: b.tag, body: String(b.body).trim() });
  }
  return merged.map((b) => `<${b.tag}>\n${b.body}\n</${b.tag}>`).join("\n\n");
}

/** Скільки важить кожен блок — щоб було видно, що різати. */
function weigh(blocks) {
  return blocks.filter((b) => b && String(b.body || "").trim())
    .map((b) => ({ tag: b.tag, chars: String(b.body).trim().length }))
    .sort((a, b) => b.chars - a.chars);
}

/* ── шапка завдання ────────────────────────────────────────────────────────── */

/**
 * ⚠️ ПОСИЛАННЯ НА СТАТТЮ ЗАВЖДИ НЕСЕ ПОВНИЙ ШЛЯХ МОВОЮ. Машинна адреса потрібна
 * скриптам, а не тому, хто читає: `sf-apps/model-building-blocks` не каже нічого, а
 * «Архітектура застосунку / Предметна модель / Цеглинки моделі» каже все одразу.
 */
const KIND_NAME = { course: "курс", cat: "каталог", sys: "довідник" };
const kindName = (k) => KIND_NAME[k] || "книга";

const head = (u) => [
  `${kindName(u.kind)}: ${u.bookTitle}`,
  `тема: ${u.title}`,
  `тип: ${u.type}${u.version ? ` — ${u.version} версія статті` : ""}`,
  u.groupTitle
    ? (u.kind === "course"
      ? `де лежить: том «${u.groupTitle}» / розділ «${u.chapterTitle}»`
      : `де лежить: група «${u.groupTitle}» / розділ «${u.chapterTitle}»`)
    : null,
  u.type === "code" && u.lang ? `мова: ${u.lang}${u.about ? `\nщо реалізує: ${u.about}` : ""}` : null,
].filter(Boolean).join("\n");

/* ── самі завдання ─────────────────────────────────────────────────────────── */

const ASK = "Треба зробити", RET = "Треба отримати";

