const RULES = `ПРАВИЛА ПОДІЛУ:
• НАЗВА — СУВОРО 1-2 СЛОВА: один термін («Геометрія», «Графи», «Архітектура», «Периферія») або стале двослівне словосполучення («Лінійна алгебра», «Теорія чисел», «Теорія ігор», «Машинне навчання», «Диференціальні рівняння»). ЗАБОРОНЕНО: 3+ слова, переліки через кому, двокрапки, сполучники «і/й/та» у назві, описові фрази. Поганий приклад: «Електрика, магнетизм і рівняння Максвелла», «Основи: складність і парадигми» — так НЕ можна.
• ПОДІЛ ЯК НАУКА, а не як книга: ділити за ГАЛУЗЯМИ/піддисциплінами, як саме поле себе ділить (кафедри, категорії arXiv, класична класифікація науки) — НЕ за главами підручника чи педагогічними блоками.
• ЖОДНИХ filler/педагогічних: заборонено «Основи», «Вступ», «Що таке…», «Якість», «Прикладне», «Різне», «Інше», «Сучасне».
• ВИЧЕРПНО, але чисто: усі головні галузі дисципліни; рівна вага; межі взаємно-виключні; логічний порядок.
• Кількість — природна для науки (зазвичай 10–20; де користувач просив «простіше» — ближче до 8–12).
• Для кожної галузі: scope (1 речення — що всередині) + 4-8 прикладів-тем (теж по 1-2 слова кожна).
• slug — ascii-kebab.`

const SECTIONS = {
  type: 'object', additionalProperties: false, required: ['sections'],
  properties: { sections: { type: 'array', items: {
    type: 'object', additionalProperties: false, required: ['slug', 'title', 'scope'],
    properties: {
      slug: { type: 'string', description: 'ascii-kebab' },
      title: { type: 'string', description: 'СУВОРО 1-2 слова' },
      scope: { type: 'string' },
      examples: { type: 'array', items: { type: 'string', description: '1-2 слова' } },
    } } } } }

function designPrompt(b) {
  return `${RULES}\n\nТи — фахівець, що класифікує предмет «${b.title}» ЗА ГАЛУЗЯМИ НАУКИ (не як підручник).\nОрієнтир галузей: ${b.hint}\nДай повний перелік галузей-розділів книги «${b.title}». КОЖНА назва — строго 1-2 слова. Поділ науковий, вичерпний, чистий. scope + examples (теж 1-2 слова) для кожної.`
}

function critiquePrompt(b, draft) {
  return `${RULES}\n\nКнига «${b.title}». Чернетка галузей:\n${JSON.stringify(draft.sections.map(s => s.title))}\n\nЯк жорсткий критик ВИПРАВ: (1) будь-яку назву >2 слів або з комою/двокрапкою/«і/й/та» → стисни до 1-2 слів терміна; (2) «книжкові»/педагогічні/filler-розділи («Основи», «Вступ», «Якість», «Прикладне», «Сучасне», «Різне») → заміни справжньою галуззю науки або влий у відповідну; (3) ПРОГАЛИНИ галузей дисципліни → додай; (4) перетини → злий. Переконайся, що поділ виглядає як КЛАСИФІКАЦІЯ НАУКИ, а не зміст підручника.\nПоверни ПОВНИЙ виправлений перелік (slug, title[1-2 слова], scope, examples).`
}

phase('Галузі')
log(`Галузевий поділ ${BOOKS.length} книг, назви 1-2 слова`)

const results = await pipeline(
  BOOKS,
  (b) => agent(designPrompt(b), { label: `branch:${b.slug}`, phase: 'Галузі', schema: SECTIONS }).then(d => ({ b, design: d })),
  (x) => (x && x.design)
    ? agent(critiquePrompt(x.b, x.design), { label: `critic:${x.b.slug}`, phase: 'Критик', schema: SECTIONS })
        .then(c => ({ slug: x.b.slug, title: x.b.title, sections: (c && c.sections && c.sections.length) ? c.sections : x.design.sections }))
    : null
)

const books = results.filter(Boolean)
books.forEach(b => {
  const longnames = b.sections.filter(s => (s.title || '').trim().split(/\s+/).length > 2).map(s => s.title)
  log(`  ${b.slug}: ${b.sections.length} галузей${longions(longnames)}`)
})
function longions(a) { return a && a.length ? ` ⚠️довгі: ${a.join(', ')}` : '' }

return { books: books.map(b => ({ slug: b.slug, title: b.title, sections: b.sections })) }
