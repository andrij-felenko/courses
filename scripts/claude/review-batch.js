/* Друге коло: редакторові дають те, що перший прохід підняв і не закрив. */
const WITH_ESC = (dir) => `${PROMPT(dir)}

═══ ПОПЕРЕДНЄ КОЛО ЛИШИЛО ПИТАННЯ ПО ЦІЙ ТЕЦІ ═══
${ROOT}\\scripts\\_finish\\_esc\\${dir.split('/').pop()}.json — прочитай його першим ділом.
Кожен пункт має поля what (про що), a і b (два твердження, що не сходяться), checked (що вже
перевірено — не повторюй цю роботу). Закрий кожен пункт за правилами розділу 3 і назви в
resolved, як саме: «<what> → <що зроблено з текстом>». Пункти про ОБСЯГ і про вкладки C++
закривати НЕ треба — цього проходу вони не судяться, просто напиши «не судиться».
Файл може не існувати — тоді працюй звичайно.`

const RET = {
  type: 'object', additionalProperties: false, required: ['dir', 'ok'],
  properties: {
    dir: { type: 'string' },
    ok: { type: 'boolean' },
    logic: { type: 'array', items: { type: 'string' } },
    code: { type: 'array', items: { type: 'string' } },
    formulas: { type: 'array', items: { type: 'string' } },
    units: { type: 'array', items: { type: 'string' } },
    language: { type: 'array', items: { type: 'string' } },
    figures: { type: 'array', items: { type: 'string' } },
    consistency: { type: 'array', items: { type: 'string' } },
    resolved: { type: 'array', items: { type: 'string' } },
    newTopics: {
      type: 'array',
      items: {
        type: 'object', additionalProperties: false, required: ['slug', 'why'],
        properties: { slug: { type: 'string' }, title: { type: 'string' }, section: { type: 'string' }, why: { type: 'string' } },
      },
    },
    escalations: {
      type: 'array',
      items: {
        type: 'object', additionalProperties: false, required: ['what', 'a', 'b'],
        properties: { what: { type: 'string' }, a: { type: 'string' }, b: { type: 'string' }, checked: { type: 'string' } },
      },
    },
    note: { type: 'string' },
  },
}

phase('Ревізія')
const ROUND2 = A.round2 !== false
log(`тем на ревізію: ${DIRS.length}${ROUND2 ? ' (з підхопленням ескалацій попереднього кола)' : ''}`)
const res = await parallel(DIRS.map((d) => () =>
  agent(ROUND2 ? WITH_ESC(d) : PROMPT(d), { label: `рев:${d.split('/').pop()}`, phase: 'Ревізія', schema: RET, effort: EFFORT })))

const ok = res.filter(Boolean)
/* Готовність судить редактор, а не лічильник ескалацій. Критерій «ok і нуль ескалацій»
   на прогоні 2026-08-15 дав 0 з 118: ретельний редактор завжди щось піднімає, тож статус
   done ставав недосяжним. Тепер ескалація — це питання про план книги, і теми вона не
   тримає; тримає лише ok = false. */
const passed = ok.filter((r) => r.ok).map((r) => r.dir)

/* ── Маніфест ────────────────────────────────────────────────────────────────
   Єдине місце, де ревізія торкається статусів: recheck → done для тем, які редактор
   довів до готовності. Операції складає локальний скрипт — агент лише запускає його
   й manifest-patch, щоб статуси версій не складав руками. */
phase('Маніфест')
let manifest = 'пропущено'
if (APPLY && passed.length) {
  const slugs = passed.map((d) => d.split('/').pop()).join(',')
  const opsFile = `scripts/_finish/_review-ops-${BOOK}.json`
  const r = await agent(
    `Виконай три команди по черзі й поверни вивід останніх двох. Нічого не редагуй руками.

1) node ${ROOT}\\scripts\\claude\\review-queue.js --book ${BOOK} --kind ${KIND} --ops-done --json ${opsFile} --slugs "${slugs}"
2) node ${ROOT}\\scripts\\manifest-patch.js "${KIND}/${BOOK}/manifest.js" --ops ${ROOT}\\${opsFile.replace(/\//g, '\\')}
3) те саме з --apply у кінці

Якщо крок 1 показав «✖ нема в маніфесті» — назви ці слуги у відповіді, але кроки 2–3 усе одно виконай.`,
    { label: 'маніфест:recheck→done', phase: 'Маніфест', model: 'sonnet', effort: 'low',
      schema: { type: 'object', additionalProperties: false, required: ['out'],
        properties: { out: { type: 'string' }, changed: { type: 'number' } } } })
  manifest = (r && r.out) || 'без відповіді'
} else if (!passed.length) manifest = 'жодна тема не дійшла до готовності — статуси не чіпали'

phase('Звід')
const esc = ok.flatMap((r) => (r.escalations || []).map((e) => ({ ...e, dir: r.dir })))
const flat = (k) => ok.flatMap((r) => (r[k] || []).map((x) => `${r.dir}: ${x}`))
log(`до готовності доведено: ${passed.length}/${DIRS.length} · лишилось питань про план: ${esc.length}`)

return {
  dirs: DIRS.length,
  reviewed: ok.length,
  failed: DIRS.length - ok.length,
  passedToDone: passed.length,
  logic: flat('logic'),
  code: flat('code'),
  formulas: flat('formulas'),
  units: flat('units'),
  language: flat('language'),
  figures: flat('figures'),
  consistency: flat('consistency'),
  resolved: flat('resolved'),
  newTopics: ok.flatMap((r) => (r.newTopics || []).map((t) => ({ ...t, from: r.dir }))),
  escalations: esc,
  stillRecheck: ok.filter((r) => !r.ok).map((r) => ({ dir: r.dir, note: r.note })),
  manifest,
}
