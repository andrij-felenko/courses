function designPrompt(b) {
  return `${LIBRARY}\n\n${BOUNDARIES}\n\n${RULES}\n\nТи — провідний фахівець і методист із предмета «${b.title}», що пише найкращий сучасний підручник.\nСпроєктуй ВИЧЕРПНУ, чітко поділену таксономію РОЗДІЛІВ книги «${b.title}» (${b.slug}).\nОбсяг: ${b.scope}\nДай повний перелік розділів (slug, title, scope, examples) у логічному порядку. Жодного filler-розділу. Покрий увесь предмет так, щоб у нього БУДЬ-ЯКА тема дисципліни мала очевидну домівку — і щоб потім не довелося переробляти структуру.`
}

function critiquePrompt(b, design) {
  return `${LIBRARY}\n\n${BOUNDARIES}\n\n${RULES}\n\nТи — безжальний критик навчальних програм. Ось чернетка розділів книги «${b.title}»:\n${JSON.stringify(design.sections, null, 1)}\n\nЗнайди й ВИПРАВ: (1) ПРОГАЛИНИ — чого бракує, щоб предмет був по-справжньому повний; (2) FILLER — будь-які «основи/вступ/оглядово/каталог/різне/прикладне» → заміни конкретними змістовними розділами; (3) ПЕРЕТИНИ й нечіткі межі між розділами цієї книги → розділи або злий; (4) ЧУЖЕ — контент, що за МЕЖАМИ належить іншій книзі → прибери. Зроби поділ красивішим і рівномірнішим за вагою.\nПоверни ПОВНУ виправлену таксономію (той самий формат slug/title/scope/examples), уже без вад.`
}

function reconcilePrompt(all) {
  return `${LIBRARY}\n\n${BOUNDARIES}\n\nОсь фінальні таксономії всіх 8 книг (slug → розділи):\n${JSON.stringify(all.map(x => ({ book: x.slug, sections: x.sections.map(s => ({ slug: s.slug, title: s.title })) })), null, 1)}\n\nТи — головний редактор бібліотеки. Перевір КРОС-КНИЖКОВУ цілісність і поверни СПИСОК ТОЧКОВИХ ПРАВОК (не переписуй усе):
(1) ПЕРЕТИНИ — поняття з домівкою у >1 книзі: лиши в правильній (за МЕЖАМИ), з інших — action:"remove" (чи "move" з toBook).
(2) ПРОГАЛИНИ — важливе поняття без жодної домівки в усіх 8: action:"add" у потрібну книгу (slug+title+scope).
(3) НЕУЗГОДЖЕНІ МЕЖІ / FILLER, що лишився: remove або rename.
Для кожної правки: book, action(remove/add/rename/move), slug, (title/scope для add/rename), (toBook для move), why. У verdict — стислий висновок про якість і повноту поділу.`
}

phase('Дизайн')
log(`Проєктую розділи для ${BOOKS.length} книг: ${BOOKS.map(b => b.slug).join(', ')}`)

const refined = await pipeline(
  BOOKS,
  (b) => agent(designPrompt(b), { label: `design:${b.slug}`, phase: 'Дизайн', schema: SECTIONS }).then(d => ({ b, design: d })),
  (x) => (x && x.design)
    ? agent(critiquePrompt(x.b, x.design), { label: `critic:${x.b.slug}`, phase: 'Критика', schema: SECTIONS })
        .then(c => ({ slug: x.b.slug, title: x.b.title, sections: (c && c.sections && c.sections.length) ? c.sections : x.design.sections }))
    : null
)

const books = refined.filter(Boolean)
books.forEach(b => log(`  ${b.slug}: ${b.sections.length} розділів`))

phase('Звід')
const recon = await agent(reconcilePrompt(books), { label: 'reconcile', phase: 'Звід', schema: RECON })
const changes = (recon && recon.changes) || []
log(`Звід: ${changes.length} крос-книжкових правок. Вердикт: ${(recon && recon.verdict) || '—'}`)

return {
  books: books.map(b => ({ slug: b.slug, title: b.title, sections: b.sections })),
  reconciliation: changes,
  verdict: (recon && recon.verdict) || '',
}
