#!/usr/bin/env node
/* Перевірка 06 — ОБСЯГ за §3: смуга виду (канон × SCALE) з підлогою на рівні розкриття.
   Ужиток: node scripts/checks/06-size.js <тека теми>   [CHECKS_SCALE=1.35]

   Питання одне: чи дописано тему до дна — і чи не роздуто її замість того.

   Смуга виду ділиться на п'ять зон; рівень із батч-файла прогону підіймає НИЖНІЙ край
   на початок своєї зони. Верхній край і виняткова стеля спільні для всіх рівнів — рівень
   стелі не має свідомо (див. _lib.js: двостороннє вікно суперечило б забороні скорочувати).

   Що дає який код:
     рівня не оголошено                                  → ДЕФЕКТ (рішення не ухвалив ніхто);
     нижче підлоги свого рівня                           → ДЕФЕКТ (машинно);
     вище виняткової стелі                               → ДЕФЕКТ (тему треба ділити);
     у винятковій смузі (hi–max)                         → ПУНКТ НА ВИРОК (чи неподільна);
     помітно вище своєї зони                             → ПУНКТ НА ВИРОК (рівень занижено?);
     базова > ½ детальної                                → ДЕФЕКТ (залізо §3).

   Чому підлога, а не орієнтир. Число, показане письменникові, стає ціллю — це заміряно
   двічі й в обидва боки (див. _lib.js). Тому число тут не спільне: рівень ставить окрема
   фаза оцінки перед письмом, і в кожної теми він свій. Заниження рівня — єдиний спосіб
   обійти підлогу, і саме тому воно судиться ЧИТАННЯМ, а не лічильником.

   Скорочувати текст заради проходження гейта заборонено: недобір лікується
   дописуванням, перебір — поділом теми, а не викиданням матеріалу. */
"use strict";
const fs = require("fs");
const L = require("./_lib.js");

const DIR = L.resolveDir(process.argv[2]);
if (!DIR) { console.error("Вкажи теку теми (шлях від кореня репо або абсолютний)"); process.exit(L.USAGE); }
const T = L.readTopic(DIR);
const LV = L.readLevel(DIR);
L.head("06", `обсяг (канон × ${L.SCALE}, підлога за рівнем)`, DIR);

const rows = T.files.filter((f) => f.kind !== "other").map((f) => {
  const lv = L.levelFor(LV, f);
  const w = L.proseWords(f.text);
  const b = L.bandOf(f.kind, lv);
  let mark = "✓", note = "";
  if (lv === undefined) { mark = "?"; note = "рівень вставки не оголошено в батч-файлі"; }
  else if (w < b.floor) {
    mark = "▽";
    note = lv ? `нижче підлоги Р${lv} (<${b.floor})` : `нижче смуги (<${b.floor})`;
  } else if (w > b.max) { mark = "▲"; note = `понад виняткову стелю (>${b.max}) — тему треба ділити`; }
  else if (w > b.hi) { mark = "⌇"; note = `виняток §3 (${b.hi}–${b.max}) — чи справді неподільна?`; }
  else if (lv && lv < L.LEVELS && w >= b.floor + 2 * b.zone) {
    mark = "↑"; note = `на ${Math.floor((w - b.floor) / b.zone)} зони вище своєї — рівень Р${lv} занижено?`;
  }
  return { f, w, b, lv, mark, note };
});
if (!rows.length) L.pass("у теці немає статей і вставок");

console.log("");
if (LV && LV.topic) console.log(`  рівень теми: Р${LV.topic} — ${L.LEVEL_NAMES[LV.topic]}\n`);
rows.forEach((r) => {
  const lab = r.lv ? `Р${r.lv} ${r.b.floor}–${r.b.hi}` : `${r.b.floor}–${r.b.hi}`;
  console.log(`  ${r.mark} ${String(r.w).padStart(5)}w  ${r.f.file.padEnd(34)} ${r.f.label.padEnd(24)} ${lab}${r.note ? "  ← " + r.note : ""}`);
});

const bad = [];
if (!LV || !LV.topic) bad.push(
  `рівень теми не оголошено: у батч-файлі (scripts/_finish/_batch-*.json або _update-*.json) ` +
  `немає запису з "dir" цієї теми і полем "level" (1–5). Рівень ставить фаза оцінки ПЕРЕД ` +
  `письмом — один агент проходить списком тем батчу й дає кожній оцінку. Без нього підлога ` +
  `обсягу невідома, і «дописано до дна» не перевіряє ніхто`);
rows.filter((r) => r.mark === "?").forEach((r) => bad.push(
  `${r.f.file} (${r.f.label}): ${r.note}. У записі теми в батч-файлі має бути ` +
  `"inserts": { "${r.f.file}": <1–5> } — наскільки ця вставка мусить бути розкрита, щоб ` +
  `виконати те, заради чого її винесли з нитки. Оцінку дає письменник у звіті, коли вирішує ` +
  `її писати; в батч-файл її переносить оркестратор перед гейтом`));
rows.filter((r) => r.mark === "▽").forEach((r) => bad.push(
  `${r.f.file} (${r.f.label}): ${r.w}w — ${r.note}; дописати до підлоги, не «водою», а тим, ` +
  `що бракує: механізм, крайові випадки, простеження, розбір`));
rows.filter((r) => r.mark === "▲").forEach((r) => bad.push(`${r.f.file} (${r.f.label}): ${r.w}w — ${r.note}`));

/* залізо §3: базова ≤ ½ детальної (відношення, від масштабу й рівня не залежить) */
if (T.basic && T.detailed) {
  const wb = L.proseWords(T.basic.text), wd = L.proseWords(T.detailed.text);
  const ratio = wd ? wb / wd : 0;
  console.log(`\n  пара база↔деталь: ${wb}w / ${wd}w = ${Math.round(ratio * 100)}%  (стеля бази ${Math.round(wd / 2)}w)`);
  if (ratio > 0.55) bad.push(`базова ${wb}w — це ${Math.round(ratio * 100)}% детальної (${wd}w); §3 дозволяє ½. Базову НЕ стискати: або ріжемо матеріал (виведення, варіації, крайові випадки), або базової тут не треба взагалі — тоді basic:empty`);
}
if (bad.length) L.defects(bad, "обсяг лікується дописуванням або поділом, ніколи — скороченням");

const soft = rows.filter((r) => r.mark === "⌇" || r.mark === "↑");
if (!soft.length) L.pass("усі файли над підлогою свого рівня і під стелею виду");

L.adjudicate(DIR, soft.map((r) => ({
  file: r.f.file, kind: r.f.kind,
  text: `${r.w}w (Р${r.lv || "—"}, зона ${r.b.floor}–${r.b.hi}) — ${r.note}`,
})),
  "по кожному файлу — одне з двох, залежно від позначки.\n" +
  "«⌇» (вище стелі виду): тема справді неподільна на цьому обсязі — чи в ній сидять дві? " +
  "Доказ «ok»: покажи, що виклад один і розрізати його можна лише по живому. " +
  "Доказ «defect»: назви, де проходить шов і які дві теми виходять.\n" +
  "«↑» (вище своєї зони): рівень занижено — чи текст роздутий? Дивись НА ЗМІСТ, не на число. " +
  "Рівень означає, наскільки тема мусить бути розкрита для книги: Р1 читач мине без утрати, " +
  "Р3 на неї спираються сусідні теми, Р5 книга на ній стоїть. " +
  "Доказ «ok»: текст відповідає своєму рівню, а обсяг узяв матеріал, якого рівень не передбачав " +
  "(довгий неподільний перелік, велике простеження) — рівень лишається. " +
  "Доказ «defect»: назви рівень, якому тема відповідає насправді, і ознаку, з якої це видно — " +
  "скільки тем на неї спираються, чи вона ціль ref у курсі, скільки механізмів мусить показати.\n" +
  "Обсяг ПОНАД підлогу дефектом сам собою не є: рівень задає низ, а не ціль.");
