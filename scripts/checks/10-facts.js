#!/usr/bin/env node
/* Перевірка 10 — ФАКТИ Й АТРИБУЦІЯ (вебпошуком).
   Ужиток: node scripts/checks/10-facts.js <тека теми>

   Тригер звужено навмисно. Раніше ловилися «Device Mapper», «Red Hat» і будь-яке
   «створити чергу» — на одній темі виходило до 17 пунктів, з них справжніх одиниці.
   Тепер твердження береться, лише коли в реченні Є РІК і при ньому людське ім'я
   або дієслово пріоритету; для api- окремо беруться твердження про версію.

   За типами:
     hist-        — серце перевірки: дати, імена, хто що зробив;
     api-         — «з якої версії»: ядро, стандарт, реліз;
     detailed/basic — історичні речення в прозі;
     math-/proj-/comp- — беруться, лише якщо там таки є датоване твердження. */
"use strict";
const fs = require("fs");
const L = require("./_lib.js");

const DIR = L.resolveDir(process.argv[2]);
if (!DIR) { console.error("Вкажи теку теми (шлях від кореня репо або абсолютний)"); process.exit(L.USAGE); }
const T = L.readTopic(DIR);
L.head("10", "факти, дати, імена, пріоритет", DIR);
if (!T.files.length) L.pass("у теці немає .md");

const YEAR = /\b(1[6-9]\d\d|20[0-4]\d)\b/;
/* ім'я людини: «Ім'я Прізвище (Latin Gloss)» або два латинські слова з великої поруч із роком */
const PERSON = /[А-ЯІЇЄҐ][а-яіїєґ']+\s+[А-ЯІЇЄҐ][а-яіїєґ']+\s*\(([A-Z][\w.'-]+\s+)+[A-Z][\w.'-]+\)/;
/* ⚠️ `\b` і `\w` у JS не знають кирилиці: `\bвперше` на українському тексті не спрацює
   ніколи, бо межу рахують по [A-Za-z0-9_]. Тому lookbehind по літері й `[\p{L}]`. */
const PRIORITY = /(?<![\p{L}])(вперше|першим|перший|першою|винайш[\p{L}]*|запатент[\p{L}]*|опублікув[\p{L}]*|запропонував[\p{L}]*|відкри(?:в|ла|ли)|створив|створила|побудував[\p{L}]*|назвав[\p{L}]*|ввів|увів)(?![\p{L}])/iu;
const VERSION = /\b(?:з|від|починаючи з|since)\s+(?:ядра|версії|релізу|стандарту)?\s*(?:v?\d+\.\d+(?:\.\d+)?|C\+\+\d\d|C\d\d|POSIX[\d.]*)\b/i;

/* заголовки, передумови, підписи під фігурами й рядки-зображення реченнями не є:
   через них у список лізли уламки на кшталт «# 📜 Як формула 1854 року…» */
function proseOnly(text) {
  return L.strip(text)
    .replace(/<preknowlist>[\s\S]*?<\/preknowlist>/g, " ")
    .split(/\r?\n/)
    .filter((l) => {
      const t = l.trim();
      return t && !/^#/.test(t) && !/^!\[/.test(t) && !/^\*[^*].*\*$/.test(t) && !/^\|/.test(t);
    })
    .join("\n");
}

const items = [];
T.files.forEach((f) => {
  proseOnly(f.text).split(/(?<=[.!?])\s+/).forEach((sent) => {
    const s = sent.trim().replace(/\s+/g, " ");
    if (s.length < 25 || (s.match(/[\p{L}]{2,}/gu) || []).length < 6) return;
    const dated = YEAR.test(s);
    const claim = PRIORITY.test(s);
    const person = PERSON.test(s);
    let why = null;
    if (dated && (claim || person)) why = "дата + " + (person ? "ім'я" : "твердження про пріоритет");
    else if (f.kind === "hist" && dated) why = "датоване твердження в історичній вставці";
    else if (f.kind === "api" && VERSION.test(s)) why = "твердження «з якої версії»";
    if (!why) return;
    items.push({ file: f.file, kind: f.kind, text: `[${why}] ${s.slice(0, 240)}` });
  });
});

if (!items.length) L.pass("датованих тверджень і заяв про пріоритет не знайдено");

L.adjudicate(DIR, items,
  "кожне твердження перевір ВЕБПОШУКОМ, не з пам'яті. " +
  "Розділяй виміри особи: етнічність · громадянство · місце народження · мова · установа · імперська належність — і не пиши просто «росіянин», коли джерела дають точніше (українець, поляк, серб, єврей, грузин, вірменин, литовець…); мішана чи непевна — так і скажи. " +
  "Розрізняй «мав ідею» / «опублікував теорію» / «побудував робочий зразок» / «зробив придатну систему» / «запатентував». Винаходи колективні — не переказуй міфів про одну людину чи одну націю. " +
  "Пиши стан доказовости: усталений факт · оспорювана атрибуція · імперське/національне обрамлення · правдоподібне, але недоведене · міф. " +
  "Доказ — назва джерела і що саме там сказано.");
