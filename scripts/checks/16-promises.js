#!/usr/bin/env node
/* Перевірка 16 — ЗОБОВ'ЯЗАННЯ ТЕМИ: чи виконано все, що тема пообіцяла.
   Ужиток: node scripts/checks/16-promises.js <тека теми>

   Питання одне: **чи можна цю тему закрити — чи в ній лишились обіцянки без файлів.**

   Тема закрита, коли: детальна на диску · рішення про базову ухвалене (13-та) ·
   КОЖНА вставка, обіцяна в прозі, написана · КОЖНА вставка, записана в маніфесті теми
   як `pending`, написана · кожне поняття, на яке стаття спирається лінком, або існує,
   або вже стоїть у черзі нових тем.

   Без цієї перевірки тему можна було «закрити» з обіцяним, але ненаписаним: проза кличе
   `math-`-вставку, файла немає, маніфест і далі тримає її `pending` — і ніхто не помітив.

   ⚖️ ВСТАВКА ЧИ ТЕМА — рішення, яке треба ухвалити свідомо (§6):
     вставка — матеріал ЦІЄЇ теми: історія цього механізму, виведення цієї формули,
               проект на цьому предметі, поверхня саме цієї речі. Живе в теці теми;
     тема    — самостійне поняття, на яке стаття лише СПИРАЄТЬСЯ і яке має власне життя
               поза нею. Живе у своїй теці; заводиться через newtopic.js і ref-иться
               як `root:<книга>/<тема>`.
   Помилка в цей бік дорога: винесене у вставку самостійне поняття читач ніколи не знайде
   пошуком, а роздута до теми вставка розриває нитку статті. */
"use strict";
const fs = require("fs");
const path = require("path");
const L = require("./_lib.js");

const DIR = L.resolveDir(process.argv[2]);
if (!DIR) { console.error("Вкажи теку теми (шлях від кореня репо або абсолютний)"); process.exit(L.USAGE); }
const T = L.readTopic(DIR);
L.head("16", "зобов'язання теми", DIR);

const bad = [];
const onDisk = new Set(T.inserts.map((i) => i.file));
const proseAll = T.prose.map((p) => p.text).join("\n");
const queued = L.queuedTopics(DIR);

/* (1) вставки СВОЄЇ теми, обіцяні в прозі root:-лінком.
       Лінк на вставку ЧУЖОЇ теми (root:<книга>/<інший-слуг>/<файл>.md) — не наша справа:
       його цілісність судить linkcheck у 05-й, а чужу теку ми не чіпаємо. */
const promised = new Set();
for (const m of proseAll.matchAll(/\]\(root:([^)]+?\.md)\)/g)) {
  const segs = m[1].split("/");
  const file = segs.pop();
  /* Власник вставки — ЗАВЖДИ останній сегмент перед файлом: і в канонному
     root:<книга>/<тема>/<файл>, і в легасі root:<книга>/<секція>/<тема>/<файл>
     (таких у корпусі ще ~2000). Брати segs[1] означало ловити секцію замість теми
     й мовчки пропускати кожну обіцянку в темах, що пишуть довгу форму. */
  const ownerSlug = segs[segs.length - 1];
  if (ownerSlug && ownerSlug !== T.slug) continue;
  if (/^(hist|comp|math|proj|api)-/.test(file)) promised.add(file);
}
promised.forEach((f) => {
  if (!onDisk.has(f)) bad.push(`проза обіцяє вставку «${f}», а файла немає — читач натисне лінк і впаде в порожнечу`);
});

/* (2) вставки, записані в маніфесті теми як pending */
const mf = L.manifestOf(DIR);
if (!mf) {
  bad.push("не знайдено маніфест книги для цієї теми — перевірити шлях теки");
} else if (!mf.topic) {
  console.log(`  ⚠ теми «${T.slug}» ще немає в маніфесті ${path.relative(L.ROOT, mf.path)} — вона зареєструється наприкінці батчу`);
} else {
  L.INSERT_TYPES.forEach((type) => {
    (mf.topic[type] || []).forEach((ins) => {
      if (!ins || !ins.file) return;
      if (ins.status === "done" && !onDisk.has(ins.file))
        bad.push(`маніфест каже, що «${ins.file}» готова (done), а файла немає — статус бреше читачеві`);
      if (ins.status === "pending" && !onDisk.has(ins.file))
        bad.push(`маніфест тримає «${ins.file}» у стані pending, а файла немає — тему не закрити, доки вставку не написано`);
    });
  });
  const status = (v) => (mf.topic[v] && mf.topic[v].status) || "—";
  console.log(`  маніфест: detailed=${status("detailed")} · basic=${status("basic")}`);
  if (!T.detailed && status("detailed") === "pending")
    bad.push("детальна стоїть pending, а файла немає — це і є незакрита тема");
}

/* Цілі лінків тут НЕ перевіряємо: для цього є linkcheck, і він у 05-й. Друга,
   слабша реалізація того самого дала б хибні спрацювання й розходження. */

if (bad.length) {
  console.log(`
⚖️ Перш ніж писати обіцяне — виріши, ЩО це (§6):
   ВСТАВКА, якщо матеріал належить ЦІЙ темі (історія цього механізму, виведення цієї
   формули, проект на цьому предметі, поверхня саме цієї речі) → файл у теці теми;
   ТЕМА, якщо це самостійне поняття, на яке стаття лише спирається → newtopic.js,
   а лінк перероби на root:<книга>/<тема>.
   Ознака теми: про неї можна написати статтю, яку читатимуть, не читавши цієї —
   і вона набирає дві ознаки з чотирьох (--meets: too-big, key, eases, searchable).
   Поняття чужої галузі йде в СВОЮ книгу (--book math), а не відкидається.
   Поняття із сусідньої галузі, якого стаття лише торкнулась, темою НЕ є: це одне
   речення в тексті або лінк. Стеля — дві нові теми на статтю.
   Ознака вставки: поза цією статтею матеріал не має власного читача.
   Пише обіцяне АВТОР (write-topic), не ремонтник.`);
  L.defects(bad, "тему не закрито, доки обіцяне не написано");
}

/* Прогалини плану (§6): вагомі поняття, на які стаття СПИРАЄТЬСЯ, мусять або мати тему,
   або вже стояти в черзі. Це не механічне питання — тому пункт на вирок, один на тему. */
/* Другий пункт — ДЗЕРКАЛЬНИЙ: не «чого бракує в плані», а «чи не сховано тему у вставці».
   Без нього правило §6 не мало виконавця: єдиний пункт судив прозу детальної й питав про
   поняття, вжиті «не пояснюючи й не лінкуючи», — а лінк на власну вставку знімав умову,
   і вставка на 2000 слів про стороннє поняття проходила як виконана обіцянка. */
const insItems = T.inserts.map((ins) => {
  const h1 = ((L.read(ins.path).match(/^#\s+(.+)$/m) || [, ""])[1] || "").replace(/[\p{Extended_Pictographic}]/gu, "").trim();
  return `${ins.file} — «${h1}»`;
});

L.adjudicate(DIR, [{
  file: T.detailed ? T.detailed.file : T.slug, kind: "detailed",
  text: `прогалини плану: назви 3–7 понять, які стаття вживає як ВІДОМІ, але яких НЕМАЄ в preknowlist і на які немає лінка — і скажи по кожному, чи є така тема`
    + (queued.length ? `. Уже в черзі: ${queued.join(", ")}` : ". Черга нових тем порожня"),
}].concat(insItems.length ? [{
  file: T.slug, kind: "inserts",
  text: `вставки теми «${T.slug}» — чи кожна розширює СВОЮ тему, а не пояснює чуже поняття: ${insItems.join(" · ")}`,
}] : []),
  "ШУКАЙ ПОЗА preknowlist. Те, що автор оголосив, він оголосив саме тому, що воно існує — звіряти цей список означає перевіряти нічого: 463 вироки поспіль дали «ok» і жодного дефекту саме через це. " +
"Читай статтю і виписуй поняття, які вона ВЖИВАЄ як зрозумілі, не пояснюючи й не лінкуючи: терміни в прозі, назви механізмів у підписах фігур і в коментарях коду, те, чим вона обґрунтовує твердження. По кожному перевір, чи є така тема: " +
  "`node -e \"const M=require('./scripts/lib/manifest7.js');console.log(M.allSlugsInCorpus().get('<слуг>')||'нема')\"` — покаже книгу теми або «нема». " +
  "Поріг — справжня залежність, без якої теми не зрозуміти, а не кожна побіжна згадка. " +
  "Немає ніде → це прогалина плану, а не привід прибрати згадку: `node scripts/antigravity/newtopic.js --book … --kind … --section … --slug … --title … --why … --meets <ознаки через кому>`, лінк лишається, стаб відкриється попапом. " +
  "Перед заведенням перевір, чи це не синонім наявної теми: вужче й ширше про те саме (aslr ↔ rop-and-aslr), абревіатура й розшифровка (ksm ↔ ksm-page-merging), два боки одного механізму. Знайшов близьке — не заводь, ref-ни наявну. " +
  "І розділяй: матеріал ЦІЄЇ теми — вставка в її теці; самостійне поняття — окрема тема. " +
  "Доказ «ok» — перелік НЕОГОЛОШЕНИХ понять із результатом grep по кожному; сам перелік порожнім бути не може, бо стаття завжди на щось спирається мовчки. " +
"Якщо після чесного пошуку все справді має теми — так і напиши, назвавши знайдені поняття поіменно. Доказ «defect» — чого бракує і що покладено в чергу. " +
  "ПУНКТ ПРО ВСТАВКИ (якщо він є) судиться інакше. Вставка розширює СВОЮ тему, а не пояснює чужу. " +
  "Відкрий кожну названу вставку й спитай: вона про механізм ЦІЄЇ теми — чи пояснює стороннє поняття, " +
  "яке має власне ім'я і власного читача? Кількісний тест той самий: матеріал про інше поняття, що не " +
  "вміщається в абзац, — це тема, а не вставка. Заголовок, який називає те, чого немає в назві теми, і " +
  "текст, що відповідає «що це таке» замість «як це працює тут», — ознака теми, схованої у вставці. " +
  "Лінк на власну вставку доказом НЕ є: він показує, що поняття згадали, а не що воно на своєму місці. " +
  "Доказ «ok» — по кожній вставці одним рядком, чим саме вона поглиблює цю тему. " +
  "Доказ «defect» — назви вставку, стороннє поняття в ній і його обсяг.");
