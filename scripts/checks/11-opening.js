#!/usr/bin/env node
/* Перевірка 11 — СЛІПИЙ ТЕСТ ВХОДУ.
   Ужиток: node scripts/checks/11-opening.js <тека теми>

   Питання одне: чи дає початок тексту вхід у тему тому, хто її не знає.
   Метод — сліпий: агент читає ЛИШЕ перші три абзаци й пробує відповісти.
   Його невдача і є доказом дефекту; жодних регулярок на слова «отже» чи «чому»
   тут немає й бути не може — текст, підігнаний під такий гейт, стає гіршим.

   За типами: вхід мають базова й детальна — це двері теми. Вставку читач
   відкриває вже зсередини статті, тож її вступ судимо м'якше: досить, щоб
   із перших рядків було ясно, ЩО це за вставка і навіщо її відкрили. */
"use strict";
const fs = require("fs");
const L = require("./_lib.js");

const DIR = L.resolveDir(process.argv[2]);
if (!DIR) { console.error("Вкажи теку теми (шлях від кореня репо або абсолютний)"); process.exit(L.USAGE); }
const T = L.readTopic(DIR);
L.head("11", "сліпий тест входу", DIR);

const targets = [...T.prose, ...T.inserts];
if (!targets.length) L.pass("у теці немає статей і вставок");

function opening(text, n) {
  const body = text
    .replace(/<preknowlist>[\s\S]*?<\/preknowlist>/, "")
    .replace(/^#\s.*$/m, "");
  return body.split(/\n\s*\n/).map((p) => p.trim())
    .filter((p) => p && !/^[#>|\-*!]/.test(p) && !/^```/.test(p))
    .slice(0, n);
}

const items = [];
targets.forEach((f) => {
  const isEntry = f.kind === "basic" || f.kind === "detailed";
  const paras = opening(f.text, isEntry ? 3 : 2);
  if (!paras.length) { items.push({ file: f.file, kind: f.kind, text: "текст починається не прозою (заголовок, список чи код одразу) — вступу немає взагалі" }); return; }
  items.push({
    file: f.file, kind: f.kind,
    text: (isEntry
      ? "ВХІД У ТЕМУ. Прочитай лише ці абзаци й дай відповідь: (1) яку задачу розв'язує стаття; (2) чому ця задача взагалі виникла — що не працювало без неї. "
      : "ВСТУП ВСТАВКИ. Прочитай лише ці абзаци й дай відповідь: що це за вставка і навіщо читач її відкрив. ")
      + "\n" + paras.map((p, i) => `      (${i + 1}) ${p.replace(/\s+/g, " ").slice(0, 700)}`).join("\n"),
  });
});

console.log("\n⚠️ Читай ЛИШЕ показані абзаци, доки не відповіси. Потім прочитай файл повністю й перевір, чи збіглося.");
L.adjudicate(DIR, items,
  "відповідай ЛИШЕ з показаних абзаців. Не можеш відповісти → «defect». Відповів — тоді прочитай файл цілком: не збіглося → теж «defect». " +
  "Лікується показом конкретної ситуації, де без цього механізму щось ламається, — а НЕ підзаголовком «Навіщо це» і НЕ скороченням вступу. " +
  "Переписує АВТОР, не ти: твій вихід — вирок і те, чого саме бракує. " +
  "Доказ «ok» — твоя власна відповідь на обидва питання, взята з цих абзаців.");
