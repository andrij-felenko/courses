#!/usr/bin/env node
/* Перевірка 13 — ГЕЙТ БАЗОВОЇ (§3): чи ухвалено рішення про базову версію — і чи виконано.
   Ужиток: node scripts/checks/13-basic.js <тека теми>

   Питання одне: **чи потрібна цій темі базова версія — і чи це рішення ухвалене за готовою
   детальною, з доказом, а не мовчазно «файлу немає, отже не потрібна»**.

   Це найтихіша дірка з усіх: без цієї перевірки відсутність файлу автоматично ставала
   `basic:empty`, тобто рішення не ухвалював ніхто. А §3 каже протилежне: у зоні понад
   верхній поріг базова ПОТРІБНА, і дефолт «ні» там не діє.

   ЗОНИ за прозою детальної (канонні 2250/4000 × SCALE):
     нижче LOW   — базової НЕ пишемо; коротка детальна сама і є входом. Рішення однозначне,
                   вироку не потребує.
     LOW…HIGH    — вирішує ЗМІСТ: усі три ознаки 2–4 мають сказати «так», вагання → ні.
     понад HIGH  — базова ПОТРІБНА, якщо її не відсіяли ознаки 2–4 чи безумовний відсів.

   Пункт на вирок описує ЗОНУ, а не точне число слів: інакше кожна правка коми в детальній
   протухала б рішення про базову. Зона змінилась — рішення питається наново, і це правильно. */
"use strict";
const fs = require("fs");
const L = require("./_lib.js");

const DIR = L.resolveDir(process.argv[2]);
if (!DIR) { console.error("Вкажи теку теми (шлях від кореня репо або абсолютний)"); process.exit(L.USAGE); }
const T = L.readTopic(DIR);
L.head("13", "гейт базової версії (§3)", DIR);

/* безумовний відсів: детальної ще немає — базову не вирішують */
if (!T.detailed) L.pass("детальної ще немає — базову за §3 не вирішують, доки її не написано");

const wd = L.proseWords(T.detailed.text);
const { low, high } = L.BASIC_GATE;
const wb = T.basic ? L.proseWords(T.basic.text) : 0;
const zone = wd < low ? "нижче порога" : wd > high ? "понад поріг" : "зона змісту";

console.log(`\n  детальна: ${wd}w прози · базова: ${T.basic ? wb + "w" : "немає"}`);
console.log(`  пороги (канон × ${L.SCALE}): <${low} не пишемо · ${low}–${high} вирішує зміст · >${high} потрібна`);
console.log(`  зона: ${zone}`);

/* нижче порога й базової немає — рішення однозначне за каноном, судити нема чого */
if (wd < low && !T.basic) L.pass(`детальна ${wd}w < ${low}: за §3 базової не пишемо, вона сама є входом у тему`);

const items = [];
if (wd < low && T.basic) {
  items.push({ file: T.basic.file, kind: "basic",
    text: `базова написана, хоч детальна в зоні «нижче порога» (<${low}) — за §3 такої базової не мало бути: доведи, що вона не переказ детальної, або її треба прибрати` });
} else if (wd > high && !T.basic) {
  items.push({ file: T.detailed.file, kind: "detailed",
    text: `детальна в зоні «понад поріг» (>${high}): за §3 базова ПОТРІБНА, і дефолт «ні» тут НЕ діє. Базової немає — або назви відсів, що її знімає, або її треба написати` });
} else if (wd > high && T.basic) {
  items.push({ file: T.basic.file, kind: "basic",
    text: `детальна в зоні «понад поріг» (>${high}), базова написана — підтверди, що вона дає швидкий огляд, а не переказ детальної` });
} else if (!T.basic) {
  items.push({ file: T.detailed.file, kind: "detailed",
    text: `детальна в зоні «вирішує зміст» (${low}–${high}), базової немає — ухвали рішення за ознаками 2–4` });
} else {
  items.push({ file: T.basic.file, kind: "basic",
    text: `детальна в зоні «вирішує зміст» (${low}–${high}), базова написана — підтверди, що всі чотири ознаки §3 сказали «так»` });
}

L.adjudicate(DIR, items,
  "рішення ухвалюється ЗА ГОТОВОЮ ДЕТАЛЬНОЮ і потребує чотирьох «так» та жодного відсіву (§3). " +
  "Ознака 2 — ОДИН СТРИЖЕНЬ: чи можеш назвати причинно-наслідковий стрижень теми одним реченням так, щоб він тримався без викинутого? " +
  "Якщо суть теми — перелік рівноправних речей (варіанти, режими, поля, команди, кроки), базової НЕ пишемо: скорочений перелік — це обрізаний довідник, а не огляд. " +
  "Ознака 3 — Є ЩО ВИКИНУТИ: щонайменше половина детальної має бути виведеннями, варіаціями, крайніми випадками й прикладами, які базова законно не бере. Детальна-кістяк не стискається. " +
  "Ознака 4 — ДЕТАЛЬНА НЕ Є ВХОДОМ САМА: якщо її перші два-три абзаци вже дають картину теми, базова лише продублює вхід. " +
  "БЕЗУМОВНІ ВІДСІВИ: тема довідкова (ядро — API, протокол, формат, набір параметрів, таблиця) · тема вузька, існує лише як деталь більшої. " +
  "⚠️ «Довідкова» — про ядро САМОЇ ЦІЄЇ статті, а НЕ про вид книги: «Планувальник: як ядро ділить час» відсів не проходить навіть у довіднику, «Набір ioctl підсистеми X» — проходить. " +
  "ВАГАННЯ 50/50 → НІ: помилка «не написали» коштує читачеві одного кроку в детальну, помилка «написали зайву» — це другий текст про те саме, який далі тримати синхронним. " +
  "Вирок «ok» = рішення ухвалено й виконано; доказ — стрижень одним реченням, що саме викидається, і чому вхід не дублюється. " +
  "Вирок «defect» = базову треба написати (або наявну прибрати); це повертається АВТОРОВІ, не ремонтникові.");
