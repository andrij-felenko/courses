#!/usr/bin/env node
/* Перевірка 15 — ОБҐРУНТОВАНІСТЬ: чи доведено те, що читач мусить прийняти (§4.6).
   Ужиток: node scripts/checks/15-claims.js <тека теми>

   Питання одне: **чи має кожне твердження опору — механізм, число, виведення чи чесно
   названу межу «беремо готовим, бо…»?**

   Канон §4.6: тиха зупинка — це діра, названа — зачинені двері, яким довіряють. Модель за
   звичкою пише «це швидше», «так робити не можна», «зазвичай достатньо» — і не каже, звідки
   це. Читач мусить або побачити доведення, або знати, що тут його свідомо немає.

   Скрипт нічого не оцінює: він витягає місця, де читачеві пропонують щось прийняти, і
   показує їх судді. Оцінює суддя — читанням сусіднього тексту.

   За типами файлу:
     math-  — твердження мусить мати виведення тут або посилання на нього;
     proj-  — «швидше/повільніше» мусить спиратися на власний вимір із цієї ж вставки;
     api-   — «не можна / завжди» мусить спиратися на документацію чи специфікацію;
     hist-  — сюди не лізе: дати й пріоритет судить 10-та;
     проза  — механізм поруч, число з походженням або чесно названа межа. */
"use strict";
const fs = require("fs");
const L = require("./_lib.js");

const DIR = process.argv[2];
if (!DIR || !fs.existsSync(DIR)) { console.error("Вкажи теку теми"); process.exit(L.USAGE); }
const T = L.readTopic(DIR);
L.head("15", "обґрунтованість тверджень (§4.6)", DIR);

const targets = [...T.prose, ...T.inserts].filter((f) => f.kind !== "hist");
if (!targets.length) L.pass("у теці немає тексту, який судить ця перевірка");

/* Три класи місць, де читач мусить щось прийняти. Це ТРИГЕР, а не вирок:
   кожне знайдене речення може виявитись цілком обґрунтованим — це вирішить суддя. */
/* ⚠️ `\w` у JS не знає кирилиці, а `\b` міряє межі саме по ньому — тому «швидш\w+» на
   українському тексті мовчить. Скрізь `[\p{L}]` і lookbehind із прапорцем `u`. */
const COMPARE = /(?<![\p{L}])(швидш[\p{L}]+|повільніш[\p{L}]+|дешевш[\p{L}]+|дорожч[\p{L}]+|безпечніш[\p{L}]+|надійніш[\p{L}]+|ефективніш[\p{L}]+|кращ[\p{L}]+|гірш[\p{L}]+|простіш[\p{L}]+|складніш[\p{L}]+|вигідніш[\p{L}]+|точніш[\p{L}]+)/iu;
const ABSOLUTE = /(?<![\p{L}])(ніколи|завжди|жодн[\p{L}]+|будь-як[\p{L}]+|неможлив[\p{L}]+|обов'язково|обовʼязково|не\s+можна|не\s+варто|не\s+слід|достатньо|як\s+правило|зазвичай|у\s+будь-якому\s+разі)/iu;
/* Чисел тут навмисно немає: їхню узгодженість судить 07-ма, а арифметику 08-ма.
   Якби 15-та бралася ще й за кожне число з одиницею, вона потонула б у технічній прозі
   й перестала б означати те, заради чого існує, — твердження, узяте читачем на віру. */

const items = [];
targets.forEach((f) => {
  const src = L.strip(f.text)
    .replace(/<preknowlist>[\s\S]*?<\/preknowlist>/g, " ")
    /* заголовки, рядки-зображення, курсивні підписи під фігурами й рядки таблиць
       твердженнями не є — інакше в список лізуть підпис до схеми й рядок розпіновки */
    .split(/\r?\n/).filter((l) => { const t = l.trim(); return t && !/^[#>|!]/.test(t) && !/^\*[^*].*\*$/.test(t); }).join("\n");
  src.split(/(?<=[.!?])\s+/).forEach((sent) => {
    const s = sent.trim().replace(/\s+/g, " ");
    if (s.length < 30 || (s.match(/[\p{L}]{2,}/gu) || []).length < 6) return;
    const why = COMPARE.test(s) ? "порівняння" : ABSOLUTE.test(s) ? "категоричне твердження" : null;
    if (!why) return;
    /* число з одиницею всередині самого речення — вже пів-опори, але не доказ: судить суддя */
    items.push({ file: f.file, kind: f.kind, text: `[${why}] ${s.slice(0, 240)}` });
  });
});

if (!items.length) L.pass("тверджень, які читач мусив би прийняти на віру, не знайдено");

L.adjudicate(DIR, items,
  "по кожному твердженню — де в тексті його опора? Дивись НАВКОЛО речення, не в саме речення.\n" +
  "Опора буває чотирьох видів: (1) механізм, показаний поруч — видно, ЧОМУ інакше не могло бути; " +
  "(2) число з походженням — сказано, звідки воно й за яких умов; (3) виведення чи вимір у цій же темі (math-/proj-вставка) або лінк на них; " +
  "(4) чесно названа межа: «беремо готовим, бо тут це не виводиться» — за §4.6 названа зупинка це не діра, а зачинені двері.\n" +
  "Вирок «ok» — цитуй саму опору. Не «твердження правильне», а «ось де воно тримається».\n" +
  "Вирок «defect» — опори немає: читач мусить вірити на слово. Лікується або показом механізму, або числом із походженням, або чесним «беремо готовим, бо…». " +
  "Викидати твердження, щоб позбутися пункту, — заборонено: це втрата змісту, а не обґрунтування.\n" +
  "Категоричне «ніколи/завжди/не можна» тримає найвищу планку: одне-єдине справжнє «а якщо» руйнує його, тому або звужуй умовами, або доводь.");
