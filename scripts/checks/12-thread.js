#!/usr/bin/env node
/* Перевірка 12 — НИТКА: чи випливає кожен розділ із попереднього.
   Ужиток: node scripts/checks/12-thread.js <тека теми>

   Питання одне: чи тримається логічний шлях від початку до кінця.
   Метод — переказ: агент називає, на яке ПИТАННЯ попереднього розділу відповідає
   кожен наступний, і переказує механізм своїми словами, не дивлячись у текст.
   Розділ, що не відповідає на жодне підняте питання, — розрив нитки. Діра в
   переказі — доказ, що пояснення не тримається.

   За типами: у детальній нитка обов'язкова (там розділів багато); у базовій —
   якщо розділів хоча б два; у вставці судимо нитку ВСЕРЕДИНІ її сюжету:
   proj- — крок за кроком до відтворюваного результату, math- — крок за кроком
   виведення, hist- — послідовність подій, comp- — спільна вісь порівняння,
   api- — від поверхні до того, що з нею роблять. */
"use strict";
const fs = require("fs");
const L = require("./_lib.js");

const DIR = process.argv[2];
if (!DIR || !fs.existsSync(DIR)) { console.error("Вкажи теку теми"); process.exit(L.USAGE); }
const T = L.readTopic(DIR);
L.head("12", "наскрізна нитка", DIR);

const ASK = {
  detailed: "назви, на яке питання попереднього розділу відповідає кожен наступний",
  basic: "назви, на яке питання попереднього розділу відповідає кожен наступний",
  hist: "перевір, чи події йдуть причиново, а не просто хронологічно",
  comp: "перевір, чи всі варіанти порівняно по ОДНІЙ і тій самій осі",
  math: "перевір, чи кожен крок виведення дозволений попереднім",
  proj: "перевір, чи веде послідовність кроків до відтворюваного результату без пропущеного кроку",
  api: "перевір, чи йде виклад від поверхні до того, що з нею роблять, без стрибків",
};

const items = [];
[...T.prose, ...T.inserts].forEach((f) => {
  const secs = (f.text.match(/^#{2,3}\s+.*$/gm) || []).map((s) => s.replace(/^#+\s+/, "").trim());
  if (secs.length < 2) return;
  items.push({
    file: f.file, kind: f.kind,
    text: `${ASK[f.kind] || ASK.detailed}. Розділи: ${secs.map((s, i) => `${i + 1}. ${s}`).join(" · ")}`,
  });
});

if (!items.length) L.pass("файлів із двома й більше розділами немає — нитку перевіряти нема на чому");

L.adjudicate(DIR, items,
  "заповни ланцюг ПОВНІСТЮ: для кожного розділу, крім першого, — на яке підняте раніше питання він відповідає. " +
  "Потім, НЕ дивлячись у текст, перекажи механізм своїми словами. Розділ без питання → розрив нитки. Переказ із дірою → пояснення не тримається. " +
  "Лікується перестановкою й добудовою пропущеного кроку, НІКОЛИ — скороченням (§4: ясність це структура, а не менше слів). " +
  "Переписує АВТОР, не ти. Доказ «ok» — сам ланцюг «розділ → на яке питання відповідає», виписаний до кінця.");
