# -*- coding: utf-8 -*-
"""Фігури до теми «Розділення привілеїв: маленький довірений процес і решта»."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', '..', '..', 'scripts'))
from svgkit import *

OUT = os.path.join(os.path.dirname(__file__), 'img')
if not os.path.isdir(OUT):
    os.makedirs(OUT)


def fig_split_of_one_daemon():
    """Той самий код до поділу й після: що саме переносить межа."""
    W, H = 1320, 720
    f = []

    f.append(text(320, 46, "один процес", size=16, bold=True))
    f.append(text(980, 46, "після поділу", size=16, bold=True))

    # ---- ліва колонка: усе в одному процесі
    b, _, h1 = textbox(320, 200,
                       "процес із euid 0\n"
                       "\n"
                       "розбір протоколу: тисячі рядків,\n"
                       "кожен байт складає незнайомець\n"
                       "\n"
                       "ключ хоста, файл хешів,\n"
                       "псевдотермінал, база входів",
                       size=14, min_w=470, fill="#fdecea", stroke=POS)
    f.append(b)

    f.append(arrow(320, 200 + h1 / 2, 320, 470))

    b, _, _ = textbox(320, 520,
                      "помилка будь-де в розборі\n"
                      "коштує всієї машини",
                      size=14, min_w=400, fill="#fdecea", stroke=POS)
    f.append(b)

    # ---- права колонка: робітник, канал, монітор
    b, _, h2 = textbox(980, 165,
                       "робітник: жодних прав, у клітці\n"
                       "\n"
                       "увесь розбір протоколу тут",
                       size=14, min_w=470, fill="#f7f9fc")
    f.append(b)

    b, _, h3 = textbox(980, 320,
                       "канал: кілька сталих запитів",
                       size=13, min_w=400, fill="#f4f6f8", stroke=MUTED)
    f.append(b)

    f.append(arrow(980, 165 + h2 / 2, 980, 320 - h3 / 2))
    f.append(arrow(980, 320 + h3 / 2, 980, 430))

    b, _, h4 = textbox(980, 505,
                       "монітор: euid 0\n"
                       "\n"
                       "підпиши блок ключем хоста\n"
                       "чи правильний цей пароль\n"
                       "готуй сесію для того, хто увійшов\n"
                       "дай псевдотермінал\n"
                       "запиши рядок про вхід",
                       size=14, min_w=470, fill="#eef3fd", stroke=NEG)
    f.append(b)

    b, _, _ = textbox(980, 660,
                      "помилка в розборі коштує процесу,\n"
                      "який і сам нічого не має",
                      size=14, min_w=440, fill="#eef3fd", stroke=NEG)
    f.append(b)

    render(os.path.join(OUT, 'split-of-one-daemon.svg'), W, H, *f,
           title="Той самий демон до поділу привілеїв і після нього")


def fig_worker_cage():
    """Шари обмежень довкола непривілейованого робітника."""
    W, H = 1260, 640
    f = []

    f.append(text(600, 44, "робітник після скидання прав: що забирає кожен шар", size=16, bold=True))

    rows = [
        "власний ідентифікатор, яким більше ніхто не користується  —  немає сусідніх процесів "
        "і файлів того ж користувача, до яких можна дістатися",
        "порожній корінь або власний простір монтувань  —  не лишається жодного імені, "
        "яке робітник міг би відкрити",
        "скинуті можливості разом з обмежувальним набором  —  підвищення неможливе навіть "
        "через запуск чужого файлу з бітом setuid",
        "фільтр seccomp  —  з усього переліку системних викликів лишаються читання, запис, "
        "вихід і повернення із сигналу",
    ]

    y = 92
    for r in rows:
        f.append(fitbox(60, y, 1090, 76, r, size=13, fill="#f4f6f8"))
        y += 100

    f.append(arrow(605, y - 24, 605, y + 26))

    b, _, _ = textbox(605, y + 82,
                      "лишається рівно одне вміння: читати й писати канал до монітора",
                      size=14, min_w=880, fill="#eef3fd", stroke=NEG)
    f.append(b)

    b, _, _ = textbox(605, y + 168,
                      "тому межа можливостей нападника дорівнює не «правам робітника»,\n"
                      "а тому, на що монітор погоджується відповідати",
                      size=14, min_w=880, fill="#fdecea", stroke=POS)
    f.append(b)

    render(os.path.join(OUT, 'worker-cage.svg'), W, H, *f,
           title="Шари обмежень довкола непривілейованої частини")


if __name__ == '__main__':
    fig_split_of_one_daemon()
    fig_worker_cage()
    print("ok")
