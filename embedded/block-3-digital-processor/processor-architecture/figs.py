# ═════════ §18.1i — історія: Беббідж і Ада Лавлейс ══════════════════════════
def _cog(cx, cy, r, col=INK, teeth=8):
    out = circle(cx, cy, r, "#ffffff", col, 2)
    out += circle(cx, cy, r * 0.42, "none", col, 1.6)
    for k in range(teeth):
        a = 2 * math.pi * k / teeth
        x1, y1 = cx + r * math.cos(a), cy + r * math.sin(a)
        x2, y2 = cx + (r + 5) * math.cos(a), cy + (r + 5) * math.sin(a)
        out += line(x1, y1, x2, y2, col, 3)
    return out


def _card(x, y, w, h, holes, col=INK):
    # перфокарта зі зрізаним кутом
    d = (f"M{x + 10},{y} L{x + w},{y} L{x + w},{y + h} L{x},{y + h} L{x},{y + 10} Z")
    out = path(d, "#fffdf5", col, 1.6)
    for (c, r) in holes:
        hx = x + 10 + c * ((w - 16) / 6)
        hy = y + 8 + r * ((h - 14) / 2)
        out += circle(hx, hy, 2.6, col, col, 0)
    return out


