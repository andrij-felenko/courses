    out += text(cx + 8, cy - h / 2 + 45, eng, 10.5, GREY, "middle", style="italic")
    for i, ln in enumerate(lines):
        out += text(cx, cy - h / 2 + 70 + i * 19, ln, 11, INK, "middle")
    return out


