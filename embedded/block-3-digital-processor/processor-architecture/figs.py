# ═══════════ §18.3 — Цикл «вибірка → декодування → виконання» ════════════════
def _clock(x, y, ticks, p, amp, col=BLUE):
    pts = [(x, y)]
    cx = x
    for _ in range(ticks):
        pts.append((cx, y - amp))
        pts.append((cx + p / 2, y - amp))
        pts.append((cx + p / 2, y))
        pts.append((cx + p, y))
        cx += p
    return polyline(pts, col, 2.2)


def _phasebox(cx, cy, w, h, num, name, eng, lines, col):
    out = rect(cx - w / 2, cy - h / 2, w, h, "#ffffff", col, 2.2, 12)
