def _alu(x, y, w, h, col=INK, bg="#fdf4f4"):
    # класичний символ АЛП: широкий верх із V-вирізом, вужчий низ
    d = (f"M{x},{y} L{x + w * 0.42:.0f},{y} L{x + w * 0.5:.0f},{y + 18} "
         f"L{x + w * 0.58:.0f},{y} L{x + w},{y} "
         f"L{x + w * 0.76:.0f},{y + h} L{x + w * 0.24:.0f},{y + h} Z")
    return path(d, bg, col, 2.2)


def _reg(x, y, name, val, w=150, h=30, col=INK, bg="#ffffff"):
    out = rect(x, y, w, h, bg, col, 1.6, 5)
    out += text(x + 10, y + h * 0.66, name, 12, col, "start", "bold")
    out += text(x + w - 10, y + h * 0.66, val, 12, INK, "end", "bold")
    return out


