#include <iostream>
#include <vector>
#include "Ws2812bBuffer.hpp"

/**
 * @file main.cpp
 * @brief Точка входу C++ для демонстрації керування буфером 74AHCT125 та світлодіодною стрічкою WS2812B.
 */

int main() {
    std::cout << "=== Ініціалізація проєкту керування WS2812B через буфер 74AHCT125 ===\n";

    // Визначення пінів мікроконтролера (наприклад, ESP32 / STM32):
    // Пін /OE підключено до лінії дозволу виходу буфера 74AHCT125
    // Пін DATA підключено до входу буфера для трансляції 3.3В -> 5В
    constexpr int OE_PIN = 4;
    constexpr int DATA_PIN = 23;

    try {
        // Створення екземпляра обгортки Ws2812bBuffer з використанням RAII
        // У конструкторі /OE автоматично встановлюється в HIGH (буфер вимкнено / Hi-Z)
        hardware::Ws2812bBuffer led_buffer(OE_PIN, DATA_PIN);

        // Перевірка стану буфера за замовчуванням
        std::cout << "Стан буфера після ініціалізації: " 
                  << (led_buffer.isEnabled() ? "Увімкнено" : "Вимкнено (Hi-Z)") << "\n";

        // Активація буфера (переведення /OE у LOW) для подачі надійних 5В сигналів на стрічку
        led_buffer.enable();
        std::cout << "Стан буфера після виклику enable(): " 
                  << (led_buffer.isEnabled() ? "Увімкнено" : "Вимкнено (Hi-Z)") << "\n";

        // Формування тестового кадру колірних даних (GRB) для 4 світлодіодів
        std::vector<hardware::Color> frame = {
            {255, 0, 0},   // Перший піксель: Зелений (Green)
            {0, 255, 0},   // Другий піксель: Червоний (Red)
            {0, 0, 255},   // Третій піксель: Синій (Blue)
            {255, 255, 255}// Четвертий піксель: Білий (White)
        };

        // Передача колірного пакета на стрічку
        led_buffer.sendPixels(frame);

        std::cout << "Демонстрація передачі успішно завершена.\n";

        // Вихід з блоку scope автоматично викличе деструктор led_buffer,
        // який надійно переведе буфер 74AHCT125 у стан Hi-Z (високий імпеданс).
    } catch (const std::exception& e) {
        std::cerr << "Помилка виконання: " << e.what() << "\n";
        return 1;
    }

    std::cout << "=== Завершення роботи програми ===\n";
    return 0;
}
