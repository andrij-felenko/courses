#define PIN_PL  5   /* → PL: знімок, активний нулем */
#define PIN_CP  6   /* → CP: такт зсуву            */
#define PIN_Q7  7   /* ← Q7: послідовні дані       */

uint8_t hc165_read(void)
{
    /* 1. Знімок. Поки PL=0, тригери прозоро повторюють входи;
          остаточним байт стає на фронті PL 0→1. */
    gpio_write(PIN_CP, 0);       /* такт лишаємо низьким на весь час знімка */
    gpio_write(PIN_PL, 0);
    delay_ns(200);               /* t_w(PL) за документом — десятки нс, беремо із запасом */
    gpio_write(PIN_PL, 1);       /* ← ось цей фронт і є «момент» */

    /* 2. Читання. Перший біт (вхід D7) стоїть на Q7 ЩЕ ДО першого такту. */
    uint8_t b = 0;
    for (int i = 0; i < 8; i++) {
        b = (uint8_t)((b << 1) | (gpio_read(PIN_Q7) & 1));  /* спершу читаємо */
        gpio_write(PIN_CP, 1);                              /* потім зсуваємо */
        gpio_write(PIN_CP, 0);
    }
    return b;   /* біт 7 = вхід D7, …, біт 0 = вхід D0 */
}
