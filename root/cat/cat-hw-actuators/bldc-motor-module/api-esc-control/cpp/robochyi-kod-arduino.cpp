#include <Servo.h>

// ESC слухає той самий сигнал, що й серво: імпульс 1000..2000 мкс раз на 20 мс.
Servo esc;                 // об'єкт керує імпульсами замість нас

const int ESC_PIN   = 9;   // сигнальний дріт ESC на цьому цифровому виводі
const int US_MIN    = 1000; // стоп / нуль газу
const int US_MAX    = 2000; // повний газ

void setup() {
  esc.attach(ESC_PIN, US_MIN, US_MAX);  // почати слати імпульси на вивід

  // ── ОЗБРОЄННЯ: без цього ESC не запуститься ──────────────────────────
  // Тримаємо мінімальний газ, поки ESC не переконається, що ми «на нулі».
  esc.writeMicroseconds(US_MIN);
  delay(3000);               // 3 с з запасом; більшості ESC досить 1-2 с
  // Тут справний ESC зазвичай коротко пищить — знак, що озброївся.
}

void loop() {
  // ── ПЛАВНИЙ РОЗГІН від стопу до половини газу ────────────────────────
  // Крок за кроком, а не кидком: різкий стрибок газу — ривок і кидок струму.
  for (int us = US_MIN; us <= 1500; us += 5) {
    esc.writeMicroseconds(us);
    delay(20);               // ~10 с на весь розгін — плавно й безпечно
  }

  esc.writeMicroseconds(1500); // тримаємо робочий газ
  delay(3000);

  // ── ПЛАВНЕ ГАЛЬМУВАННЯ назад до стопу ───────────────────────────────
  // Так само поступово: скидаємо газ вниз, даючи мотору сповільнитись,
  // а не жбурляючи всю інерцію назад у ESC зворотною ЕРС.
  for (int us = 1500; us >= US_MIN; us -= 5) {
    esc.writeMicroseconds(us);
    delay(20);
  }

  esc.writeMicroseconds(US_MIN); // повний стоп
  delay(3000);
}
