#ifndef GEARMOTOR_DRIVER_H
#define GEARMOTOR_DRIVER_H

#include <stdint.h>
#include <stdbool.h>

/**
 * @brief Стани кінцевого автомата драйвера H-моста
 */
typedef enum {
    MOTOR_STATE_STOP = 0,    /**< Вільний вибіг (coasting): усі ключі моста розімкнені */
    MOTOR_STATE_FORWARD,     /**< Пряме обертання з активним ШІМ-керуванням */
    MOTOR_STATE_REVERSE,     /**< Зворотне обертання з активним ШІМ-керуванням */
    MOTOR_STATE_BRAKE        /**< Активне динамічне гальмування: обмотка замкнена на GND */
} motor_state_t;

/**
 * @brief Напрямок обертання вала двигуна
 */
typedef enum {
    MOTOR_DIR_FORWARD = 0,   /**< Напрямок обертання вперед */
    MOTOR_DIR_REVERSE        /**< Напрямок обертання назад */
} motor_dir_t;

/**
 * @brief Параметри конфігурації для ініціалізації драйвера
 */
typedef struct {
    uint16_t pwm_period;        /**< Період таймера ШІМ у відліках (ARR/TOP) */
    uint16_t dead_time_counts;  /**< Апаратний захисний час (dead-time) у тактах таймера */
    uint16_t ramp_step;         /**< Крок зміни шпаруватості за тік update (софт-старт) */
    uint16_t deadband_ticks;    /**< Пауза в нульовому стані при зміні напрямку (тіки update) */
} gearmotor_config_t;

/**
 * @brief Дескриптор екземпляра драйвера мотор-редуктора
 *
 * Містить параметри апаратного таймера ШІМ, налаштування захисту (dead-time),
 * параметри темпу розгону (ramp_step) та змінні поточного стану.
 */
typedef struct {
    /* Конфігурація апаратного ШІМ та захисту від наскрізних струмів */
    uint16_t pwm_period;        /**< Період таймера ШІМ (максимальна шпаруватість) */
    uint16_t dead_time_counts;  /**< Захисний час затримки (dead-time) у тактах таймера */
    uint16_t ramp_step;         /**< Темп лінійного наростання/спаду шпаруватості за один крок */
    uint16_t deadband_ticks;    /**< Тривалість захисної паузи мертвої зони при реверсі */

    /* Змінні динамічного стану приводу */
    uint16_t current_duty;      /**< Поточна активна шпаруватість у відліках (0 .. pwm_period) */
    uint16_t target_duty;       /**< Задана цільова шпаруватість у відліках (0 .. pwm_period) */
    motor_state_t state;        /**< Поточний стан кінцевого автомата приводу */
    motor_dir_t target_dir;     /**< Цільовий напрямок обертання */
    uint16_t deadband_counter;  /**< Лічильник відліків паузи в нульовій точці при реверсі */
} gearmotor_t;

/**
 * @brief Ініціалізація драйвера мотор-редуктора із заданою конфігурацією
 * @param motor Вказівник на структуру екземпляра драйвера
 * @param config Вказівник на структуру з конфігураційними параметрами
 * @return true, якщо параметри валідні й ініціалізація успішна; false за помилки
 */
bool gearmotor_init(gearmotor_t *motor, const gearmotor_config_t *config);

/**
 * @brief Встановлення цільової швидкості (шпаруватості ШІМ)
 *
 * Шпаруватість задається у відліках таймера від 0 до pwm_period.
 * Зміна швидкості відбувається плавно (софт-старт / софт-стоп)
 * із кроком ramp_step під час викликів gearmotor_update().
 *
 * @param motor Вказівник на екземпляр драйвера
 * @param duty Бажана шпаруватість у відліках таймера
 */
void gearmotor_set_speed(gearmotor_t *motor, uint16_t duty);

/**
 * @brief Завдання цільового напрямку обертання вала
 *
 * Якщо двигун уже обертається, функція ініціює безпечний цикл реверсу:
 * плавне гальмування до 0, витримку мертвої зони (deadband), зміну полярності
 * ключів моста та наступний плавний розгін у зворотному напрямку.
 *
 * @param motor Вказівник на екземпляр драйвера
 * @param dir Бажаний напрямок (MOTOR_DIR_FORWARD або MOTOR_DIR_REVERSE)
 */
void gearmotor_set_direction(gearmotor_t *motor, motor_dir_t dir);

/**
 * @brief Періодичний неблокувальний крок оновлення кінцевого автомата
 *
 * Викликається регулярно із головного суперциклу або обробника системного таймера.
 * Реалізує розрахунок лінійного темпу зміни шпаруватості, відлік мертвої зони
 * під час реверсу та оновлення регістрів таймера.
 *
 * @param motor Вказівник на екземпляр драйвера
 */
void gearmotor_update(gearmotor_t *motor);

/**
 * @brief Негайний перехід у режим вільного вибігу (coasting stop)
 *
 * Усі ключі H-моста розмикаються (стан високого імпедансу), мотор вільно
 * вибігає за рахунок інерції та власного тертя в редукторі.
 *
 * @param motor Вказівник на екземпляр драйвера
 */
void gearmotor_stop(gearmotor_t *motor);

/**
 * @brief Активне електродинамічне гальмування (active low-side clamp)
 *
 * Верхні ключі моста вимикаються, нижні замикаються на GND.
 * Замкнене коло обмотки гасить ЕРС обертання, створюючи гальмівний момент.
 *
 * @param motor Вказівник на екземпляр драйвера
 */
void gearmotor_brake(gearmotor_t *motor);

/**
 * @brief Отримання поточного стану кінцевого автомата приводу
 * @param motor Вказівник на екземпляр драйвера
 * @return Поточний стан (STOP, FORWARD, REVERSE, BRAKE)
 */
motor_state_t gearmotor_get_state(const gearmotor_t *motor);

/**
 * @brief Отримання поточної шпаруватості ШІМ у відліках таймера
 * @param motor Вказівник на екземпляр драйвера
 * @return Поточне значення шпаруватості (0 .. pwm_period)
 */
uint16_t gearmotor_get_current_duty(const gearmotor_t *motor);

/**
 * @brief Перевірка, чи досягнуто заданої швидкості та напрямку
 * @param motor Вказівник на екземпляр драйвера
 * @return true, якщо перехідний процес завершено; false, якщо триває розгін/гальмування/пауза
 */
bool gearmotor_is_ramp_complete(const gearmotor_t *motor);

#endif /* GEARMOTOR_DRIVER_H */
