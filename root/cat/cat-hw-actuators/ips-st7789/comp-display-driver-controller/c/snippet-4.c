#include <stdint.h>

/**
 * Апаратний запуск та первинна ініціалізація контролера-драйвера дисплея.
 * Демонструє дотримання обов'язкових часових пауз стабілізації напруг.
 */
void Display_Controller_Hardware_Reset_And_Init(void)
{
    /* 1. Апаратне скидання: формуємо активний низький рівень на лінії RESET */
    Display_Platform_SetReset(0);
    Display_Platform_DelayMs(20);    /* Утримання сигналу скидання: 20 мс */
    
    /* 2. Зняття сигналу скидання: переводимо лінію RESET у високий рівень */
    Display_Platform_SetReset(1);
    Display_Platform_DelayMs(10);    /* Пауза стабілізації генератора й ROM: 10 мс */

    /* 3. Програмний вихід із режиму сну */
    Display_Write_Command(0x11);     /* Команда SLPOUT (Sleep Out) */
    
    /* 
     * КРИТИЧНА ПАУЗА: помпи заряду накачують напруги VGH (+13 В) та VGL (-8 В).
     * Категорично заборонено передавати команди відображення до завершення 120 мс!
     */
    Display_Platform_DelayMs(120);

    /* 4. Конфігурація формату пікселів (RGB565 - 16 біт/піксель) */
    Display_Write_Command(0x3A);     /* Команда COLMOD */
    Display_Write_Data(0x55);        /* 16 біт на піксель для інтерфейсу та панелі */

    /* 5. Увімкнення лінії синхронізації розриву кадру (TE) */
    Display_Write_Command(0x35);     /* Команда TEON */
    Display_Write_Data(0x00);        /* Режим 1: тільки V-sync (вертикальне гасіння) */

    /* 6. Увімкнення генерації зображення на матриці */
    Display_Write_Command(0x29);     /* Команда DISPON (Display On) */
    Display_Platform_DelayMs(20);    /* Пауза для включення першого кадру */
}
