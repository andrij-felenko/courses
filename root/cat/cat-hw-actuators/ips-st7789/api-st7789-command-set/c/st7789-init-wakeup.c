// Коди команд живлення та запуску ST7789
const uint8_t ST7789_SWRESET = 0x01; // Програмне скидання
const uint8_t ST7789_SLPOUT  = 0x11; // Вихід із режиму сну
const uint8_t ST7789_DISPON  = 0x29; // Увімкнення виводу матриці

void st7789_init_wakeup(int pin_rst) {
    // 1. Апаратне скидання (якщо пін підключено)
    if (pin_rst >= 0) {
        pinMode(pin_rst, OUTPUT);
        digitalWrite(pin_rst, HIGH);
        delay(10);
        digitalWrite(pin_rst, LOW);  // Активний низький рівень скидання
        delay(10);                   // Імпульс тривалістю не менше 10 мкс (тут 10 мс)
        digitalWrite(pin_rst, HIGH);
        delay(10);                   // Пауза перед початком надсилання команд
    }

    // 2. Програмне скидання регістрів
    st7789_write_command(ST7789_SWRESET);
    delay(120); // Обов'язкова затримка: перезавантаження конфігурації з пам'яті

    // 3. Запуск помп живлення та пробудження
    st7789_write_command(ST7789_SLPOUT);
    delay(120); // Критична пауза: вихід помп напруги на стабільний режим

    // Тут виконується проміжне налаштування регістрів (COLMOD, MADCTL, INVON)
    // доти, доки матриця вимкнена, що запобігає появі артефактів на екрані.

    // 4. Увімкнення генерації зображення
    st7789_write_command(ST7789_DISPON);
    delay(20);  // Додаткова стабілізація першого кадрового циклу
}
