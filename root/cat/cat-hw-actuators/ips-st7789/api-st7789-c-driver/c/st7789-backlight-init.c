// Зворотний виклик для встановлення шпаруватості апаратного таймера ШІМ
typedef void (*st7789_pwm_set_duty_fn)(uint8_t duty, void *user_data);

typedef struct {
    st7789_pwm_set_duty_fn set_pwm_duty; // Покажчик на функцію запису в регістр таймера
    void *user_data;                     // Контекст апаратного модуля таймера
    uint8_t perceived_level;             // Поточний заданий візуальний рівень (0..255)
} st7789_backlight_t;

// Ініціалізація підсистеми керування підсвічуванням
void st7789_backlight_init(st7789_backlight_t *bl, st7789_pwm_set_duty_fn pwm_fn, void *user_data) {
    bl->set_pwm_duty = pwm_fn;
    bl->user_data = user_data;
    bl->perceived_level = 0;
    if (bl->set_pwm_duty) {
        bl->set_pwm_duty(0, bl->user_data); // Початковий стан: підсвічування вимкнено
    }
}

// Встановлення рівня сприйнятої яскравості з нелінійним перетворенням
void st7789_backlight_set_level(st7789_backlight_t *bl, uint8_t level) {
    if (!bl || !bl->set_pwm_duty) {
        return;
    }
    bl->perceived_level = level;
    // Отримання апаратного коефіцієнта заповнення з таблиці Flash за час O(1)
    uint8_t hardware_duty = ST7789_GAMMA_LUT[level];
    bl->set_pwm_duty(hardware_duty, bl->user_data);
}
