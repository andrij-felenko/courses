#ifndef WS2812B_H
#define WS2812B_H

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "ws2812b_dma.h"

/**
 * @file ws2812b.h
 * @brief Високорівневий C-драйвер для керування адресною світлодіодною стрічкою WS2812B.
 *
 * Драйвер забезпечує підготовку колірного буфера GRB (Green-Red-Blue), конвертацію 
 * 24-бітних кольорів у часові імпульси TIM PWM / SPI та асинхронну передачу даних
 * за допомогою подвійної буферизації DMA без простою процесора.
 */

/**
 * @brief Тривалість періоду та тривалості імпульсів T0H/T1H (у відліках таймера).
 * Для частоти таймера 800 кГц (період T = 1.25 мкс):
 * - WS2812B_PWM_PERIOD = 90  (при частоті тактування 72 МГц)
 * - T0H (Логічний 0): ~0.35-0.4 мкс -> ~29 відліків (1/3 періоду)
 * - T1H (Логічна 1): ~0.8 мкс      -> ~58 відліків (2/3 періоду)
 */
#define WS2812B_PWM_PERIOD    90U
#define WS2812B_DUTY_BIT_0    29U
#define WS2812B_DUTY_BIT_1    58U
#define WS2812B_DUTY_RESET    0U

/**
 * @brief Структура 24-бітного кольору пікселя WS2812B у форматі GRB.
 * WS2812B вимагає порядок передачі байтів: Зелений (MSB), Червоний (MSB), Синій (MSB).
 */
typedef struct {
    uint8_t g; /**< Інтенсивність зеленого каналу (0..255) */
    uint8_t r; /**< Інтенсивність червоного каналу (0..255) */
    uint8_t b; /**< Інтенсивність синього каналу (0..255) */
} ws2812b_color_t;

/**
 * @brief Коди результатів виконання функцій драйвера WS2812B.
 */
typedef enum {
    WS2812B_OK              =  0, /**< Операція успішна */
    WS2812B_ERR_INVALID_ARG = -1, /**< Некоректні вхідні параметри */
    WS2812B_ERR_BUSY        = -2, /**< Драйвер зайнятий поточним оновленням стрічки */
    WS2812B_ERR_DMA_FAIL    = -3  /**< Помилка ініціалізації або запуску DMA */
} ws2812b_err_t;

/**
 * @brief Стан передавача кадру WS2812B.
 */
typedef enum {
    WS2812B_STATE_IDLE      = 0, /**< Передавач у стані спокою */
    WS2812B_STATE_SENDING   = 1, /**< Передача бітів кольорів пікселів */
    WS2812B_STATE_RESETTING = 2  /**< Генерація паузи скидання (RESET pulse > 50 мкс) */
} ws2812b_state_t;

/**
 * @brief Контекстний об'єкт драйвера стрічки WS2812B.
 */
typedef struct ws2812b {
    ws2812b_color_t *pixel_buffer; /**< Вказівник на масив кадру кольорів пікселів (RAM) */
    uint16_t num_leds;              /**< Кількість світлодіодів у стрічці */
    volatile ws2812b_state_t state; /**< Поточний стан передачі кадру */
    uint16_t current_pixel_idx;     /**< Індекс пікселя, що обробляється генератором подвійного буфера */
    uint8_t reset_bytes_sent;       /**< Лічильник надісланих байтів паузи RESET */
    ws2812b_dma_t dma_hw;           /**< Контекст низькорівневого периферійного модуля DMA/TIM */
} ws2812b_t;

/* --- Прототипи функцій драйвера WS2812B --- */

/**
 * @brief Ініціалізація C-драйвера WS2812B та прив'язка апаратного шару DMA.
 * 
 * @param ws Вказівник на екземпляр драйвера.
 * @param buffer Масив кольорів пікселів кадру розміру num_leds.
 * @param num_leds Кількість світлодіодів у стрічці.
 * @param timer_reg Вказівник на периферійний регістр порівняння таймера (CCR).
 * @return WS2812B_OK при успіху або відповідний код помилки.
 */
ws2812b_err_t ws2812b_init(ws2812b_t *ws, ws2812b_color_t *buffer, uint16_t num_leds, volatile uint32_t *timer_reg);

/**
 * @brief Встановлення кольору конкретного пікселя в форматі RGB.
 *
 * @param ws Вказівник на екземпляр драйвера.
 * @param index Індекс світлодіода (0 .. num_leds - 1).
 * @param r Компонента червоного (0..255).
 * @param g Компонента зеленого (0..255).
 * @param b Компонента синього (0..255).
 * @return WS2812B_OK або WS2812B_ERR_INVALID_ARG при виході за межі.
 */
ws2812b_err_t ws2812b_set_pixel_rgb(ws2812b_t *ws, uint16_t index, uint8_t r, uint8_t g, uint8_t b);

/**
 * @brief Встановлення кольору пікселя зі структури ws2812b_color_t (GRB).
 */
ws2812b_err_t ws2812b_set_pixel_color(ws2812b_t *ws, uint16_t index, ws2812b_color_t color);

/**
 * @brief Перетворення кольору з простору HSV (Hue, Saturation, Value) у формат GRB та запис у піксель.
 *
 * @param ws Вказівник на екземпляр драйвера.
 * @param index Індекс світлодіода.
 * @param hue Тон кольору (0..359 градусів).
 * @param sat Насиченість (0..255).
 * @param val Яскравість (0..255).
 * @return WS2812B_OK або помилка аргументу.
 */
ws2812b_err_t ws2812b_set_pixel_hsv(ws2812b_t *ws, uint16_t index, uint16_t hue, uint8_t sat, uint8_t val);

/**
 * @brief Очищення всіх пікселів кадру (встановлення чорного кольору 0,0,0).
 */
ws2812b_err_t ws2812b_clear(ws2812b_t *ws);

/**
 * @brief Запуск асинхронного неблокуючого оновлення стрічки світлодіодів через DMA.
 * 
 * Наповнює первинний подвійний буфер DMA бітовими імпульсами T0H/T1H і запускає
 * передачу в круговому режимі.
 *
 * @param ws Вказівник на екземпляр драйвера.
 * @return WS2812B_OK при успішному запуску, WS2812B_ERR_BUSY якщо оновлення вже триває.
 */
ws2812b_err_t ws2812b_update(ws2812b_t *ws);

/**
 * @brief Перевірка, чи триває зараз асинхронна передача даних через DMA.
 */
bool ws2812b_is_busy(const ws2812b_t *ws);

/**
 * @brief Створює об'єкт кольору ws2812b_color_t з окремих RGB компонент.
 */
ws2812b_color_t ws2812b_make_color(uint8_t r, uint8_t g, uint8_t b);

/**
 * @brief Внутрішня функція заповнення половини подвійного буфера DMA.
 * Викликається з обробників переривань DMA HT (Half Transfer) та TC (Transfer Complete).
 *
 * @param ws Вказівник на екземпляр драйвера.
 * @param half_idx Індекс половини буфера (0 - перша половина, 1 - друга половина).
 */
void ws2812b_fill_dma_half(ws2812b_t *ws, uint8_t half_idx);

#endif /* WS2812B_H */
