#ifndef ADC_H
#define ADC_H

#include <stdint.h>
#include <stdbool.h>

/**
 * @file adc.h
 * @brief Інтерфейс модуля аналого-цифрового перетворення (АЦП).
 *
 * Служить для оцифрування напруги з ручного або механічного потенціометра керування,
 * перетворення вхідної аналогової напруги на цифровий відлік та його первинного фільтрування.
 */

#define ADC_RESOLUTION_BITS  10      /*!< Розрядність АЦП (10 біт = 0..1023) */
#define ADC_MAX_VALUE        1023    /*!< Максимальний цифровий відлік (2^10 - 1) */
#define ADC_VREF_MV          3300    /*!< Опорна напруга АЦП у мілівольтах (3.3 В) */

/**
 * @brief Структура конфігурації модуля АЦП
 */
typedef struct {
    uint8_t channel;           /*!< Номер вхідного аналогового каналу (0..7) */
    uint8_t prescaler;         /*!< Коефіцієнт преддільника системної частоти АЦП */
    bool use_internal_vref;    /*!< Використання внутрішнього джерела опорної напруги */
} adc_config_t;

/**
 * @brief Ініціалізація апаратного модуля АЦП.
 *
 * @param config Указник на структуру конфігурації
 */
void adc_init(const adc_config_t *config);

/**
 * @brief Проведення одиночного оцифрування напруги з вказаного каналу.
 *
 * @param channel Номер аналогового каналу
 * @return uint16_t Цифровий відлік АЦП у діапазоні [0..ADC_MAX_VALUE]
 */
uint16_t adc_read(uint8_t channel);

/**
 * @brief Отримання усредненого відліку АЦП (усунення шуму та дребезгу ковзаючого контакту).
 *
 * @param channel Номер аналогового каналу
 * @param samples Кількість вибірок для обчислення середнього арифметичного (1..64)
 * @return uint16_t Фільтрований цифровий відлік
 */
uint16_t adc_read_filtered(uint8_t channel, uint8_t samples);

/**
 * @brief Математичне перетворення цифрового відліку АЦП у напругу (в мілівольтах).
 *
 * @param adc_value Оцифроване значення
 * @return float Вхідна напруга в мілівольтах
 */
float adc_to_millivolts(uint16_t adc_value);

#endif /* ADC_H */
