#ifndef SERVO_H
#define SERVO_H

#include <stdint.h>
#include <stdbool.h>

/**
 * @file servo.h
 * @brief Інтерфейс драйвера RC-сервоприводу для мікроконтролера.
 *
 * Драйвер забезпечує генерацію ШІМ-сигналу з періодом кадру 20 мс (50 Гц)
 * та тривалістю позитивного керуючого імпульсу від 0.5 мс (0°) до 2.5 мс (180°).
 */

/* Часові параметри ШІМ-сигналу керування сервоприводом */
#define SERVO_FRAME_PERIOD_MS    20      /*!< Загальний період кадру ШІМ (20 мс = 50 Гц) */
#define SERVO_FRAME_PERIOD_US    20000   /*!< Період кадру у мікросекундах */
#define SERVO_MIN_PULSE_US       500     /*!< Мінімальна тривалість імпульсу (0.5 мс -> 0°) */
#define SERVO_MAX_PULSE_US       2500    /*!< Максимальна тривалість імпульсу (2.5 мс -> 180°) */
#define SERVO_NEUTRAL_PULSE_US   1500    /*!< Нейтральне положення вала (1.5 мс -> 90°) */

/* Діапазон кутів повороту вала */
#define SERVO_MIN_ANGLE_DEG      0.0f    /*!< Мінімальний кут повороту у градусах */
#define SERVO_MAX_ANGLE_DEG      180.0f  /*!< Максимальний кут повороту у градусах */

/* Параметри тактування апаратного таймера мікроконтролера */
#define SERVO_CPU_FREQ_HZ        16000000UL /*!< Тактова частота ядра мікроконтролера (16 МГц) */
#define SERVO_TIMER_PRESCALER    8          /*!< Преддільник таймера (16 МГц / 8 = 2 МГц -> 0.5 мкс/такт) */

/**
 * @brief Структура конфігурації та поточного стану RC-сервоприводу.
 */
typedef struct {
    uint8_t channel_id;        /*!< Номер каналу ШІМ / апаратного таймера */
    uint16_t min_pulse_us;     /*!< Гранична мінімальна тривалість імпульсу (мкс) */
    uint16_t max_pulse_us;     /*!< Гранична максимальна тривалість імпульсу (мкс) */
    uint16_t current_pulse_us; /*!< Поточна розрахована тривалість керуючого імпульсу (мкс) */
    float current_angle_deg;   /*!< Поточний встановлений кут повороту вала (0..180°) */
    uint32_t timer_ticks;      /*!< Розраховане значення для регістру порівняння таймера */
    bool is_enabled;           /*!< Прапор активації виходу ШІМ */
} servo_t;

/**
 * @brief Ініціалізація структури конфігурації сервоприводу та апаратного таймера.
 *
 * @param servo Указник на об'єкт сервоприводу
 * @param channel_id Ідентифікатор каналу ШІМ
 * @param min_pulse_us Мінімальна ширина імпульсу у мікросекундах (за замовчуванням 500)
 * @param max_pulse_us Максимальна ширина імпульсу у мікросекундах (за замовчуванням 2500)
 * @return true Якщо ініціалізація пройшла успішно
 * @return false Якщо передані некоректні вхідні параметри
 */
bool servo_init(servo_t *servo, uint8_t channel_id, uint16_t min_pulse_us, uint16_t max_pulse_us);

/**
 * @brief Встановлення кута повороту вала сервоприводу в градусах (0..180°).
 *
 * @param servo Указник на об'єкт сервоприводу
 * @param angle_deg Бажаний кут у градусах
 */
void servo_set_angle(servo_t *servo, float angle_deg);

/**
 * @brief Пряме завдання тривалості імпульсу у мікросекундах (0.5 мс .. 2.5 мс).
 *
 * @param servo Указник на об'єкт сервоприводу
 * @param pulse_us Тривалість імпульсу у мікросекундах
 */
void servo_set_pulse_us(servo_t *servo, uint16_t pulse_us);

/**
 * @brief Лінійне мапування значення з АЦП потенціометра у тривалість ШІМ-імпульсу.
 *
 * @param servo Указник на об'єкт сервоприводу
 * @param adc_value Цифровий відлік з АЦП
 * @param adc_max_value Максимально можливий відлік АЦП (наприклад, 1023 для 10-бітного АЦП)
 */
void servo_update_from_adc(servo_t *servo, uint16_t adc_value, uint16_t adc_max_value);

/**
 * @brief Перетворення тривалості імпульсу у мікросекундах у відліки регістру порівняння таймера.
 *
 * @param pulse_us Тривалість імпульсу у мікросекундах
 * @return uint32_t Кількість тактів таймера
 */
uint32_t servo_pulse_us_to_timer_ticks(uint16_t pulse_us);

/**
 * @brief Увімкнення або вимкнення генерації ШІМ-сигналу для каналу.
 *
 * @param servo Указник на об'єкт сервоприводу
 * @param enable true для увімкнення, false для вимкнення
 */
void servo_enable(servo_t *servo, bool enable);

#endif /* SERVO_H */
