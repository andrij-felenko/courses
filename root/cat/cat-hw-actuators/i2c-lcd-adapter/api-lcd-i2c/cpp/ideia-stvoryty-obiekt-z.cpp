#include <Wire.h>
#include <LiquidCrystal_I2C.h>

// (адреса, стовпці, рядки). Адресу взяли зі сканера!
LiquidCrystal_I2C lcd(0x27, 16, 2);

void setup() {
  // ВАЖЛИВО на ESP32/STM32/Pico: свою шину піднімаємо САМІ, до дисплея,
  // бо lcd.init() усередині кличе Wire.begin() БЕЗ аргументів (дефолтні ніжки).
  Wire.begin(21, 22);            // SDA=21, SCL=22 — приклад для ESP32
  // На класичній Arduino цей рядок не потрібен — там ніжки жорсткі.

  lcd.init();                    // ініціалізація контролера HD44780 через розширювач
  lcd.backlight();               // увімкнути підсвітку (без неї екран темний!)

  lcd.setCursor(0, 0);           // стовпець 0, рядок 0 (відлік із нуля)
  lcd.print("Hello, world!");

  lcd.setCursor(0, 1);           // другий рядок
  lcd.print("I2C LCD 1602");
}

void loop() {
  // усе вже на екрані — циклу нічого робити
}
