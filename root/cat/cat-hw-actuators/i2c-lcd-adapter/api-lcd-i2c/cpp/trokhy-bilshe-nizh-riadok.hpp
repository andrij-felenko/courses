lcd.clear();                 // стерти весь екран, курсор → (0,0)
lcd.home();                  // курсор → (0,0), НЕ стираючи (швидше за clear())

lcd.setCursor(11, 0);        // праве вирівнювання: рахуємо позицію самі
lcd.print("OK");

// свій символ (напр. градус) — 8 рядків по 5 біт, малюнок 5×8:
byte degree[8] = {
  0b00110,
  0b01001,
  0b01001,
  0b00110,
  0b00000,
  0b00000,
  0b00000,
  0b00000
};
lcd.createChar(0, degree);   // зберегли у слот 0 (усього слотів 8: 0..7)
lcd.setCursor(0, 1);
lcd.print("Temp: 25");
lcd.write((uint8_t)0);       // вивести свій символ зі слота 0
lcd.print("C");              // -> "Temp: 25°C"
