lcd.move_to(11, 0)            # праве вирівнювання: рахуємо позицію самі
lcd.putstr("OK")

# свій символ (напр. градус) — 8 рядків по 5 біт, малюнок 5×8:
degree = bytearray([
    0b00110,
    0b01001,
    0b01001,
    0b00110,
    0b00000,
    0b00000,
    0b00000,
    0b00000,
])
lcd.custom_char(0, degree)    # зберегли у слот 0 (усього слотів 8: 0..7)
lcd.move_to(0, 1)
lcd.putstr("Temp: 25")
lcd.putchar(chr(0))           # вивести свій символ зі слота 0
lcd.putstr("C")               # -> "Temp: 25°C"
