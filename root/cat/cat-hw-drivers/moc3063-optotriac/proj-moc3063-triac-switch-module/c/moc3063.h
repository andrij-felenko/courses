#ifndef MOC3063_H
#define MOC3063_H

#include <stdint.h>
#include <stdbool.h>

/**
 * @file moc3063.h
 * @brief Заголовний файл драйвера оптосимістора MOC3063 з вбудованим детектором нуля (Zero-Cross).
 *
 * Драйвер реалізує абстракцію керування вхідним світлодіодом оптопари MOC3063
 * через цифровий вивід GPIO мікроконтролера для безпечної комутації змінної напруги.
 */

/**
 * @brief Коди статусу виконання функцій драйвера MOC3063.
 */
typedef enum {
    MOC3063_OK = 0,               /**< Операція виконана успішно */
    MOC3063_ERROR_INVALID_PARAM,  /**< Передано некоректні аргументи */
    MOC3063_ERROR_NOT_INITIALIZED /**< Драйвер не було ініціалізовано */
} moc3063_status_t;

/**
 * @brief Активний логічний рівень керування світлодіодом оптопари.
 */
typedef enum {
    MOC3063_ACTIVE_HIGH = 0, /**< Active HIGH: HIGH (1) вмикає LED (MCU джерело струму / Sourcing) */
    MOC3063_ACTIVE_LOW  = 1  /**< Active LOW: LOW (0) вмикає LED (MCU сток струму / Sinking) */
} moc3063_active_level_t;

/**
 * @brief Логічний стан комутованого силового навантаження.
 */
typedef enum {
    MOC3063_STATE_OFF = 0, /**< Навантаження вимкнено (світлодіод оптопари знеструмлено) */
    MOC3063_STATE_ON  = 1  /**< Навантаження увімкнено (світлодіод оптопари заживлено) */
} moc3063_state_t;

/**
 * @brief Тип вказівника на апаратну функцію запису логічного рівня у вивід GPIO.
 * @param pin Номер або ідентифікатор штифта GPIO.
 * @param level Логічний рівень (true = HIGH, false = LOW).
 */
typedef void (*moc3063_gpio_write_fn)(uint8_t pin, bool level);

/**
 * @brief Конфігураційна структура для ініціалізації драйвера MOC3063.
 */
typedef struct {
    uint8_t gpio_pin;                    /**< Номер виводу GPIO мікроконтролера */
    moc3063_active_level_t active_level; /**< Полярність активного сигналу керування */
    moc3063_state_t initial_state;       /**< Початковий стан навантаження при старті */
    moc3063_gpio_write_fn gpio_write;    /**< Вказівник на функцію апаратного запису GPIO */
} moc3063_config_t;

/**
 * @brief Структура дескриптора драйвера MOC3063.
 */
typedef struct {
    moc3063_config_t config;      /**< Збережена конфігурація драйвера */
    moc3063_state_t current_state; /**< Поточний логічний стан навантаження */
    bool is_initialized;          /**< Прапорець завершення ініціалізації */
} moc3063_t;

/**
 * @brief Безпечна ініціалізація драйвера MOC3063 та встановлення початкового стану.
 * 
 * @param handle Вказівник на дескриптор драйвера.
 * @param config Вказівник на структуру конфігурації.
 * @return MOC3063_OK у разі успіху або відповідний код помилки.
 */
moc3063_status_t moc3063_init(moc3063_t *handle, const moc3063_config_t *config);

/**
 * @brief Встановлення заданого стану навантаження (ON або OFF).
 * 
 * @param handle Вказівник на дескриптор драйвера.
 * @param state Бажаний стан навантаження (MOC3063_STATE_ON / MOC3063_STATE_OFF).
 * @return MOC3063_OK у разі успіху або код помилки.
 */
moc3063_status_t moc3063_set_state(moc3063_t *handle, moc3063_state_t state);

/**
 * @brief Подача сигналу увімкнення навантаження.
 * 
 * Внутрішній апаратний детектор нуля оптосимістора MOC3063 автоматично
 * зачекає найближчого переходу напруги AC через нуль перед відкриттям симістора.
 * 
 * @param handle Вказівник на дескриптор драйвера.
 * @return MOC3063_OK у разі успіху або код помилки.
 */
moc3063_status_t moc3063_turn_on(moc3063_t *handle);

/**
 * @brief Зняття сигналу керування для вимкнення навантаження.
 * 
 * Силовий симістор закриється автоматично при спаданні струму навантаження нижче струму утримання (Ih).
 * 
 * @param handle Вказівник на дескриптор драйвера.
 * @return MOC3063_OK у разі успіху або код помилки.
 */
moc3063_status_t moc3063_turn_off(moc3063_t *handle);

/**
 * @brief Перемикання стану навантаження на протилежний (Toggle).
 * 
 * @param handle Вказівник на дескриптор драйвера.
 * @return MOC3063_OK у разі успіху або код помилки.
 */
moc3063_status_t moc3063_toggle(moc3063_t *handle);

/**
 * @brief Зчитування поточного логічного стану драйвера.
 * 
 * @param handle Вказівник на дескриптор драйвера.
 * @param state Вказівник для запису поточного стану.
 * @return MOC3063_OK у разі успіху або код помилки.
 */
moc3063_status_t moc3063_get_state(const moc3063_t *handle, moc3063_state_t *state);

#endif /* MOC3063_H */
