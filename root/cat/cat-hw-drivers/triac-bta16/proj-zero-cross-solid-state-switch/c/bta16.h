#ifndef BTA16_H
#define BTA16_H

/**
 * @file bta16.h
 * @brief Заголовочний файл процедурного драйвера симістора BTA16-600B.
 *
 * Драйвер забезпечує дискретне керування оптосимісторним ключем (наприклад, MOC3041/MOC3021)
 * для безпечної комутації зміннострумового силового навантаження 220 В.
 */

#include <stdint.h>
#include <stdbool.h>

/* ========================================================================= */
/*                   КОНФІГУРАЦІЯ АПАРАТНОГО ВИВОДУ GPIO                     */
/* ========================================================================= */

/**
 * @brief Номер пина GPIO мікроконтролера, підключеного до світлодіода оптодрайвера.
 */
#define BTA16_GPIO_PIN              5

/**
 * @brief Активний рівень керування силовим ключем:
 * 1 — активний високий рівень (High-side drive, логічна 1 вмикає світлодіод оптопари),
 * 0 — активний низький рівень (Low-side drive, логічний 0 вмикає світлодіод оптопари).
 */
#define BTA16_ACTIVE_LEVEL          1

/**
 * @brief Логічні стани силового ключа BTA16.
 */
#define BTA16_STATE_OFF             0
#define BTA16_STATE_ON              1

/**
 * @brief Безпечна часова затримка ініціалізації (у мілісекундах)
 * для стабілізації перехідних процесів після скидання мікроконтролера.
 */
#define BTA16_INIT_SAFETY_DELAY_MS  50

/**
 * @brief Мінімальна часова затримка між перемиканнями (у мілісекундах)
 * для запобігання перегріву та хибного повторного відкриття симістора.
 */
#define BTA16_MIN_SWITCH_DELAY_MS   10

/* ========================================================================= */
/*                         ПРОТОТИПИ ФУНКЦІЙ ДРАЙВЕРА                         */
/* ========================================================================= */

/**
 * @brief Первинна безпечна ініціалізація GPIO для керування симістором.
 *
 * @note КРИТИЧНО ДЛЯ БЕЗПЕКИ: Спочатку встановлюється безпечний вимкнений стан
 * у вихідному регістрі даних (Output Data Register), і лише потім пин переводиться
 * у режим виходу (Output Mode). Це унеможливлює короткочасне хибне увімкнення
 * навантаження 220 В при подачі живлення або скиданні МК.
 */
void bta16_init(void);

/**
 * @brief Переведення симісторного ключа BTA16 у відкритий (увімкнений) стан.
 * Подає керуючий струм на світлодіод оптопари MOC3041/MOC3021.
 */
void bta16_on(void);

/**
 * @brief Переведення симісторного ключа BTA16 у закритий (вимкнений) стан.
 * Знімає керуючий струм зі світлодіода оптопари.
 */
void bta16_off(void);

/**
 * @brief Безпечна зміна стану силового ключа на протилежний (Toggle).
 */
void bta16_toggle(void);

/**
 * @brief Перевірка поточного стану симісторного ключа BTA16.
 * @return true — симістор увімкнений (навантаження під напругою 220 В),
 *         false — симістор вимкнений (навантаження знеструмлене).
 */
bool bta16_is_on(void);

/**
 * @brief Процедура витримування часової затримки у мілісекундах.
 * Використовується для безпечних інтервалів перемикання силового модулю.
 *
 * @param ms Тривалість затримки в мілісекундах.
 */
void bta16_delay_ms(uint32_t ms);

#endif /* BTA16_H */
