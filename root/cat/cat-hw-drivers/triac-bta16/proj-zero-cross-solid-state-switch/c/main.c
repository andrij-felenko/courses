/**
 * @file main.c
 * @brief Демонстраційний приклад процедурного керування симістором BTA16-600B.
 *
 * Демонструє безпечний старт-ап драйвера та послідовну комутацію
 * зміннострумового силового навантаження 220 В у головному циклі програми.
 */

#include <stdio.h>
#include <stdbool.h>
#include "bta16.h"

int main(void)
{
    printf("=====================================================\n");
    printf("   Драйвер симісторного силового ключа BTA16-600B     \n");
    printf("=====================================================\n");
    printf("[ІНФО] Запуск системи та первинна ініціалізація...\n");

    /*
     * Крок 1: Виклик процедури безпечної ініціалізації GPIO.
     * Гарантує вимкнений стан симістора при старт-апі мікроконтролера.
     */
    bta16_init();

    printf("[УСПІХ] Драйвер BTA16 ініціалізовано. Силовий ключ вимкнено.\n");
    printf("[ІНФО] Поточний стан ключа: %s\n", bta16_is_on() ? "УВІМКНЕНО" : "ВИМКНЕНО");
    printf("-----------------------------------------------------\n");

    /*
     * Крок 2: Демонстраційний цикл безпечної комутації силового навантаження (3 цикли)
     */
    for (int cycle = 1; cycle <= 3; cycle++) {
        printf("[ЦИКЛ %d] Початок комутації навантаження 220 В...\n", cycle);

        /* Увімкнення навантаження */
        printf("  -> Подача сигналу відкриття симістора (BTA16 ON)...\n");
        bta16_on();
        printf("  -> Стан: %s (Навантаження під напругою 220 В)\n",
               bta16_is_on() ? "УВІМКНЕНО" : "ВИМКНЕНО");

        /* Навантаження працює протягом 3000 мс (3 секунди) */
        printf("  -> Витримування робочого інтервалу 3000 мс...\n");
        bta16_delay_ms(3000);

        /* Вимкнення навантаження */
        printf("  -> Зняття сигналу керування симістором (BTA16 OFF)...\n");
        bta16_off();
        printf("  -> Стан: %s (Навантаження знеструмлено)\n",
               bta16_is_on() ? "УВІМКНЕНО" : "ВИМКНЕНО");

        /* Пауза між перемиканнями 2000 мс (2 секунди) */
        printf("  -> Пауза безпеки 2000 мс...\n");
        bta16_delay_ms(2000);

        printf("-----------------------------------------------------\n");
    }

    printf("[ІНФО] Завершення демонстраційної роботи. Робота виконана успішно.\n");
    return 0;
}
