#ifndef TRIAC_DRIVER_H
#define TRIAC_DRIVER_H

#include <Arduino.h>

/**
 * @brief Клас для безпечного керування симісторним силовим ключем (наприклад, BTA16-600B)
 * через оптопару (MOC3021/MOC3041/MOC3063) або твердотільне реле.
 *
 * Забезпечує безпечну початкову ініціалізацію GPIO-пина для запобігання
 * хибному ввімкненню навантаження при скиданні мікроконтролера, а також
 * неблокуюче таймерне автовимкнення.
 */
class TriacDriver {
public:
    /**
     * @brief Конструктор драйвера симістора.
     * @param pin Номер GPIO-пина мікроконтролера, підключеного до керуючого входу оптопари.
     * @param activeHigh Активний рівень керування: true — високий рівень (HIGH) вмикає симістор,
     *                   false — низький рівень (LOW) вмикає симістор. За замовчуванням true.
     */
    explicit TriacDriver(uint8_t pin, bool activeHigh = true);

    /**
     * @brief Безпечна ініціалізація GPIO-пина.
     * 
     * Встановлює вихідний рівень у вимкнений стан ДО перемикання режиму пина в OUTPUT,
     * що запобігає короткочасним сплескам та хибному спрацьовуванню силового ключа.
     */
    void begin();

    /**
     * @brief Увімкнути симісторний ключ.
     * Скасовує активний таймер автовимкнення, якщо він був запущений.
     */
    void turnOn();

    /**
     * @brief Вимкнути симісторний ключ.
     * Скасовує активний таймер автовимкнення.
     */
    void turnOff();

    /**
     * @brief Переключити стан симісторного ключа (ON -> OFF або OFF -> ON).
     * Скасовує активний таймер автовимкнення.
     */
    void toggle();

    /**
     * @brief Увімкнути симісторний ключ на заданий проміжок часу.
     * @param durationMs Час роботи навантаження в мілісекундах. Після закінчення часу ключ вимкнеться автоматично.
     */
    void turnOnFor(uint32_t durationMs);

    /**
     * @brief Неблокуюче оновлення стану драйвера.
     * Необхідно регулярно викликати в головному циклі loop().
     * Перевіряє плин часу таймера та автоматично вимикає навантаження після закінчення інтервалу.
     */
    void update();

    /**
     * @brief Перевірити, чи увімкнено симісторний ключ наразі.
     * @return true, якщо навантаження увімкнено; false, якщо вимкнено.
     */
    bool isOn() const;

    /**
     * @brief Перевірити, чи активний таймер автовимкнення.
     * @return true, якщо залучено неблокуючий таймер.
     */
    bool isTimerActive() const;

    /**
     * @brief Отримати залишок часу роботи таймера в мілісекундах.
     * @return Залишок часу у ms або 0, якщо таймер неактивний.
     */
    uint32_t getRemainingTimeMs() const;

private:
    uint8_t pin_;             ///< Номер керуючого GPIO пина
    bool activeHigh_;         ///< Прапорець активного рівня керування
    bool isOn_;               ///< Поточний стан симістора (true - увімкнено, false - вимкнено)
    uint32_t startTimeMs_;    ///< Час запуску таймера (значення millis())
    uint32_t durationMs_;     ///< Тривалість роботи таймера у мілісекундах
    bool timerActive_;        ///< Прапорець активності неблокуючого таймера

    /**
     * @brief Внутрішній метод запису фізичного рівня на GPIO пин.
     * @param state Бажаний логічний стан ключа (true — увімкнено, false — вимкнено).
     */
    void applyState(bool state);
};

#endif // TRIAC_DRIVER_H
