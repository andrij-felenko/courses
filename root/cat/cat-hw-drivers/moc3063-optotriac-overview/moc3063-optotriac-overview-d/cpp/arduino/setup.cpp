#include <Arduino.h>

// Вивід керування вхідним світлодіодом оптопари MOC3063
const uint8_t MOC3063_PIN = 5;

void setup() {
    // Ініціалізація виводу в режимі цифрового виходу
    pinMode(MOC3063_PIN, OUTPUT);
    
    // Початковий стан: високий рівень (світлодіод вимкнено)
    digitalWrite(MOC3063_PIN, HIGH);
}

void loop() {
    // Активний низький рівень вмикає світлодіод і відкриває оптосимістор
    digitalWrite(MOC3063_PIN, LOW);
    delay(5000); // Робочий такт 5 секунд

    // Високий рівень вимикає світлодіод
    digitalWrite(MOC3063_PIN, HIGH);
    delay(5000); // Пауза 5 секунд
}
