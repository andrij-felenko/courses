#!/usr/bin/env bash

# ==============================================================================
# Скрипт автоматизованої перевірки, резервного копіювання та прошивання ESP-01
# ==============================================================================

# Завершувати виконання при будь-якій неочікуваній помилці в конвеєрі
set -o pipefail

# Конфігураційні параметри за замовчуванням
PORT="${1:-/dev/ttyUSB0}"
BAUD="${2:-460800}"
FIRMWARE_IMAGE="${3:-firmware.bin}"
BACKUP_IMAGE="${4:-backup_esp01_1MB.bin}"
FLASH_SIZE="1MB"
FLASH_MODE="dout"

# Кольорове виведення логів
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # Без кольору

log_info() {
    echo -e "${BLUE}[ІНФО]${NC} $1"
}

log_success() {
    echo -e "${GREEN}[УСПІХ]${NC} $1"
}

log_warn() {
    echo -e "${YELLOW}[УВАГА]${NC} $1"
}

log_error() {
    echo -e "${RED}[ПОМИЛКА]${NC} $1"
}

# ------------------------------------------------------------------------------
# 1. Перевірка наявності утиліти esptool та послідовного порту
# ------------------------------------------------------------------------------
log_info "Перевірка системних залежностей..."

ESPTOOL_CMD=""
if command -v esptool.py &> /dev/null; then
    ESPTOOL_CMD="esptool.py"
elif command -v esptool &> /dev/null; then
    ESPTOOL_CMD="esptool"
else
    log_error "Утиліту esptool не знайдено. Встановіть її через 'pip install esptool'."
    exit 1
fi

log_info "Знайдено утиліту: $ESPTOOL_CMD"

if [ ! -c "$PORT" ] && [ ! -e "$PORT" ]; then
    log_error "Послідовний порт '$PORT' не існує або недоступний."
    log_warn "Перевірте підключення USB-UART адаптера та права доступу (команда 'sudo usermod -a -G dialout $USER')."
    exit 1
fi

log_info "Використовується порт: $PORT (швидкість: $BAUD біт/с)"

# ------------------------------------------------------------------------------
# 2. Зчитування ідентифікаторів чипа та SPI Flash
# ------------------------------------------------------------------------------
log_info "Крок 1: Зчитування ідентифікаційних даних ESP8266..."

if ! $ESPTOOL_CMD --port "$PORT" --baud "$BAUD" chip_id; then
    log_error "Не вдалося зчитати Chip ID. Перевірте режим завантажника (GPIO0 = GND, RST імпульс)."
    exit 1
fi

log_info "Зчитування параметрів флеш-пам'яті (Flash ID)..."
if ! $ESPTOOL_CMD --port "$PORT" --baud "$BAUD" flash_id; then
    log_error "Помилка при виконанні команди flash_id."
    exit 1
fi

log_success "Ідентифікація чипа пройшла успішно."

# ------------------------------------------------------------------------------
# 3. Створення резервної копії (дампу) 1 МБ Flash-пам'яті
# ------------------------------------------------------------------------------
log_info "Крок 2: Створення резервної копії пам'яті (1 МБ) у файл '$BACKUP_IMAGE'..."

# 1 МБ = 0x100000 байтів (1048576 байтів)
if $ESPTOOL_CMD --port "$PORT" --baud "$BAUD" read_flash 0x00000 0x100000 "$BACKUP_IMAGE"; then
    log_success "Дамп флеш-пам'яті успішно збережено у файл '$BACKUP_IMAGE'."
else
    log_error "Збій під час зчитування дампа пам'яті."
    exit 1
fi

# ------------------------------------------------------------------------------
# 4. Повне стирання секторів флеш-пам'яті
# ------------------------------------------------------------------------------
log_info "Крок 3: Повне стирання флеш-пам'яті (erase_flash)..."

if $ESPTOOL_CMD --port "$PORT" --baud "$BAUD" erase_flash; then
    log_success "Очищення секторів SPI Flash виконано успішно."
else
    log_error "Збій під час стирання флеш-пам'яті."
    exit 1
fi

# ------------------------------------------------------------------------------
# 5. Запис нового бінарного образу прошивки
# ------------------------------------------------------------------------------
if [ ! -f "$FIRMWARE_IMAGE" ]; then
    log_error "Файл прошивки '$FIRMWARE_IMAGE' не знайдено!"
    log_warn "Вкажіть шлях до бінарного файла як третій аргумент: ./flash_esp01.sh /dev/ttyUSB0 460800 my_firmware.bin"
    exit 1
fi

log_info "Крок 4: Запис образу '$FIRMWARE_IMAGE' за адресою 0x00000 (mode: $FLASH_MODE, size: $FLASH_SIZE)..."

if $ESPTOOL_CMD --port "$PORT" --baud "$BAUD" write_flash --flash_mode "$FLASH_MODE" --flash_size "$FLASH_SIZE" 0x00000 "$FIRMWARE_IMAGE"; then
    log_success "Прошивка успішно записана в модуль ESP-01!"
else
    log_error "Помилка запису прошивки."
    exit 1
fi

log_info "Операція повністю завершена. Переведіть ESP-01 у режим звичайного завантаження (GPIO0 = VCC) та виконайте перезапуск (RST)."
exit 0
