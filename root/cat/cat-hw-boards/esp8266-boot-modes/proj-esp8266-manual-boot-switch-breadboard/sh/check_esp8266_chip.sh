#!/usr/bin/env bash

# Сценарій для опитування первинного ROM-завантажувача мікроконтролера ESP8266.
# Зчитує ідентифікатор чипа (chip_id), MAC-адресу та параметри Flash-пам'яті (flash_id).

set -euo pipefail

# Параметри за замовчуванням (можуть перевизначатися аргументами командного рядка)
PORT="${1:-/dev/ttyUSB0}"
BAUD="${2:-115200}"

# Перевірка наявності утиліти esptool або esptool.py в системі
ESPTOOL=""
if command -v esptool.py &> /dev/null; then
    ESPTOOL="esptool.py"
elif command -v esptool &> /dev/null; then
    ESPTOOL="esptool"
else
    echo "[ПОМИЛКА] Утиліту esptool/esptool.py не знайдено. Встановіть її за допомогою: pip install esptool" >&2
    exit 1
fi

echo "=========================================================="
echo " Ініціалізація опитування ESP8266 через $ESPTOOL"
echo " Послідовний порт: $PORT"
echo " Швидкість передачі: $BAUD біт/с"
echo "=========================================================="

# Перевірка доступності послідовного порту
if [ ! -e "$PORT" ]; then
    echo "[ПОМИЛКА] Послідовний пристрій $PORT не існує. Перевірте підключення плати." >&2
    exit 1
fi

# Крок 1. Перевірка з'єднання та зчитування ідентифікатора чипа (Chip ID)
echo -e "\n---> [Крок 1/3] Запит ідентифікатора чипа (chip_id)..."
if "$ESPTOOL" --port "$PORT" --baud "$BAUD" --chip esp8266 chip_id; then
    echo "[ОК] Успішно отримано ідентифікатор чипа."
else
    echo "[ПОМИЛКА] Не вдалося перевірити chip_id. Перевірте режими завантаження (GPIO0=HIGH, GPIO15=LOW, CH_PD=HIGH) та живлення." >&2
    exit 1
fi

# Крок 2. Зчитування фізичної MAC-адреси (Read MAC)
echo -e "\n---> [Крок 2/3] Зчитування фізичної MAC-адреси пристрою..."
if "$ESPTOOL" --port "$PORT" --baud "$BAUD" --chip esp8266 read_mac; then
    echo "[ОК] Фізичну MAC-адресу успішно зчитано."
else
    echo "[ПОМИЛКА] Збій під час зчитування MAC-адреси." >&2
    exit 1
fi

# Крок 3. Зчитування параметрів Flash-пам'яті (Flash ID, обсяг та режим)
echo -e "\n---> [Крок 3/3] Опитування характеристик та обсягу Flash-пам'яті..."
if "$ESPTOOL" --port "$PORT" --baud "$BAUD" --chip esp8266 flash_id; then
    echo "[ОК] Характеристики Flash-пам'яті успішно зчитано."
else
    echo "[ПОМИЛКА] Збій під час зчитування flash_id." >&2
    exit 1
fi

echo -e "\n=========================================================="
echo " [УСПІХ] Діагностику ESP8266 завершено успішно!"
echo "=========================================================="
