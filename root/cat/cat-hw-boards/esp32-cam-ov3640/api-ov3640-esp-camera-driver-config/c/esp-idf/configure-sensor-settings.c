#include "esp_camera.h"

// Динамічна конфігурація параметрів сенсора у реальному часі
void configure_sensor_settings(void) {
    sensor_t *s = esp_camera_sensor_get();
    if (s == NULL) {
        return;
    }

    // Налаштування орієнтації кадру
    s->set_vflip(s, 1);       // Увімкнути вертикальне перевертання
    s->set_hmirror(s, 1);     // Увімкнути горизонтальне дзеркалювання

    // Налаштування контрасту та яскравості (діапазон від -2 до 2)
    s->set_brightness(s, 1);  // Збільшити яскравість
    s->set_contrast(s, 0);    // Нормальний контраст

    // Налаштування автоматичних балансів
    s->set_whitebal(s, 1);    // Увімкнути автоматичний баланс білого (AWB)
    s->set_exposure_ctrl(s, 1);// Увімкнути автоматичну експозицію (AEC)
    s->set_gain_ctrl(s, 1);   // Увімкнути автоматичне підсилення (AGC)
}
