#ifndef F_CPU
#define F_CPU 16000000UL
#endif

#include <avr/io.h>
#include <avr/interrupt.h>
#include <util/delay.h>
#include <stdbool.h>
#include "uart.h"

/*
 * ==============================================================================
 * ОСОБЛИВОСТІ ПІДКТЮЧЕННЯ ТА ЖИВЛЕННЯ ESP-01 ДО МІКРОКОНТРОЛЕРА AVR:
 * ==============================================================================
 *
 * 1. Вимоги до живлення та струму:
 *    - ESP-01 працює строго від напруги 3.3V (допустимий діапазон 3.0V - 3.6V).
 *    - Під час передачі даних по Wi-Fi модуль споживає імпульсний струм до 300-500 мА.
 *    - КАДЕГОРИЧНО ВБОРОНЕНО живити ESP-01 від лінійки 3.3V стандартної плати Arduino/AVR!
 *      Вбудовані регулятори Arduino видають лише 50-150 мА, що спричинить просідання
 *      напруги та постійний перезапуск (boot loop) ESP-01.
 *    - Використовуйте окремий LDO-регулятор (наприклад, AMS1117 3.3V) або спеціальну
 *      плату-адаптер ESP-01 із вбудованим регулятором живлення.
 *    - Обов'язково встановіть керамічний конденсатор 0.1 мкФ та електроліт 10-470 мкФ
 *      безпосередньо біля виводів VCC і GND модуля ESP-01.
 *
 * 2. Узгодження логічних рівнів (Level Shifting):
 *    - AVR (наприклад, ATmega328P) працює на логіці 5V, а ESP-01 — на 3.3V.
 *    - Лінія AVR TX (5V) -> ESP-01 RX (3.3V): обов'язково потребує резистивного
 *      дільника напруги (наприклад, 1 кОм до AVR TX і 2 кОм на GND) або адаптера рівнів.
 *    - Лінія ESP-01 TX (3.3V) -> AVR RX (5V): підключається напряму, оскільки 3.3V
 *      впевнено розпізнається AVR як логічна 1 (HIGH threshold >= 3.0V при VCC 5V).
 *
 * 3. Конфігурація виводів ESP-01:
 *    - VCC     -> 3.3V (від потужного джерела)
 *    - GND     -> Спільна земля (GND AVR та 3.3V джерела мусять бути з'єднані!)
 *    - CH_PD/EN-> Підтяжка до 3.3V через резистор 10 кОм (вмикає модуль)
 *    - RST     -> Підтяжка до 3.3V через резистор 10 кОм (скидання при подачі LOW)
 *    - GPIO0   -> Підтяжка до 3.3V для нормального режиму завантаження з Flash
 * ==============================================================================
 */

int main(void) {
    // Ініціалізація апаратного модуля USART AVR на стандартну швидкість ESP-01 (115200 бод)
    uart_init(115200);

    // Вмикаємо глобальні переривання для забезпечення роботи кільцевих буферів RX та TX
    sei();

    // Пауза 2 секунди для стабілізації живлення та завершення завантаження прошивки ESP-01
    _delay_ms(2000);

    // Надсилання тестової AT-команди для перевірки з'єднання з модулем
    uart_puts("AT\r\n");

    // Головний нескінченний цикл прозорого мосту / обробки AT-команд
    while (1) {
        uint8_t byte;

        // Перевіряємо наявність байтів, отриманих від ESP-01 через UART
        if (uart_getc(&byte)) {
            // Отриманий байт можна аналізувати, зберігати або передавати далі
            // Наприклад, при отриманні символу переведення рядка '\n' від відповіді ESP-01:
            if (byte == '\n') {
                // Рядок відповіді (наприклад, "OK" або "ERROR") успішно прийнято
            }
        }
    }

    return 0;
}
