#!/usr/bin/env bash

# ==============================================================================
# flash_esp01.sh — Автоматизація прошивки мікроконтролера ESP-01 через esptool
#
# Скрипт виконує послідовний процес обслуговування ESP-01 (ESP8266):
# 1. Перевірка наявності інструментів та файлу прошивки.
# 2. Ідентифікація модуля та зчитування його параметрів (chip_id, flash_id).
# 3. Повне стирання вмісту flash-пам'яті (erase_flash).
# 4. Запис бінарного образу прошивки (write_flash) за вказаною адресою.
# ==============================================================================

set -euo pipefail

# ------------------------------------------------------------------------------
# Конфігураційні параметри за замовчуванням
# ------------------------------------------------------------------------------
PORT="${PORT:-/dev/ttyUSB0}"          # Послідовний порт USB-програматора
BAUD="${BAUD:-115200}"                # Швидкість передачі даних (baud rate)
FLASH_MODE="${FLASH_MODE:-dout}"      # Режим роботи Flash для ESP-01 (dout — найсумісніший)
FLASH_FREQ="${FLASH_FREQ:-40m}"        # Частота SPI Flash (40m = 40 MHz)
FLASH_SIZE="${FLASH_SIZE:-1MB}"       # Розмір flash-пам'яті (1MB для більшості ESP-01)
FIRMWARE="${1:-firmware.bin}"         # Шлях до бінарного файлу прошивки (перший аргумент)
OFFSET="${OFFSET:-0x00000}"           # Початкова адреса запису прошивки

# Пошук доступного виконуваного файлу esptool
if command -v esptool &> /dev/null; then
    ESPTOOL="esptool"
elif command -v esptool.py &> /dev/null; then
    ESPTOOL="esptool.py"
else
    ESPTOOL=""
fi

# ------------------------------------------------------------------------------
# Допоміжна функція виводу довідки
# ------------------------------------------------------------------------------
show_help() {
    echo "Використання: $0 [шлях_до_прошивки.bin]"
    echo ""
    echo "Змінні середовища для налаштування:"
    echo "  PORT        Послідовний порт (за замовчуванням: /dev/ttyUSB0)"
    echo "  BAUD        Швидкість зв'язку (за замовчуванням: 115200)"
    echo "  FLASH_MODE  Режим SPI Flash (dout, dio, qio; за замовчуванням: dout)"
    echo "  FLASH_FREQ  Частота SPI Flash (40m, 80m; за замовчуванням: 40m)"
    echo "  FLASH_SIZE  Розмір flash-пам'яті (1MB, 2MB, detect; за замовчуванням: 1MB)"
    echo "  OFFSET      Адреса запису прошивки (за замовчуванням: 0x00000)"
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
    show_help
    exit 0
fi

# ------------------------------------------------------------------------------
# Крок 0: Валідація середовища та вхідних даних
# ------------------------------------------------------------------------------
echo "=== [Крок 0/3] Перевірка вимог та вхідних даних ==="

if [[ -z "$ESPTOOL" ]]; then
    echo "Помилка: esptool не знайдено в системі. Встановіть його через 'pip install esptool'." >&2
    exit 1
fi

if [[ ! -e "$PORT" ]]; then
    echo "Помилка: Послідовний порт '$PORT' не знайдено." >&2
    echo "Перевірте підключення USB-програматора ESP-01 та права доступу (sudo usermod -a -G dialout \$USER)." >&2
    exit 1
fi

if [[ ! -f "$FIRMWARE" ]]; then
    echo "Помилка: Файл прошивки '$FIRMWARE' не існує." >&2
    echo "Вкажіть коректний шлях до бінарного файлу: $0 <шлях_до_файлу.bin>" >&2
    exit 1
fi

echo "Інструмент esptool: $ESPTOOL"
echo "Порт:                $PORT ($BAUD baud)"
echo "Файл прошивки:       $FIRMWARE"
echo "Параметри flash:      mode=$FLASH_MODE, freq=$FLASH_FREQ, size=$FLASH_SIZE"
echo ""

# ------------------------------------------------------------------------------
# Крок 1: Перевірка зв'язку та ідентифікація модуля ESP-01
# ------------------------------------------------------------------------------
echo "=== [Крок 1/3] Перевірка зв'язку та ідентифікація ESP-01 ==="
echo "Опитування чипа (chip_id)..."
"$ESPTOOL" --port "$PORT" --baud "$BAUD" chip_id

echo ""
echo "Зчитування інформації про flash-пам'ять (flash_id)..."
"$ESPTOOL" --port "$PORT" --baud "$BAUD" flash_id

echo ""
echo "Зв'язок з ESP-01 успішно встановлено."
echo ""

# ------------------------------------------------------------------------------
# Крок 2: Очищення flash-пам'яті модуля
# ------------------------------------------------------------------------------
echo "=== [Крок 2/3] Стирання flash-пам'яті ==="
echo "Увага: Всі дані на flash-пам'яті будуть знищені."
"$ESPTOOL" --port "$PORT" --baud "$BAUD" erase_flash

echo ""
echo "Flash-пам'ять успішно очищено."
echo ""

# ------------------------------------------------------------------------------
# Крок 3: Запис бінарного образу прошивки
# ------------------------------------------------------------------------------
echo "=== [Крок 3/3] Запис бінарного образу прошивки ==="
echo "Запис '$FIRMWARE' за адресою $OFFSET..."

"$ESPTOOL" --port "$PORT" \
           --baud "$BAUD" \
           write_flash \
           --flash_mode "$FLASH_MODE" \
           --flash_freq "$FLASH_FREQ" \
           --flash_size "$FLASH_SIZE" \
           "$OFFSET" \
           "$FIRMWARE"

echo ""
echo "=== Процес обслуговування та прошивки ESP-01 успішно завершено! ==="
