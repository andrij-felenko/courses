#ifndef UART_H
#define UART_H

#include <stdint.h>
#include <stddef.h>

/**
 * @file uart.h
 * @brief Заголовний файл драйвера UART для мікроконтролера ESP8266 (модуль ESP-01).
 * 
 * Оголошує функції для ініціалізації апаратного послідовного порту UART0,
 * відправки окремих символів, текстових рядків та форматованих діагностичних повідомлень.
 */

// Стандартна швидкість передачі даних за замовчуванням (115200 бод)
#define UART_DEFAULT_BAUD_RATE 115200U

/**
 * @brief Ініціалізує апаратний модуль UART0 мікроконтролера ESP8266.
 * 
 * Налаштовує дільник тактової частоти для заданого значення baud rate,
 * скидає приймальний та передавальний бафери (FIFO), конфігурує кадр 8N1
 * (8 біт даних, без паритету, 1 стоп-біт).
 * 
 * @param baud_rate Швидкість передачі у бодах (наприклад, 115200 або 9600).
 */
void uart_init(uint32_t baud_rate);

/**
 * @brief Передає один символ через послідовний інтерфейс UART0.
 * 
 * Очікує наявність вільного місця в апаратному бафері передачі (TX FIFO)
 * та відправляє базований символ на програматор-адаптер.
 * 
 * @param c Символ для відправки.
 */
void uart_send_char(char c);

/**
 * @brief Передає нуль-термінований текстовий рядок через UART0.
 * 
 * Автоматично виконує підстановку символу повернення каретки '\r'
 * перед кожним символом переведення рядка '\n' для коректного відображення в терміналі.
 * 
 * @param str Вказівник на рядок символів.
 */
void uart_send_string(const char *str);

/**
 * @brief Відправляє форматоване діагностичне повідомлення про стан модуля ESP-01.
 * 
 * @param cycle_count Номер поточного циклу виконання головного миготливого/діагностичного процесу.
 * @param uptime_ms Загальний час роботи системи з моменту подачі живлення або скидання (у мілісекундах).
 */
void uart_send_diagnostic_status(uint32_t cycle_count, uint32_t uptime_ms);

#endif // UART_H
