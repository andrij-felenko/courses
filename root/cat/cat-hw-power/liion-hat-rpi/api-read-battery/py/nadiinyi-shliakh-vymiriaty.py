# Вольтметрія SOC для одного Li-ion елемента (LiCoO2/NMC).
# Таблиця — приблизна крива "напруга спокою → % заряду".
# Точки з поширених довідкових таблиць; крок навмисно грубий.
SOC_TABLE = [
    (4.20, 100), (4.06,  90), (3.98,  80), (3.92,  70),
    (3.87,  60), (3.82,  50), (3.79,  40), (3.77,  30),
    (3.74,  20), (3.68,  10), (3.45,   5), (3.00,   0),
]

def voltage_to_soc(v: float) -> int:
    """Груба оцінка % заряду з напруги спокою. Насичення на краях."""
    if v >= SOC_TABLE[0][0]:
        return 100
    if v <= SOC_TABLE[-1][0]:
        return 0
    # знайти сусідні точки таблиці й лінійно проінтерполювати між ними
    for (v_hi, s_hi), (v_lo, s_lo) in zip(SOC_TABLE, SOC_TABLE[1:]):
        if v_lo <= v <= v_hi:
            k = (v - v_lo) / (v_hi - v_lo)          # 0..1 усередині відрізка
            return round(s_lo + k * (s_hi - s_lo))
    return 0  # сюди не дійде, але хай функція завжди повертає число


# --- приклад читання напруги з ADS1115 (спосіб B) ---
# ADS1115 сидить на I²C 0x48; дільник ділить напругу елемента навпіл.
from smbus2 import SMBus

ADS1115  = 0x48
DIVIDER  = 2.0          # два однакові резистори: Vбат = Vадц · 2
# (нижче — спрощено: реальні читання ADS1115 потребують налаштування
#  підсилення й режиму; тут показано лише перетворення числа у напругу)

def read_cell_voltage(adc_volts: float) -> float:
    return adc_volts * DIVIDER

# зібрали докупи:
v_cell = read_cell_voltage(1.91)     # напр., АЦП намірив 1.91 В на дільнику
print(f"елемент: {v_cell:.2f} В  →  ~{voltage_to_soc(v_cell)}% заряду")
# елемент: 3.82 В  →  ~50% заряду
