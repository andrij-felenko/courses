import math

# ── параметри друку (усе в міліметрах) ──────────────────────────────
SIDE       = 40.0      # сторона квадрата
CENTER     = 110.0     # центр столу 220×220 → квадрат посередині
LAYER_H    = 0.2       # висота шару
LINE_W     = 0.45      # ширина лінії (трохи більша за сопло 0.4)
FIL_D      = 1.75      # діаметр нитки
LAYERS     = 20        # скільки шарів (20 × 0.2 = 4 мм заввишки)
T_NOZZLE   = 210       # °C, сопло (PLA)
T_BED      = 60        # °C, стіл
F_PRINT    = 1200      # мм/хв, робочий хід
F_TRAVEL   = 3000      # мм/хв, переїзд без друку

# площа перерізу нитки — знаменник формули екструзії
FIL_AREA = math.pi * (FIL_D / 2) ** 2

def extrusion_for(length_mm):
    """Скільки мм нитки видати на пряму завдовжки length_mm (E-формула)."""
    volume = length_mm * LINE_W * LAYER_H
    return volume / FIL_AREA

def gcode():
    out = []
    def emit(line):            # накопичувач рядків
        out.append(line)

    half = SIDE / 2
    # чотири кути квадрата, обходимо проти годинникової
    x0, y0 = CENTER - half, CENTER - half
    x1, y1 = CENTER + half, CENTER + half
    corners = [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]

    # ── ПРЕАМБУЛА: дім, нагрів, режими ──────────────────────────────
    emit("; --- рамка %g×%g мм, %d шарів ---" % (SIDE, SIDE, LAYERS))
    emit("G28")                       # дім по всіх осях (ОБОВ'ЯЗКОВО перше)
    emit("G90")                       # абсолютні координати руху
    emit("M83")                       # ВІДНОСНА подача: E = скільки додати
    emit("M140 S%d" % T_BED)          # почати гріти стіл (не чекаючи)
    emit("M104 S%d" % T_NOZZLE)       # почати гріти сопло (не чекаючи)
    emit("M190 S%d" % T_BED)          # дочекатися столу
    emit("M109 S%d" % T_NOZZLE)       # дочекатися сопла (аж тепер можна E)
    emit("G92 E0")                    # обнулити лічильник подачі

    # ── ШАРИ ────────────────────────────────────────────────────────
    z = LAYER_H
    for layer in range(LAYERS):
        emit("; --- шар %d, Z=%.2f ---" % (layer + 1, z))
        # переїзд у стартовий кут БЕЗ друку, підняти на висоту шару
        emit("G0 X%.3f Y%.3f Z%.3f F%d" % (x0, y0, z, F_TRAVEL))
        if layer == 0:
            emit("M106 S255")         # увімкнути обдув після 1-го шару
        # обвести периметр: до кожного наступного кута — робочий хід із E
        path = corners[1:] + [corners[0]]       # 3 сторони + повернення
        px, py = x0, y0
        for (cx, cy) in path:
            length = math.hypot(cx - px, cy - py)
            e = extrusion_for(length)
            emit("G1 X%.3f Y%.3f E%.5f F%d" % (cx, cy, e, F_PRINT))
            px, py = cx, cy
        z += LAYER_H

    # ── ФІНАЛ: прибрати за собою ─────────────────────────────────────
    emit("; --- кінець ---")
    emit("G1 E-3 F1800")              # відкат нитки на 3 мм (проти капання)
    emit("M104 S0")                   # вимкнути сопло
    emit("M140 S0")                   # вимкнути стіл
    emit("M107")                      # вимкнути обдув
    emit("G0 Z%.2f F%d" % (z + 10, F_TRAVEL))   # підняти голову
    emit("G0 X0 Y%g F%d" % (CENTER + half + 20, F_TRAVEL))  # вивезти стіл уперед
    emit("M84")                       # знеструмити мотори
    return "\n".join(out)

if __name__ == "__main__":
    print(gcode())
