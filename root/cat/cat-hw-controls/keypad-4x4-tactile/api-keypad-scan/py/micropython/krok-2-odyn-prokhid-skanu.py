# Прочитати весь стан клавіатури в бітову карту 4×4.
# Повертає 16 бітів: біт (row*4 + col) = 1, якщо кнопка (row,col) натиснута.
def keypad_scan_raw():
    bits = 0

    for col in range(4):
        cols[col].value(0)              # 1) активуємо стовпець: тягнемо до землі
        # тут корисна крихітна пауза — див. пастку «повільний loop / надто швидкий скан»
        for row in range(4):            # 2) читаємо всі рядки
            if rows[row].value() == 0:  # рядок просів → кнопка натиснута
                bits |= 1 << (row * 4 + col)
        cols[col].value(1)              # 3) відпускаємо стовпець назад у HIGH
    return bits
