# Розкладка: що надруковано на кнопці на перетині [row][col].
# Рядок = рядок клавіатури, стовпець = стовпець. Типовий телефонний розклад.
KEYMAP = (
    ('1', '2', '3', 'A'),
    ('4', '5', '6', 'B'),
    ('7', '8', '9', 'C'),
    ('*', '0', '#', 'D'),
)

# За індексом (row,col) повертає символ клавіші.
def keypad_char(row, col):
    return KEYMAP[row][col]
