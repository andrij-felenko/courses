// Розкладка: що надруковано на кнопці на перетині [row][col].
// Рядок масиву = рядок клавіатури, стовпець = стовпець. Типовий телефонний розклад.
static const char KEYMAP[4][4] = {
    { '1', '2', '3', 'A' },
    { '4', '5', '6', 'B' },
    { '7', '8', '9', 'C' },
    { '*', '0', '#', 'D' },
};

// За індексом (row,col) повертає символ клавіші.
static inline char keypad_char(uint8_t row, uint8_t col)
{
    return KEYMAP[row][col];
}
