def configure_remote(ser: serial.Serial):
    """Налаштувати ВІДДАЛЕНИЙ (бортовий) модуль через наземний по радіо.
    Працює, лише поки пара бачить одне одного (канал живий)."""
    # Читаємо параметри бортового модуля — RTI5 замість ATI5
    print("--- параметри ВІДДАЛЕНОГО модуля (RTI5) ---")
    print(at(ser, "RTI5", wait=0.6))     # по радіо відповідь іде повільніше — даємо більше часу

    # Міняємо йому NETID і зберігаємо — усе з префіксом RT
    print("RTS3=25 ->", at(ser, "RTS3=25", wait=0.6))
    print("RT&W   ->", at(ser, "RT&W",   wait=0.6))
    # RTZ перезавантажить бортовий модуль — і на кілька секунд обірве канал,
    # доки він не підніметься наново. Робимо це ОСТАННІМ.
    ser.write(b"RTZ\r\n")
    ser.flush()
