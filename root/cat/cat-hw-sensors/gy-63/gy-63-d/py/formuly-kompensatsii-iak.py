if TEMP < 2000:                          # нижче 20 °C
    t2    = dT * dT >> 31
    off2  = 5 * (TEMP - 2000) * (TEMP - 2000) // 2
    sens2 = 5 * (TEMP - 2000) * (TEMP - 2000) // 4
    if TEMP < -1500:                     # нижче −15 °C — ще сильніше
        off2  += 7 * (TEMP + 1500) * (TEMP + 1500)
        sens2 += 11 * (TEMP + 1500) * (TEMP + 1500) // 2
    TEMP -= t2
    OFF  -= off2
    SENS -= sens2
