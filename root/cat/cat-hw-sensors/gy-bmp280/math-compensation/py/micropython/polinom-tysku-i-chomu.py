# Повертає тиск у Pa у форматі Q24.8 (24 цілих біти, 8 дробових).
# Значення "24674867" означає 24674867/256 = 96386.2 Pa = 963.862 hPa.
# t_fine приходить із функції компенсації температури; dig — кортеж коефіцієнтів.
def compensate_P(adc_P, t_fine, dig):
    var1 = t_fine - 128000
    var2 = var1 * var1 * dig[6]
    var2 = var2 + ((var1 * dig[5]) << 17)
    var2 = var2 + (dig[4] << 35)
    var1 = ((var1 * var1 * dig[3]) >> 8) + ((var1 * dig[2]) << 12)
    var1 = ((1 << 47) + var1) * dig[1] >> 33
    if var1 == 0:
        return 0  # уникнути ділення на нуль
    p = 1048576 - adc_P
    p = ((p << 31) - var2) * 3125 // var1
    var1 = (dig[9] * (p >> 13) * (p >> 13)) >> 25
    var2 = (dig[8] * p) >> 19
    p = ((p + var1 + var2) >> 8) + (dig[7] << 4)
    return p
