#include <stdint.h>
#include <stdbool.h>

// Схема підключення платинового термоопору PT100
typedef enum {
    PT100_WIRE_2 = 2,  // 2-провідне підключення (без компенсації дротів)
    PT100_WIRE_3 = 3,  // 3-провідне підключення (компенсація через два джерела струму)
    PT100_WIRE_4 = 4   // 4-провідне підключення Кельвіна (повна компенсація)
} pt100_wire_mode_t;

// Конфігураційні параметри апаратної обв'язки та алгоритму
typedef struct {
    pt100_wire_mode_t wire_mode;   // Режим підключення дротів
    float r_ref_ohms;              // Опір еталонного резистора R_ref (наприклад, 400.0f)
    float r_0_ohms;                // Номінальний опір PT100 при 0 °C (100.0f)
    uint16_t excitation_current_ua;// Струм збудження в мкА (наприклад, 250 мкА)
    float alpha_coef;              // Температурний коефіцієнт (0.003851 °C⁻¹)
    float filter_alpha;            // Коефіцієнт експоненційного фільтра (0.0f .. 1.0f)
} pt100_config_t;
