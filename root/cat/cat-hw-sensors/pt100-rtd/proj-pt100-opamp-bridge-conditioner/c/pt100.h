#ifndef PT100_H
#define PT100_H

#include <stdint.h>
#include <stdbool.h>

/**
 * @file pt100.h
 * @brief Модуль обробки сигналів платинового термоопору PT100 (0–5 В).
 *
 * Оголошення структур конфігурації АЦП, двохточкового калібрування аналогового
 * тракту та математичних функцій перетворення цифрового коду в температуру.
 */

/* Фізичні параметри платинового термоопору за стандартом IEC 60751 (DIN EN 60751) */
#define PT100_R0_OHM            100.0f     /**< Опір при 0 °C (Ом) */
#define PT100_ALPHA_PER_DEG_C   0.003851f  /**< Температурний коефіцієнт α (1/°C) */

/* Параметри АЦП за замовчуванням */
#define PT100_ADC_VREF_DEFAULT  5.0f       /**< Опорна напруга АЦП (В) */
#define PT100_ADC_BITS_DEFAULT  12U        /**< Розрядність АЦП (12 біт = 4096 рівнів) */

/**
 * @brief Структура двохточкового калібрування для компенсації похибок аналогового тракту.
 *
 * Зберігає коефіцієнт масштабування (gain) та зсуву нуля (offset).
 * Математична модель корекції: V_calib = (V_raw * gain) + offset
 */
typedef struct {
    float gain;   /**< Коефіцієнт нахилу калібрувальної прямої (безрозмірний) */
    float offset; /**< Коефіцієнт зсуву нуля (у Вольтах) */
} pt100_calib_t;

/**
 * @brief Конфігурація вимірювача PT100 та параметрів периферії АЦП.
 *
 * Зберігає характеристику АЦП, межі температурного діапазону нормувального підсилювача
 * та калібрувальні коефіцієнти.
 */
typedef struct {
    uint8_t adc_bits;    /**< Розрядність АЦП у бітах (наприклад, 10 або 12) */
    float vref_v;        /**< Опорна напруга АЦП у Вольтах (0–5 В) */
    float temp_min;      /**< Температура при напрузі 0.0 В (°C) */
    float temp_max;      /**< Температура при напрузі 5.0 В (°C) */
    pt100_calib_t calib; /**< Структура калібрувальних коефіцієнтів тракту */
} pt100_config_t;

/**
 * @brief Ініціалізація структури конфігурації вимірювача.
 *
 * @param config Вказівник на структуру конфігурації
 * @param adc_bits Розрядність АЦП (біт)
 * @param vref_v Опорна напруга АЦП (В)
 * @param temp_min Мінімальна температура вимірювального діапазону (°C)
 * @param temp_max Максимальна температура вимірювального діапазону (°C)
 * @return true при успішній ініціалізації, false при некоректних аргументах
 */
bool pt100_init_config(pt100_config_t *config,
                       uint8_t adc_bits,
                       float vref_v,
                       float temp_min,
                       float temp_max);

/**
 * @brief Розрахунок двохточкових калібрувальних коефіцієнтів (gain та offset).
 *
 * Приймає дві виміряні сирі напруги та дві відповідні їм еталонні напруги.
 *
 * @param v_meas1 Перша виміряна сира напруга (В)
 * @param v_ref1  Перша еталонна напруга (В)
 * @param v_meas2 Друга виміряна сира напруга (В)
 * @param v_ref2  Друга еталонна напруга (В)
 * @param calib   Вказівник для збереження коефіцієнтів
 * @return true при успіху, false якщо виміряні точки збігаються (ділення на нуль)
 */
bool pt100_calc_calibration(float v_meas1, float v_ref1,
                             float v_meas2, float v_ref2,
                             pt100_calib_t *calib);

/**
 * @brief Перетворення сирого цифрового коду АЦП у напругу (0–5 В).
 *
 * @param adc_raw Сирий відлік АЦП (0..2^N - 1)
 * @param config  Конфігураційні параметри АЦП
 * @return Виміряна сира напруга у Вольтах
 */
float pt100_adc_to_voltage(uint32_t adc_raw, const pt100_config_t *config);

/**
 * @brief Застосування калібрувальної корекції до напруги.
 *
 * @param v_raw Сира напруга з АЦП (В)
 * @param calib Калібрувальні коефіцієнти (gain, offset)
 * @return Скоригована напруга у Вольтах
 */
float pt100_correct_voltage(float v_raw, const pt100_calib_t *calib);

/**
 * @brief Розрахунок фізичної температури (°C) за скоригованою напругою (0–5 В).
 *
 * @param v_corr Скоригована напруга (В)
 * @param config Конфігурація вимірювача
 * @return Розрахована температура в градусах Цельсія (°C)
 */
float pt100_voltage_to_temperature(float v_corr, const pt100_config_t *config);

/**
 * @brief Повний конвеєр обробки відліку АЦП до значення температури.
 *
 * @param adc_raw  Сирий цифровий код з АЦП
 * @param config   Конфігурація вимірювача
 * @param out_temp Вказівник для збереження розрахованої температури (°C)
 * @return true якщо обчислення успішне та в межах норми, false при виході за межі
 */
bool pt100_process_sample(uint32_t adc_raw, const pt100_config_t *config, float *out_temp);

#endif /* PT100_H */
