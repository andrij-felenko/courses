g_prev     = 0.0                    # хвиля на попередньому кроці (для перетину нуля)
g_peak     = 0.0                    # найвище значення в поточному підйомі
g_lastBeat = 0                      # час останнього ЗАРАХОВАНОГО удару
MIN_AMP = 8.0                       # мін. висота горба, щоб зарахувати удар (одиниці АЦП)
MIN_GAP = 250                       # «глухе» вікно між ударами, мс (стеля пульсу)

# Викликаємо на кожен свіжий згладжений відлік g_smooth.
# Повертає True рівно в мить зарахованого удару.
def detect_beat(s, now):
    global g_prev, g_peak, g_lastBeat
    beat = False

    # Слідкуємо за вершиною поточного підйому.
    if s > g_peak:
        g_peak = s

    # Перетин нуля ЗНИЗУ ВГОРУ: минулого разу під нулем, тепер над.
    if g_prev < 0 and s >= 0:
        # Зараховуємо, лише якщо підйом був досить високий І минуло глухе вікно.
        if g_peak >= MIN_AMP and now - g_lastBeat >= MIN_GAP:
            g_lastBeat = now
            beat = True
        g_peak = 0.0                # почався новий цикл — обнуляємо лічильник вершини

    g_prev = s
    return beat
