float    g_prev      = 0;           // хвиля на попередньому кроці (для перетину нуля)
float    g_peak      = 0;           // найвище значення в поточному підйомі
uint32_t g_lastBeat  = 0;           // час останнього ЗАРАХОВАНОГО удару
const float    MIN_AMP  = 8.0;      // мін. висота горба, щоб зарахувати удар (одиниці АЦП)
const uint32_t MIN_GAP  = 250;      // «глухе» вікно між ударами, мс (стеля пульсу)

// Викликаємо на кожен свіжий згладжений відлік g_smooth.
// Повертає true рівно в мить зарахованого удару.
bool detectBeat(float s, uint32_t now) {
    bool beat = false;

    // Слідкуємо за вершиною поточного підйому.
    if (s > g_peak) g_peak = s;

    // Перетин нуля ЗНИЗУ ВГОРУ: минулого разу під нулем, тепер над.
    if (g_prev < 0 && s >= 0) {
        // Зараховуємо, лише якщо підйом був досить високий І минуло глухе вікно.
        if (g_peak >= MIN_AMP && now - g_lastBeat >= MIN_GAP) {
            g_lastBeat = now;
            beat = true;
        }
        g_peak = 0;                 // почався новий цикл — обнуляємо лічильник вершини
    }

    g_prev = s;
    return beat;
}
