#ifndef AHT20_H
#define AHT20_H

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "i2c_bus.h"

/**
 * @file aht20.h
 * @brief Модульний C-драйвер цифрового давача температури та вологості AHT20 для шини I2C.
 * 
 * Оголошення констант адресації I2C, команд керування, бітових масок статусу,
 * структури показань aht20_data_t, кодів помилок та прототипів драйвера.
 */

/* 7-бітова адреса пристрою AHT20 за замовчуванням на шині I2C */
#define AHT20_I2C_ADDR                  0x38

/* Команди керування чипом AHT20 */
#define AHT20_CMD_INIT                  0xBE  /* Команда ініціалізації чипа */
#define AHT20_CMD_TRIGGER_MEASURE       0xAC  /* Команда запуску АЦП-вимірювання */
#define AHT20_CMD_SOFT_RESET            0xBA  /* Команда програмного перезавантаження (Soft Reset) */

/* Параметри команди ініціалізації 0xBE */
#define AHT20_CMD_INIT_ARG1             0x08
#define AHT20_CMD_INIT_ARG2             0x00

/* Параметри команди запуску вимірювання 0xAC */
#define AHT20_CMD_TRIGGER_ARG1          0x33
#define AHT20_CMD_TRIGGER_ARG2          0x00

/* Маски бітів статусного байта (State byte) */
#define AHT20_STATUS_BUSY_MASK          0x80  /* Біт 7: 1 - чип зайнятий вимірюванням, 0 - вимірювання завершено */
#define AHT20_STATUS_CALIBRATED_MASK    0x08  /* Біт 3: 1 - чип відкалібрований, 0 - вимагається виконання ініціалізації */

/* Затримки та тайм-аути у мілісекундах */
#define AHT20_DELAY_POWER_ON_MS         100   /* Час стабілізації живлення при старті */
#define AHT20_DELAY_SOFT_RESET_MS       20    /* Затримка після виконання м'якого скидання */
#define AHT20_DELAY_MEASUREMENT_MS      80    /* Мінімальний час АЦП-перетворення вологості й температури */
#define AHT20_TIMEOUT_BUSY_POLL_MS      200   /* Граничний тайм-аут опитування статусного біта Busy */

/* Константи обчислення контрольної суми CRC-8 */
#define AHT20_CRC8_POLYNOMIAL           0x31  /* Поліном CRC-8 (x^8 + x^5 + x^4 + 1) */
#define AHT20_CRC8_INIT_VAL             0xFF  /* Початкове значення регістру CRC-8 */

/**
 * @brief Коди результатів виконання функцій C-драйвера AHT20.
 */
typedef enum {
    AHT20_OK                   =  0,  /**< Операцію виконано успішно */
    AHT20_ERR_I2C              = -1,  /**< Помилка зв'язку або транзакції на шині I2C */
    AHT20_ERR_TIMEOUT          = -2,  /**< Перевищено граничний час очікування готовності (Busy bit) */
    AHT20_ERR_NOT_CALIBRATED   = -3,  /**< Давач не відкалібрований (біт калібрування 0x08 дорівнює 0) */
    AHT20_ERR_CRC              = -4,  /**< Невідповідність контрольної суми CRC-8 у прийшлому пакеті */
    AHT20_ERR_INVALID_PARAM    = -5   /**< Передано недопустимий аргумент або NULL-вказівник */
} aht20_err_t;

/**
 * @brief Структура для збереження результатів вимірювання AHT20.
 */
typedef struct {
    float humidity_rh;     /**< Розрахована відносна вологість (% RH) */
    float temperature_c;   /**< Розрахована температура у градусах Цельсія (°C) */
    uint32_t raw_humidity; /**< Сире 20-бітне значення АЦП вологості */
    uint32_t raw_temp;     /**< Сире 20-бітне значення АЦП температури */
    bool crc_ok;           /**< Ознака цілісності даних (true — CRC-8 успішно пройшов перевірку) */
} aht20_data_t;

/**
 * @brief Контекст дескриптора давача AHT20.
 */
typedef struct {
    const i2c_bus_t *i2c;  /**< Вказівник на абстракцію шинного інтерфейсу I2C */
    uint8_t i2c_addr;      /**< 7-бітна адреса пристрою на шині I2C */
    bool is_initialized;   /**< Прапорець успішної ініціалізації чипа */
} aht20_t;

/* --- Прототипи функцій C-драйвера AHT20 --- */

/**
 * @brief Ініціалізація C-драйвера AHT20 та перевірка стану калібрування чипа.
 * @param dev Вказівник на дескриптор пристрою.
 * @param i2c Вказівник на структуру апаратного шинного інтерфейсу I2C.
 * @return AHT20_OK у разі успіху або код помилки.
 */
aht20_err_t aht20_init(aht20_t *dev, const i2c_bus_t *i2c);

/**
 * @brief Виконання м'якого скидання давача (Soft Reset).
 * @param dev Вказівник на дескриптор пристрою.
 * @return AHT20_OK при успішному надсиланні команди 0xBA.
 */
aht20_err_t aht20_soft_reset(aht20_t *dev);

/**
 * @brief Надсилання команди тригера вимірювання (0xAC 0x33 0x00).
 * @param dev Вказівник на дескриптор пристрою.
 * @return AHT20_OK у разі успішного запису команди в I2C.
 */
aht20_err_t aht20_start_measurement(aht20_t *dev);

/**
 * @brief Зчитування статусного байта та перевірка прапорця Busy (біт 7).
 * @param dev Вказівник на дескриптор пристрою.
 * @param is_busy Вказівник для збереження статусу (true — триває АЦП-перетворення).
 * @return AHT20_OK у разі успішного зчитування.
 */
aht20_err_t aht20_is_busy(aht20_t *dev, bool *is_busy);

/**
 * @brief Обчислення контрольної суми CRC-8 за поліномом 0x31 (ініціалізація 0xFF).
 * @param data Вказівник на буфер даних.
 * @param len Кількість байтів для розрахунку.
 * @return Обчислений 8-бітний значення CRC.
 */
uint8_t aht20_calc_crc8(const uint8_t *data, size_t len);

/**
 * @brief Повний вимірювальний цикл: запуск, опитування готовності, зчитування 7 байтів, перевірка CRC-8 та розпакування показань.
 * @param dev Вказівник на дескриптор пристрою.
 * @param data Вказівник на структуру результатів вимірювання.
 * @return AHT20_OK при успішному зчитуванні та валідному CRC-8.
 */
aht20_err_t aht20_read_data(aht20_t *dev, aht20_data_t *data);

/**
 * @brief Отримання текстового опису коду помилки українською мовою.
 * @param err Код помилки AHT20.
 * @return Рядок із описом помилки.
 */
const char* aht20_err_to_string(aht20_err_t err);

#endif /* AHT20_H */
