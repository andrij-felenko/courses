#ifndef I2C_BUS_H
#define I2C_BUS_H

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

/**
 * @file i2c_bus.h
 * @brief Оголошення низькорівневої абстракції апаратного шинного інтерфейсу I2C.
 * 
 * Надає єдиний прототип для виконання шинних транзакцій запису та зчитування
 * буферів даних, затримок мікроконтролера та вимірювання системного часу.
 */

/**
 * @brief Коди статусу виконання транзакцій шини I2C.
 */
typedef enum {
    I2C_SUCCESS       =  0,  /**< Транзакція пройшла успішно */
    I2C_ERR_NACK      = -1,  /**< Пристрій відповів NACK (відсутній на шині) */
    I2C_ERR_BUS_BUSY  = -2,  /**< Шина I2C у стані розриву або заблокована */
    I2C_ERR_TIMEOUT   = -3,  /**< Перевищено тайм-аут очікування сигналу ACK/STOP */
    I2C_ERR_PARAM     = -4   /**< Некоректний параметр виклику I2C */
} i2c_status_t;

/**
 * @brief Структура функціональних вказівників апаратної абстракції I2C.
 */
typedef struct {
    /**
     * @brief Передача командної послідовності або буфера байтів на I2C.
     * @param addr 7-бітна адреса пристрою.
     * @param data Вказівник на масив даних для відправлення.
     * @param len Кількість байтів для передачі.
     * @return I2C_SUCCESS у разі успіху або код помилки.
     */
    i2c_status_t (*write)(uint8_t addr, const uint8_t *data, size_t len);

    /**
     * @brief Зчитування буфера даних від веденого пристрою I2C.
     * @param addr 7-бітна адреса пристрою.
     * @param data Вказівник на буфер для збереження прочитаних даних.
     * @param len Кількість байтів для читання.
     * @return I2C_SUCCESS у разі успіху або код помилки.
     */
    i2c_status_t (*read)(uint8_t addr, uint8_t *data, size_t len);

    /**
     * @brief Затримка виконання поточного потоку в мілісекундах.
     * @param ms Час затримки в мс.
     */
    void (*delay_ms)(uint32_t ms);

    /**
     * @brief Отримання поточного значення системного лічильника часу в мс.
     * @return Системні мілісекунди (тіки).
     */
    uint32_t (*get_ticks_ms)(void);
} i2c_bus_t;

#endif /* I2C_BUS_H */
