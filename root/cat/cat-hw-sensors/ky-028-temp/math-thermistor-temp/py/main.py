from math import log

# паспортні сталі термістора
R0 = 10000.0    # опір за опорної температури, Ом
T0 = 298.15     # опорна температура, КЕЛЬВІНИ (25 °C)
B  = 3950.0     # стала Бета, K

# температура (°C) з виміряного опору термістора (Ом)
def temp_from_resistance(R):
    inv_t = 1.0 / T0 + (1.0 / B) * log(R / R0)   # 1/T у 1/K
    t_k   = 1.0 / inv_t                          # назад у кельвіни
    return t_k - 273.15                          # у °C
