// Z -> Y оберненням матриці 2×2: Y = Z⁻¹.
// Повертає об'єкт Y при успіху, null якщо матриця вироджена (det ≈ 0).
function zToY(z) {
    const det = z.z11 * z.z22 - z.z12 * z.z21;   // ΔZ — визначник
    if (Math.abs(det) < 1e-12) return null;      // вироджена: Y не існує
    return {
        y11:  z.z22 / det,     // діагональ міняється місцями!
        y12: -z.z12 / det,
        y21: -z.z21 / det,
        y22:  z.z11 / det,
    };
}
// Приклад: Z = {60, 40, 40, 80} Ом (взаємна, бо z12=z21).
//   det = 60·80 − 40·40 = 4800 − 1600 = 3200
//   y11 = 80/3200 = 0.025 См;  y22 = 60/3200 = 0.01875 См
//   y12 = y21 = −40/3200 = −0.0125 См   ← взаємність збереглася: Y₁₂ = Y₂₁
