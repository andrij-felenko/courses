// Один такт sigma-delta модулятора першого порядку.
// level — потрібний середній рівень 0..255 (8 розрядів роздільності).
// Повертає 1, якщо вихід на цей такт треба ввімкнути, інакше 0.
static uint16_t acc;                 // акумулятор похибки, ширший за рівень

uint8_t sd_tick(uint8_t level) {
    acc += level;                    // накопичуємо «борг»
    if (acc >= 256) {                // переповнення через повну шкалу?
        acc -= 256;                  // лишаємо тільки залишок-«здачу»
        return 1;                    // видали порцію: вихід ON цей такт
    }
    return 0;                        // ще не набралося: вихід OFF
}
