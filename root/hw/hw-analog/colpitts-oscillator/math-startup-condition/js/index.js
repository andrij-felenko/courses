// Перевірка умови самозбудження Колпітца й запас над порогом.
// Вхід: котушка L (Гн), ємності C1,C2 (Ф), добротність контуру Q,
//       робочий струм транзистора Ic (А).
// Друкує gm·Rp, поріг C2/C1 і кратність запасу.
function colpittsStartup(L, C1, C2, Q, Ic) {
    const VT = 0.026;                  // тепловий потенціал, ~26 мВ

    const Cs  = (C1 * C2) / (C1 + C2); // послідовна ємність контуру
    const w0  = 1.0 / Math.sqrt(L * Cs); // кутова частота резонансу
    const XL  = w0 * L;                // реактивний опір котушки
    const Rp  = Q * XL;                // паралельний опір втрат контуру

    const gm  = Ic / VT;               // крутість у робочій точці
    const lhs = gm * Rp;               // підсилення активної частини
    const rhs = C2 / C1;               // плата за дільник (поріг)

    console.log(`f0    = ${(w0 / (2.0 * Math.PI) / 1e6).toFixed(2)} МГц`);
    console.log(`Rp    = ${Rp.toFixed(0)} Ом,  gm = ${(1000.0 * gm).toFixed(0)} мА/В`);
    console.log(`gm*Rp = ${lhs.toFixed(1)}   проти порога C2/C1 = ${rhs.toFixed(2)}`);
    console.log(`запас = x${(lhs / rhs).toFixed(1)}  ->  ` +
                `${lhs > rhs ? "ЗАВЕДЕТЬСЯ" : "НЕ ЗАВЕДЕТЬСЯ"}`);
}

// L=1 мкГн, C1=C2=1 нФ, Q=80, Ic=2 мА  (контур на ~7 МГц)
colpittsStartup(1e-6, 1000e-12, 1000e-12, 80.0, 2.0e-3);
