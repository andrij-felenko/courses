package main

import (
	"fmt"
	"math"
)

// Перевірка умови самозбудження Колпітца й запас над порогом.
// Вхід: котушка L (Гн), ємності C1,C2 (Ф), добротність контуру Q,
//       робочий струм транзистора Ic (А).
// Друкує gm·Rp, поріг C2/C1 і кратність запасу.
func colpittsStartup(L, C1, C2, Q, Ic float64) {
	const VT = 0.026 // тепловий потенціал, ~26 мВ

	Cs := (C1 * C2) / (C1 + C2) // послідовна ємність контуру
	w0 := 1.0 / math.Sqrt(L*Cs) // кутова частота резонансу
	XL := w0 * L                // реактивний опір котушки
	Rp := Q * XL                // паралельний опір втрат контуру

	gm := Ic / VT // крутість у робочій точці
	lhs := gm * Rp // підсилення активної частини
	rhs := C2 / C1 // плата за дільник (поріг)

	verdict := "НЕ ЗАВЕДЕТЬСЯ"
	if lhs > rhs {
		verdict = "ЗАВЕДЕТЬСЯ"
	}
	fmt.Printf("f0    = %.2f МГц\n", w0/(2.0*math.Pi)/1e6)
	fmt.Printf("Rp    = %.0f Ом,  gm = %.0f мА/В\n", Rp, 1000.0*gm)
	fmt.Printf("gm*Rp = %.1f   проти порога C2/C1 = %.2f\n", lhs, rhs)
	fmt.Printf("запас = x%.1f  ->  %s\n", lhs/rhs, verdict)
}

func main() {
	// L=1 мкГн, C1=C2=1 нФ, Q=80, Ic=2 мА  (контур на ~7 МГц)
	colpittsStartup(1e-6, 1000e-12, 1000e-12, 80.0, 2.0e-3)
}
