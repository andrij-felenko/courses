# Перетворення відліку звуку (−1..+1) на ширину імпульсу ШІМ.
# duty = 0.5 відповідає сигналу 0 (тиша = меандр 50%).
def sample_to_pwm(sample: float, period: int) -> int:
    duty = 0.5 + 0.5 * sample          # −1→0.0, 0→0.5, +1→1.0
    duty = min(1.0, max(0.0, duty))    # захист від виходу за межі
    return int(duty * period + 0.5)    # ширина в кроках таймера

