# Контурний метод матрицею для схеми з ДВОХ вікон: R·I = V за правилом Крамера.
# R — матриця опорів 2×2 (Ом), V — стовпець джерел (В).
# Повертає струми (А) або None, якщо система вироджена.
def mesh_solve_cramer(R, V):
    D = R[0][0]*R[1][1] - R[0][1]*R[1][0]        # визначник матриці опорів
    if D == 0.0:                                  # D=0 → єдиного розв'язку нема
        return None
    # чисельники: стовпець V замість 1-го та 2-го стовпця матриці
    i1 = (V[0]*R[1][1] - R[0][1]*V[1]) / D         # I₁
    i2 = (R[0][0]*V[1] - V[0]*R[1][0]) / D         # I₂
    return i1, i2

# Приклад: R = [[3000,-2000],[-2000,3000]], V = [12,0]
#          -> (0.0072, 0.0048), тобто 7.2 мА і 4.8 мА
