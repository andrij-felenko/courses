// Контурний метод матрицею для схеми з ДВОХ вікон: R·I = V за правилом Крамера.
// R[2][2] — матриця опорів (Ом), V[2] — стовпець джерел (В).
// Повертає 1 і кладе струми (А) у out[2]; повертає 0, якщо система вироджена.
int mesh_solve_cramer(const float R[2][2], const float V[2], float out[2])
{
    float D = R[0][0]*R[1][1] - R[0][1]*R[1][0];   // визначник матриці опорів
    if (D == 0.0f)                                  // D=0 → єдиного розв'язку нема
        return 0;
    // чисельники: стовпець V замість 1-го та 2-го стовпця матриці
    out[0] = (V[0]*R[1][1] - R[0][1]*V[1]) / D;     // I₁
    out[1] = (R[0][0]*V[1] - V[0]*R[1][0]) / D;     // I₂
    return 1;
}
// Приклад: R = {{3000,-2000},{-2000,3000}}, V = {12,0}
//          -> out = {0.0072, 0.0048}, тобто 7.2 мА і 4.8 мА
