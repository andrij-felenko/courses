import numpy as np

# Контурний метод для схеми з двох вікон зі спільним резистором.
# Повертає контурні струми (i1, i2) в амперах.
# Система:  (R1+R2)*i1 -  R2*i2 = V1
#           -R2*i1 + (R2+R3)*i2 = V2
def mesh_solve_2(V1, V2, R1, R2, R3):
    A = np.array([[R1 + R2,   -R2   ],   # матриця коефіцієнтів
                  [  -R2,   R2 + R3 ]])  # (симетрична)
    b = np.array([V1, V2])               # права частина — джерела
    i1, i2 = np.linalg.solve(A, b)       # розв'язок системи 2×2
    return i1, i2

# mesh_solve_2(10, 6, 100, 200, 100) -> (0.084, 0.076)
# струм крізь спільний R2 = i1 - i2 ≈ 0.008 А
