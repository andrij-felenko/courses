// Контурний метод для схеми з двох вікон зі спільним резистором.
// Повертає контурні струми i1, i2 (ампери) через вихідні параметри.
// Система:  (R1+R2)*i1 -  R2*i2 = V1
//           -R2*i1 + (R2+R3)*i2 = V2
void mesh_solve_2(float V1, float V2,
                  float R1, float R2, float R3,
                  float *i1, float *i2)
{
    float a11 =  R1 + R2,  a12 = -R2;     // коефіцієнти першого рівняння
    float a21 = -R2,       a22 =  R2 + R3; // коефіцієнти другого
    float det = a11 * a22 - a12 * a21;     // визначник системи
    *i1 = (V1 * a22 - a12 * V2) / det;     // правило Крамера
    *i2 = (a11 * V2 - V1 * a21) / det;
}
