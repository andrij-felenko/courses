// CheckLimits перевіряє робочі межі двовивідного джерела на JFET.
// Повертає 0, якщо все в межах; інакше — код порушеної межі.
//
//	uDs   — напруга на двополюснику, В
//	iD    — робочий струм, А
//	vKnee — напруга коліна V_K, В
//	pov   — гранична робоча напруга (пробій), В
//	pMax  — дозволена потужність корпусу, Вт
func CheckLimits(uDs, iD, vKnee, pov, pMax float64) int {
	if uDs < vKnee {
		return 1 // замало напруги — струм провалиться
	}
	if uDs > pov {
		return 2 // пробій — регулювання зникає
	}
	if uDs*iD > pMax {
		return 3 // перегрів — потужність завелика
	}
	return 0 // у вікні піддатливості, все гаразд
}
