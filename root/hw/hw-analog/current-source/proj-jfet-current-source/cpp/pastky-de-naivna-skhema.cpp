// Перевірка робочих меж двовивідного джерела на JFET.
// Повертає 0, якщо все в межах; інакше — код порушеної межі.
int checkLimits(float uDs,       // напруга на двополюснику, В
                float iD,        // робочий струм, А
                float vKnee,     // напруга коліна V_K, В
                float pov,       // гранична робоча напруга (пробій), В
                float pMax)      // дозволена потужність корпусу, Вт
{
    if (uDs < vKnee)      return 1;  // замало напруги — струм провалиться
    if (uDs > pov)        return 2;  // пробій — регулювання зникає
    if (uDs * iD > pMax)  return 3;  // перегрів — потужність завелика
    return 0;                        // у вікні піддатливості, все гаразд
}
