def check_limits(u_ds: float,    # напруга на двополюснику, В
                 i_d: float,     # робочий струм, А
                 v_knee: float,  # напруга коліна V_K, В
                 pov: float,     # гранична робоча напруга (пробій), В
                 p_max: float) -> int:  # дозволена потужність корпусу, Вт
    """Перевірка робочих меж двовивідного джерела на JFET.
    Повертає 0, якщо все в межах; інакше — код порушеної межі."""
    if u_ds < v_knee:       return 1  # замало напруги — струм провалиться
    if u_ds > pov:          return 2  # пробій — регулювання зникає
    if u_ds * i_d > p_max:  return 3  # перегрів — потужність завелика
    return 0                          # у вікні піддатливості, все гаразд
