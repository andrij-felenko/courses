# Реальний максимальний симетричний розмах каскаду зі спільним емітером.
# Q поставлено посередині СТАЛОЇ прямої; рахуємо, що дасть СИГНАЛЬНА.

Vsupply = 12.0    # напруга живлення, В
Rc      = 1000.0  # колекторний резистор, Ом
Rload   = 1000.0  # навантаження через конденсатор, Ом

# Q посередині сталої прямої:
Vceq = 6.0                     # напруга спокою, В
Icq  = (Vsupply - Vceq) / Rc   # струм спокою, А → 6 мА

# Сигнальний (AC) опір — R_к паралельно R_навант:
r_ac = (Rc * Rload) / (Rc + Rload)   # 500 Ом

# Два плеча розмаху по сигнальній прямій:
swing_left  = Vceq          # транзистор у насичення
swing_right = Icq * r_ac    # транзистор у відсічку

# Симетричний пік — менше з плечей:
swing_ac = min(swing_left, swing_right)

# Оманливе число — розмах, прикинутий по сталій прямій:
swing_dc_naive = Icq * Rc   # = Vceq = 6 В (симетрично по DC)

print(f"r_ac (R_к || R_навант) = {r_ac:.0f} Ом")          # 500
print(f"плече вліво  (насичення) = {swing_left:.2f} В")    # 6.00
print(f"плече вправо (відсічка)  = {swing_right:.2f} В")   # 3.00
print(f"РЕАЛЬНИЙ симетричний пік = {swing_ac:.2f} В")      # 3.00
print(f"оманливий розмах по DC   = {swing_dc_naive:.2f} В")# 6.00
