// теплова напруга при кімнатній температурі (~25 °C)
const float U_T = 0.026f;   // 26 мВ

float r_diff(float I) {     // диференційний опір ідеального діода
    return U_T / I;         // Ом, якщо I в амперах
}

// режим 1: робочий струм 1 мА
float r1 = r_diff(0.001f);  //  = 0.026 / 0.001  = 26 Ом
// режим 2: робочий струм 10 мА
float r2 = r_diff(0.010f);  //  = 0.026 / 0.010  = 2.6 Ом
