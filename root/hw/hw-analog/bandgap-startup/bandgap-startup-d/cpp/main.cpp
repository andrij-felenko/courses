// Старт системи: не вірити АЦП, поки не доведено, що опора піднялась.
// Міряємо вузол із ВІДОМОЮ часткою живлення (тут — рівно половина,
// заданий точним дільником) і перевіряємо, що результат правдоподібний.
static bool reference_is_alive(void)
{
    const uint16_t full = adc_read(CH_VREF_HALF);   // має бути ≈ половина шкали
    // Якщо опора мертва (≈0 В), будь-який вхід читається як майже повна шкала
    // або як шум коло нуля — у будь-якому разі НЕ біля середини.
    return (full > (ADC_FULL_SCALE * 7 / 16)) &&    // не надто низько
           (full < (ADC_FULL_SCALE * 9 / 16));      // не надто високо
}

void system_bringup(void)
{
    adc_init();
    // Дати джерелу час прокинутись (типово десятки–сотні мкс після живлення).
    delay_us(500);
    if (!reference_is_alive()) {
        // Опора не піднялась: НЕ виходити в робочий режим зі сліпими вимірами.
        fault_latch(FAULT_VREF_DEAD);   // зафіксувати й, напр., перезавантажитись
        return;
    }
    enter_normal_mode();
}
