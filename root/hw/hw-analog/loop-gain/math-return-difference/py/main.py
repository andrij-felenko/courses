# Усі чотири дари зворотного зв'язку з єдиного T = A·β.
# Вхід: голе A, зворотна частка β і голі параметри каскаду.
# Вихід: замкнене підсилення, вихідний/вхідний опір, фактор лінеаризації.

def feedback_gains(A, beta, Ro_open, Rd_open, thd_open):
    T = A * beta          # підсилення в контурі
    F = 1.0 + T           # різниця повернення — ЄДИНИЙ важіль

    Gclosed = A / F           # замкнене підсилення → прямує до 1/β
    Gideal  = 1.0 / beta      # ідеал 1/β
    Rout    = Ro_open / F     # вихідний опір ділиться на F
    Rin     = Rd_open * F     # вхідний опір множиться на F
    thd     = thd_open / F    # спотворення діляться на F

    print(f"T = {T:.0f},  F = 1+T = {F:.0f}")
    print(f"підсилення: {Gclosed:.4f}  (ідеал 1/β = {Gideal:.4f}, "
          f"похибка {100.0 * (Gideal - Gclosed) / Gideal:.4f}%)")
    print(f"вих. опір:  {Rout:.4g} Ом  (з {Ro_open:.0f} Ом, ÷{F:.0f})")
    print(f"вх. опір:   {Rin:.4g} Ом  (з {Rd_open:.0f} Ом, ×{F:.0f})")
    print(f"спотвор.:   {100.0 * thd:.4g} %  (з {100.0 * thd_open:.2f} %, ÷{F:.0f})")


# A = 100000, β = 0.1 (ціль ×10); голий каскад: Ro=75 Ом, Rd=1 МОм, THD=2%
feedback_gains(100000.0, 0.1, 75.0, 1.0e6, 0.02)
