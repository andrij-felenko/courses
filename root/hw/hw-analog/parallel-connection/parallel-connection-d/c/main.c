// Паралельне коло: R_екв через суму провідностей, тоді струм кожної гілки
float V = 12.0f;                      // спільна напруга, В
float R1 = 6, R2 = 3, R3 = 2;         // опори гілок, Ω

float Geq = 1/R1 + 1/R2 + 1/R3;       // сума провідностей = 1.0 См
float Req = 1.0f / Geq;               // = 1.0 Ω   (менший за 2 Ω!)
float I1  = V / R1;                    // = 2 А
float I2  = V / R2;                    // = 4 А
float I3  = V / R3;                    // = 6 А
float I   = I1 + I2 + I3;              // = 12 А
// перевірка KCL: I == V/Req = 12/1 = 12 А  ✓
