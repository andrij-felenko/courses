// Груповий час із масиву виміряних фаз phi[k] на сітці частот із кроком df (Гц).
// phi — у радіанах; результат tau[k] — у секундах. N точок.
// τг = −dφ/dω = −(Δφ) / (2π·Δf)  — центральна різниця між сусідами.
void group_delay_from_phase(const float *phi, int N, float df, float *tau)
{
    const float two_pi_df = 2.0f * 3.14159265f * df;
    for (int k = 1; k < N - 1; ++k) {
        float dphi = phi[k + 1] - phi[k - 1];   // різниця через дві точки (апертура 2·df)
        // розгортання стрибка ±2π, якщо фаза «перескочила» межу:
        if (dphi >  3.14159265f) dphi -= 2.0f * 3.14159265f;
        if (dphi < -3.14159265f) dphi += 2.0f * 3.14159265f;
        tau[k] = -dphi / (2.0f * two_pi_df);    // ділимо на 2·(2π·df): центральна різниця
    }
    tau[0] = tau[1];                            // краї — копією сусіда
    tau[N - 1] = tau[N - 2];
}
