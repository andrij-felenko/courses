#include <cmath>

// Груповий час однополюсного RC-ФНЧ на частоті f.
// fc — частота зрізу (−3 дБ), Гц.  Повертає τг у секундах.
float rc_group_delay(float f, float fc)
{
    float r  = f / fc;                 // нормована частота ω/ωc
    float wc = 2.0f * 3.14159265f * fc;
    return (1.0f / wc) / (1.0f + r * r);   // τг = (1/ωc) / (1 + (ω/ωc)²)
}

// На частоті зрізу f = fc = 1000 Гц:
//   r  = 1
//   wc = 6283.2 рад/с
//   τг = (1 / 6283.2) / (1 + 1) = 1.5915e-4 / 2 = 7.96e-5 с ≈ 79.6 мкс
