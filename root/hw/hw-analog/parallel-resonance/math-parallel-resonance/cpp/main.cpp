#include <cmath>

double L = 100e-6;     // 100 мкГн
double C = 250e-12;    // 250 пФ
double R = 5.0;        // опір обмотки

// 1) точна резонансна частота: w0^2 = 1/(LC) - R^2/L^2
double a  = 1.0/(L*C);            // 4.000e13  — головний член
double b  = (R*R)/(L*L);          // 2.500e9   — поправка від втрат
double w0 = std::sqrt(a - b);     // ≈ 6.3244e6 рад/с
double f0 = w0/(2*M_PI);          // ≈ 1.0066 МГц

// 2) добротність — через характеристичний опір rho = sqrt(L/C)
double rho = std::sqrt(L/C);      // rho = √(L/C) ≈ 632.46 Ом
double Q   = rho/R;               // 632.46/5 ≈ 126.5

// 3) динамічний опір — трьома еквівалентними дорогами, збігаються точно
double Rd_1 = L/(C*R);            // 100e-6 / (250e-12 * 5) = 80 000 Ом
double Rd_2 = Q*Q*R;              // Q^2*R = rho^2/R = 80 000 Ом
double Rd_3 = (R*R + w0*w0*L*L)/R;// (R^2 + w0^2 L^2)/R — пряме 1/G, теж 80 000 Ом
