// Опитати N каналів мультиплексора одним ADC
for (uint8_t i = 0; i < N; i++) {
    uint8_t ch = scan_order[i];           // див. нижче про порядок
    gpio_write(A0, (ch >> 0) & 1);        // виставити адресу:
    gpio_write(A1, (ch >> 1) & 1);        //   три молодші біти номера каналу
    gpio_write(A2, (ch >> 2) & 1);        //   лягають на A0…A2
    delay_us(t_settle);                   // головна пауза: вихід MUX має «сісти»
    values[ch] = adc_read();              // власне перетворення
}

