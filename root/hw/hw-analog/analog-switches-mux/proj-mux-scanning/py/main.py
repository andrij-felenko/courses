# Опитати N каналів мультиплексора одним ADC
for ch in scan_order:                     # див. нижче про порядок
    gpio_write(A0, (ch >> 0) & 1)         # виставити адресу:
    gpio_write(A1, (ch >> 1) & 1)         #   три молодші біти номера каналу
    gpio_write(A2, (ch >> 2) & 1)         #   лягають на A0…A2
    sleep_us(t_settle)                    # головна пауза: вихід MUX має «сісти»
    values[ch] = adc_read()               # власне перетворення

# Скільки чекати: t_settle = k·τ,  τ ≈ (Rₒₙ + R_джерела)·C_вузла
# k обираємо за потрібною точністю в бітах:
#   k ≈ (n+1)·ln 2     →   8 біт ≈ 6.2·τ,   10 біт ≈ 7.6·τ,   12 біт ≈ 9.0·τ
