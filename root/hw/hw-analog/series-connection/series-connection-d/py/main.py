# Послідовне коло: спершу R_екв, тоді спільний струм, тоді спади
V = 12.0                               # напруга джерела, В
R1, R2, R3 = 100, 220, 330             # опори, Ω

Req = R1 + R2 + R3                     # = 650 Ω
I = V / Req                            # = 0.01846 А ≈ 18.5 мА  (струм спільний)
V1 = I * R1                            # ≈ 1.85 В
V2 = I * R2                            # ≈ 4.07 В
V3 = I * R3                            # ≈ 6.08 В
# перевірка KVL: V1 + V2 + V3 = 1.85 + 4.07 + 6.08 ≈ 12.0 В  ✓
