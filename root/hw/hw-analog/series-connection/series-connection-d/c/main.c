// Послідовне коло: спершу R_екв, тоді спільний струм, тоді спади
float V = 12.0f;                       // напруга джерела, В
float R1 = 100, R2 = 220, R3 = 330;    // опори, Ω

float Req = R1 + R2 + R3;              // = 650 Ω
float I   = V / Req;                   // = 0.01846 А ≈ 18.5 мА  (струм спільний)
float V1  = I * R1;                    // ≈ 1.85 В
float V2  = I * R2;                    // ≈ 4.07 В
float V3  = I * R3;                    // ≈ 6.08 В
// перевірка KVL: V1 + V2 + V3 = 1.85 + 4.07 + 6.08 ≈ 12.0 В  ✓
