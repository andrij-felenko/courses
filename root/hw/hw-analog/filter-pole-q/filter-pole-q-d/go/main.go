package filter

import "math"

// SallenKeyQ — добротність полюсів ланки Саллена–Кі (рівні R, коефіцієнт 1) із двох ємностей.
// c1, c2 — у фарадах (одиниці скоротяться, важить лише відношення). Повертає Q.
func SallenKeyQ(c1, c2 float64) float64 {
	return 0.5 * math.Sqrt(c1/c2) // Q = ½·√(C₁/C₂)
}

// Для C₁ = 10 нФ, C₂ = 2.2 нФ:
//   C₁/C₂ = 10 / 2.2 = 4.545
//   √4.545 = 2.132
//   Q = 0.5 · 2.132 = 1.066
