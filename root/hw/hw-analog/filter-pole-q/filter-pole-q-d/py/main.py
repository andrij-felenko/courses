import math

# Добротність полюсів ланки Саллена–Кі (рівні R, коефіцієнт 1) із двох ємностей.
# c1, c2 — у фарадах (одиниці скоротяться, важить лише відношення). Повертає Q.
def sallen_key_q(c1, c2):
    return 0.5 * math.sqrt(c1 / c2)        # Q = ½·√(C₁/C₂)

