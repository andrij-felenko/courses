# Вихідна похибка = (зсув + дрейф·ΔT) · підсилення
gain = 1000.0    # підсилення тракту
dT   = 40.0      # зміна температури, °C

# Звичайний прецизійний ОП
vos_ord   = 150e-6    # зсув 150 мкВ
drift_ord = 1.0e-6    # дрейф 1 мкВ/°C
err_ord = (vos_ord + drift_ord * dT) * gain
# = (150e-6 + 1e-6*40) * 1000 = (150e-6 + 40e-6)*1000 = 0.190 В

# Zero-drift ОП (типу ADA4528)
vos_zd   = 2.5e-6     # зсув 2.5 мкВ
drift_zd = 0.015e-6   # дрейф 0.015 мкВ/°C
err_zd = (vos_zd + drift_zd * dT) * gain
# = (2.5e-6 + 0.015e-6*40) * 1000 = (2.5e-6 + 0.6e-6)*1000 = 0.0031 В
