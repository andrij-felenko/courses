# Вихідна похибка нуля = (Vos + dVos/dT · ΔT) · підсилення
gain = 100.0     # підсилення тракту
dT   = 30.0      # прогрів, °C

# Звичайний прецизійний ОП
vos_ord   = 100e-6    # зсув 100 мкВ
drift_ord = 1.5e-6    # дрейф 1.5 мкВ/°C
err_ord = (vos_ord + drift_ord * dT) * gain
# = (100e-6 + 1.5e-6*30) * 100 = (100e-6 + 45e-6)*100 = 0.0145 В  → 14.5 мВ

# Zero-drift ОП (типові числа класу)
vos_zd   = 5e-6       # зсув 5 мкВ
drift_zd = 0.02e-6    # дрейф 0.02 мкВ/°C = 20 нВ/°C
err_zd = (vos_zd + drift_zd * dT) * gain
# = (5e-6 + 0.02e-6*30) * 100 = (5e-6 + 0.6e-6)*100 = 0.00056 В  → 0.56 мВ
