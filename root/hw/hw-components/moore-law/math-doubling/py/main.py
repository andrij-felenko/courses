import math

# Множник зростання за `years` років при подвоєнні кожні `T` років.
# Серце закону Мура: 2^(t/T). Усе інше — похідні цього рядка.
def moore_factor(years, T):
    return 2.0 ** (years / T)            # 2 у степені (минуло періодів)

# Річний приріст (CAGR) для періоду подвоєння T років: 2^(1/T) − 1.
def moore_cagr(T):
    return 2.0 ** (1.0 / T) - 1.0        # T=2 → √2 − 1 ≈ 0.4142

# Миттєвий (неперервний) темп r для періоду T: ln2 / T.
def moore_rate(T):
    return math.log(2.0) / T            # T=2 → 0.693/2 ≈ 0.347

def main():
    T = 2.0                              # подвоєння щодва роки

    # Три імені одного темпу — переконуємося, що крива одна:
    print(f"CAGR = {moore_cagr(T):.4f} ({100 * moore_cagr(T):.1f}% на рік)")
    print(f"r    = {moore_rate(T):.4f} ({100 * moore_rate(T):.1f}% миттєво)")
    print(f"звірка 1+CAGR проти e^r: {1.0 + moore_cagr(T):.4f} vs "
          f"{math.exp(moore_rate(T)):.4f}")   # мають збігтися

    # Екстраполяція крізь півстоліття від першого мікропроцесора.
    # 1971: Intel 4004 — 2300 транзисторів.
    base = 2300.0
    factor = moore_factor(50.0, T)             # 2^(50/2) = 2^25 ≈ 33.5 млн
    print(f"прогноз на 2021: {base * factor:.3g} транзисторів")  # ≈ 7.7e10

if __name__ == "__main__":
    main()
