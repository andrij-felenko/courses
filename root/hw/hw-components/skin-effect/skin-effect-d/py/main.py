# У скільки разів скін-ефект підіймає опір круглого проводу на частоті f.
# Порівнюємо повний переріз πr² з робочим кільцем завтовшки δ (площа ≈ 2πrδ).
import math

def skin_depth_cu(f):
    """Глибина проникнення для міді, м; f — частота, Гц."""
    rho = 1.68e-8    # питомий опір міді, Ом·м
    mu0 = 1.256637e-6  # магнітна стала (мідь немагнітна), Гн/м
    w = 2.0 * math.pi * f
    return math.sqrt(2.0 * rho / (w * mu0))

r = 5.0e-3            # радіус шини 5 мм
f = 1.0e6             # 1 МГц
d = skin_depth_cu(f)  # глибина проникнення

area_dc = math.pi * r * r      # повний переріз
area_ac = 2.0 * math.pi * r * d  # робоче кільце ≈ окружність × δ
print(f"delta = {d * 1e6:.1f} um")
print(f"R_ac / R_dc ≈ {area_dc / area_ac:.0f}")  # у стільки разів опір вищий
