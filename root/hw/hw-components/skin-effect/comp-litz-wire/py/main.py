# Очікуваний опір ліцендрат-джгута на постійному струмі, Ом/м.
# N жилок увімкнено паралельно -> опір джгута = опір однієї жилки / N.
# Якщо вимір помітно вищий за розрахунок — пропаялися не всі жилки.

N            = 100     # жил у джгуті («100/40»)
r_strand_pm  = 3.5     # опір однієї жилки 40 AWG, Ом/м

r_bundle_pm = r_strand_pm / N          # паралель N жил
print(f"R_dc джгута = {r_bundle_pm:.4f} Om/m")   # ~0.035 Ом/м

# приклад перевірки: намотали 4 м, а зміряли 0.28 Ом замість ~0.14
length, measured = 4.0, 0.28
expected = r_bundle_pm * length
print(f"очікувано {expected:.3f} Om, зміряно {measured:.3f} Om "
      f"-> коеф {measured / expected:.1f}")       # коеф ~2 -> половина жил не в ділі
