// Побудувати таблицю відповідей із "справжньої" функції f(a,b,c).
// Проходимо всі 8 адрес, розкладаємо кожну на біти в ТОМУ Ж порядку (a — старший),
// кладемо результат f у комірку. Тепер lut повністю задає ту саму функцію.
void lut_build3(uint8_t *lut, bool (*f)(bool, bool, bool)) {
    for (uint32_t s = 0; s < 8; ++s) {
        bool a = (s >> 2) & 1;
        bool b = (s >> 1) & 1;
        bool c = (s >> 0) & 1;
        lut[s] = f(a, b, c) ? 1 : 0;
    }
}
