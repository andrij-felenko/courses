// Клітинка FPGA: 3-входова таблиця відповідей + мультиплексор, що її читає.
// Спершу lut заповнюють конфігурацією (bitstream), потім вона рахує задану логіку.
typedef struct {
    uint8_t cell[8];        // 8 бітів конфігурації = вміст таблиці
} lut3_cell_t;

// "Прошити" клітинку 8-бітовою конфігурацією: біт i → відповідь для адреси i.
void lut3_program(lut3_cell_t *c, uint8_t config) {
    for (int i = 0; i < 8; ++i)
        c->cell[i] = (config >> i) & 1;    // розкласти байт конфігурації по комірках
}

// Обчислити: адреса зі змінних → читання таблиці мультиплексором.
bool lut3_eval(const lut3_cell_t *c, bool a, bool b, bool cin) {
    return c->cell[addr3(a, b, cin)] != 0;
}
