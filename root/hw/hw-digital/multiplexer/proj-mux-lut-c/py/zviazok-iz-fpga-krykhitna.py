# Клітинка FPGA: 3-входова таблиця відповідей + мультиплексор, що її читає.
# Спершу lut заповнюють конфігурацією (bitstream), потім вона рахує задану логіку.
class Lut3Cell:
    def __init__(self):
        self.cell = [0] * 8            # 8 бітів конфігурації = вміст таблиці

    # "Прошити" клітинку 8-бітовою конфігурацією: біт i → відповідь для адреси i.
    def program(self, config: int) -> None:
        for i in range(8):
            self.cell[i] = (config >> i) & 1   # розкласти байт конфігурації по комірках

    # Обчислити: адреса зі змінних → читання таблиці мультиплексором.
    def eval(self, a: bool, b: bool, cin: bool) -> bool:
        return self.cell[addr3(a, b, cin)] != 0
