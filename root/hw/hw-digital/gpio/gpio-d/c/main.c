#include <avr/io.h>

int main(void) {
    // --- налаштування ніжок ---
    DDRB |=  (1 << PB5);   // PB5 — вихід (світлодіод)
    DDRB &= ~(1 << PB0);   // PB0 — вхід (кнопка)
    PORTB |= (1 << PB0);   // увімкнути внутрішню підтяжку вгору на PB0

    for (;;) {
        // кнопка на землю: натиснено → на ніжці «0»
        if (!(PINB & (1 << PB0)))
            PORTB |=  (1 << PB5);   // засвітити
        else
            PORTB &= ~(1 << PB5);   // згасити
    }
}
