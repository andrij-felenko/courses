N = 4                            # довжина «регістра»: 4 відводи
line = [0] * N                   # лінія затримки: line[0]=x[n] … line[N-1]=x[n-3]
b = [1, 1, 1, 1]                 # коефіцієнти (тут — просте середнє)

# Один такт: зсунули історію, завели новий відлік, порахували вихід.
def fir_step(sample: int) -> int:
    for k in range(N - 1, 0, -1):    # зсув: усе на щабель «у минуле»
        line[k] = line[k - 1]
    line[0] = sample                 # новий відлік x[n] — у перший відвід

    acc = 0
    for k in range(N):               # y[n] = Σ b[k]·x[n-k]
        acc += b[k] * line[k]
    return acc // N                  # ділення на суму ваг (4) — нормування
