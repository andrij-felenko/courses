# Плавний профіль ваг (трикутник): менше «дзвону», ніж у рівного середнього.
B = (1, 2, 3, 2, 1)
N = len(B)
GAIN = sum(B)                      # сума ваг = 9 → нормування

line = [0] * N                     # лінія затримки: line[0]=x[n] … line[N-1]=x[n-4]

def fir_step(sample):
    """Один такт FIR: зсунути історію, завести відлік, порахувати зважену суму."""
    for k in range(N - 1, 0, -1):  # зсув «у минуле» — це фронт такту
        line[k] = line[k - 1]
    line[0] = sample               # новий відлік у перший відвід

    acc = 0                        # у Python ціле не переповнюється — розрядності досить
    for k in range(N):             # y[n] = Σ b[k]·x[n-k]
        acc += B[k] * line[k]

    return acc // GAIN             # ділення на суму ваг — щоб рівень не поплив
