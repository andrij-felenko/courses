# Прикидка вихідної частоти каскаду декад у прошивці-помічнику

def main():
    f_clk  = 32768.0     # вхідний такт, Гц (годинниковий кварц)
    stages = 3           # скільки декад у каскаді (кожна ділить на 10)
    f_out  = f_clk
    for _ in range(stages):
        f_out /= 10.0    # кожен CO → CLK наступного = ще одне ÷10
    print(f"після {stages} декад: {f_out:.4f} Hz")  # 32.7680 Hz

main()
