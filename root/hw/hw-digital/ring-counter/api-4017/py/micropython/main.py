from machine import Pin
import time

# Ніжки контролера, з'єднані з лічильником:
clk = Pin(6, Pin.OUT)   # → CLK (крок по фронту 0→1)
mr  = Pin(7, Pin.OUT)   # → MR  (скид у Q0; 1 = скинути)

def chaser_init():
    # Скид на старті: коротким MR=1 гарантовано ставимо лічильник у Q0.
    # Це прибирає ризик стартувати з невизначеного стану (див. «граблі»).
    mr.value(1)
    mr.value(0)           # відпустили скид — тепер рахуємо від Q0
    clk.value(0)          # такт у низькому, чекає на фронт

def chaser_step():
    # Один крок вогника: даємо рівно один фронт 0→1 на CLK.
    clk.value(1)          # фронт наростання — лічильник крокує на наступний вихід
    clk.value(0)          # повертаємо CLK у низький, готуючи наступний фронт

chaser_init()
while True:
    chaser_step()         # активний вихід перескочив на сусідній Qn
    time.sleep_ms(100)    # темп вогника: 10 кроків/с → повне коло за ~1 с
