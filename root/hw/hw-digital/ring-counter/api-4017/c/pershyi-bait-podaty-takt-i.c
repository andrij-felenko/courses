#include <stdint.h>

// Ніжки контролера, з'єднані з лічильником:
#define PIN_CLK  6    // → CLK (крок по фронту 0→1)
#define PIN_MR   7    // → MR  (скид у Q0; 1 = скинути)

// pinWrite/delayMs — обгортки вашого HAL/Arduino; замініть на свої.

void chaser_init(void) {
    // Скид на старті: коротким MR=1 гарантовано ставимо лічильник у Q0.
    // Це прибирає ризик стартувати з невизначеного стану (див. «граблі»).
    pinWrite(PIN_MR, 1);
    pinWrite(PIN_MR, 0);      // відпустили скид — тепер рахуємо від Q0
    pinWrite(PIN_CLK, 0);     // такт у низькому, чекає на фронт
}

// Один крок вогника: даємо рівно один фронт 0→1 на CLK.
void chaser_step(void) {
    pinWrite(PIN_CLK, 1);     // фронт наростання — лічильник крокує на наступний вихід
    pinWrite(PIN_CLK, 0);     // повертаємо CLK у низький, готуючи наступний фронт
}

int main(void) {
    chaser_init();
    for (;;) {
        chaser_step();        // активний вихід перескочив на сусідній Qn
        delayMs(100);         // темп вогника: 10 кроків/с → повне коло за ~1 с
    }
}
