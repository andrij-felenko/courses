// Прикидка вихідної частоти каскаду декад у прошивці-помічнику
package main

import "fmt"

func main() {
	fClk := 32768.0 // вхідний такт, Гц (годинниковий кварц)
	stages := 3     // скільки декад у каскаді (кожна ділить на 10)
	fOut := fClk
	for i := 0; i < stages; i++ {
		fOut /= 10.0 // кожен CO → CLK наступного = ще одне ÷10
	}
	fmt.Printf("після %d декад: %.4f Hz\n", stages, fOut) // 32.7680 Hz
}
