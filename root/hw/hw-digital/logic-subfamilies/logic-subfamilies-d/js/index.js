// Скільки HC-входів витримає один HC-вихід за заданого фронту.
// Дано: вихідний струм HC  Ioh ≈ 4 мА (гарантований під навантаженням)
//       ємність одного входу  Cin ≈ 5 пФ
//       ємність доріжки       Ctrace ≈ 15 пФ
//       бажаний час фронту     t_rise ≈ 10 нс на розмах ΔV = 3.3 В
//
// Заряд ємності струмом:  I = C · ΔV / t  →  C_max = I · t / ΔV
//   C_max = 4e-3 · 10e-9 / 3.3 = 12.1 пФ  (доступно на весь фронт)
//
// Це МЕНШЕ, ніж уже «з'їдає» доріжка (15 пФ) — тобто на 10 нс
// фронту й один вхід не влазить: або беремо швидший/сильніший
// вихід (AHC, LVC — 8…24 мА), або дозволяємо повільніший фронт.
//
// Дозволимо t_rise = 30 нс:  C_max = 4e-3 · 30e-9 / 3.3 = 36.4 пФ
//   лишок під входи = 36.4 − 15 (доріжка) = 21.4 пФ
//   входів = 21.4 / 5 ≈ 4 входи

const I_OH = 4.0e-3;    // А, сила виходу HC
const V_SW = 3.3;       // В, розмах
const C_IN = 5.0e-12;   // Ф, один вхід
const C_TR = 15.0e-12;  // Ф, доріжка

function hcFanout(tRiseS) {
    const cMax = I_OH * tRiseS / V_SW;      // скільки ємності встигаємо
    const cForInputs = cMax - C_TR;         // за відрахуванням доріжки
    if (cForInputs <= 0) return 0;          // навіть доріжка не влазить
    return Math.trunc(cForInputs / C_IN);   // цілих входів
}
