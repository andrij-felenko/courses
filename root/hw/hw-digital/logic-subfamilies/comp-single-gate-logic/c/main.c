// «Перший байт»: одновентильний буфер 1G як розв'язка сигналу.
// Приклад: строб від зовнішнього джерела заводимо на вхід МК
// ЧЕРЕЗ буфер 74LVC1G125 (вихід — три станів, керується піном OE).
//
// Розводка (типова для 5-ногого корпусу цієї функції):
//   пін 1 → OE  (дозвіл виходу, активний «0»)
//   пін 2 → A   (вхід: строб від джерела; терпить 5 В навіть на Vcc=3V3)
//   пін 3 → GND
//   пін 4 → Y   (вихід → на пін МК, чисті 3.3 В)
//   пін 5 → Vcc (3.3 В), поряд — 100 нФ на землю
//
// OE тримаємо в «0» апаратно (на GND), щоб вихід був завжди активний;
// у коді МК бачить лише звичайний вхід із уже приведеним рівнем.

#define STROBE_IN  GPIO_NUM_5      // сюди приходить Y буфера (3.3 В)

void strobe_input_init(void) {
    gpio_config_t io = {
        .pin_bit_mask = 1ULL << STROBE_IN,
        .mode         = GPIO_MODE_INPUT,
        .pull_up_en   = GPIO_PULLUP_DISABLE,   // рівень тримає буфер, не МК
        .pull_down_en = GPIO_PULLDOWN_DISABLE,
    };
    gpio_config(&io);
}

// читаємо строб — буфер уже привів 5-вольтовий вхід до 3.3 В
static inline int strobe_is_active(void) {
    return gpio_get_level(STROBE_IN);          // 1 = строб присутній
}
