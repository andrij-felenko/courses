#include <stdint.h>

// вихідну частоту задаємо повним коефіцієнтом D = f_out / f_ref
const uint32_t f_ref = 25000u;        // Гц — він же крок сітки каналів
const uint32_t N     = 64u;           // модуль прескейлера ÷64/÷65
const uint32_t f_out = 902400000u;    // Гц — бажаний канал

uint32_t D = f_out / f_ref;           // = 36096  повний коефіцієнт ділення
uint32_t P = D / N;                   // = 564    головний лічильник
uint32_t S = D % N;                   // = 0      ковтач (36096 = 64·564 рівно)

// перевірка: (N·P + S)·f_ref = (64·564 + 0)·25000
//          = 36096 · 25000 = 902 400 000 Гц = 902.4 МГц  ✓
// умова неперервності: P = 564 ≥ N = 64  →  канал у суцільній частині сітки ✓
