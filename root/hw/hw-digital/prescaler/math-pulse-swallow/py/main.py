# вихідну частоту задаємо повним коефіцієнтом D = f_out / f_ref
f_ref = 25000       # Гц — він же крок сітки каналів
N     = 64          # модуль прескейлера ÷64/÷65
f_out = 902400000   # Гц — бажаний канал

D = f_out // f_ref  # = 36096  повний коефіцієнт ділення
P = D // N          # = 564    головний лічильник
S = D % N           # = 0      ковтач (36096 = 64·564 рівно)

# перевірка: (N·P + S)·f_ref = (64·564 + 0)·25000
#          = 36096 · 25000 = 902 400 000 Гц = 902.4 МГц  ✓
# умова неперервності: P = 564 ≥ N = 64  →  канал у суцільній частині сітки ✓
