// рівневе переривання (активне, поки INT тримається низьким)
void sensor_irq_level_handler(void) {
    // ОБОВ'ЯЗКОВО гасимо джерело: читаємо дані, аж поки давач не відпустить INT.
    while (sensor_data_ready()) {     // поки давач сигналить
        uint8_t v = sensor_read();    // читання знімає його внутрішній прапорець
        consume(v);
    }
    // тепер давач відпустив INT (рівень знявся) — переривання більше не активне.
    // Якби ми вийшли, не дочитавши, рівень лишився б — і оброблювач
    // спрацював би НЕГАЙНО знову. Це і є "залипання" на рівні.
}
