#include <stdint.h>

void exti0_rising_setup(void) {
    EXTI->RTSR |=  (1u << 0);   // дозволити фронт наростання на лінії 0
    EXTI->FTSR &= ~(1u << 0);   // спад — вимкнути, ловимо лише 0->1
    EXTI->IMR  |=  (1u << 0);   // зняти маску: переривання дозволено
}

// оброблювач: для ФРОНТУ прапорець треба зняти ВРУЧНУ,
// інакше те саме переривання спрацює знову й знову
void EXTI0_IRQHandler(void) {
    if (EXTI->PR & (1u << 0)) {   // це справді наша лінія?
        EXTI->PR = (1u << 0);     // зняти прапорець (запис 1 у PR його скидає)
        on_button_press();        // корисна робота
    }
}
