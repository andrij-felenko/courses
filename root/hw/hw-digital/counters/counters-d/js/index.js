const DIV = 1000;                 // на скільки ділимо півперіод

let periods = 0;                  // скільки повних періодів уже було
let cnt = 0;                      // лічильник усередині (як ланцюг тригерів)
let out = 0;                      // стан виходу (0/1)

function onInputEdge() {          // викликається на кожному фронті входу
    if (++cnt >= DIV) {           // дорахували до межі —
        cnt = 0;                  // скидаємо (як mod-N повертається в 0)
        out ^= 1;                 // перемикаємо вихід: ^=1 — це toggle-тригер у коді
        if (out === 0)            // повний період виходу завершився —
            periods++;            // лічимо його
    }
}
