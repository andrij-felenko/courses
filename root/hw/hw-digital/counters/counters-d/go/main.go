const DIV = 1000 // на скільки ділимо півперіод

var periods uint32 // скільки повних періодів уже було
var cnt uint16     // лічильник усередині (як ланцюг тригерів)
var out uint8      // стан виходу (0/1)

func onInputEdge() { // викликається на кожному фронті входу
	cnt++
	if cnt >= DIV { // дорахували до межі —
		cnt = 0     // скидаємо (як mod-N повертається в 0)
		out ^= 1    // перемикаємо вихід: ^=1 — це toggle-тригер у коді
		if out == 0 { // повний період виходу завершився —
			periods++ // лічимо його
		}
	}
}
