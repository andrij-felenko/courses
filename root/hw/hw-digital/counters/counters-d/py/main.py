DIV = 1000                        # на скільки ділимо півперіод

periods = 0                       # скільки повних періодів уже було
_cnt = 0                          # лічильник усередині (як ланцюг тригерів)
_out = 0                          # стан виходу (0/1)

def on_input_edge():              # викликається на кожному фронті входу
    global _cnt, _out, periods
    _cnt += 1
    if _cnt >= DIV:               # дорахували до межі —
        _cnt = 0                  # скидаємо (як mod-N повертається в 0)
        _out ^= 1                 # перемикаємо вихід: ^=1 — це toggle-тригер у коді
        if _out == 0:             # повний період виходу завершився —
            periods += 1          # лічимо його
