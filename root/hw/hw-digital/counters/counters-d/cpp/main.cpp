#define DIV 1000u                 // на скільки ділимо півперіод

volatile uint32_t periods = 0;    // скільки повних періодів уже було

void on_input_edge(void) {        // викликається на кожному фронті входу
    static uint16_t cnt = 0;      // лічильник усередині (як ланцюг тригерів)
    if (++cnt >= DIV) {           // дорахували до межі —
        cnt = 0;                  // скидаємо (як mod-N повертається в 0)
        OUT_PIN ^= 1;             // перемикаємо вихід: ^=1 — це toggle-тригер у коді
        if (OUT_PIN == 0)         // повний період виходу завершився —
            periods++;            // лічимо його
    }
}
