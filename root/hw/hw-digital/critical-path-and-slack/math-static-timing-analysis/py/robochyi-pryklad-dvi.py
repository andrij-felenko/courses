# Час приходу (arrival) у кожному вузлі, наносекунди. Прохід УПЕРЕД.
tcq = 0.6                       # clock-to-Q джерел A і B
aA  = tcq;  aB = tcq            # A = 0.6 ;  B = 0.6
aG1 = aA + 1.4                  # 0.6 + 1.4 = 2.0
aG2 = aB + 2.1                  # 0.6 + 2.1 = 2.7
aG3 = max(aG1, aG2) + 2.3       # max(2.0, 2.7) + 2.3 = 5.0  ← пізній вхід G2 переміг
aG4 = aG3 + 1.8                 # 5.0 + 1.8 = 6.8
aG5 = aG2 + 0.4                 # 2.7 + 0.4 = 3.1
arrD1 = aG4                     # на вході D1: 6.8
arrD2 = aG5                     # на вході D2: 3.1
