// Лічильник вмикань MCU: чому проста змінна «забуває» і як це полагодити.

// RAM-змінна: живе на бістабільних комірках → при ввімкненні значення НЕ визначене
uint32_t boot_count;                       // після power-on тут сміття, а не 0

// та сама величина в постійній пам'яті (умовний доступ до Flash)
uint32_t saved = flash_read(BOOT_SLOT);    // переживає вимкнення
if (saved == 0xFFFFFFFF) saved = 0;        // стерта Flash читається як самі одиниці
saved += 1;                                // порахували це вмикання
flash_write(BOOT_SLOT, saved);             // зберегли назад — інакше забудеться
// boot_count тут чіпати марно: його петлі щойно «осіли» випадково
