#include <stdint.h>

// Помножити многочлен a на x за модулем p (обидва — бітові маски
// коефіцієнтів); n — степінь p. Один крок LFSR у чистій алгебрі.
static uint32_t mul_x_mod(uint32_t a, uint32_t p, int n) {
    a <<= 1;                       // множення на x — зсув степенів угору
    if (a & (1u << n))             // виліз старший член x^n?
        a ^= p;                    // замінюємо: віднімаємо (=XOR) p(x)
    return a & ((1u << n) - 1u);   // лишаємо n молодших розрядів
}

// Порядок x за модулем p: скільки множень на x, поки не повернемось у 1.
static uint32_t order_of_x(uint32_t p, int n) {
    uint32_t s = 1u;               // старт зі стану 1 = x^0
    for (uint32_t k = 1; k <= ((1u << n) - 1u); k++) {
        s = mul_x_mod(s, p, n);    // s = x^k mod p
        if (s == 1u) return k;     // повернулись — це і є період
    }
    return 0;                      // не повернулись (p звідний) — циклу нема
}
