`timescale 1ns/1ps        // одиниця модельного часу — 1 нс, крок — 1 пс

module tb_counter;        // тестбенч: жодного виводу назовні
    // ── сигнали, якими з'єднуємося з DUT ──
    reg        clk = 1'b0;
    reg        rst = 1'b1; // стартуємо У СКИДІ — навмисно (див. пастку нижче)
    reg        en  = 1'b0;
    wire [3:0] count;      // вихід DUT читаємо сюди (він його жене → wire)

    // ── еталон: наш незалежний лічильник очікуваного ──
    reg  [3:0] expected = 4'd0;

    // ── під'єднуємо DUT ──
    counter dut (
        .clk(clk), .rst(rst), .en(en), .count(count));

    // ── генератор такту: живе весь час, період 10 нс ──
    always #5 clk = ~clk;
