// Дескриптор DMA для ESP32-класу (форма апаратного GDMA).
// Лежить у звичайній RAM; апаратура читає його як є — тому
// розкладка полів і вирівнювання фіксовані, не змінюй їх.
typedef struct dma_desc_s {
    uint32_t size    : 12;  // місткість буфера, байтів (кратна, з вирівнюванням)
    uint32_t length  : 12;  // скільки байтів реально передати з цього буфера
    uint32_t rsv     : 6;   // зарезервовано
    uint32_t eof     : 1;   // 1 = останній шматок: підняти переривання
    uint32_t owner   : 1;   // 1 = власник DMA (зайнято), 0 = власник CPU
    uint8_t  *buf;          // адреса даних цього шматка
    struct dma_desc_s *next; // наступний вузол; NULL = кінець ланцюга
} dma_desc_t;
