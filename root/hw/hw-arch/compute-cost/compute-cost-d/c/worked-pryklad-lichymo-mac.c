// Собель 3×3 над сірим кадром QVGA: ручна лічба вартості.
// Один піксель: дві згортки 3×3 → 2 · (3·3) = 18 MAC,
// плюс величина градієнта ≈ 3 операції (два квадрати + корінь/abs).
// Пікселів (без країв) ≈ 320 · 240.

#define W 320
#define H 240

// очікувана лічба:
//   MAC = W · H · 2 · 3 · 3  =  320 · 240 · 18  =  1 382 400  ≈ 1.4 M MAC

uint8_t  src[H][W];      // вхідний сірий кадр
uint8_t  dst[H][W];      // карта меж

static const int8_t Gx[3][3] = {{-1,0,1},{-2,0,2},{-1,0,1}};
static const int8_t Gy[3][3] = {{-1,-2,-1},{0,0,0},{1,2,1}};

void sobel(void) {
    for (int y = 1; y < H - 1; y++) {
        for (int x = 1; x < W - 1; x++) {
            int sx = 0, sy = 0;
            for (int j = -1; j <= 1; j++)
                for (int i = -1; i <= 1; i++) {
                    int v = src[y + j][x + i];   // 1 читання
                    sx += Gx[j + 1][i + 1] * v;  // 1 MAC
                    sy += Gy[j + 1][i + 1] * v;  // 1 MAC
                }
            int mag = abs(sx) + abs(sy);         // дешевша заміна √(sx²+sy²)
            dst[y][x] = mag > 255 ? 255 : mag;
        }
    }
}
