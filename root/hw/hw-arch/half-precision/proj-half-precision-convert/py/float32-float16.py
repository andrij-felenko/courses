import struct

# float32 -> float16 (IEEE 754 binary16) з округленням до найближчого-парного,
# обробкою ∞/NaN, переповнення під стелю 65504, денормалей і зникнення до нуля.
def f32_to_f16(x: float) -> int:
    bits = struct.unpack("<I", struct.pack("<f", x))[0]

    sign = (bits >> 16) & 0x8000   # знак одразу на місце в 16-бітному слові
    rest = bits & 0x7FFFFFFF        # усе, крім знаку

    # --- ∞ і NaN: порядок float32 = усі одиниці (rest >= 0x7F800000) ---
    if rest >= 0x7F800000:
        if rest > 0x7F800000:              # мантиса ≠ 0 → NaN
            m = (rest >> 13) & 0x03FF      # урізаємо мантису до 10 бітів
            if m == 0:
                m = 0x0200                 # не дати їй стати ∞: лишаємо quiet-біт
            return sign | 0x7C00 | m
        return sign | 0x7C00               # ∞  (0x7C00 = порядок float16 усі одиниці)

    # --- звичайне число: перерахунок порядку зі зсуву 127 у зсув 15 ---
    e = (rest >> 23) - 127 + 15

    # Переповнення під стелю: порядок float16 не вміщає → ∞.
    if e >= 0x1F:
        return sign | 0x7C00               # усе, що більше за 65504, стає ∞

    mant = rest & 0x007FFFFF               # 23 біти мантиси float32

    # --- денормаль float16 або зникнення до нуля (порядок вийшов ≤ 0) ---
    if e <= 0:
        if e < -10:
            return sign                    # надто мале навіть для денормалі → ±0
        mant |= 0x00800000                 # повертаємо неявну старшу одиницю
        shift = 14 - e                     # на скільки зсунути, щоб лягло в денормаль
        half = 1 << (shift - 1)
        m    = mant >> shift
        rem  = mant & ((1 << shift) - 1)
        # округлення до найближчого-парного
        if rem > half or (rem == half and (m & 1)):
            m += 1
        return sign | m                    # переповнення денормалі в нормаль вийде саме

    # --- нормальне число: 10 бітів мантиси + округлення до найближчого-парного ---
    m   = mant >> 13                       # лишаємо старші 10 з 23 бітів
    rem = mant & 0x1FFF                     # 13 відкиданих бітів
    out = sign | (e << 10) | m
    if rem > 0x1000 or (rem == 0x1000 and (m & 1)):  # переніс сам підніме порядок
        out += 1
    return out
