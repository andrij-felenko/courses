import struct

# Чесне float32 -> bfloat16 з округленням до найближчого-парного (RTNE)
# і збереженням NaN. Це «правильна» версія для реальних обчислень.
def f32_to_bf16(x: float) -> int:
    bits = struct.unpack("<I", struct.pack("<f", x))[0]

    # NaN: порядок = усі одиниці (0x7F800000) і мантиса ≠ 0.
    # Її треба зловити ОКРЕМО — інакше округлення нижче може занулити
    # молодші біти мантиси й перетворити NaN на ∞ (усі одиниці + 0).
    if (bits & 0x7F800000) == 0x7F800000 and (bits & 0x007FFFFF) != 0:
        hi = (bits >> 16) & 0xFFFF
        hi |= 0x0040              # вмикаємо quiet-біт bf16 (старший біт її мантиси)
        return hi                 # гарантовано лишається NaN

    # Округлення до найближчого-парного одним додаванням:
    #   0x7FFF — це «майже половина» відкиданого хвоста;
    #   + молодший біт того, що лишаємо, — вирішує нічию на користь парного.
    lsb  = (bits >> 16) & 1
    bias = 0x7FFF + lsb
    bits = (bits + bias) & 0xFFFFFFFF   # переніс сам підніме старше поле, якщо треба
    return bits >> 16


def bf16_to_float(b: int) -> float:
    bits = b << 16                                   # дописати 16 молодших нулів
    return struct.unpack("<f", struct.pack("<I", bits))[0]
