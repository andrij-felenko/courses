#include <stdint.h>
#include <stdbool.h>
#include <string.h>

#define REGS   32          /* регістрів у файлі; R0 — завжди нуль */
#define NOP_RD 0           /* «нічого не пише» кодуємо записом у R0 */

/* Коди операцій — рівно стільки, скільки треба для демонстрації. */
typedef enum { OP_NOP, OP_ADD, OP_SUB, OP_LOAD, OP_BRANCH } opcode_t;

/* Один «пакет» команди, що тече конвеєром від стадії до стадії.
   Це і є вміст міжстадійного регістра: усе, що стадія передає далі. */
typedef struct {
    opcode_t op;           /* що робити */
    uint8_t  rs1, rs2;     /* номери регістрів-джерел */
    uint8_t  rd;           /* номер регістра-призначення */
    int32_t  imm;          /* безпосереднє значення / зсув переходу */
    int32_t  val;          /* порахований результат (з'являється у ВК) */
    bool     wen;          /* чи справді пише в регістровий файл */
    bool     valid;        /* пакет справжній, а не бульбашка */
} slot_t;

/* Стан усього конвеєра. reg[0..3] — чотири міжстадійні регістри:
   [0]=IF/ID  [1]=ID/EX  [2]=EX/MEM  [3]=MEM/WB. */
typedef struct {
    int32_t regfile[REGS]; /* архітектурні регістри */
    slot_t  reg[4];        /* пайплайн-регістри між п'ятьма стадіями */
    uint32_t pc;           /* лічильник команд: адреса наступної вибірки */
    bool     take_branch;  /* стадія ВК підняла: перехід узято */
    uint32_t branch_pc;    /* куди саме стрибнути */
} cpu_t;
