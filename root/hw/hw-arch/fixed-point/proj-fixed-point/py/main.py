def q_mul(a, b):                      # a, b — Q-числа (масштаб 2^Q)
    p = a * b                         # 1) цілі Python довільної ширини — добуток не переповниться
    p += 1 << (Q - 1)                 # 2) додати пів-біта → округлення замість усічення
    p >>= Q                           # 3) арифметичний зсув назад до масштабу 2^Q
    if p > QMAX: p = QMAX             # 4) насичення згори
    if p < QMIN: p = QMIN             #    і знизу
    return p                          #    звузити назад

def q_add(a, b):                      # додавання теж може переповнитись!
    s = a + b                         # цілі й так широкі, та межі формату все одно тримаємо
    if s > QMAX: s = QMAX
    if s < QMIN: s = QMIN
    return s
