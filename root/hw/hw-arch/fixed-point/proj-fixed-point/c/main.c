q8_8 q_mul(q8_8 a, q8_8 b) {          // a, b — Q-числа (масштаб 2^Q)
    int32_t p = (int32_t)a * b;       // 1) ширший тип: добуток має масштаб 2^(2Q)
    p += (1 << (Q - 1));              // 2) додати пів-біта → округлення замість усічення
    p >>= Q;                          // 3) арифметичний зсув назад до масштабу 2^Q
    if (p > QMAX) p = QMAX;           // 4) насичення згори
    if (p < QMIN) p = QMIN;           //    і знизу
    return (q8_8)p;                   //    звузити назад
}

q8_8 q_add(q8_8 a, q8_8 b) {          // додавання теж може переповнитись!
    int32_t s = (int32_t)a + b;       // рахуємо ширше, щоб побачити вихід за межі
    if (s > QMAX) s = QMAX;
    if (s < QMIN) s = QMIN;
    return (q8_8)s;
}
