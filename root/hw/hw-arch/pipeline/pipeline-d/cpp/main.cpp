    if (buf[i] > thr)        // непередбачуваний if на кожній ітерації
        sum += buf[i];

// Б) без розгалуження — те саме без стрибка в циклі
uint32_t sum = 0;
for (int i = 0; i < n; i++) {
    int32_t v = buf[i];
    int32_t m = -(v > thr);  // маска: 0xFFFFFFFF якщо так, інакше 0
    sum += v & m;            // додаємо v або 0 — гілки немає
}
