// AVR: обробник переривання від таймера. Атрибут ISR() каже компілятору
// САМ згенерувати пролог (push SREG у стек) і епілог (pop SREG назад).
#include <avr/interrupt.h>

volatile uint16_t ticks = 0;

ISR(TIMER0_OVF_vect) {
    // Компілятор уже зберіг SREG у стек ДО цього рядка.
    ticks++;              // це INC/ADD — воно затирає Z, N, C, V!
    if (ticks == 1000) {  // ще й CMP — знову перезаписує прапорці
        ticks = 0;
    }
    // На виході компілятор відновить SREG зі стека — головна програма
    // не помітить, що її прапорці й біт I хтось чіпав.
}
