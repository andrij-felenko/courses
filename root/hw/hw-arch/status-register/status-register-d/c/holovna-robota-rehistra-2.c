// Правильний захист критичної ділянки: зберегти ВЕСЬ SREG, а не гасити I наосліп
#include <avr/interrupt.h>

uint8_t sreg_saved = SREG;   // знімок усього регістра стану (разом із бітом I)
cli();                        // тепер точно вимкнули переривання
// ... критична ділянка: атомарний доступ до спільних із ISR даних ...
SREG = sreg_saved;           // відновили стан ТОЧНО як був: якщо I був 0 — лишиться 0

// avr-libc загортає рівно це у зручний макрос:
ATOMIC_BLOCK(ATOMIC_RESTORESTATE) {
    // весь блок виконується з вимкненими перериваннями;
    // на виході SREG (і біт I) відновлюється таким, яким був до входу
}
