#include <stddef.h>
#define N 1024
static int a[N][N];

// Дружньо до кешу: внутрішній цикл біжить по сусідніх адресах (j → j+1).
// Один промах підтягує рядок кешу — наступні кілька десятків звернень влучають.
long sum_rows(void) {
    long s = 0;
    for (size_t i = 0; i < N; i++)
        for (size_t j = 0; j < N; j++)
            s += a[i][j];          // крок у пам'яті = 1 елемент
    return s;
}

// Вороже до кешу: сусідні звернення стрибають на цілий рядок (N·4 байти).
// Майже кожне звернення — промах; підтягнутий рядок майже не використано.
long sum_cols(void) {
    long s = 0;
    for (size_t j = 0; j < N; j++)
        for (size_t i = 0; i < N; i++)
            s += a[i][j];          // крок у пам'яті = N елементів
    return s;
}
