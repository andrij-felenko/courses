// Замість голого покажчика — явна пара «банк + зсув».
// Це і є та повна адреса, яку C-покажчик виразити не вміє.
typedef struct {
    uint8_t  bank;    // який банк
    uint16_t off;     // зсув усередині банку (0…0x3FFF)
} far_ref;

// Прочитати за далеким посиланням: банк вмикаємо саме тут, в останню мить.
uint8_t far_read(far_ref r) {
    select_bank(r.bank);
    return WINDOW[r.off];
}

void caller_ok(void) {
    far_ref r = { .bank = 2, .off = 0x0100 };   // «байт у банку 2» — цілісно
    // …тепер хай хоч хтось перемикає банк — r несе свій банк у собі…
    uint8_t x = far_read(r);                     // всередині знову ввімкнеться банк 2
}
