#include <stdint.h>

/* Регістр керування каналом DMA (адреса умовна, з даташита) */
#define DMA_CH_CTRL  (*(volatile uint32_t *)0x40020010)

/* Поле «розмір пакета» — скільки слів за одне захоплення шини */
#define BURST_1     (0u << 12)   /* по слову: часті рукостискання, м'який відгук */
#define BURST_8     (2u << 12)   /* 8 слів за раз: рідші захоплення, менше плати */
#define BURST_16    (3u << 12)   /* 16 слів: ще менше накладних, довші паузи іншим */

#define DMA_PRIO_HI (3u << 16)   /* пріоритет каналу для арбітра шини */
#define DMA_ENABLE  (1u << 0)

/* Налаштувати канал на швидкий потік: великий пакет + високий пріоритет */
void dma_cfg_stream(void) {
    /* 16 слів на захоплення — мало рукостискань на великому потоці,
       але на час пакета ядро довше чекає шину. Компроміс — свідомий. */
    DMA_CH_CTRL = BURST_16 | DMA_PRIO_HI | DMA_ENABLE;
}
