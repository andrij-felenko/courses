// PFC-каскад аналоговий — MCU лише вмикає його й чекає, поки шина вийде на норму.
gpio_set(PFC_EN, 1);                   // дозвіл контролеру PFC — пішов м'який старт

uint32_t t0 = millis();
while (adc_read_bus_mv() < PFC_BUS_OK_MV) {   // чекаємо, поки шина ~400 В підніметься
    if (millis() - t0 > 200) {                // 200 мс не вийшла — несправність
        gpio_set(PFC_EN, 0);
        fault(FAULT_PFC_BUS);
        return;
    }
}
// шина в нормі → далі можна будити наступний DC-DC каскад
