// Що дає даташит приладу (діод)
float i2t_withstand = 450.0f;   // стійкість кристала, А²·с
float u_peak_diode  = 1200.0f;  // піковa напруга діода, В

// Що дає даташит обраного запобіжника (клас aR, U_n = 690 В AC)
float i2t_clearing_690 = 320.0f; // clearing I²t при НОМІНАЛЬНІЙ 690 В, А²·с
float k_voltage_400    = 0.55f;  // поправка K(U) для 400 В із кривої даташита
float u_arc_400        = 900.0f; // пікова дугова напруга при 400 В, з кривої

// 1) Реальна пропущена доза на нашій робочій напрузі (400 В < 690 В → менша)
float i2t_clearing_real = i2t_clearing_690 * k_voltage_400;
//  i2t_clearing_real = 320 · 0.55 = 176 А²·с

// 2) Перевірка за СТРУМОМ: пропущена доза < стійкості приладу?
if (i2t_clearing_real < i2t_withstand) {
    //  176 < 450  → так, кристал не перегріється. З добрим запасом.
}

// 3) Перевірка за НАПРУГОЮ: дугова напруга < пікової приладу?
if (u_arc_400 < u_peak_diode) {
    //  900 < 1200 → так, перенапруга обриву не проб'є діод.
}
