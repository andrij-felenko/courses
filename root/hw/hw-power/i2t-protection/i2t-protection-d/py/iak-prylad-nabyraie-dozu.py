# Стійкість силового діода за одну півхвилю 50 Гц
Ifsm = 300.0      # пікова ударна півхвиля, А
t    = 0.010      # півперіод 50 Гц = 10 мс

# Доза за півхвилю: середній квадрат = пік²/2
i2t_withstand = (Ifsm * Ifsm / 2.0) * t
#  i2t = (300 · 300 / 2) · 0.010
#      = (90000 / 2) · 0.010
#      = 45000 · 0.010
#      = 450 А²·с
