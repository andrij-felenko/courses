// Стійкість силового діода за одну півхвилю 50 Гц
float Ifsm = 300.0f;      // пікова ударна півхвиля, А
float t    = 0.010f;      // півперіод 50 Гц = 10 мс

// Доза за півхвилю: середній квадрат = пік²/2
float i2t_withstand = (Ifsm * Ifsm / 2.0f) * t;
//  i2t = (300 · 300 / 2) · 0.010
//      = (90000 / 2) · 0.010
//      = 45000 · 0.010
//      = 450 А²·с
