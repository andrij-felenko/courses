import numpy as np

# фізичні сталі й тепловий потенціал
q, k, T = 1.602176634e-19, 1.380649e-23, 298.15   # Кл, Дж/К, К (25 °C)
Vt = k * T / q                                     # ≈ 0.0257 В

# параметри кремнієвого елемента (однодіодна модель)
n   = 1.0        # коефіцієнт ідеальності діода
I0  = 6.5e-10    # струм насичення діода, А
Iph = 9.0        # фотострум під повним сонцем, А
Vbp = 0.40       # пряме падіння байпасного діода (Шотткі), В

def cell_V(I, iph):
    """Напруга елемента при струмі I і фотострумі iph.
    З рівняння I = iph − I0·(exp(V/(n·Vt)) − 1), розв'язаного відносно V:
        V = n·Vt·ln((iph − I)/I0 + 1)."""
    return n * Vt * np.log(np.maximum((iph - I) / I0 + 1.0, 1e-12))
