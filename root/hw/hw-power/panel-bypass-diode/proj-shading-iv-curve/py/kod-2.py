def subrow_V(I, cells):
    """Напруга підрядка (20 елементів, cells — їхні фотоструми) з байпасним діодом.
    Поки струм рядка нижчий за фотострум найслабшого елемента, усі елементи в
    прямому зміщенні й напруги додаються. Щойно рядок вимагає більше, ніж здатен
    дати найслабший елемент, байпасний діод відмикається й фіксує підрядок на −Vbp."""
    V = cell_V(I[None, :], cells[:, None]).sum(axis=0)
    V[I > cells.min()] = -Vbp
    return V

