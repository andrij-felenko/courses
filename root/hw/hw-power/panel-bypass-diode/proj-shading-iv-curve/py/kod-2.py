subrows = [
    np.full(20, 9.0),               # підрядок 1 — повне сонце
    np.r_[np.full(19, 9.0), 6.0],   # підрядок 2 — один елемент у півтіні (2/3 світла)
    np.r_[np.full(19, 9.0), 3.0],   # підрядок 3 — один елемент у глибшій тіні (1/3 світла)
]

I = np.linspace(0, Iph - 1e-6, 4000)        # струм рядка, А
V = sum(subrow_V(I, s) for s in subrows)    # напруга модуля, В
