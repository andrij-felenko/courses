// Увімкнути шину живлення й дочекатися, поки модуль підтвердить норму.
gpio_set(PWR_EN, 1);                 // подали дозвіл на ніжку EN модуля

uint32_t t0 = millis();
while (!gpio_read(PWR_PG)) {         // чекаємо сигнал power-good від модуля
    if (millis() - t0 > 10) {        // 10 мс не піднявся — щось не так
        fault(FAULT_RAIL_3V3);       // у захист: шина не вийшла на норму
        break;
    }
}
// PG = 1 → вихід у межах; тепер можна запускати наступний чип
