#include <stdint.h>
#include <stdbool.h>

// Одиниці, зафіксовані раз і назавжди:
//   напруга — 0.1 мВ (4.2 В = 42000);  заряд — проміле (1000 = 100.0 %)
typedef struct { uint16_t v_01mv; uint16_t soc_pm; } knot_t;

typedef struct {
    const knot_t *k;
    uint8_t       n;      // вузлів; відрізків, отже, n−1
    int16_t       t_c;    // за якої температури знято цю криву, °C
} ocv_table_t;

// Li-ion, 25 °C. Вузли згущені там, де крива гнеться, — біля порожньої
// та повної; у пологій середині їх мало, бо там і без них усе пряме.
static const knot_t LI_25C[] = {
    { 30000,    0 }, { 34200,   60 }, { 35600,  140 }, { 36600,  260 },
    { 37600,  450 }, { 38600,  650 }, { 39800,  800 }, { 40800,  900 },
    { 42000, 1000 },
};
static const ocv_table_t TAB_25C = { LI_25C, sizeof LI_25C / sizeof LI_25C[0], 25 };
