// Поріг спрацювання crowbar = напруга пробою стабілітрона + запуск затвора
float Vz   = 5.6f;    // стабілітрон 1N5231, В
float Vgt  = 0.7f;    // типова напруга запуску затвора SCR, В
float Vtrip = Vz + Vgt;
//  Vtrip = 5.6 + 0.7 = 6.3 В   → вище 5 В робочих, нижче за 12 В аварійних

// Резистор затвора: обмежує струм у затвор при пробої.
// При аварійних 12 В над затвором лишається (Vbus - Vtrip),
// і цей надлишок треба пустити через Rg як струм запуску Igt.
float Vbus = 12.0f;   // що подасть пробитий стабілізатор, В
float Igt  = 0.020f;  // потрібний струм запуску, 20 мА
float Rg   = (Vbus - Vtrip) / Igt;
//  Rg = (12 - 6.3) / 0.020 = 285 Ом   → беремо стандартні 270 Ом
