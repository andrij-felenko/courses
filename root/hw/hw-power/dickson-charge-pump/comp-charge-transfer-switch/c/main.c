// Типовий цикл роботи з інтегрованою помпою (псевдорегістри умовні,
// але послідовність — та сама в будь-якому флеш-контролері).
#include <stdint.h>

void hv_pump_enable(void) {
    PUMP_CTRL |= PUMP_CLK_EN;      // пустити тактовий генератор помпи
    PUMP_CTRL |= PUMP_EN;          // увімкнути сам ланцюжок сходинок
    // Чекаємо, поки вихід накачається до порога готовності.
    // Помпа має чималий вихідний опір — розгін не миттєвий.
    while (!(PUMP_STAT & PUMP_HV_READY))
        ;                          // опитуємо прапорець «висока напруга готова»
}

void hv_pump_disable(void) {
    PUMP_CTRL &= ~PUMP_EN;         // спершу зупинити накачку
    PUMP_CTRL &= ~PUMP_CLK_EN;     // тоді прибрати такт
    // Розряджати вихід через штатний розрядник, а не лишати «висіти».
    PUMP_CTRL |= PUMP_DISCHARGE;
}
