volatile uint8_t power = 0;     // 0..100, оновлює регулятор у головному циклі
static uint16_t  acc   = 0;     // накопичувач Брезенхема
const  uint8_t   M     = 100;   // вікно = 100 півперіодів = 1 с на 50 Гц

// викликається з переривання детектора нуля (кожні 10 мс):
void on_zero_cross() {
    acc += power;               // power порцій на M тактів
    if (acc >= M) {
        acc -= M;
        fire_triac_pulse();     // короткий імпульс у затвор для ЦІЄЇ півхвилі
    }
    // інакше затвор мовчить — симістор сам згасне в наступному нулі
}
