R = 64            # коефіцієнт децимації (OSR): 3.072 МГц → 48 кГц
R_BYTES = R // 8  # 8 байтів PDM на один вихідний відлік

MASK32 = 0xFFFFFFFF  # інтегратор ведемо в 32 бітах, щоб імітувати переповнення

# Стан одноступеневого CIC. Інтегратор накопичує без обмежень —
# тримаємо його в 32 бітах, щоб він фізично не переповнювався за розумний час.
class Cic1:
    def __init__(self):
        self.integ = 0      # біжуча сума ВСІХ бітів (інтегратор)
        self.comb_prev = 0  # значення integ на минулому вихідному відліку

# Згодувати один блок із R_BYTES вхідних байтів PDM.
# Повертає один центрований відлік звуку.
def cic1_push_block(s, pdm):
    # 1) ІНТЕГРАТОР: додати всі одиниці цього блоку до біжучої суми.
    #    (еквівалент R окремих acc += біт, лише пачкою через popcount)
    for i in range(R_BYTES):
        s.integ = (s.integ + pdm[i].bit_count()) & MASK32

    # 2) ГРЕБІНКА (раз на блок, тобто на прорідженій частоті):
    #    різниця integ «тепер» і «R бітів тому» = сума останніх R бітів ∈ [0, R].
    now = s.integ
    diff = (now - s.comb_prev) & MASK32
    if diff >= 0x80000000:          # трактуємо як знакове 32-бітне
        diff -= 0x100000000
    s.comb_prev = now

    # 3) Центрувати: середина шкали (тиша) — R/2 = 32.
    return diff - (R // 2)          # ∈ [−32, +32]
