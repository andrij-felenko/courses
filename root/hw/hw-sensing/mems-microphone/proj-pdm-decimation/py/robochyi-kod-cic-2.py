R = 64
R_BYTES = R // 8
N_STAGES = 4      # 4 інтегратори + 4 гребінки — аудіоклас

# integ[] біжать на високій частоті; comb[] — на прорідженій.
# Цілі Python необмежені, тож переповнення просто не існує —
# те, для чого в C потрібні 64-бітні лічильники, тут дається задарма.
class CicN:
    def __init__(self):
        self.integ = [0] * N_STAGES      # каскад інтеграторів
        self.comb_prev = [0] * N_STAGES  # затримка кожної гребінки на 1 відлік

def cicN_push_block(s, pdm):
    # ── ІНТЕГРАТОРИ: на КОЖНОМУ вхідному біті (тут — байті) ──
    # Перший ступінь їсть popcount байта; решта — вихід попереднього.
    for i in range(R_BYTES):
        s.integ[0] += pdm[i].bit_count()
        for k in range(1, N_STAGES):
            s.integ[k] += s.integ[k - 1]     # каскад накопичень

    # ── ПРОРІДЖУВАННЯ + ГРЕБІНКИ: раз на блок (частота звуку) ──
    x = s.integ[N_STAGES - 1]                # знімок останнього інтегратора
    for k in range(N_STAGES):
        y = x - s.comb_prev[k]                # різниця «тепер − R відліків тому»
        s.comb_prev[k] = x
        x = y                                 # вихід гребінки → у наступну

    # x має розмах ~2^24; зсуваємо у 16-бітний звук.
    # Точний зсув = log2((R·M)^N) − потрібні_біти. Тут: 24 − 8 = 16.
    return x >> (24 - 16)                     # 24-бітне поле → int16-масштаб
