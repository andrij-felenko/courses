# R = 64: один відлік звуку = 8 вхідних байтів PDM (8 × 8 = 64 біти).
PDM_BYTES_PER_SAMPLE = 8

# Перетворити блок PDM-байтів на один 16-бітний відлік звуку.
# pdm — послідовність із 8 сирих байтів; повертає центрований відлік.
# Таблиця popcount не потрібна — int.bit_count() рахує одиниці нативно.
def pdm_block_to_sample(pdm):
    ones = sum(b.bit_count() for b in pdm)    # 0…64 одиниць у блоці

    # ones ∈ [0, 64]; середина шкали (тиша) — 32.
    # Центруємо: віднімаємо половину, множимо, щоб зайняти діапазон int16.
    centered = ones - 32                       # ∈ [−32, +32]
    return centered * 1000                     # грубе масштабування у int16
