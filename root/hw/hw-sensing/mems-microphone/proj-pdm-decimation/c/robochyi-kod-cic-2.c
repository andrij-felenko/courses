#include <stdint.h>

#define R  64
#define R_BYTES   (R/8)
#define N_STAGES  4       // 4 інтегратори + 4 гребінки — аудіоклас

extern uint8_t popcnt8[256];

// integ[] біжать на високій частоті; comb[] — на прорідженій.
// 64-бітні лічильники: за 4 ступенів підсилення сягає 2^24,
// а 64 біти дають запас, щоб різниці ніколи не переповнились.
typedef struct {
    int64_t integ[N_STAGES];      // каскад інтеграторів
    int64_t comb_prev[N_STAGES];  // затримка кожної гребінки на 1 відлік
} cicN_t;

int32_t cicN_push_block(cicN_t *s, const uint8_t *pdm) {
    // ── ІНТЕГРАТОРИ: на КОЖНОМУ вхідному біті (тут — байті) ──
    // Перший ступінь їсть popcount байта; решта — вихід попереднього.
    for (int i = 0; i < R_BYTES; i++) {
        s->integ[0] += popcnt8[pdm[i]];
        for (int k = 1; k < N_STAGES; k++)
            s->integ[k] += s->integ[k - 1];   // каскад накопичень
    }

    // ── ПРОРІДЖУВАННЯ + ГРЕБІНКИ: раз на блок (частота звуку) ──
    int64_t x = s->integ[N_STAGES - 1];       // знімок останнього інтегратора
    for (int k = 0; k < N_STAGES; k++) {
        int64_t y = x - s->comb_prev[k];       // різниця «тепер − R відліків тому»
        s->comb_prev[k] = x;
        x = y;                                  // вихід гребінки → у наступну
    }

    // x має розмах ~2^24; зсуваємо у 16-бітний звук.
    // Точний зсув = log2((R·M)^N) − потрібні_біти. Тут: 24 − 8 = 16.
    return (int32_t)(x >> (24 - 16));           // 24-бітне поле → int16-масштаб
}
