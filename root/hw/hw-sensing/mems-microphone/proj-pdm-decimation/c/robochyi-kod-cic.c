#include <stdint.h>

#define R  64          // коефіцієнт децимації (OSR): 3.072 МГц → 48 кГц
#define R_BYTES  (R/8) // 8 байтів PDM на один вихідний відлік

extern uint8_t popcnt8[256];   // таблиця popcount із popcount_init()

// Стан одноступеневого CIC. Інтегратор накопичує без обмежень —
// беремо 32 біти, щоб він фізично не переповнювався за розумний час.
typedef struct {
    uint32_t integ;       // біжуча сума ВСІХ бітів (інтегратор)
    uint32_t comb_prev;   // значення integ на минулому вихідному відліку
} cic1_t;

// Згодувати один блок із R_BYTES вхідних байтів PDM.
// Повертає один центрований відлік звуку.
int32_t cic1_push_block(cic1_t *s, const uint8_t *pdm) {
    // 1) ІНТЕГРАТОР: додати всі одиниці цього блоку до біжучої суми.
    //    (еквівалент R окремих acc += біт, лише пачкою через popcount)
    for (int i = 0; i < R_BYTES; i++)
        s->integ += popcnt8[pdm[i]];

    // 2) ГРЕБІНКА (раз на блок, тобто на прорідженій частоті):
    //    різниця integ «тепер» і «R бітів тому» = сума останніх R бітів ∈ [0, R].
    uint32_t now  = s->integ;
    int32_t  sum  = (int32_t)(now - s->comb_prev);  // 0…64
    s->comb_prev  = now;

    // 3) Центрувати: середина шкали (тиша) — R/2 = 32.
    return sum - (R / 2);                            // ∈ [−32, +32]
}
