# дві відомі точки, зняті при калібруванні (відома напруга → код АЦП)
V_LO = 0.500;  CODE_LO =  600    # мав би бути ≈ 620 — є зсув і масштаб
V_HI = 2.500;  CODE_HI = 3000

# код → напруга по прямій, що проходить через обидві точки
def adc_to_volts(code):
    return V_LO + (V_HI - V_LO) * (code - CODE_LO) / (CODE_HI - CODE_LO)

# перевірка: рівно посередині між точками маємо вийти на 1.500 В
v = adc_to_volts(1800)   # = 0.500 + 2.000 × 1200 / 2400 = 1.500 В
