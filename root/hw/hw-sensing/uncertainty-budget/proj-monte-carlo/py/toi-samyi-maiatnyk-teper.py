import numpy as np

rng = np.random.default_rng(20240517)      # сучасний ГВЧ, свій потік
M = 1_000_000

# кожен вхід — за СВОЇМ розподілом, а не одним числом u
L   = rng.uniform(0.9500 - 0.001, 0.9500 + 0.001, M)   # рулетка: рівномірно в межах ±1 мм
t50 = rng.normal(97.77, 0.25, M)                        # тип A: нормально, σ = 0.25 с
T   = t50 / 50

g = 4 * np.pi**2 * L / T**2                 # проганяємо КОЖНУ вибірку крізь модель

y  = g.mean()
u  = g.std(ddof=1)                          # стандартне відхилення виходу = u_c
lo, hi = np.percentile(g, [2.5, 97.5])      # інтервал охоплення 95 % — перцентилі

print(f"g    = {y:.4f} м/с²")
print(f"u(g) = {u:.4f} м/с²   (лінійний бюджет давав 0.0505)")
print(f"інтервал 95 % (перцентилі) = [{lo:.3f}, {hi:.3f}],  ширина {hi-lo:.3f}")
print(f"симетричний  y ± 2u        = [{y-2*u:.3f}, {y+2*u:.3f}]")
print(f"асиметрія (skewness) = {((g-y)**3).mean()/u**3:.3f}")
