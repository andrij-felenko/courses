// 1) час зчитування цілого кадру = час рядка × кількість рядків
float line_time_us = 27.8f;                 // мкс на один рядок
int   rows         = 1080;
float frame_us     = line_time_us * rows;   // 27.8 · 1080
//                 = 30024 мкс  ≈  30 мс

// 2) швидкість об'єкта В КАДРІ (пікселів за секунду)
float v_px = 1920.0f / 0.2f;                // = 9600 пікс/с

// 3) за час зчитування кадру об'єкт зсунеться вбік
float shift_px = v_px * (frame_us * 1e-6f); // 9600 · 0.030
//             = 288 пікселів
