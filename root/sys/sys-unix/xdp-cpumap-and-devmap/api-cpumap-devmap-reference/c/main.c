struct xdp_frame {
    void *data;             /* Вказівник на початок корисного навантаження кадра */
    u16 len;                /* Довжина пакетного кадра у байтах */
    u16 headroom;           /* Доступний розмір headroom (мінімум 256 байт) */
    u32 metasize;           /* Розмір збережених eBPF-метаданих */
    struct xdp_mem_info mem;/* Інформація про модель пам'яті (page_pool) */
    struct net_device *dev_rx;/* Вказівник на вхідний мережевий пристрій */
    u32 frame_sz;           /* Загальний розмір виділеного буфера сторінки */
    u32 flags;              /* Прапорці (включаючи мультибуферні фрагменти) */
};
