typedef struct {
    Elf64_Word  p_type;    /* Тип сегмента: зафіксоване значення PT_TLS = 7 */
    Elf64_Word  p_flags;   /* Права доступу: PF_R (значення 4, читання) */
    Elf64_Off   p_offset;  /* Базове зміщення шаблону .tdata у файлі на диску */
    Elf64_Addr  p_vaddr;   /* Віртуальна адреса шаблону при відображенні у пам'ять */
    Elf64_Addr  p_paddr;   /* Зарезервоване поле стандарту ELF (не використовується) */
    Elf64_Xword p_filesz;  /* Точний розмір ініціалізованих даних (.tdata) у байтах */
    Elf64_Xword p_memsz;   /* Загальний обсяг пам'яті для TLS (.tdata + .tbss) у байтах */
    Elf64_Xword p_align;   /* Максимальне вирівнювання пам'яті (потужність числа 2) */
} Elf64_Phdr;
