/* Дескриптор окремого слота або ланцюжка слотів у пулі */
struct io_tlb_slot {
    phys_addr_t orig_addr;       /* Фізична адреса оригінального буфера пам'яті */
    size_t alloc_size;           /* Повний виділений розмір пам'яті з урахуванням вирівнювання */
    unsigned int list;           /* Кількість вільних суміжних слотів, доступних після цього слота */
};

/* Окрема ділянка пулу для паралельного виділення на багатоядерних системах */
struct io_tlb_area {
    spinlock_t lock;             /* Спин-блокування, що захищає розподіл слотів у межах цієї ділянки */
    unsigned long index;         /* Поточний індекс кругового пошуку для рівномірного зносу слотів */
    unsigned int used;           /* Поточна кількість зайнятих слотів у цій конкретній ділянці */
};

/* Головний контекст пулу пам'яті swiotlb */
struct io_tlb_mem {
    phys_addr_t start;           /* Початкова фізична адреса суцільного діапазону пулу */
    phys_addr_t end;             /* Кінцева фізична адреса суцільного діапазону пулу */
    void *vaddr;                 /* Віртуальна адреса відображення пулу в адресному просторі ядра */
    unsigned long nslabs;        /* Загальна кількість доступних слотів по 2 КіБ */
    unsigned int nareas;         /* Кількість незалежних ділянок (типово дорівнює числу CPU) */
    struct io_tlb_area *areas;   /* Динамічний масив ділянок із власними блокуваннями */
    struct io_tlb_slot *slots;   /* Масив метаданих усіх слотів для відстеження адрес повернення */
    bool force_bounce;           /* Прапорець примусової підміни для всіх пристроїв системи */
    bool for_alloc;              /* Дозвіл використовувати пул для узгоджених виділень dma_alloc_coherent */
    struct list_head pools;      /* Список додаткових пулів у разі динамічного розширення */
};
