#!/usr/bin/env bash
# Обрізання пробілів, слешів і префікса протоколу розширеними шаблонами extglob.
# Усе робиться в пам'яті процесу: жодного sed, tr чи awk.
#
# ВАЖЛИВО: `shopt -s extglob` виконується під час ЗАВАНТАЖЕННЯ модуля, тобто
# перед тим, як інтерпретатор розбере тіла функцій нижче. Шаблон на кшталт
# `+(/)` усередині [[ ]] розбирається разом із самою командою, тому вмикання
# опції вже всередині функції на розібране тіло не вплинуло б.
shopt -s extglob

# Знімає провідні пробільні символи (пробіл, табуляція, новий рядок).
strip_leading_space() {
    local value=$1
    printf '%s' "${value##*([[:space:]])}"
}

# Знімає кінцеві пробільні символи.
strip_trailing_space() {
    local value=$1
    printf '%s' "${value%%*([[:space:]])}"
}

# Обрізає з обох боків за один прохід по буферу.
trim_space() {
    local value=$1
    value=${value##*([[:space:]])}
    printf '%s' "${value%%*([[:space:]])}"
}

# Нормалізує кінцеві слеші: /var/log/nginx/// -> /var/log/nginx
# Шлях, що складається з самих слешів, — це корінь; його не можна з'їсти дощенту,
# інакше жадібний шаблон *(/) повернув би порожній рядок замість "/".
strip_trailing_slashes() {
    local value=$1
    if [[ $value == +(/) ]]; then
        printf '/'
        return 0
    fi
    printf '%s' "${value%%*(/)}"
}

# Знімає префікс протоколу: https://api.internal.net -> api.internal.net
# Список схем перелічено явно: @(...) зіставляє рівно один варіант.
strip_url_scheme() {
    local value=$1
    printf '%s' "${value##@(http|https|ftp|ftps|file)://}"
}
