#!/usr/bin/env bash
# Захоплення змінної (variable capture) при передаванні імені у функцію —
# і робочий спосіб його уникнути.
#
# Корінь пастки — динамічна область видимості: пошук імені починається з
# найглибшого локального фрейму й піднімається вгору. Тому nameref
# знаходить ПЕРШУ видиму змінну з такою назвою, а не обов'язково ту, яку
# мав на увазі викликач. Достатньо, щоб проміжна функція бібліотеки мала
# власну тимчасову змінну з тим самим «природним» іменем.
#
# Потрібен Bash 4.3+ (nameref). Запуск: ./nameref-capture-demo.sh
set -uo pipefail

if (( BASH_VERSINFO[0] < 4 || (BASH_VERSINFO[0] == 4 && BASH_VERSINFO[1] < 3) )); then
    printf 'Потрібен Bash 4.3+ (nameref), маємо %s\n' "$BASH_VERSION" >&2
    exit 1
fi

# --- Наївна бібліотека: короткі імена локальних змінних ---------------------

naive_set_value() {
    local -n target=$1
    target=$2
}

# Проміжна функція тримає свій лічильник у змінній `count`. Ім'я коротке й
# «природне» — і саме воно перехоплює запис, коли викликач попросить
# записати у ВЛАСНУ змінну з такою самою назвою.
naive_bump() {
    local count=100
    naive_set_value "$1" 999
    printf '    локальна count усередині naive_bump: %s\n' "$count"
}

# --- Захищена бібліотека: усі локальні мають префікс простору імен ----------

# 0 — записано, 1 — попросили записати у власне посилання функції.
safe_set_value() {
    # Самозахоплення: якщо викликач передав назву НАШОГО ж посилання,
    # bash утворив би циклічне посилання, а запис пішов би в нікуди.
    # Перевіряємо ДО оголошення nameref — після нього питати нема в кого.
    if [[ $1 == __safe_dest_ref ]]; then
        printf 'safe_set_value: передано назву власного посилання\n' >&2
        return 1
    fi

    local -n __safe_dest_ref=$1
    local __safe_value=$2
    __safe_dest_ref=$__safe_value
}

# Тимчасова змінна має префікс модуля, тож збіг із назвою змінної викликача
# практично неможливий — і захоплення не відбувається.
safe_bump() {
    local __safe_bump_count=100
    safe_set_value "$1" 999
    printf '    локальний лічильник усередині safe_bump: %s\n' "$__safe_bump_count"
}

# Читання не потребує nameref узагалі: непряме розгортання ${!name} нічого
# не мутує, тож і захоплювати нічого. Форма з "-" не падає під set -u.
read_value() {
    local __read_value_name=$1
    printf '%s' "${!__read_value_name-}"
}

main() {
    local count

    printf '# Наївний варіант\n'
    count=1
    naive_bump count
    printf '    змінна викликача count=%s — мутували не ту змінну\n' "$count"

    printf '# Захищений варіант\n'
    count=1
    safe_bump count
    printf '    змінна викликача count=%s\n' "$count"

    printf '# Читання без мутації\n'
    printf '    ${!name} -> %s\n' "$(read_value count)"

    printf '# Самозахоплення посилання\n'
    safe_set_value __safe_dest_ref 42 \
        || printf '    відмовлено — саме так і має бути\n'
}

main "$@"
