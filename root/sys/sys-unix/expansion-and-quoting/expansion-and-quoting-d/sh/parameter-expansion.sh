#!/usr/bin/env bash
# Фаза 3: розгортання параметрів. Оболонка вміє різати рядок масками —
# для шляхів це замінює basename(1) і dirname(1), не породжуючи процесу.
set -u

# Друкуємо запис і його результат. Запис іде АРГУМЕНТОМ, а не форматом:
# інакше printf спробував би витлумачити %-послідовності всередині нього.
p() { printf '%-26s %s\n' "$1" "$2"; }

path=/var/log/nginx/access.log.1
p 'вихідний шлях' "$path"

echo '--- обрізання з початку (#) і з кінця (%) ---'
p '${path##*/}' "${path##*/}"     # найдовший збіг з початку → ім'я файла
p '${path#*/}'  "${path#*/}"      # найкоротший збіг з початку → перший сегмент геть
p '${path%/*}'  "${path%/*}"      # найкоротший з кінця → каталог
p '${path%%/*}' "${path%%/*}"     # найдовший з кінця → порожній рядок

file=${path##*/}
p '${file%%.*}' "${file%%.*}"     # access
p '${file%.*}'  "${file%.*}"      # access.log
p '${#path}'    "${#path}"        # довжина значення в символах

echo '--- значення за замовчуванням ---'
unset -v OPT_A
OPT_B=''
p '${OPT_A:-типове}' "${OPT_A:-типове}"   # змінної немає
p '${OPT_B:-типове}' "${OPT_B:-типове}"   # порожнє прирівняно до відсутнього
p '${OPT_B-типове}'  "${OPT_B-типове}"    # без двокрапки порожнє — дійсне значення
p '${OPT_A:+є}'      "${OPT_A:+є}"        # порожньо: змінної немає
OPT_B=admin
p '${OPT_B:+є}'      "${OPT_B:+є}"        # значення є — підставили альтернативу

# := не лише підставляє, а й ПРИСВОЮЄ. Двокрапка попереду — команда-порожняк,
# бо саме розгортання нам тут потрібне заради побічного ефекту.
unset -v CACHE_DIR
: "${CACHE_DIR:=/tmp/cache}"
p 'після ${CACHE_DIR:=…}' "$CACHE_DIR"

# :? зупиняє скрипт, тож перевіряємо його в підоболонці — інакше тут усе й скінчиться.
unset -v REQUIRED
if ( : "${REQUIRED:?змінну не задано}" ) 2>/dev/null; then
    echo 'несподівано: підоболонка вціліла'
else
    echo 'підоболонка впала на ${REQUIRED:?…} — саме так падають і скрипти'
fi

echo '--- заміна й регістр (Bash 4+) ---'
p '${path/log/LOG}'  "${path/log/LOG}"    # перше входження
p '${path//log/LOG}' "${path//log/LOG}"   # усі входження
p '${path//\//:}'    "${path//\//:}"      # слеш у масці екрановано

name='ivan petrenko'
p '${name^}'  "${name^}"
p '${name^^}' "${name^^}"
upper=IVAN
p '${upper,}'  "${upper,}"
p '${upper,,}' "${upper,,}"
