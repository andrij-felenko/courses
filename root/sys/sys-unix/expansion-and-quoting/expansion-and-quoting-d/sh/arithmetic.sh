#!/usr/bin/env bash
# Арифметичне розгортання $(( … )): цілі числа, 64 біти зі знаком.
set -u

p() { printf '%-34s = %s\n' "$1" "$2"; }

x=6
y=7

echo '--- імена змінних усередині дужок долара не потребують ---'
p '$(( x * y ))'   "$(( x * y ))"
p '$(( $x + $y ))' "$(( $x + $y ))"     # з доларом теж дозволено

echo '--- набір операторів успадковано від C ---'
p '$(( x > y ? x : y ))' "$(( x > y ? x : y ))"   # тернарний
p '$(( 1 << 10 ))'       "$(( 1 << 10 ))"         # зсув
p '$(( 0xff & 0x0f ))'   "$(( 0xff & 0x0f ))"     # побітове І, шістнадцяткові
p '$(( 2#1011 ))'        "$(( 2#1011 ))"          # число в основі 2
p '$(( 17 / 5 ))'        "$(( 17 / 5 ))"          # ділення цілочисельне
p '$(( 17 % 5 ))'        "$(( 17 % 5 ))"

echo '--- присвоєння працює й без підстановки результату ---'
count=0
(( count += 5, count *= 2 ))
p 'count після (( += , *= ))' "$count"

echo '--- 64-бітний знаковий тип: за межею значення загортається ---'
p '$(( 9223372036854775807 + 1 ))' "$(( 9223372036854775807 + 1 ))"

echo '--- ділення на нуль — помилка розгортання, а не нуль у результаті ---'
divisor=0
# Дужки з перенаправленням ставимо НАВКОЛО групи: інакше повідомлення про
# помилку встигне вийти у stderr до того, як подіє перенаправлення.
if result=$( { echo "$(( 10 / divisor ))"; } 2>/dev/null ); then
    p 'ділення' "$result"
else
    echo 'підстановку відхилено, статус ненульовий — скрипт це може перевірити'
fi

echo '--- дійсних чисел в оболонці немає ---'
# $(( 17 / 5.0 )) — синтаксична помилка; дробову частину рахує зовнішня утиліта.
printf 'через awk: %s\n' "$(awk 'BEGIN { printf "%.2f", 17 / 5 }')"
