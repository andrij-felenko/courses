#!/usr/bin/env bash
# Показує межі аргументів після розгортання: те саме ім'я файла
# без лапок і в подвійних лапках, спершу очима функції, потім очима xtrace.
set -u

work="$(mktemp -d)" || exit 1
trap 'rm -rf -- "$work"' EXIT   # тимчасова тека зникає і після помилки

: > "$work/my document.txt"
FILE="$work/my document.txt"

# Функція друкує рівно те, що ядро побачило б у argv[] при execve(2).
show_argv() {
    printf 'слів: %d\n' "$#"
    local i=1
    for arg in "$@"; do
        printf '  argv[%d] = «%s»\n' "$i" "$arg"
        i=$((i + 1))
    done
}

echo '--- без лапок: Word Splitting розбиває шлях по пробілу ---'
show_argv $FILE

echo '--- у подвійних лапках: поділ на слова пригнічено ---'
show_argv "$FILE"

# PS4 задає префікс трасування; $LINENO показує, який рядок скрипту виконується.
# xtrace друкує команду ПІСЛЯ всіх фаз розгортання й видалення лапок,
# але ДО її виконання — і сам бере в одинарні лапки слова з пробілами.
PS4='+ [рядок $LINENO] '
set -x
ls -l $FILE || echo 'очікувана невдача: ls дістав два неіснуючих імені'
ls -l "$FILE"
set +x

# Для порівняння: set -v друкує рядок ДО розгортання, як його набрано.
set -v
ls -l "$FILE" > /dev/null
set +v
