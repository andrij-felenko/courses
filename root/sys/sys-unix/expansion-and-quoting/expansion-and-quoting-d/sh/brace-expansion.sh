#!/usr/bin/env bash
# Фаза 1 конвеєра: розгортання фігурних дужок.
# Воно суто текстове — працює до перевірки змінних і до будь-якого звертання
# до файлової системи, тому породжує слова навіть для неіснуючих файлів.
set -u

# Друкує вихідний запис і всі слова, які з нього утворилися.
show() {
    local src=$1
    shift
    printf '%-26s %d сл.' "$src" "$#"
    if [ "$#" -gt 0 ]; then
        printf ' [%s]' "$@"
    fi
    printf '\n'
}

echo '--- списки ---'
show 'file_{A,B}.txt'     file_{A,B}.txt
show 'img{,-2x}.png'      img{,-2x}.png         # порожній елемент теж елемент
show '{src,test}/{a,b}.c' {src,test}/{a,b}.c    # добуток двох списків
show '{a,b{1,2},c}'       {a,b{1,2},c}          # довільне вкладення

echo '--- діапазони ---'
show '{1..5..2}'   {1..5..2}
show '{10..0..-5}' {10..0..-5}    # крок може бути від'ємним
show '{01..05}'    {01..05}       # провідні нулі задають ширину поля
show '{a..e}'      {a..e}         # символьний діапазон

echo '--- коли розгортання НЕ відбувається ---'
show '{single}' {single}     # немає ні коми, ні коректного діапазону
show "'{A,B}'"  '{A,B}'      # лапки скасовують фазу цілком
show '\{A,B\}'  \{A,B\}      # те саме зворотним слешем

echo '--- порядок фаз: дужки спрацьовують раніше за глобінг ---'
work=$(mktemp -d) || exit 1
trap 'rm -rf -- "$work"' EXIT
: > "$work/report_A.txt"          # report_B.txt навмисно не створюємо

cd "$work" || exit 1
show 'report_{A,B}.txt' report_{A,B}.txt
show 'report_*.txt'     report_*.txt
echo 'дужки дали два слова, хоч на диску лежить лише один файл:'
ls -1
