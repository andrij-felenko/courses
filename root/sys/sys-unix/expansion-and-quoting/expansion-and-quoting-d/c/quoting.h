/* quoting.h — примітиви розбору лапок і поділ сирого рядка на слова.
 *
 * Лапки тут НЕ знімаються. Фаза 1 (дужки) мусить бачити їх на місці, бо
 * саме лапки її й скасовують: '{A,B}' лишається трьома символами тексту.
 * Знімає лапки фаза 6 — вона живе у word.c.
 */
#ifndef QUOTING_H
#define QUOTING_H

#include <stddef.h>

#include "strvec.h"

/* Чи є байт роздільником слів на етапі лексики. */
int quoting_is_blank(char c);

/* Індекс першого байта ПІСЛЯ лапки чи екрана, що починається на line[i];
   для звичайного байта — просто i + 1. Незакрита лапка тягнеться до кінця
   рядка: так помилку побачить той, хто вміє про неї сказати. */
size_t quoting_skip(const char *line, size_t i);

/* Поділ рядка на сирі слова за незахищеними пробілами. 0 або -1. */
int quoting_split_words(const char *line, strvec *out);

#endif /* QUOTING_H */
