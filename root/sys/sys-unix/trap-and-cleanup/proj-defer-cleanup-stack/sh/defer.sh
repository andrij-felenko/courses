#!/usr/bin/env bash
# ==============================================================================
# defer.sh — Промислова бібліотека надійного прибирання ресурсів для Bash
# ==============================================================================
# Сумісність: Bash 4.0+
# ==============================================================================

# Глобальний масив для збереження команд очищення
declare -a __DEFER_STACK=()

# Атомарний прапорець стану виконання стека (захист від рекурсії)
declare -i __DEFER_RUNNING=0

# Додавання довільної команди або блоку коду до стека очищення
defer() {
    local cmd="$*"
    if [[ -z "${cmd}" ]]; then
        echo "defer: помилка: передано порожній рядок дії" >&2
        return 1
    fi
    __DEFER_STACK+=("${cmd}")
}

# Розгортання та послідовне виконання стека
__defer_execute() {
    # Зберігаємо вихідний код повернення попередньої операції
    local orig_exit_code=$?
    
    # Якщо стек уже виконується, негайно повертаємо керування
    if (( __DEFER_RUNNING != 0 )); then
        return 0
    fi
    __DEFER_RUNNING=1

    local total=${#__DEFER_STACK[@]}
    if (( total > 0 )); then
        # Ітерація від останнього доданого індексу до нульового (LIFO)
        for (( idx = total - 1; idx >= 0; idx-- )); do
            local action="${__DEFER_STACK[idx]}"
            # Виконуємо команду через eval.
            # Обов'язково додаємо '|| true', щоб збій однієї команди не зупинив решту
            eval "${action}" >&2 2>&1 || true
        done
    fi

    # Відновлюємо оригінальний статус завершення сценарію
    return "${orig_exit_code}"
}

# Обробник асинхронних сигналів операційної системи
__defer_handle_signal() {
    local sig="$1"
    
    # 1. Скидаємо обробник сигналу на стан ядра за замовчуванням (SIG_DFL)
    trap - "${sig}"
    
    # 2. Посилаємо сигнал самі собі.
    # Ядро поставить сигнал у чергу процесу. Перед смертю процес викличе
    # пастку trap EXIT (де відпрацює __defer_execute), після чого
    # завершиться безпосередньо від сигналу з кодом 128 + SIG.
    kill -s "${sig}" "$$"
}

# Ініціалізація глобальних пасток оболонки
defer_init() {
    # Реєстрація головного хука на завершення роботи
    trap '__defer_execute' EXIT

    # Перехоплення стандартних сигналів переривання та зупинки
    local sig
    for sig in INT TERM HUP QUIT; do
        trap "__defer_handle_signal ${sig}" "${sig}"
    done
}
