/* Крок 4 фази 5: консоль нового кореня.
 *
 * Дескриптори 0, 1 і 2 процес дістав від ядра ще у фазі 3 — вони вказують на
 * вузол /dev/console старої rootfs. Сам пристрій нікуди не подівся (devtmpfs
 * ми перенесли цілим), але після підміни кореня консоль правильніше відкрити
 * заново з нового дерева: так системний менеджер дістане саме той вузол,
 * який описує конфігурація нової системи.
 *
 * Крок необов'язковий: не вдалося — працюємо на успадкованих дескрипторах.
 */

#define _GNU_SOURCE
#include <fcntl.h>
#include <unistd.h>

#include "log.h"
#include "steps.h"

void reopen_console(void)
{
	int fd;

	/* O_NOCTTY: керівним терміналом консоль зробить системний менеджер,
	 * а не ми — випадково захопити його тут було б неввічливо. */
	fd = open("/dev/console", O_RDWR | O_NOCTTY);
	if (fd < 0) {
		boot_errno("open", "/dev/console");
		boot_err("лишаю успадковані дескриптори 0, 1, 2");
		return;
	}

	/* dup2 сам закриває ціль, тож перевіряти зайнятість 0/1/2 не треба.
	 * dup2(fd, fd) — не помилка, а тотожність, тому окремої гілки на
	 * випадок fd <= 2 теж не потрібно. */
	if (dup2(fd, STDIN_FILENO) < 0 ||
	    dup2(fd, STDOUT_FILENO) < 0 ||
	    dup2(fd, STDERR_FILENO) < 0)
		boot_errno("dup2", "/dev/console");

	/* А ось закривати можна лише зайвий дескриптор: якщо котрийсь зі
	 * стандартних був закритий, open міг сісти просто на нього. */
	if (fd > STDERR_FILENO)
		close(fd);
}
