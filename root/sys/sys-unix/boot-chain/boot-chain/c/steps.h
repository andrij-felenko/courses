#ifndef STEPS_H
#define STEPS_H

/* Кроки переходу з initramfs на справжній корінь — рівно ті, що перелічені
   у фазі 5, і в тому самому порядку. Реалізація кожного лежить в окремому
   файлі, а main.c лише проганяє їх один за одним.

   Розподіл відповідальності однаковий скрізь:
     - те, без чого перехід неможливий, повертає -1 і зупиняє main;
     - те, що робиться "за можливості" (перенесення, чистка), повертає
       кількість невдач і йде далі.
   PID 1 не має куди відступати: його завершення — це паніка ядра, а не
   повідомлення про помилку, тож зупинятися можна лише там, де наступний
   крок був би небезпечним. */

/* checks.c — усе, що перевіряється ДО першої незворотної дії: ми справді
   PID 1, старий корінь живе в пам'яті, newroot є окремою змонтованою ФС,
   а init на ньому запускний. 0 — можна йти далі, -1 — не можна. */
int ensure_can_switch(const char *newroot, const char *init);

/* mounts.c — знімає з дерева монтувань спільне поширення (shared).
   Без цього MS_MOVE нижче відмовляє з EINVAL. 0 — успіх. */
int make_mount_tree_private(void);

/* mounts.c — переставляє /dev, /proc, /sys та /run зі старого кореня
   всередину newroot системним викликом mount(..., MS_MOVE, ...).
   Демонтувати їх не можна: на них тримаються відкриті дескриптори
   й активні структури ядра. Повертає кількість неперенесених. */
unsigned long move_special_mounts(const char *newroot);

/* wipe.c — рекурсивно стирає вміст файлової системи, якій належить rootfd.
   Усе, що лежить на ІНШОМУ пристрої (тобто кожна точка монтування,
   включно з новим коренем), лишається недоторканим.
   Повертає кількість записів, які стерти не вдалося. */
unsigned long wipe_filesystem(int rootfd);

/* console.c — перевідкриває /dev/console вже в новому корені й ставить його
   на дескриптори 0, 1, 2. Не вийшло — лишаються успадковані від ядра, тому
   крок нічого не повертає. */
void reopen_console(void);

#endif /* STEPS_H */
