#!/bin/sh
# ci-gate.sh — потоковий валідатор журналу збірки.
#
# sed друкує перший критичний рядок і виходить із кодом 2, не дочитуючи решту
# журналу: на 10-гігабайтному файлі це різниця між секундою й десятками хвилин.
set -u

LOG=${1:-build.log}

if [ ! -r "$LOG" ]; then
    echo "ci-gate: журнал $LOG не читається" >&2
    exit 2
fi

sed -n '/CRITICAL_PANIC/ { p; q 2; }' "$LOG"
status=$?

case $status in
    0)
        echo "ci-gate: критичних відмов не знайдено"
        ;;
    2)
        echo "ci-gate: збірку зупинено через критичну помилку в коді" >&2
        exit 1
        ;;
    141)
        # 128 + SIGPIPE: споживач нижче по конвеєру закрився раніше за sed
        echo "ci-gate: канал обірвано споживачем" >&2
        exit 1
        ;;
    *)
        echo "ci-gate: sed завершився з кодом $status" >&2
        exit "$status"
        ;;
esac
