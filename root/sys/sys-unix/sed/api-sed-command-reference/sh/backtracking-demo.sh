#!/bin/sh
# backtracking-demo.sh — заміряє ціну бектрекінгу в рушії регулярних виразів sed.
#
# Скрипт нічого не стверджує наперед: він проганяє три шаблони на вхідних
# рядках, що ростуть, і друкує заміряний час. Різниця між лінійним відкиданням
# і повним перебором видно просто з таблиці.
#
# Запуск: sh backtracking-demo.sh [макс_довжина]
set -u

LIMIT=${SED_DEMO_TIMEOUT:-10}      # скільки секунд даємо одному прогону
MAXLEN=${1:-30}

if ! command -v timeout >/dev/null 2>&1; then
    echo "backtracking-demo: потрібна утиліта timeout(1)" >&2
    exit 2
fi

# Рядок із n символів 'x' і фінальним '!'. Збігу з шаблоном НЕМАЄ — і саме
# невдалий збіг змушує рушій перебрати всі розбиття послідовності.
make_input() {
    n=$1
    s=''
    i=0
    while [ "$i" -lt "$n" ]; do
        s="${s}x"
        i=$((i + 1))
    done
    printf '%s!\n' "$s"
}

# Один замір: шаблон, довжина входу. Друкує секунди або мітку зупинки.
probe() {
    pattern=$1
    n=$2
    start=$(date +%s)
    make_input "$n" | timeout "$LIMIT" sed -E "s/$pattern/MATCH/" >/dev/null 2>&1
    rc=$?
    end=$(date +%s)
    if [ "$rc" -eq 124 ]; then
        printf '%-14s' ">${LIMIT}s стоп"
    else
        printf '%-14s' "$((end - start))s"
    fi
}

printf '%-9s%-14s%-14s%-14s\n' "довжина" "(x+)+y" "()(x+)+y\\1" "^x+y\$"
printf '%-9s%-14s%-14s%-14s\n' "" "DFA-фільтр" "чистий NFA" "прив'язаний"

n=18
while [ "$n" -le "$MAXLEN" ]; do
    printf '%-9s' "$n"
    # 1) Класичний «катастрофічний» шаблон. У GNU sed його рятує швидкий
    #    DFA-фільтр: рядок без 'y' відкидається за один лінійний прохід.
    probe '(x+)+y' "$n"
    # 2) Той самий шаблон плюс порожня група і посилання \1. Мова та сама
    #    (\1 завжди збігається з порожнім рядком), але саме зворотне посилання
    #    вимикає DFA — лишається перебір розбиттів на NFA.
    probe '()(x+)+y\1' "$n"
    # 3) Прив'язаний і специфічний шаблон: перебирати нема чого.
    probe '^x+y$' "$n"
    printf '\n'
    n=$((n + 2))
done
