# Вимкнути відлуння клавіш (наприклад, для безпечного читання пароля)
stty -echo

# Увімкнути відлуння назад
stty echo

# Перемкнути термінал у повністю сирий режим (аналог cfmakeraw())
stty raw

# Повернути термінал у нормальний канонічний режим
stty -raw   # або: stty cooked

# Перепризначити клавішу забою (Backspace) на код 0x08 (^H) або 0x7F (^?)
stty erase '^?'
stty erase '^H'

# Перепризначити клавішу переривання на іншу комбінацію
stty intr '^C'
