int p[2];
if (pipe(p) < 0) return -1;

pid_t pid = fork();
if (pid > 0) {                      /* пускач */
    close(p[1]);                    /* йому потрібен лише кінець читання */
    char c;
    ssize_t n = read(p[0], &c, 1);  /* блокується, доки демон не озветься */
    _exit(n == 1 && c == 'R' ? 0 : 1);
}
close(p[0]);                        /* далі — майбутній демон */
/* setsid, друге розділення, дескриптори, сигнали, ініціалізація… */
write(p[1], "R", 1);                /* готовий: порт відкрито, конфіг прочитано */
close(p[1]);
