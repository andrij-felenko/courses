/* так не можна: розкладка залежить від розрядності */
struct bad_cfg {
        int     n;
        void   *buf;
        long    len;
};

/* так треба: однаково для 32- і 64-бітних програм */
struct good_cfg {
        __u32   n;
        __u32   flags;
        __u64   buf;      /* адреса як число, не покажчик */
        __u64   len;
        __u64   __pad;    /* запас на майбутнє, мусить бути 0 */
};
