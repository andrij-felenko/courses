# Чи влізе бажана телеметрія у повітряний канал модема?
# Серійна швидкість тут НЕ важить — обмежує повітряна.

def fits(air_bps, need_bps):
    usable = air_bps * 0.90             # ~90% без корекції помилок
    return need_bps <= usable

air  = 64000.0                          # повітряна швидкість SiK, біт/с
need = 8000.0                           # кілька потоків телеметрії
print(f"повітряна:    {air:.0f} б/с")
print(f"корисна:      {air * 0.90:.0f} б/с")   # 57600
print(f"влізе? {'так' if fits(air, need) else 'ні'}")  # так
