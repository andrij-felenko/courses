import math

# стан апарата на цей такт (зі стеку локалізації)
# px, py, theta — позиція [м] і курс [рад]
# v             — поточна швидкість [м/с]
# gx, gy        — ціль-точка на шляху (світові координати) [м]

# параметри апарата/налаштування
wheelbase = 0.32   # колісна база [м]
k_look    = 0.9    # коеф. випередження [с]
L_min     = 0.4    # мінімальне випередження [м]
delta_max = 0.5    # межа кута керма [рад]

# 1) випередження, пропорційне швидкості (з нижньою межею)
L = max(k_look * v, L_min)

# 2) бічний зсув цілі в системі апарата (поворот на -theta)
dx = gx - px
dy = gy - py
x  = -math.sin(theta) * dx + math.cos(theta) * dy

# 3) кривина дуги pure pursuit
kappa = 2.0 * x / (L * L)

# 4) переклад у кут керма (велосипедна модель) + затиск межами
delta = math.atan(wheelbase * kappa)
delta = max(-delta_max, min(delta_max, delta))

steer_set(delta)          # видати наказ керму
