#include <stdint.h>

// f — 25 байтів кадру S.BUS (f[0]==0x0F, f[24]==0x00).
// Канал 1 = усі 8 біт f[1] + молодші 3 біти f[2], зсунуті на 8 позицій угору.
uint16_t sbus_ch1_raw(const uint8_t *f) {
    // (f[1]) дає біти 0..7; (f[2] & 0x07) дає біти 8..10.
    return (uint16_t)( f[1] | ((f[2] & 0x07) << 8) );   // 0..2047
}

// Сире значення S.BUS (≈192..1792) → мікросекунди (1000..2000).
int sbus_raw_to_us(uint16_t raw) {
    // опорні точки Futaba: 192 → 1000 мкс, 1792 → 2000 мкс
    // нахил = (2000 − 1000) / (1792 − 192) = 1000 / 1600 = 0.625 мкс/крок
    return 1000 + (int)((int32_t)(raw - 192) * 1000 / 1600);
}

