// 22 байти даних → 16 каналів по 11 біт, little-endian
// Ідея: тримаємо «конвеєр бітів» у 32-бітному акумуляторі
void crsf_unpack_channels(const uint8_t *data, uint16_t ch[16]) {
    uint32_t acc = 0;   // накопичувач бітів
    int bits = 0;       // скільки валідних бітів зараз в acc
    int c = 0;          // індекс каналу
    for (int i = 0; i < 22 && c < 16; ++i) {
        acc |= (uint32_t)data[i] << bits;   // додаємо байт зверху
        bits += 8;
        if (bits >= 11) {                   // назбиралось на канал
            ch[c++] = acc & 0x7FF;          // нижні 11 біт = 0x7FF
            acc >>= 11;                      // прибираємо їх
            bits -= 11;
        }
    }
}

// data = { 0xE8, 0x03, 0x9F, ... }:
//   i=0: acc = 0x0000_00E8, bits = 8   (8 < 11, ще рано)
//   i=1: acc |= 0x03 << 8 = 0x0000_03E8, bits = 16
//        16 ≥ 11 → ch[0] = 0x03E8 & 0x7FF = 0x3E8 = 1000
//        acc >>= 11 → 0x0000_0000, bits = 5
//   … канал 0 = 1000 (сире значення CRSF)
