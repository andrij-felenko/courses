# Вивести всі активні параметри з зазначенням файлу, де їх визначено
pip config list -v

# Отримати поточне значення конкретного параметра
pip config get global.index-url

# Встановити нове значення в конфігураційний файл поточного віртуального середовища
pip config --site set global.index-url https://artifactory.corp/simple

# Переглянути статистику локального кешу пакетів
pip cache info

# Повністю очистити кеш коліс та HTTP-відповідей
pip cache purge

# Вивести повний діагностичний звіт про системні шляхи, CA-сертифікати та теги коліс
pip debug
