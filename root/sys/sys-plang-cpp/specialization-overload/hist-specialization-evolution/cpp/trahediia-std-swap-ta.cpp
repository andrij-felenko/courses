// 1. Первинний шаблон для довільного типу
template<typename T>
void f(T);

// 2. Повна спеціалізація первинного шаблону для вказівника на int
template<>
void f<int*>(int*);

// 3. Нове перевантаження первинного шаблону для довільних вказівників
template<typename T>
void f(T*);

int main() {
    int* p = nullptr;
    f(p); // Яка функція буде викликана?
}
