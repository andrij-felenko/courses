std::string s1 = "Hello World";
std::string s2 = s1; // Обидва рядки ділять один буфер у купі!

const char* p1 = s1.data(); // Вказівник на символ 'H'

s2[0] = 'X'; // COW розділяє буфер: s2 виділяє новий буфер!
             // Буфер s1 залишається незмінним, але...
             // виклик non-const operator[] на s2 міг викликати unshare()!

