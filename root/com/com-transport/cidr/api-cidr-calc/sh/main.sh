# Перегляд інтерфейсів із префіксами у CIDR-форматі:
ip -4 addr show

# Призначення IP-адреси з префіксом /26 на мережевий адаптер:
sudo ip addr add 198.51.100.45/26 dev eth0

# Додавання статичного маршруту для агрегованого блоку /22 через шлюз:
sudo ip route add 198.51.100.0/22 via 10.0.0.1 dev eth0

# Перевірка вибору маршруту за правилом Longest Prefix Match для конкретної IP:
ip route get 198.51.100.45
# Виводить вихідний інтерфейс, точний співпалий префікс та адресу next-hop.

# Автоматичний розрахунок параметрів підмережі через ipcalc:
ipcalc 198.51.100.45/26
