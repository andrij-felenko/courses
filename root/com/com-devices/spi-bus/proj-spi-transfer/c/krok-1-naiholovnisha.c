#include <stdint.h>

// Обмін одним байтом: повертає те, що прийшло від веденого,
// поки ми висували tx. Це і пише, і читає за одну операцію.
uint8_t spi_transfer(uint8_t tx) {
    SPI_DATA = tx;                       // покласти байт у зсувний регістр → пішли 8 тактів
    while (!(SPI_STATUS & SPI_DONE)) {   // чекати, поки апарат прокрутить усі 8 біт
        ;
    }
    return SPI_DATA;                      // у тому самому регістрі вже лежить прийнятий байт
}
