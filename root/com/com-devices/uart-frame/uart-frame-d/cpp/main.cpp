// 'A' = 0x41 = 0100 0001; на дроті біти йдуть молодшим уперед (D0..D7)
//   старт  D0 D1 D2 D3 D4 D5 D6 D7  стоп
//     0    1  0  0  0  0  0  1  0    1     ← 10 біт у форматі 8N1

uint16_t frame = (1u << 9)            // стоп-біт      (позиція 9)
               | ((0x41u & 0xFF) << 1) // 8 біт даних  (позиції 1..8, D0 праворуч)
               | 0u;                   // старт-біт «0» (позиція 0)
// frame = 0b10_1000_0010 = 0x282; молодший біт frame виходить у лінію першим

