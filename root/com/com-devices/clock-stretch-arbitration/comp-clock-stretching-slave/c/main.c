// SCL — відкритий колектор: high = відпустити (ввід), low = тягнути вниз.
// Підняти такт у «1», ПОВАЖАЮЧИ розтягування з боку веденого.
// Повертає 0 — лінія піднялась; -1 — ведений тримає SCL надто довго (зависання).
static int scl_high_respecting_stretch(void) {
    scl_release();                 // відпускаємо: підтяжка тягне лінію в «1»
    int guard = 100000;            // запобіжник: ~межа розумного розтягування
    while (scl_read() == 0) {      // ведений ще тримає SCL унизу?
        if (--guard == 0)
            return -1;             // надто довго → це вже не розтягування, а збій
    }
    return 0;                      // SCL справді високий — такт дійсний
}
