# Довжина чвертьхвильової антени для частоти каналу.
# c у мм/с, щоб одразу дістати міліметри.
def quarter_wave_mm(freq_hz):
    c = 299792458.0 * 1000.0        # швидкість світла, мм/с
    lambda_mm = c / freq_hz          # λ = c / f
    return lambda_mm / 4.0           # чверть хвилі

# 433 МГц → ≈173 мм (17 см);  2.4 ГГц → ≈31 мм (3 см)
ant_433  = quarter_wave_mm(433.0e6)
ant_2400 = quarter_wave_mm(2400.0e6)
