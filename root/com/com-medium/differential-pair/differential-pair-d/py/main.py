from machine import UART, Pin

# DE/RE — спільний вивід керування напрямом приймача-передавача (напр. MAX485):
#   високий → драйвер передає,  низький → приймає.
uart = UART(1, baudrate=115200)
de = Pin(4, Pin.OUT)               # вивід керування напрямом

def rs485_send(buf):
    de.value(1)                    # взяли шину на передачу
    uart.write(buf)                # байти йдуть у драйвер, далі — у пару A/B

    uart.flush()                   # КЛЮЧОВЕ: чекаємо, поки останній біт ПОКИНЕ зсувний регістр,
                                   # інакше вимкнемо драйвер посеред стоп-біта й обріжемо кадр
    de.value(0)                    # відпустили шину — тепер можна приймати
