# Бюджет лінії земля-борт: чи долетить сигнал і з яким запасом.
# Уся арифметика в децибелах — множення потужностей стає додаванням.
from math import log10


def fspl_db(d_km, f_mhz):
    """Загасання у вільному просторі, дБ.  d — км, f — МГц."""
    return 32.44 + 20.0 * log10(d_km) + 20.0 * log10(f_mhz)


p_tx = 20.0     # потужність передавача, дБм (100 мВт)
g_tx = 2.0      # виграш антени передавача, дБі
g_rx = 2.0      # виграш антени приймача, дБі
sens = -110.0   # чутливість приймача, дБм

loss = fspl_db(3.0, 915.0)          # ≈ 101.2 дБ
p_rx = p_tx + g_tx - loss + g_rx    # прийнято, дБм
margin = p_rx - sens                # запас, дБ

print(f"загасання (3 км): {loss:.1f} дБ")    # 101.2
print(f"прийнято:         {p_rx:.1f} дБм")   # -77.2
print(f"запас:            {margin:.1f} дБ")  #  32.8
