package fir

const (
	Q   = 15
	RND = 1 << (Q - 1) // 0.5 молодшого розряду — для округлення
)

// затиск 32-бітного значення у діапазон int16 (насичення замість загортання)
func sat16(v int32) int16 {
	if v > 32767 {
		return 32767
	}
	if v < -32768 {
		return -32768
	}
	return int16(v)
}

// один вихідний відлік КІХ на 3 відводи; b[] і x[] — у Q15
func Fir3Q15(b, x [3]int16) int16 {
	var acc int64 = 0 // широкий акумулятор: сума не переповниться
	for k := 0; k < 3; k++ {
		acc += int64(b[k]) * int64(x[k]) // Q15 × Q15 = Q30, копимо в Q30
	}
	acc = (acc + RND) >> Q      // округлюємо й вертаємо Q30 → Q15
	return sat16(int32(acc))    // звужуємо в 16 біт із насиченням
}
