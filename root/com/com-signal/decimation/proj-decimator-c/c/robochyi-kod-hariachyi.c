/* Подати один вхідний відлік x. Якщо він завершив групу з M входів —
   обчислити вихідний відлік, покласти в *y і повернути 1; інакше 0. */
int decim_put(decim_t *d, q15_t x, q15_t *y)
{
    int64_t acc;
    int idx, k;

    d->buf[d->widx] = x;                        /* записали найновіший відлік */
    if (++d->widx == TAPS) d->widx = 0;         /* обгортання кільця */

    if (++d->phase < d->M) return 0;            /* ще не M-та подача — виходу нема */
    d->phase = 0;                               /* почали нову групу */

    acc = 0;
    idx = (d->widx == 0) ? TAPS - 1 : d->widx - 1;      /* найновіший відлік */
    for (k = 0; k < TAPS; k++) {
        acc += (int64_t)d->h[k] * d->buf[idx];  /* Q15·Q15 = Q30, розширено ДО множення */
        idx = (idx == 0) ? TAPS - 1 : idx - 1;  /* крок назад у часі, з обгортанням */
    }
    acc = (acc + (1 << 14)) >> 15;              /* Q30 → Q15 з округленням (2¹⁴ = ½ LSB) */
    if (acc >  32767) acc =  32767;             /* насичення, а не обгортання */
    if (acc < -32768) acc = -32768;
    *y = (q15_t)acc;
    return 1;
}
