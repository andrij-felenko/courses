// Один такт комплементарного злиття висоти (виклик кожні dt секунд)
float fuse_altitude(float h_prev,   // м: оцінка висоти з минулого такту
                    float v_z,      // м/с: вертикальна швидкість (з оцінювача)
                    float a_z,      // м/с²: верт. прискорення з акселерометра
                    float h_baro,   // м: свіжий вимір барометра
                    float dt,       // с: крок (0.01 при 100 Гц)
                    float alpha)    // довіра до інерції (0..1), тут 0.98
{
    // 1. ПЕРЕДБАЧЕННЯ: куди нас веде інерція за цей такт
    float h_pred = h_prev + v_z * dt + 0.5f * a_z * dt * dt;
    //            = 12.00 + 0.50*0.01 + 0.5*2.0*0.0001
    //            = 12.00 + 0.0050   + 0.0001  = 12.0051 м

    // 2. КОРЕКЦІЯ: підмішуємо барометр часткою (1 - alpha)
    return alpha * h_pred + (1.0f - alpha) * h_baro;
    //   = 0.98*12.0051 + 0.02*12.20
    //   = 11.76500     + 0.24400  = 12.0090 м
}
