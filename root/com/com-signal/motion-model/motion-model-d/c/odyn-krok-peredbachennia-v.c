// Стан руху по одній осі та крок передбачення.
typedef struct { float x; float v; } State;   // положення (м), швидкість (м/с)

// Чисте числення шляху: жодного входу, лише стала швидкість.
void predict(State *s, float dt) {
    s->x += s->v * dt;          // положення набігає на v·dt
    // s->v лишається — модель припускає сталу швидкість
}

// Передбачення з відомим входом: акселерометр дав прискорення a.
void predict_accel(State *s, float a, float dt) {
    s->x += s->v * dt + 0.5f * a * dt * dt;   // рух + розгін за цей такт
    s->v += a * dt;                           // швидкість набігає на a·dt
}
