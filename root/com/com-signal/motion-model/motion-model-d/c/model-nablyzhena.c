// Передбачення наосліп проти правди, якої модель не знає.
float x_est = 0.0f, v_est = 3.0f;    // оцінка: модель сталої швидкості
float x_true = 0.0f, v_true = 3.0f;  // правда
float a_wind = 0.4f;                 // вітер розганяє — CV цього не бачить
float dt = 0.02f;

for (int k = 1; k <= 100; k++) {     // 2 с наосліп, без жодного виміру
    x_est  += v_est  * dt;           // модель веде сталу швидкість
    v_true += a_wind * dt;           // насправді тіло прискорюється
    x_true += v_true * dt;
    if (k % 25 == 0)                 // щопівсекунди: розрив росте
        printf("t=%.1fs  розрив=%.3f м\n", k * dt, x_true - x_est);
}
// t=0.5s  розрив=0.052 м
// t=1.0s  розрив=0.204 м
// t=1.5s  розрив=0.456 м
// t=2.0s  розрив=0.808 м
