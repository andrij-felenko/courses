# Стан руху по одній осі та крок передбачення.
class State:
    def __init__(self, x, v):
        self.x, self.v = x, v          # положення (м), швидкість (м/с)

def predict(s, dt):                    # чисте числення шляху
    s.x += s.v * dt                    # положення набігає на v·dt
    # s.v лишається — модель припускає сталу швидкість

def predict_accel(s, a, dt):           # передбачення з відомим входом
    s.x += s.v * dt + 0.5 * a * dt * dt  # рух + розгін за цей такт
    s.v += a * dt                        # швидкість набігає на a·dt
