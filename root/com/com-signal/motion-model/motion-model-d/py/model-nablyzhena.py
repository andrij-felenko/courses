# Передбачення наосліп проти правди, якої модель не знає.
x_est,  v_est  = 0.0, 3.0     # оцінка: модель сталої швидкості
x_true, v_true = 0.0, 3.0     # правда
a_wind, dt = 0.4, 0.02        # вітер (CV його не бачить), такт

for k in range(1, 101):       # 2 с наосліп, без жодного виміру
    x_est  += v_est  * dt     # модель веде сталу швидкість
    v_true += a_wind * dt     # насправді тіло прискорюється
    x_true += v_true * dt
    if k % 25 == 0:           # щопівсекунди: розрив росте
        print(f"t={k*dt:.1f}s  розрив={x_true - x_est:.3f} м")
# t=0.5s розрив=0.052 · t=1.0s 0.204 · t=1.5s 0.456 · t=2.0s 0.808
