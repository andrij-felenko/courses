M    = 4                       # GF(2^m), тут m = 4
N    = (1 << M) - 1            # довжина n = 2^m − 1 = 15
PRIM = 0b10011                 # примітивний многочлен x⁴+x+1

antilog = [0] * N              # antilog[i] = αⁱ як 4-бітове число
log     = [0] * (N + 1)        # log[v] = показник степеня елемента v
x = 1
for i in range(N):
    antilog[i] = x
    log[x] = i
    x <<= 1                     # множення на α — зсув ліворуч
    if x & (1 << M):           # виліз x⁴ — згортаємо примітивним многочленом
        x ^= PRIM
