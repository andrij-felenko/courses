# Угода про біти: біт i числа (значення 1 << i) ↔ позиція i+1 кодового слова.
# Контрольні позиції 1,2,4 → біти 0,1,3; дані (3,5,6,7) → біти 2,4,5,6.
MASK = (0x55, 0x66, 0x78)   # групи p1, p2, p4
PPOS = (0, 1, 3)            # куди лягає кожен parity


def parity8(x: int) -> int:            # XOR усіх бітів байта
    x ^= x >> 4
    x ^= x >> 2
    x ^= x >> 1
    return x & 1


def ham74_encode(data: int) -> int:    # 4 біти даних → 7-бітне слово
    w = 0
    w |= (data & 1) << 2               # d1 → позиція 3
    w |= ((data >> 1) & 1) << 4        # d2 → позиція 5
    w |= ((data >> 2) & 1) << 5        # d3 → позиція 6
    w |= ((data >> 3) & 1) << 6        # d4 → позиція 7
    for k in range(3):                 # parity = парність своєї групи
        w |= parity8(w & MASK[k]) << PPOS[k]
    return w


def ham74_decode(w: int) -> tuple[int, bool]:  # 7 біт → (4 біти даних, чи лагодили)
    s = 0
    for k in range(3):                 # три перевірки складають синдром
        s |= parity8(w & MASK[k]) << k
    if s:                              # синдром = адреса; перевертаємо біт
        w ^= 1 << (s - 1)
    data = (((w >> 2) & 1)        | (((w >> 4) & 1) << 1)   # збираємо дані
          | (((w >> 5) & 1) << 2) | (((w >> 6) & 1) << 3))  # з позицій 3,5,6,7
    return data, s != 0                # (дані, чи довелося лагодити)
