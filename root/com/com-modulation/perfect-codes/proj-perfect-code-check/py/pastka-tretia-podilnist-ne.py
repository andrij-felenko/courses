def linear_parity_roots(n):
    """Двійковий код, t = 2, гіпотетично досконалий і ЛІНІЙНИЙ.
    Нехай r — скільки з n стовпців мають непарну вагу. Непарний синдром дають
    r стовпців і r(n−r) пар «непарний+парний», разом r(n+1−r); а непарних
    векторів у просторі синдромів рівно половина, V/2.
    Немає цілого r → лінійного досконалого коду такої довжини не існує."""
    V = ball(n, 2, 2)
    if V & (V - 1):                     # V не степінь 2 — синдромів стільки не буває
        return None, None
    D = (n + 1) ** 2 - 4 * (V // 2)     # дискримінант r² − (n+1)r + V/2 = 0
    if D < 0:
        return [], D
    s = isqrt(D)
    if s * s != D:
        return [], D                    # цілого кореня нема → коду нема
    return sorted({(n + 1 - s) // 2, (n + 1 + s) // 2}), D
