CODES = [
    # назва                       n   t   q   M
    ("повторення [3,1]",           3, 1,  2, 2),
    ("повторення [4,1]",           4, 1,  2, 2),
    ("повторення [5,1]",           5, 2,  2, 2),
    ("повторення [3,1] трійкове",  3, 1,  3, 3),
    ("Геммінг [7,4]",              7, 1,  2, 2 ** 4),
    ("Геммінг [15,11]",           15, 1,  2, 2 ** 11),
    ("Геммінг [31,26]",           31, 1,  2, 2 ** 26),
    ("Геммінг [4,2] трійковий",    4, 1,  3, 3 ** 2),
    ("Голей [23,12]",             23, 3,  2, 2 ** 12),
    ("Голей [11,6] трійковий",    11, 2,  3, 3 ** 6),
    ("розшир. Голей [24,12]",     24, 3,  2, 2 ** 12),
    ("SECDED [8,4]",               8, 1,  2, 2 ** 4),
]

def report_table():
    print("%-26s %3s %2s %2s %8s %10s %11s" % ("код", "n", "t", "q", "V", "M", "заповнення"))
    print("─" * 74)
    for name, n, t, q, M in CODES:
        V = ball(n, t, q)
        fill = 100.0 * M * V / q ** n
        verdict = "  ← ДОСКОНАЛИЙ" if is_perfect(n, t, M, q) else ""
        print("%-26s %3d %2d %2d %8d %10d %10.3f%%%s"
              % (name, n, t, q, V, M, fill, verdict))
