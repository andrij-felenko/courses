// Виштовхнути один байт у лінію по одному біту, старшим уперед.
// set_line(bit) кладе рівень на дріт; clock_tick() дає такт приймачу.
void serialize_byte(uint8_t data)
{
    for (int i = 7; i >= 0; i--) {   // від 7-го (старшого) до 0-го (молодшого)
        uint8_t bit = (data >> i) & 1;   // витягли i-й біт
        set_line(bit);                    // поклали його на лінію
        clock_tick();                     // «ось новий біт» — приймач читає
    }
}
