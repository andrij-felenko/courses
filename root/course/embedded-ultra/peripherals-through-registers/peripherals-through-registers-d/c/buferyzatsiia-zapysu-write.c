/* Потенційно хибний обробник переривання в C через буферизацію шини */
void TIM6_DAC_IRQHandler(void) {
    if (TIM6->SR & (1UL << 0)) {
        /* Скидання прапорця події в регістрі таймера */
        TIM6->SR &= ~(1UL << 0);
        
        /* Читання назад для гарантії завершення запису до виходу */
        (void)TIM6->SR;
    }
}
