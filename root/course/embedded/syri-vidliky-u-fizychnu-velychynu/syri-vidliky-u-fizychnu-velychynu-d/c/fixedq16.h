#ifndef FIXEDQ16_H
#define FIXEDQ16_H

#include <stdint.h>

/* Арифметика з фіксованою комою у форматі Q16.16.
   1 біт знака, 15 бітів цілої частини, 16 дробових;
   вага молодшого розряду 2^-16 = 0.0000152587890625. */

#define Q16_FRAC 16
#define Q16_ONE  ((int32_t)1 << Q16_FRAC)
#define Q16_HALF ((int32_t)1 << (Q16_FRAC - 1))

/* Константу рахує КОМПІЛЯТОР на етапі трансляції: у прошивку йде готове
   ціле, жодної плаваючої коми в машинному коді не залишається.
   Вживати лише з літералами, не зі змінними. */
#define Q16_CONST(x) ((int32_t)((x) * 65536.0 + ((x) < 0 ? -0.5 : 0.5)))

/* --- насичення: те, що Cortex-M3/M4/M7 робить інструкцією SSAT --- */

/* Звуження 64→32 біти з обмеженням по краях діапазону. */
int32_t sat_from_i64(int64_t v);
int32_t sat_add_i32(int32_t a, int32_t b);
int32_t sat_sub_i32(int32_t a, int32_t b);
/* Обмеження знакового числа розрядністю bits (аналог SSAT Rd, #bits, Rn). */
int32_t sat_bits(int32_t v, unsigned bits);
int16_t sat_to_i16(int32_t v);

/* --- власне Q16.16 --- */

int32_t q16_from_int(int32_t v);
int32_t q16_to_int(int32_t q);
/* Множення: проміжок у 64 бітах (SMULL), симетричне округлення, насичення. */
int32_t q16_mul(int32_t a, int32_t b);
/* Ділення: ділене піднімається у 64 біти й зсувається на 16 розрядів. */
int32_t q16_div(int32_t a, int32_t b);
/* (raw - zero) * W, де W — вага молодшого розряду у форматі Q16.16.
   Повертає ЦІЛЕ число фізичних одиниць, а не Q16.16. */
int32_t q16_scale_raw(int16_t raw, int16_t zero, int32_t w_q16);

/* Ціла частина квадратного кореня: модуль вектора без FPU. */
uint32_t u64_isqrt(uint64_t v);

#endif /* FIXEDQ16_H */
