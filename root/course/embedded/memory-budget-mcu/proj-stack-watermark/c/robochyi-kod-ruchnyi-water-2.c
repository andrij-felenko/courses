// Залити вільну частину стекової ділянки візерунком.
// Викликати МАКСИМАЛЬНО рано (стартовий код / перший рядок main),
// поки виклична глибина мінімальна.
void stack_paint(void) {
    // поточна вершина стека — приблизно адреса локальної змінної
    uint8_t *sp_now = (uint8_t *)__builtin_frame_address(0);

    // заливаємо від дна (stack_lo) вгору, але НЕ чіпаємо те, на чому
    // стек стоїть зараз: лишаємо запас від поточного sp униз
    uint8_t *fill_to = sp_now - 64;        // 64 Б форою — щоб не затерти живе
    for (uint8_t *p = stack_lo; p < fill_to; ++p) {
        *p = STACK_PATTERN;
    }
}
