#include <stdint.h>
#include <stdbool.h>
#include <math.h>     // fabsf

// Який анти-віндап застосувати. ВИМКНУТИ не можна навмисно —
// "ПІД без анти-віндапу" це найдорожча помилка початківця.
typedef enum {
    AW_CLAMP,        // затиск: простий, надійний, трохи різкий
    AW_BACKCALC,     // зворотний перерахунок: плавніший, потрібен Kaw
} aw_mode_t;

typedef struct {
    // ── НАЛАШТУВАННЯ (задають при ініціалізації) ─────────────────────────
    float Kp, Ki, Kd;        // коефіцієнти регулятора
    float u_min, u_max;      // фізичні межі виходу (стеля/підлога привода)
    float N;                 // "гострість" фільтра похідної (8…20; менше = глухіше)
    float Kaw;               // коеф. зворотного перерахунку (лише для AW_BACKCALC)
    float b, c;              // ваги завдання: b — для P, c — для D (обидва 0…1)
    aw_mode_t aw;            // обраний метод анти-віндапу

    // ── СТАН (живе між викликами; НЕ чіпати ззовні) ──────────────────────
    float integral;          // накопичена сума Ki·∫e dt
    float meas_prev;         // попередній вимір (для похідної від виміру)
    float deriv_filt;        // стан одно-полюсного фільтра похідної
    bool  initialized;       // чи був перший виклик (для коректного старту)
} pid_t;
