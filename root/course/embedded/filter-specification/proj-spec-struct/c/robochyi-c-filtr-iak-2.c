// Юніт-тест 1: наївна спроба — ОДИН біквад проти суворої телефонної маски.
// Наперед: суддя його завалить — і правильно зробить.
int test_single_biquad_vs_phone(void) {
    // ── дано: сувора специфікація з прикладу статті (мікрофон, телефонна смуга) ──
    FilterSpec spec = {
        .fp = 3400.0f, .fs = 4000.0f,
        .Ap_dB = 0.5f, .As_dB = 60.0f,
        .fs_sample = 16000.0f,
    };
    // Найдешевше, що спадає на думку: один біквад 2-го порядку (ФНЧ Баттерворта,
    // зріз ~1.8 кГц). Це рівно ДВА накопичувачі енергії — порядок лише 2.
    Biquad lpf = { .b0=0.0934f, .b1=0.1868f, .b2=0.0934f,
                   .a1=-0.9216f, .a2=0.2951f };

    // ── сітка частот: густо біля fp і fs, де маска тисне найдужче ──────────
    float freq[] = {
        100, 500, 1000, 2000, 3000,
        3300, 3380, 3400,                 // підхід до краю пропускання — включно
        4000, 4050, 4200,                 // одразу за краєм затримання
        5000, 6000, 7000, 7900,           // углиб затримання, до ~Найквіста
    };
    const size_t n = sizeof(freq) / sizeof(freq[0]);
    float mag[sizeof(freq) / sizeof(freq[0])];

    // ── коли: зняли характеристику ────────────────────────────────────────
    sweep(lpf, &spec, freq, mag, n);

    // ── тоді: вкладається в коридор чи ні ─────────────────────────────────
    SpecResult r = spec_check(&spec, freq, mag, n);
    if (!r.pass) {
        printf("ПРОВАЛ: фільтр виліз із маски на %.1f дБ при %.0f Гц\n",
               -r.worst_margin_dB, r.worst_freq);
        return 1;                          // червоний тест — і це ПРАВИЛЬНО
    }
    printf("OK (несподівано): запас %.2f дБ\n", r.worst_margin_dB);
    return 0;
}
