#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include <math.h>     // powf, log10f, fabsf
#include <stdio.h>

// ── Специфікація фільтра низьких частот як маска допуску ──────────────────
// П'ять чисел зі статті. Частоти — у Гц, рівні — у ДОДАТНИХ децибелах
// (Ap_dB = 1.0 означає "дозволено впасти на 1 дБ"; As_dB = 60.0 означає
// "треба прибити на 60 дБ"). Знак нерівності зашитий у логіку перевірки,
// тому самі числа лишаємо натуральними й додатними — так їх і диктує ТЗ.
typedef struct {
    float fp;          // край смуги пропускання, Гц (до неї — берегти)
    float fs;          // край смуги затримання,  Гц (з неї — давити)
    float Ap_dB;       // дозволені брижі пропускання, дБ (напр. 1.0)
    float As_dB;       // потрібне придушення затримання, дБ (напр. 60.0)
    float fs_sample;   // частота дискретизації, Гц (стеля = fs_sample/2)
} FilterSpec;

// ── Перекладачі між децибелами амплітуди й лінійними "разами" ─────────────
// Амплітуда (не потужність!), тому коефіцієнт 20, а не 10 — як у статті.
//   дБ = 20 * log10(|H|)          |H| = 10^(дБ / 20)
// Беремо ABS аргумента: характеристика може приходити зі знаком фази,
// а маска нормує лише МОДУЛЬ коефіцієнта пропускання.
static inline float lin_to_db(float mag) {
    // захист від log10(0): дуже малий модуль = дуже глибоке придушення.
    float m = fabsf(mag);
    if (m < 1e-12f) m = 1e-12f;         // −240 дБ — «практично нуль»
    return 20.0f * log10f(m);
}

static inline float db_to_lin(float db) {
    return powf(10.0f, db / 20.0f);     // 10^(дБ/20)
}
