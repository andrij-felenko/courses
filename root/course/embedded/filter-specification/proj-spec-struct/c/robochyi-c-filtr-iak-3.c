// Юніт-тест 2: ТОЙ САМИЙ біквад, але маска йому до снаги —
// пологий ФНЧ, широкий перехід 1 → 6 кГц, помірне придушення. Тепер буде "так".
int test_single_biquad_gentle(void) {
    // ── дано: м'яка маска, яку біквад 2-го порядку реально тягне ──
    FilterSpec spec = {
        .fp = 1000.0f, .fs = 6000.0f,      // широкий перехід 1 → 6 кГц
        .Ap_dB = 2.0f, .As_dB = 25.0f,     // помірні брижі й придушення
        .fs_sample = 16000.0f,
    };
    Biquad lpf = { .b0=0.0934f, .b1=0.1868f, .b2=0.0934f,
                   .a1=-0.9216f, .a2=0.2951f };   // той самий фільтр, що вгорі

    // ── сітка: смуга пропускання, пропущений перехід, глиб затримання ─────
    float freq[] = {
        100, 300, 600, 900, 1000,          // пропускання, край включно
        2000, 4000,                        // перехідна смуга — не перевіряємо
        6000, 6500, 7000, 7500, 7900,      // затримання, до ~Найквіста
    };
    const size_t n = sizeof(freq) / sizeof(freq[0]);
    float mag[sizeof(freq) / sizeof(freq[0])];

    sweep(lpf, &spec, freq, mag, n);
    SpecResult r = spec_check(&spec, freq, mag, n);

    if (!r.pass) {
        printf("ПРОВАЛ: виліз на %.1f дБ при %.0f Гц\n",
               -r.worst_margin_dB, r.worst_freq);
        return 1;
    }
    // Пройшов — але застережемо, якщо запас підозріло малий:
    if (r.worst_margin_dB < 1.0f)
        printf("УВАГА: запас лише %.2f дБ при %.0f Гц — фільтр на межі\n",
               r.worst_margin_dB, r.worst_freq);
    printf("OK: фільтр відповідає специфікації (запас %.2f дБ при %.0f Гц)\n",
           r.worst_margin_dB, r.worst_freq);
    return 0;                              // зелений тест
}
