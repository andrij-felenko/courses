// Виносить вердикт за вже порахованими числами. Окремо від арифметики,
// щоб логіку рішень було видно й перевіряти незалежно.
void clamp_classify(clamp_input_t in, clamp_result_t *r)
{
    if (!r->valid) { r->verdict = CLAMP_INFEASIBLE; return; }

    // --- прапорці небезпеки ставимо першими: вони важать над вибором класу ---

    // (а) потрібний кламп вищий за те, що тримає ключ (з запасом 15 %)?
    r->clamp_exceeds_bv = (r->clamp_V > in.bv_dss_V * BV_DERATING);

    // (б) у ШІМ — чи не перегріє супресор середня потужність?
    r->pwm_overheat_risk = (r->avg_power_W > SUPPRESSOR_AVG_POWER_LIMIT_W);

    // --- крок 1: чи вистачить простого діода ЗА ШВИДКІСТЮ? ---
    // діод догасить струм за ~5·L/R; якщо це вкладається в бюджет — найдешевше.
    bool diode_fast_enough = (r->diode_decay_s <= in.t_off_target_s);

    if (diode_fast_enough) {
        // діод повільний за напругою (0.7 В), зате й найхолодніший: у ШІМ майже
        // вся потужність осідає на ОПОРІ ОБМОТКИ, не на діоді — перегріву нема.
        r->verdict = CLAMP_SIMPLE_DIODE;
        r->pwm_overheat_risk = false;   // діод-кламп не вантажить супресор
        return;
    }

    // --- діода замало: треба ШВИДКЕ вимкнення (високий кламп) ---

    // крок 2: чи витримає ключ потрібну напругу клампу?
    if (r->clamp_exceeds_bv) {
        // потрібний кламп вищий за пробивну ключа — цим ключем не вдовольнити.
        r->verdict = CLAMP_INFEASIBLE;
        return;
    }

    // крок 3: чи можна покластися на лавину самого ключа замість зовнішнього клампу?
    // тільки для РІДКІСНИХ спрацювань (f≈0): лавина щоцикл зносить кристал.
    bool single_shot = (in.pwm_freq_Hz <= 0.0);
    if (single_shot) {
        r->verdict = CLAMP_AVALANCHE_OK;  // зовнішній кламп не обов'язковий (звір E_AS!)
        return;
    }

    // ШІМ із швидким вимкненням: потрібен зовнішній Зенер/TVS.
    r->verdict = CLAMP_NEED_ZENER_TVS;
}
