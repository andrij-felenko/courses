// kalman2.c — двозмінний фільтр, матриця 2×2 розписана вручну.
#include "kalman2.h"

void kalman2_init(kalman2_t *k, float x0, float b0,
                  float Qx, float Qb, float R)
{
    k->x = x0;
    k->b = b0;
    // Стартова непевність: у величині помірна, у зсуві ВЕЛИКА (нічого про нього
    // не знаємо), зв'язок нульовий — фільтр його сам напрацює.
    k->P00 = 1.0f;  k->P01 = 0.0f;
    k->P10 = 0.0f;  k->P11 = 1.0f;
    k->Qx = Qx;
    k->Qb = Qb;
    k->R  = R;
}

float kalman2_step(kalman2_t *k, float z)
{
    // ── ПЕРЕДБАЧ ──
    // Модель: x ← x, b ← b (обидві сталі), вимір бачить суму h = x + b.
    // Стан не рухається; росте лише непевність — кожна змінна на свій Q.
    // (Якби величина мала динаміку, тут був би й зсув x.)
    k->P00 += k->Qx;          // непевність величини розпливається
    k->P11 += k->Qb;          // непевність зсуву — ледь-ледь (Qb крихітний)
    // P01, P10 від додавання Q не міняються (Q діагональний)

    // ── ВИПРАВ ──
    // Вимір z пов'язаний зі станом як z = x + b + шум, тобто матриця виміру
    // H = [1 1]. Нев'язка та її розкид:
    float y = z - (k->x + k->b);             // нев'язка (innovation)
    float S = k->P00 + k->P01 + k->P10 + k->P11 + k->R;  // H·P·Hᵀ + R

    // Підсилення K = P·Hᵀ / S (вектор-стовпець із двох чисел):
    float K0 = (k->P00 + k->P01) / S;        // на величину
    float K1 = (k->P10 + k->P11) / S;        // на зсув

    // Поправка стану:
    k->x += K0 * y;
    k->b += K1 * y;

    // Оновлення коваріації P ← (I − K·H)·P. Розписано почленно;
    // зберігаємо старі значення, бо нові залежать від старих.
    float P00 = k->P00, P01 = k->P01, P10 = k->P10, P11 = k->P11;
    k->P00 = P00 - K0 * (P00 + P10);
    k->P01 = P01 - K0 * (P01 + P11);
    k->P10 = P10 - K1 * (P00 + P10);
    k->P11 = P11 - K1 * (P01 + P11);

    return k->x;   // очищена від зсуву оцінка
}
