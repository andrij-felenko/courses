// kalman.h — скалярний фільтр Калмана для прошивки.
// Голе залізо: без malloc, фіксований розмір, без блокувань.
#ifndef KALMAN_H
#define KALMAN_H

#include <stdint.h>
#include <stdbool.h>

// Стан одного скалярного фільтра. Заводь по одному на кожну величину.
typedef struct {
    float x;     // оцінка величини
    float P;     // непевність оцінки (дисперсія)
    float Q;     // шум процесу: як мало довіряємо моделі за такт
    float R;     // шум виміру: наскільки шумний давач (дисперсія)
} kalman_t;

// Налаштувати фільтр. x0 — стартова оцінка; P0 — стартова непевність
// (велика, якщо в x0 не певні); Q, R — див. розділ про налаштування.
void  kalman_init(kalman_t *k, float x0, float P0, float Q, float R);

// Один такт «стала величина»: передбач (P росте на Q), тоді виправ виміром z.
// Повертає оновлену оцінку.
float kalman_step(kalman_t *k, float z);

#endif // KALMAN_H
