// kalman.c — реалізація базового скалярного фільтра.
#include "kalman.h"

void kalman_init(kalman_t *k, float x0, float P0, float Q, float R)
{
    k->x = x0;
    k->P = P0;
    k->Q = Q;
    k->R = R;
}

float kalman_step(kalman_t *k, float z)
{
    // ── ПЕРЕДБАЧ ── модель «стала величина»: оцінка не рухається, P росте.
    // x не змінюється;
    k->P += k->Q;                      // непевність розпливається на Q

    // ── ВИПРАВ ── підсилення з поточних непевностей, тоді крок до виміру.
    float K = k->P / (k->P + k->R);    // повзунок довіри 0…1
    k->x += K * (z - k->x);            // крок на частку нев'язки
    k->P  = (1.0f - K) * k->P;         // прийнявши вимір, стали певніші

    return k->x;
}
