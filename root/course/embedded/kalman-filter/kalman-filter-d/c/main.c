/* Стан фільтра живе між викликами */
static float x = 0.0f;        /* оцінка величини (напр. кут) */
static float P = 1.0f;        /* непевність оцінки (дисперсія) */

const float Q = 0.001f;       /* шум процесу: як мало довіряємо моделі за такт */
const float R = 0.05f;        /* шум виміру: наскільки шумний давач */

/* Один такт. z — свіжий вимір давача. Повертає оновлену оцінку. */
float kalman_step(float z)
{
    /* ── ПЕРЕДБАЧ ──
       модель «стала величина»: оцінка не рухається, лише непевність росте */
    /* x = x; */                 /* передбачення стану (тут без змін) */
    P = P + Q;                   /* непевність розпливається на Q */

    /* ── ВИПРАВ ──
       рахуємо підсилення з поточних непевностей, тоді підтягуємо оцінку */
    float K = P / (P + R);       /* повзунок довіри 0…1 */
    x = x + K * (z - x);         /* крок до виміру на частку нев’язки */
    P = (1.0f - K) * P;          /* прийнявши вимір, стали певніші */

    return x;
}
