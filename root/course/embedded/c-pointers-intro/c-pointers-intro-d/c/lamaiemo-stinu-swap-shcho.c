void swap(int *px, int *py) {   // приймаємо АДРЕСИ, а не значення
    int t = *px;                // візьми значення за адресою px
    *px = *py;                  // запиши в оригінал px те, що лежить за py
    *py = t;                    // і навпаки
}

int main(void) {
    int a = 3, b = 7;
    swap(&a, &b);               // передаємо АДРЕСИ a і b
    // тепер a == 7, b == 3 — спрацювало!
}
