#include <stdint.h>
#include <stdbool.h>
#include <stdio.h>
#include <assert.h>   // для _Static_assert у C11

// ── ТЗ на вузол живлення як єдина незмінна структура ───────────────────
// Усі межі — у ЦІЛИХ базових одиницях: напруга у мВ, струм у мА,
// температура в °C, ємність у мкФ, опір у мОм. Жодного float — щоб не
// було ні похибки округлення, ні порівнянь "майже рівно".
typedef struct {
    // ── МЕЖА 1: ВХІД ───────────────────────────────────────────────────
    uint16_t vin_min_mv;       // сіла батарея — найгірше для дотягування виходу
    uint16_t vin_max_mv;       // повна батарея — найгірше за нагрівом
    uint16_t vin_absmax_mv;    // гранично-допустимий вхід (комутаційні викиди!)
    uint16_t vin_droop_mv;     // дозволене просідання входу під пусковим струмом

    // ── МЕЖА 2: ВИХІД ──────────────────────────────────────────────────
    uint16_t vout_mv;          // номінал виходу
    uint8_t  vout_tol_pct;     // допуск виходу, % (вікно навколо номіналу)
    uint16_t vout_ripple_mvpp; // дозволена пульсація, мВ розмаху (peak-to-peak)
    uint16_t vout_noise_mvrms; // дозволений шум, мВ rms (важить для АЦП/радіо)

    // ── МЕЖА 3: НАВАНТАЖЕННЯ ───────────────────────────────────────────
    uint16_t iout_typ_ma;      // середній струм — нагрів і автономність
    uint16_t iout_peak_ma;     // піковий струм — вибір перетворювача
    uint16_t iout_transient_ma;// амплітуда раптового стрибка (load transient)
    uint16_t transient_slew_ma_us; // швидкість стрибка, мА/мкс (тисне на петлю ЗЗ)

    // ── МЕЖА 4: СЕРЕДОВИЩЕ ─────────────────────────────────────────────
    int8_t   ta_min_c;         // нижня межа температури середовища
    int8_t   ta_max_c;         // верхня межа середовища
    int8_t   ta_derate_c;      // температура, з якої починається дератинг
    uint16_t life_hours_kh;    // очікуваний термін служби, тисячі годин
} power_spec_t;

// Конкретне ТЗ: шина 5 В для логіки дрона, живлення від 4S LiPo.
