// p_controller.h — один самодостатній пропорційний контур
#include <stdint.h>
#include <stdbool.h>

typedef struct {
    // ── налаштування (задаються один раз при конфігурації) ─────────────
    float kp;          // пропорційний коефіцієнт [одиниць виходу / одиницю помилки]
    float beta;        // вага завдання в P: 1.0 = P-на-помилці, 0.0 = P-на-вимірі
    float u_min;       // нижня межа виходу (реальна межа виконавчого органу)
    float u_max;       // верхня межа виходу
    float u_bias;      // стала поправка / живлення наперед (0, якщо не треба)

    // ── діагностика останнього такту (тільки для читання ззовні) ───────
    float last_u;      // що віддали минулого разу (до обмеження — сирий)
    bool  saturated;   // чи вихід уперся в межу минулого такту
} p_ctrl_t;
