// Медіана з невеликої вибірки кодів АЦП (стійка до поодиноких викидів).
// Сортування вставками — для 5–9 елементів це швидше за будь-яку «розумну» сортувалку.
uint16_t adc_median(uint16_t *buf, int n) {
    for (int i = 1; i < n; i++) {
        uint16_t key = buf[i];
        int j = i - 1;
        while (j >= 0 && buf[j] > key) { buf[j + 1] = buf[j]; j--; }
        buf[j + 1] = key;
    }
    return buf[n / 2];          // серединний елемент відсортованого масиву
}
