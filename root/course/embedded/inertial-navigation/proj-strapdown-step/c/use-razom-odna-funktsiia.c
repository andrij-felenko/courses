typedef struct {
    quat  q;       /* орієнтація відносно світу */
    vec3  v;       /* швидкість у світових осях, м/с */
    vec3  p;       /* положення у світових осях, м */
    vec3  bias;    /* зсув нуля гіроскопа, виміряний у спокої, рад/с */
} nav_state;

/* Один безкарданний крок інерціальної навігації.
   w_raw — кутова швидкість гіроскопа (рад/с) в осях апарата;
   a_b   — питома сила акселерометра (м/с²) в осях апарата;
   dt    — крок часу від попереднього відліку (с). */
void strapdown_step(nav_state *s, vec3 w_raw, vec3 a_b, float dt) {
    /* 1) ОРІЄНТАЦІЯ: проінтегрувати гіроскоп (мінус bias) і нормувати */
    s->q = orientation_step(s->q, w_raw, s->bias, dt);

    /* 2) ПОВОРОТ: акселерометр з осей апарата → у світові осі */
    vec3 a_world = quat_rotate(s->q, a_b);

    /* 3) ТЯЖІННЯ: відняти сталий вектор g → прискорення руху */
    vec3 a = remove_gravity(a_world);

    /* 4) ПОДВІЙНИЙ ІНТЕГРАЛ (напівнеявний Ейлер: спершу v, тоді p) */
    s->v.x += a.x * dt;  s->v.y += a.y * dt;  s->v.z += a.z * dt;
    s->p.x += s->v.x * dt;  s->p.y += s->v.y * dt;  s->p.z += s->v.z * dt;
}
