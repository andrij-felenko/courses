/* Калібрування в спокої: апарат НЕ рухати N відліків.
   Збираємо середній зсув гіроскопа й нульові швидкість/положення. */
void nav_calibrate_rest(nav_state *s, const vec3 *gyro, int n) {
    vec3 sum = {0, 0, 0};
    for (int i = 0; i < n; i++) {      /* усереднити гіроскоп у спокої */
        sum.x += gyro[i].x;  sum.y += gyro[i].y;  sum.z += gyro[i].z;
    }
    s->bias.x = sum.x / n;             /* це і є зсув нуля */
    s->bias.y = sum.y / n;
    s->bias.z = sum.z / n;

    quat id = {1, 0, 0, 0};            /* старт «рівно»; точніше — з вектора g */
    s->q = id;
    s->v = (vec3){0, 0, 0};            /* знаємо, що стоїмо */
    s->p = (vec3){0, 0, 0};            /* стартуємо з початку координат */
}
