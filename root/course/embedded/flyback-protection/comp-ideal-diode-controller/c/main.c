// Найпростіша "розмова" з контролером ідеального діода з боку МК.
// Багато контролерів взагалі не мають цифрових ніжок — тоді МК їх не чіпає.
// Тут — варіант із дозволом (EN) і сигналом аварії (FLT, open-drain + підтяжка).
#define ID_EN    18   // ніжка "дозвіл" контролера (HIGH = працювати)
#define ID_FLT   19   // ніжка fault: LOW = зворот / зникло джерело (open-drain)

// Увімкнути "ідеальний діод" і переконатися, що джерело справді тримає шину.
bool ideal_diode_enable(void)
{
    gpio_set(ID_EN);                 // дозволили; далі контролер веде затвор сам
    // Дати насосу підняти затвор і серву вийти на робочу точку.
    // Час малий (десятки-сотні мкс), але ненульовий — насос не миттєвий.
    delay_us(300);
    return gpio_get(ID_FLT) != 0;    // FLT неактивний (HIGH) => джерело в нормі, канал веде
}

// Приклад використання у ORing: два входи, кожен зі своїм контролером.
// Нам важливо ЛИШЕ знати, чи є жива шина; перемикання робить кремній сам.
bool rail_is_alive(void)
{
    // Досить, щоб хоч один канал не сигналив аварію: вищий сам тримає шину,
    // нижчий відсічено компаратором зворотного струму без жодного коду.
    return (gpio_get(ID_FLT) != 0) || (gpio_get(ID_FLT_B) != 0);
}
