#include <stdint.h>

// Параметри котушки й захисту (з даташита реле та розрахунку вище)
#define COIL_L_H        0.100f    // індуктивність котушки, Гн
#define COIL_R_OHM      300.0f    // опір обмотки, Ом
#define CLAMP_V         0.7f      // простий гасний діод: тримає ~0.7 В

// Час згасання струму в гасній петлі до практичного нуля (5 сталих часу).
// Саме стільки якір реле ще утримується магнітним полем після "вимкнути".
static uint32_t relay_release_us(void)
{
    float tau = COIL_L_H / COIL_R_OHM;      // τ = L/R
    float t5  = 5.0f * tau;                  // ~99% згасання
    return (uint32_t)(t5 * 1e6f);            // у мікросекунди
}

void relay_off_and_settle(void)
{
    gpio_clear(RELAY_PIN);                    // розмикаємо ключ
    // Гасний діод замикає струм у петлю; чекаємо, поки поле спаде,
    // інакше наступна комутація застане якір ще притягнутим.
    delay_us(relay_release_us());             // для нашого реле ≈ 1670 мкс
}
