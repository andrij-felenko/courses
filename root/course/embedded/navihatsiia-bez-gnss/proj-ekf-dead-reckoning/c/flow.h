/* flow.h — перетворення сирих відліків оптичного потоку PMW3901 на
   вимірювання горизонтальної швидкості, придатне для фільтра.

   Сенсор віддає не швидкість, а зсув текстури в пікселях за час кадру.
   Між цим зсувом і швидкістю апарата стоять три речі, і кожна з них уміє
   зіпсувати вимірювання мовчки:

     · обертання. Кадр зсувається однаково і коли апарат летить, і коли він
       просто нахиляється. Без деротації гіроскопом фільтр приймає нахил за
       політ — це найдорожча помилка в усій схемі;
     · дальність. Кутова швидкість потоку перетворюється на лінійну
       множенням на відстань до поверхні. Помилка в дальності входить у
       швидкість множником, а не доданком;
     · якість поверхні. Над однорідним асфальтом, водою чи в темряві
       сенсор віддає числа, які виглядають правдоподібно, але означають
       шум. Показник SQUAL — єдине, що про це попереджає. */
#ifndef FLOW_H
#define FLOW_H

#include <stdbool.h>
#include <stdint.h>

typedef struct {
    /* Паспортні сталі сенсора. */
    float rad_per_pixel;      /* кут на піксель: PMW3901 — поле 42° на 35 пікселів */
    uint8_t squal_min;        /* нижній поріг якості поверхні (0..255) */
    uint8_t squal_ref;        /* якість, за якої шум дорівнює паспортному */
    float max_rate;           /* рад/с: вище — це вже змаз, а не потік */
    float min_range;          /* м: ближче сенсор не фокусується */
    float max_range;          /* м: далі не вистачає контрасту */
    float min_tilt_cos;       /* косинус найбільшого допустимого нахилу */
    float r_base;             /* базова дисперсія шуму, (м/с)² на 1 м дальності */

    /* Лічильники відмов — на них дивляться при розборі невдалого польоту. */
    uint32_t n_quality;
    uint32_t n_rate;
    uint32_t n_range;
    uint32_t n_tilt;
} flow_cfg_t;

typedef struct {
    float vx_world;           /* швидкість у світовій системі NED, м/с */
    float vy_world;
    float r_cov;              /* дисперсія цього конкретного вимірювання */
    float range_used;         /* дальність по нормалі до поверхні, м */
} flow_meas_t;

void flow_init(flow_cfg_t *cfg);

/* Перетворює один кадр сенсора на вимірювання швидкості.
   dpx, dpy — накопичений зсув у пікселях за час dt (регістри Delta_X/Delta_Y);
   squal    — показник якості поверхні з того самого читання;
   gyro     — кутові швидкості в системі тіла (рад/с), той самий момент часу;
   R_wb     — поворот «тіло → світ»;
   range_m  — сира дальність від ToF уздовж променя (тобто вздовж осі тіла Z).
   Повертає false, якщо кадр забракований; причина осідає в лічильниках. */
bool flow_measure(flow_cfg_t *cfg,
                  int16_t dpx, int16_t dpy, uint8_t squal, float dt,
                  const float gyro[3], const float R_wb[3][3], float range_m,
                  flow_meas_t *out);

#endif /* FLOW_H */
