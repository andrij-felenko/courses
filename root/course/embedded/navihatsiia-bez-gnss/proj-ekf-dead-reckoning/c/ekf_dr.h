/* ekf_dr.h — ядро розширеного фільтра Калмана для автономного числення
   координат (dead reckoning) без GNSS.

   Вектор стану (9 елементів, світова система NED, вісь Z вниз):

       x = [ px py pz | vx vy vz | bax bay baz ]ᵀ

   Зсув нуля акселерометра `b_a` тримається в стані навмисно: без нього
   постійна похибка нуля перетворюється на квадратичний по часу відліт
   координати, а з ним оптичний потік поступово «перетікає» в оцінку зсуву.

   Модуль не виділяє пам'яті, не має глобального стану й не залежить ні від
   чого, крім <math.h>. Уся арифметика — float32: на Cortex-M4F/M7 це один
   такт на множення, а double з'їв би весь бюджет 500 Гц. */
#ifndef EKF_DR_H
#define EKF_DR_H

#include <stdbool.h>
#include <stdint.h>

#define EKF_DR_N 9

/* Індекси у векторі стану. */
enum {
    EKF_PX = 0, EKF_PY = 1, EKF_PZ = 2,
    EKF_VX = 3, EKF_VY = 4, EKF_VZ = 5,
    EKF_BAX = 6, EKF_BAY = 7, EKF_BAZ = 8
};

/* Прискорення вільного падіння, м/с². У NED вісь Z спрямована вниз, тому
   гравітація входить у світове прискорення зі знаком «плюс». */
#define EKF_GRAVITY_MSS 9.80665f

typedef enum {
    EKF_FUSED = 0,        /* вимірювання прийнято й вбудовано у стан */
    EKF_REJECT_GATE,      /* відкинуто стробуванням Махаланобіса (викид) */
    EKF_REJECT_NUMERIC    /* NaN/Inf на вході або вироджена інноваційна дисперсія */
} ekf_result_t;

typedef struct {
    float x[EKF_DR_N];                /* вектор стану */
    float P[EKF_DR_N][EKF_DR_N];      /* коваріація похибок оцінки, симетрична */

    /* Спектральні густини шумів процесу (множаться на dt у predict). */
    float q_pos;                      /* м²/с³     — шум самої координати */
    float q_vel;                      /* (м/с²)²·с — шум акселерометра, що йде у швидкість */
    float q_bias;                     /* (м/с²)²/с — випадкове блукання зсуву */

    /* Запобіжники чисельного колапсу. */
    float p_min;                      /* нижній затиск дисперсій */
    float p_max;                      /* верхній затиск дисперсій */
    float bias_max;                   /* фізична межа зсуву акселерометра, м/с² */

    /* Лічильники для телеметрії: скільки вимірювань відкинуто й чому. */
    uint32_t n_gated;
    uint32_t n_numeric;
    uint32_t n_reset;                 /* скільки разів коваріацію довелося рятувати */
} ekf_dr_t;

void ekf_dr_init(ekf_dr_t *ekf);

/* Крок передбачення за даними IMU.
   a_body — питома сила з акселерометра в системі тіла (м/с²);
   R_wb   — матриця повороту «тіло → світ NED» від оцінювача орієнтації;
   dt     — крок інтегрування (с), зазвичай 0.002–0.005.
   Повертає false, якщо вхід не пройшов перевірку і крок пропущено. */
bool ekf_dr_predict(ekf_dr_t *ekf, const float a_body[3], const float R_wb[3][3], float dt);

/* Загальне скалярне злиття: одне вимірювання z із рядком спостереження H.
   Послідовне скалярне злиття замість матричного дає той самий результат для
   некорельованих вимірювань, але не потребує обертання матриці S — на MCU
   це різниця між сотнею мікросекунд і кількома.
   gate > 0 вмикає тест Махаланобіса: d² = y²/S > gate → відмова.
   d2_out (може бути NULL) віддає обчислену відстань навіть при відмові. */
ekf_result_t ekf_dr_fuse_scalar(ekf_dr_t *ekf, const float H[EKF_DR_N],
                                float z, float r, float gate, float *d2_out);

/* Корекція за оптичним потоком: горизонтальна швидкість у світовій системі.
   Осі зливаються послідовно й незалежно — змазаний кадр псує зазвичай одну
   вісь, і другу через це втрачати немає причини. */
ekf_result_t ekf_dr_update_velocity2d(ekf_dr_t *ekf, float vx_meas, float vy_meas,
                                      float r_cov, float gate);

/* Корекція висоти далекоміром ToF або барометром: вимірюється pz (вниз-додатна). */
ekf_result_t ekf_dr_update_altitude(ekf_dr_t *ekf, float pz_meas, float r_cov, float gate);

/* ZUPT — злиття «швидкість дорівнює нулю» по всіх трьох осях.
   Викликається, коли детектор нерухомості каже, що апарат стоїть: саме тут
   фільтр найкраще бачить зсув акселерометра, бо будь-яке ненульове
   прискорення на стоянці — це або зсув, або похибка орієнтації. */
ekf_result_t ekf_dr_update_zupt(ekf_dr_t *ekf, float r_zupt);

void ekf_dr_get_state(const ekf_dr_t *ekf, float pos[3], float vel[3], float bias[3]);

/* Кореневі середньоквадратичні похибки оцінки — з діагоналі P. */
float ekf_dr_pos_sigma(const ekf_dr_t *ekf, int axis);
float ekf_dr_vel_sigma(const ekf_dr_t *ekf, int axis);

/* ── Дрібна геометрія, спільна для модуля потоку ──
   Домовленості про системи координат живуть тут, у фільтрі, тому й
   перетворення між ними — теж: інакше два модулі почали б розходитися
   в тому, що таке «тіло» і що таке «світ». */

/* out = R · v (вектор-стовпець). */
void ekf_rotate(float out[3], const float R[3][3], const float v[3]);

bool ekf_vec3_finite(const float v[3]);

/* Перевірка, що матриця справді ортонормальна (стовпці одиничні й попарно
   ортогональні з допуском tol). Оцінювач орієнтації іноді віддає сміття —
   NaN після ділення на нуль у нормуванні кватерніона, — і таку матрицю
   треба відкинути ДО того, як вона потрапить у коваріацію. */
bool ekf_is_rotation(const float R[3][3], float tol);

#endif /* EKF_DR_H */
