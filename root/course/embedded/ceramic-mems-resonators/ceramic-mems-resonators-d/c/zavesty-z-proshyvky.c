// STM32-подібний HAL: старт генератора на зовнішньому резонаторі (HSE)
RCC->CR |= RCC_CR_HSEON;                 // увімкнути підсилювач генератора

uint32_t guard = 100000;                  // сторожовий лічильник
while (!(RCC->CR & RCC_CR_HSERDY)) {      // ждати прапорець «розгойдалось»
    if (--guard == 0) {
        fault_no_clock();                 // резонатор не завівся — аварія
        return;
    }
}
// Кераміка (низька Q) дійде сюди за десятки мкс, кварц — за одиниці мс.
// Прапорець HSERDY і є апаратна перевірка «τ минуло, амплітуда є».
