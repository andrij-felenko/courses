#ifndef CALIB_H
#define CALIB_H

/*
 * Двоточкове лінійне калібрування (розділ 5). Компенсує ОДРАЗУ всі статичні
 * похибки тракту: несиметрію моста, зсув нуля підсилювачів, розкид R_g,
 * неточність V_ref і чутливості самого давача. Знати номінали на платі
 * для цього не треба — треба дві еталонні точки.
 *
 * Фізика тримається в грамах цілим числом: 20 кг це 20000, у int32 влазить
 * із запасом, а плаваючої коми в мікроконтролері може не бути взагалі.
 */

#include <stdbool.h>
#include <stdint.h>

typedef struct {
    int32_t raw_p1;   /* усереднений код у першій точці (тара) */
    int32_t raw_p2;   /* усереднений код у другій точці (еталонна гиря) */
    int32_t phys_p1;  /* фізичне значення першої точки, грами */
    int32_t phys_p2;  /* фізичне значення другої точки, грами */
} calib_t;

/*
 * Повертає false, коли калібрувати нема по чому: коди двох точок збіглися або
 * розійшлися менше ніж на CALIB_MIN_SPAN квантів. Прийняти таку пару означає
 * поділити на майже нуль і вивести шкалу, де один квант шуму важить кілограми, —
 * прошивка мусить відмовитися і лишити стару калібрувальну таблицю.
 */
#define CALIB_MIN_SPAN 100

bool calib_init(calib_t *cal,
                int32_t raw_p1, int32_t phys_p1_grams,
                int32_t raw_p2, int32_t phys_p2_grams);

/* Інтерполяція прямої через дві точки: X = (N - N1)*(X2 - X1)/(N2 - N1) + X1. */
int32_t calib_to_grams(const calib_t *cal, int32_t raw);

/* Скільки кодів АЦП припадає на кілограм за цим калібруванням — саме це число
   порівнюють із розрахунковим, щоб побачити похибку чутливості тракту. */
double calib_counts_per_kg(const calib_t *cal);

#endif /* CALIB_H */
