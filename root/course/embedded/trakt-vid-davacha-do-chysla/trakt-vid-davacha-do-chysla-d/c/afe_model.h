#ifndef AFE_MODEL_H
#define AFE_MODEL_H

/*
 * Модель аналогового тракту з розділів 2-4: тензоміст -> інструментальний
 * підсилювач AD620 (R_g = 330 Ом) -> зміщення рівня на 1.65 В -> антиаліасинговий
 * RC-фільтр -> 12-бітний SAR АЦП з V_ref = 3.3 В.
 *
 * Модель рахує аналогову напругу з кроком 10 мкс (100 кГц) — це та сама сітка,
 * на якій у розділі 3 працює передискретизація. Прошивка бачить лише те, що
 * повертає afe_step(): дванадцятибітний код. Уся інформація про справжню частоту
 * сигналу гине саме тут — тому аліасинг і незворотний.
 */

#include <stdbool.h>
#include <stdint.h>

#define AFE_STEP_S  1.0e-5   /* крок аналогової моделі, с */
#define AFE_STEP_HZ 100000   /* та сама величина як частота, Гц */

typedef struct {
    double   t;         /* астрономічний час моделі, с */
    double   aaf_state; /* стан однополюсного ФНЧ перед АЦП, В */
    double   load_kg;   /* вага на платформі просто зараз */
    bool     aaf_on;    /* чи стоїть антиаліасинговий фільтр перед входом */
    uint64_t rng;       /* стан генератора теплового шуму */
} afe_t;

void afe_init(afe_t *afe, uint64_t seed, bool aaf_on);

/* Вага на платформі; модель не робить стрибок миттєвим — механіка встигає осісти
   за час, який прошивка однаково відводить на заспокоєння тракту. */
void afe_set_load(afe_t *afe, double load_kg);

/* Просуває аналоговий час на AFE_STEP_S і повертає код АЦП у цю мить.
   Викликати рідше — означає стробувати рідше з усіма наслідками розділу 3. */
uint16_t afe_step(afe_t *afe);

/* Розрахункова чутливість тракту за паспортними номіналами (кодів на кілограм).
   Реальний тракт від неї відхиляється — саме це й ловить двоточкове калібрування. */
double afe_nominal_counts_per_kg(void);

#endif /* AFE_MODEL_H */
