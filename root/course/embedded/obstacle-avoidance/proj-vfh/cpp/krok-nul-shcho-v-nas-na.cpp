// ── Пороги «долини» (гістерезис, два пороги — про це нижче) ──────
#define THR_LOW     0.60f       // нижче — точно вільно (вихід із перешкоди)
#define THR_HIGH    1.20f       // вище — точно зайнято (вхід у перешкоду)

// ── Прохідна долина ─────────────────────────────────────────────
#define S_MAX       18          // «широка» долина ≥ стількох секторів (≈ 90°)
#define S_MIN        4          // вужчу за стільки секторів (≈ 20°) не беремо

