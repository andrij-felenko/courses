#ifndef BSP_ENV_SENSORS_H
#define BSP_ENV_SENSORS_H

#include "bsp/types.h"

/*
 * Внутрішній шар BSP: два давачі на спільній шині I2C домену SENSORS.
 * Застосунок цих імен не бачить — для нього є лише board_read_environment().
 */

/**
 * @brief Повний цикл вимірювання: SHT3x (T, RH) + BMP280 (тиск).
 *
 * Викликається вже під захопленим м'ютексом шини й при увімкненому домені.
 * Перевіряє CRC пакетів SHT3x, ідентифікатор та калібрувальну сторінку BMP280
 * і правдоподібність результату.
 */
bsp_status_t env_sensors_read(board_env_metrics_t *out_env);

/**
 * @brief Скинути кеш калібрувальних коефіцієнтів.
 *
 * Обов'язково після знеструмлення домену або відновлення шини: мікросхема
 * втратила живлення, отже кешовані коефіцієнти могли бути прочитані з биттям.
 */
void env_sensors_invalidate(void);

#endif /* BSP_ENV_SENSORS_H */
