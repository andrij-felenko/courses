// Кожне навантаження має свій MOSFET-обмежувач; вивід лише "дозволяє" пуск,
// а повільність наростання задає RC у затворі (тут — десятки мілісекунд).
#define RAMP_MS   30   // час наростання, заданий RC у затворі (з розрахунку SOA)
#define STAGGER_MS 50  // пауза між пусками, > RAMP_MS: другий стартує після першого

void power_up_sequence(void)
{
    gpio_set(EN_RAIL_A);          // дозволили пуск шини A — вона плавно наростає за RC
    delay_ms(STAGGER_MS);         // чекаємо, поки шина A повністю встала

    gpio_set(EN_RAIL_B);          // тепер пускаємо шину B — її кидок не накладеться на A
    delay_ms(STAGGER_MS);

    // обидві шини під напругою; тепер можна вмикати решту логіки
}
