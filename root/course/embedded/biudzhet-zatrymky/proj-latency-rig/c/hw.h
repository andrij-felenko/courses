// Апаратний шар вимірювального стенда: STM32F411 (Cortex-M4), тактування HSI 16 МГц.
//
//   PA5  — вихід на затвор MOSFET, що керує надяскравим світлодіодом;
//   PA0  — вхід EXTI0 з виходу компаратора фотоприймача (фронт наростання);
//   PA2  — USART2_TX, 115200 8N1, ним стенд віддає протокол вимірювання.
//
// Часова база — TIM2 (32-бітний лічильник) із ціною поділки рівно 1 мкс.
#ifndef HW_H
#define HW_H

#include <stdbool.h>
#include <stdint.h>

// Ініціалізує тактування, GPIO, TIM2, USART2 та контролер EXTI.
// EXTI0 після ініціалізації ЗАМАСКОВАНИЙ: вікно чутливості відкриває стенд.
void hw_init(void);

// Поточне значення часової бази в мікросекундах.
// Лічильник 32-бітний, переповнюється раз на 71.6 хвилини; усі різниці
// рахуються в беззнаковій арифметиці, тому перехід через нуль коректний.
uint32_t hw_now_us(void);

// Керує світлодіодом збудження. Запис у BSRR атомарний і триває один такт шини.
void hw_led(bool on);

// Відкриває або закриває вікно чутливості фотоприймача. Поза вікном перериван-
// ня замасковане, інакше пульсації ламп на 100 Гц сипали б хибні спрацювання.
// Відкриваючи вікно, функція гасить накопичений прапорець EXTI_PR.
void hw_optical_window(bool open);

// Блокувальна пауза за часовою базою (без циклів «на око»).
void hw_delay_us(uint32_t us);

// Вивід у послідовний порт.
void hw_print(const char *text);
void hw_print_u32(uint32_t value);
// Друкує мікросекунди як мілісекунди з трьома знаками: 16340 -> "16.340".
void hw_print_ms(uint32_t microseconds);
void hw_print_nl(void);

#endif // HW_H
