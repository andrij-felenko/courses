// Скінченний автомат одиничного випробування: спалах -> очікування відгуку
// фотоприймача -> охолодження. Обробник EXTI пише лише в атомарні поля, тому
// головний цикл читає результат без заборони переривань.
#ifndef RIG_H
#define RIG_H

#include <stdbool.h>
#include <stdint.h>

// Захисний таймаут очікування відгуку: 250 мс. Усе, що довше, — не затримка
// тракту, а втрачений кадр (обрив відеопотоку, пакет, що не долетів).
#define RIG_TIMEOUT_US 250000u

typedef enum {
    RIG_IDLE,    // готовий до наступного спалаху
    RIG_WAITING, // світлодіод горить, чекаємо на фронт від компаратора
    RIG_COOLDOWN // випробування завершене, результат ще не забрано або пауза
} rig_state_t;

typedef struct {
    bool     completed;  // випробування дійшло кінця
    bool     timed_out;  // відгуку не було за RIG_TIMEOUT_US
    uint32_t latency_us; // виміряний інтервал; при таймауті — RIG_TIMEOUT_US
} rig_result_t;

// Приводить автомат у RIG_IDLE і гасить світлодіод. Викликати після hw_init().
void rig_init(void);

// Запускає випробування: відкриває вікно EXTI, вмикає світлодіод, ставить
// мітку старту. Поза станом RIG_IDLE не робить нічого й повертає false.
bool rig_trigger(void);

// Неблокувальне опитування. completed == false — випробування триває.
rig_result_t rig_poll(void);

// Повертає автомат у RIG_IDLE після паузи охолодження.
void rig_arm(void);

rig_state_t rig_state(void);

#endif // RIG_H
