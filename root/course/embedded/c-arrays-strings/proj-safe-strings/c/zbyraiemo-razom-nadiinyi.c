#include <string.h>
#include <stdio.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

#define RX_CAP  64                 // МІСТКІСТЬ буфера під ТЕКСТ (символи команди)
static char rx_buf[RX_CAP + 1];    // +1 комірка ЗАВЖДИ під '\0' — це не забаганка

// Викликається, коли драйвер UART склав у rx_buf рівно n сирих байтів.
// n — те, що ПРИЙШЛО; довіряти можна тільки йому й розміру буфера.
void on_uart_frame(size_t n) {
    // 1) ОБМЕЖИТИ прийняте розміром буфера: якщо кадр довший за місткість,
    //    беремо лише те, що влізло, — але НІКОЛИ не пишемо за межу масиву.
    if (n > RX_CAP) {
        n = RX_CAP;                // відсікаємо надлишок: далі RX_CAP не чіпаємо
    }
    rx_buf[n] = '\0';              // ← ставимо термінатор ВЛАСНОРУЧ, у комірку [n]

    parse_command(rx_buf);         // тепер rx_buf — гарантовано коректний рядок
}
