// Розібрати рядок команди. Нічого не припускає: будь-який вхід — законний,
// на будь-якому або розбираємо, або чесно відмовляємо. За межу — ніколи.
void parse_command(const char *line) {
    // Приймачі під розібрані поля — кожен зі СВОЄЮ місткістю + місце під '\0':
    char verb[8 + 1];              // ім'я команди: до 8 символів
    char field[8 + 1];             // поле: до 8 символів
    unsigned long value = 0;

    // sscanf з ЯВНОЮ шириною %8s — читає щонайбільше 8 символів у приймач
    // місткістю 8(+1 під нуль), сам дописує '\0'. Ширина тут — та сама межа
    // приймача, що й скрізь. Повертає, СКІЛЬКИ полів реально розібрано.
    int got = sscanf(line, "%8s %8s %lu", verb, field, &value);

    if (got < 1) {
        // жодного слова: порожній рядок, самі пробіли або сміття — відмовляємо
        reply("ERR empty");
        return;
    }

    // Далі порівнюємо verb — і це БЕЗПЕЧНО, бо %8s гарантовано лишив '\0'.
    if (strcmp(verb, "SET") == 0) {
        if (got < 3) {                     // "SET" є, а поля чи числа бракує
            reply("ERR need: SET <field> <value>");
            return;
        }
        apply_setting(field, value);       // обидва поля розібрані й термі­новані
        reply("OK");
    } else if (strcmp(verb, "GET") == 0) {
        reply_current_value(got >= 2 ? field : "");
    } else {
        reply("ERR unknown cmd");          // невідома команда — теж штатний вихід
    }
}
