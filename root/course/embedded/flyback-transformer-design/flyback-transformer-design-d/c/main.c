// Захист трансформатора за піковим струмом (peak-current mode).
// I_PEAK_MAX — той самий Iпік, під який порахували витки на НЕнасичення.
// Перевищити його — означає загнати осердя в насичення й спалити ключ.
#define I_PEAK_MAX   1.75f                 // А, межа з розрахунку трансформатора
#define R_SENSE      0.33f                 // Ом, струмовий шунт у витоку ключа
#define V_LIMIT      (I_PEAK_MAX * R_SENSE) // поріг для компаратора, ≈0.58 В

void flyback_isr(void) {
    float v_sense = adc_read_csns();         // напруга на шунті = струм·R_SENSE
    if (v_sense >= V_LIMIT) {                // струм первинної дійшов до Iпік
        gate_off();                          // розмикаємо ключ — пакет набрано
    }
    // якщо вихід просів, регулятор підніме шпаруватість, але НІКОЛИ
    // не дасть струму вийти за I_PEAK_MAX — осердя лишається під Bнас
}
