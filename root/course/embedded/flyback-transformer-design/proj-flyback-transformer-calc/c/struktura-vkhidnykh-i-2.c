// Підсумок розрахунку трансформатора: усі чотири числа + поріг для прошивки.
typedef struct {
    float lp_primary_H;   // 1) індуктивність первинної Lпр, Гн
    float i_peak_A;       // піковий струм первинної Iпік, А (тягнеться скрізь)
    float turns_ratio;    // 2) відношення витків Np/Ns
    int   np_turns;       // 3) витки первинної (мінімум на НЕнасичення, угору)
    int   ns_turns;       //    витки вторинної за відношенням (угору)
    float al_nH_per_t2;   //    цільовий параметр осердя AL під зазор, нГн/виток²

    float i_pri_rms_A;    // діючий струм первинної, А
    float i_sec_rms_A;    // діючий струм вторинної, А
    float wire_pri_mm2;   // 4) переріз проводу первинної, мм²
    float wire_sec_mm2;   //    переріз проводу вторинної, мм²

    float reflected_V;    // відбита напруга на ключі у фазі ВИКЛ, В
    float vds_peak_V;     // оцінка піку напруги на стоку ключа, В
    float i_peak_threshold_A; // поріг для peak-current-mode прошивки (= i_peak_A)

    float duty_required;     // шпаруватість, потрібна на нижньому вході для Pвих
    bool  switch_overvolt;   // ПРАПОРЕЦЬ: пік на стоку перевищує BV_DSS ключа
    bool  ccm_risk;          // ПРАПОРЕЦЬ: потрібна D перевищує задану → вихід із DCM
    bool  duty_unrealistic;  // ПРАПОРЕЦЬ: задана D надто близька до 1 (нема паузи)
    bool  valid;             // false = вхідне ТЗ безглузде, решта полів недійсна
} flyback_result_t;
