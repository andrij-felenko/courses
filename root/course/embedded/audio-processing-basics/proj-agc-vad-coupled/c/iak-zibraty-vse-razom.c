static vad_t     g_vad;      // сторож (з модуля VAD)
static agc_vad_i_t g_agc;    // зчеплений AGC (цілочисловий)

void audio_dsp_init(void)
{
    // Сторож — типовими налаштуваннями (16 кГц, кадр 256).
    vad_config_t vcfg;
    vad_config_default(&vcfg);
    vad_init(&g_vad, &vcfg);

    // AGC — ціль −20 dBFS, атака ~2 кадри, відпускання ~64, стеля 32×, утримання 300 мс.
    agc_vad_i_init(&g_agc,
        /*target*/    3000,   // цільовий RMS (≈ −20 dBFS від 32767)
        /*atk_shift*/ 1,      // атака ~2 кадри (швидко вниз)
        /*rel_shift*/ 6,      // відпускання ~64 кадри ≈ 1 с (повільно вгору)
        /*max_gain*/  32.0f,  // стеля проти витягування шуму
        /*hold_ms*/   300,    // час утримання перед заморозкою
        /*T_frame_ms*/16);    // тривалість кадру для перерахунку hold у кадри
}

// Один кадр повного тракту обробки.
void audio_dsp_step(int16_t *frame, int n)
{
    dc_block(frame, n);          // 1. зняти постійну   (з теми)
    bandpass(frame, n);          // 2. смуговий фільтр   (з теми)

    // 3. Сторож дивиться на вже чистий кадр і віддає прапорець.
    bool voice = vad_feed(&g_vad, frame);

    // 4. Зрідка синхронізуємо шумовий поріг AGC із фоном сторожа.
    static uint16_t tick = 0;
    if ((++tick & 0x0F) == 0)    // раз на 16 кадрів досить — фон повзе повільно
        agc_vad_sync_gate_i(&g_agc, &g_vad, /*margin*/ 2.0f);

    // 5. Зчеплений AGC веде підсилення (або морозить) залежно від прапорця.
    agc_vad_process_i(&g_agc, frame, n, voice);

    // Кадр готовий: рівний за гучністю, без дихання. Далі — запис/стиснення/KWS.
}
