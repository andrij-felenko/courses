// Коефіцієнти заздалегідь переведені у Q14: c_q14 = round(c_float * 16384).
// Стан і вхід — Q0 (цілі 16-бітні відліки); акумулятор — 64 біти.
typedef struct {
    int16_t b0, b1, b2, a1, a2;   // Q14
    int32_t x1, x2, y1, y2;       // минулі входи/виходи, Q0
} biquad_q14;

int16_t biquad_step(biquad_q14 *f, int16_t x) {
    // Акумулятор у Q14: коеф(Q14)*відлік(Q0) = добуток(Q14)
    int64_t acc =  (int64_t)f->b0 * x
                 + (int64_t)f->b1 * f->x1
                 + (int64_t)f->b2 * f->x2
                 - (int64_t)f->a1 * f->y1
                 - (int64_t)f->a2 * f->y2;
    int32_t y = (int32_t)(acc >> 14);      // назад у Q0
    if (y >  32767) y =  32767;            // насичення проти переповнення
    if (y < -32768) y = -32768;
    f->x2 = f->x1; f->x1 = x;              // зсув стану входу
    f->y2 = f->y1; f->y1 = y;              // зсув стану виходу
    return (int16_t)y;
}
