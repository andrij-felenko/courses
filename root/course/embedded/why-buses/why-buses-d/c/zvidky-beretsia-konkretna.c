// Серійна:    біт 0.8 нс (1.25 ГГц на ОДНІЙ парі) → 1.25 Гбіт/с… з ОДНІЄЇ лінії
//   а поставивши кілька таких серійних смуг поряд — множимо й обганяємо джгут
