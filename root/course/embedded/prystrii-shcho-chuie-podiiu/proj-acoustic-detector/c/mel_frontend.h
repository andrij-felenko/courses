/* Кадровий фронтенд: 256 відліків → 32 логарифмічні мел-ознаки int8_t. */
#ifndef MEL_FRONTEND_H
#define MEL_FRONTEND_H

#include <stdint.h>

#include "acoustic_detector.h"

/* Один кадр: преакцент → вікно Хеммінга → FFT → мел-банк → log2 → int8.
 *
 * Класичний MFCC після логарифма робить ще й дискретне косинусне
 * перетворення, щоб розкорелювати смуги. Згортковій мережі це шкодить:
 * DCT перемішує сусідні частоти, а згортка 3×3 саме на сусідстві смуг і
 * тримається. Тому конвеєр спиняється на логарифмічних мел-енергіях.
 *
 * pre_state — стан преакцентного фільтра (останній відлік попереднього кадру);
 * він живе в контексті детектора, тож на кожен мікрофонний канал свій.
 *
 * УВАГА: робочі масиви FFT усередині статичні й спільні — фронтенд НЕ
 * реентерабельний. Два канали обробляє одна задача по черзі; двох задач
 * на цей код ставити не можна.
 */
void mel_frontend_frame(int16_t *pre_state, const int16_t *frame, int8_t *out_mel);

#endif /* MEL_FRONTEND_H */
