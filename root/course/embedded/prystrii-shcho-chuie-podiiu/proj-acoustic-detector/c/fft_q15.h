/* Комплексна FFT на 512 точок у форматі Q15 — без рухомої коми й без libm. */
#ifndef FFT_Q15_H
#define FFT_Q15_H

#include <stdint.h>

#include "acoustic_detector.h"

/* Перетворення на місці: re[] та im[] по AED_FFT_SIZE елементів.
 *
 * Кожен щабель метеликів ділить результат на 2, тож на виході стоїть
 * X[k] / N. Це не косметика: без поділу сума 512 доданків вилітає за int16
 * на першому ж гучному кадрі, а насичення знищило б спектр. Ціною йде
 * молодший біт на щабель — для мел-ознак, які далі йдуть у логарифм і
 * квантуються в int8, цієї точності з запасом.
 */
void fft_q15_512(int16_t *re, int16_t *im);

/* Квадрат модуля однієї комірки спектра: |X[k]|². */
uint32_t fft_q15_power(int16_t re, int16_t im);

#endif /* FFT_Q15_H */
