// Єдиний спосіб змінити стан. Тримає g_net_up у згоді зі станом ЗАВЖДИ.
static void net_goto(net_state_t s) {
    g_net_state   = s;
    t_state_enter = millis();
    g_net_up      = (s == NET_ONLINE);   // похідне — рахується тут і ніде більше

    if (s == NET_BACKOFF) {
        // Повний джитер: фактичну паузу кидаємо РІВНО ТУТ, один раз на вхід у стан —
        // рівномірно випадкове значення від 0 до поточної стелі. Далі крок автомата
        // лише ЗВІРЯЄТЬСЯ з цим фіксованим числом, а не перекидає його щовитка.
        g_backoff_wait = esp_random() % (g_backoff_ceil + 1u);   // 0 .. g_backoff_ceil
    }
}
