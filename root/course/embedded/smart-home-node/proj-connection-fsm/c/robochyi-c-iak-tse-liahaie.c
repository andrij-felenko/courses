void loop(void) {
    uint32_t now = millis();

    control_step();        // ШВИДКА петля: давач + правило. Завжди, миттєво.
    net_step(now);         // Крок мережевого автомата. Теж миттєво, не блокує.
    report_step(now);      // ПОВІЛЬНА петля: звіт, якщо g_net_up і настав час.

    // mqtt_loop() тут НЕ потрібен: ESP-MQTT крутиться у власному завданні,
    // а до нас говорить подіями через mqtt_event_handler. Ми лише керуємо станом.
}
