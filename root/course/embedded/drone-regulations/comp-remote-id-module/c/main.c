#include <stdint.h>

// Стан начіпного модуля, як його бачить апарат ЗЗОВНІ.
// Модуль самодостатній: апарат у кращому разі читає один пін «ready».
typedef enum {
    MOD_ABSENT   = 0,   // модуля нема або він не живиться
    MOD_NO_FIX   = 1,   // модуль живий, але GNSS ще не зловив фікс
    MOD_READY    = 2,   // фікс є, самоперевірка пройдена — можна злітати
    MOD_FAULT    = 3,   // модуль сигналить про відмову
} rid_module_state_t;

// Читаємо стан модуля з його сигнального піна(ів). Реалізація платформна:
// хтось дає один булевий "ready", хтось — кілька рівнів індикації.
rid_module_state_t rid_module_read(void);

// Дозвіл на зліт з погляду Remote ID: злітати можна ЛИШЕ коли модуль готовий.
// Це і є весь «контракт» апарата з начіпним модулем — не більше.
int rid_takeoff_allowed(void) {
    switch (rid_module_read()) {
        case MOD_READY:
            return 1;                 // фікс є, самотест ок — legal to fly
        case MOD_NO_FIX:
            return 0;                 // ще нема місця — злетиш «невідомим», не можна
        case MOD_FAULT:
        case MOD_ABSENT:
        default:
            return 0;                 // несправний або відсутній — не легальний
    }
}
