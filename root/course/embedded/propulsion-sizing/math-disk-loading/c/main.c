// Модель актуаторного диска для висіння. Рахуємо у СІ (Н, м, Вт),
// маси-грами й дюйми переводимо на вході. float тут доречний — це
// прикидка «на землі», не гаряча ділянка прошивки.
#include <math.h>

const float RHO      = 1.225f;   // густина повітря на рівні моря, кг/м^3
const float G        = 9.81f;    // прискорення вільного падіння, м/с^2
const float MASS_KG  = 1.200f;   // злітна маса, кг
const int   N_PROPS  = 4;        // кількість гвинтів
const float D_IN     = 10.0f;    // діаметр гвинта, дюйми

float hover_ideal(float d_in) {
    float R      = (d_in * 0.0254f) / 2.0f;      // радіус, м (1 дюйм = 0.0254 м)
    float A      = (float)N_PROPS * (float)M_PI * R * R; // сумарна площа дисків, м^2
    float T      = MASS_KG * G;                   // сумарна тяга на висінні = вага, Н
    float DL     = T / A;                          // навантаження на диск, Н/м^2
    float v_i    = sqrtf(T / (2.0f * RHO * A));   // індукована швидкість, м/с
    float P_id   = T * v_i;                        // ідеальна потужність, Вт
    // грамів тяги на ват (ідеал): (маса у грамах) / потужність
    // ... друкуємо DL, v_i, P_id, і T/ P у наступних рядках
    return P_id;
}
