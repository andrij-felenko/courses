// Перед важким сплеском (увімкнення радіо, стрибок тактової частоти)
// даємо живленню наздогнати: піднімаємо навантаження сходинками,
// а не одним ривком — тоді й менша місцева ємність утримає напругу.
static void power_up_radio_gently(void) {
    radio_enable_ldo();        // спершу лише внутрішній регулятор радіо
    delay_us(200);             // пауза: bulk встигає підживити місцеву ємність
    radio_enable_pa_stage();   // тоді найжадібніший вузол — підсилювач
    delay_us(200);             // ще пауза перед першою передачею
    radio_start_tx();
}
