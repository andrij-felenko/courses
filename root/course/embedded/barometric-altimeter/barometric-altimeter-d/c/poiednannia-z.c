// Комплементарний фільтр вертикалі: об'єднує барометричну висоту (повільну,
// абсолютну) з вертикальним прискоренням (швидким, дрейфливим).
// tau — стала часу (с); задає частоту зрізу ~ 1/(2*pi*tau).
// az_world — вертикальне прискорення у світовій системі, БЕЗ g (м/с²).
// baro_alt — сира барометрична висота (м); dt — крок часу (с).
static float est_alt = 0.0f;   // оцінена висота, м
static float est_vz  = 0.0f;   // оцінена вертикальна швидкість, м/с

float fuse_altitude(float baro_alt, float az_world, float dt, float tau) {
    // 1) прогноз від акселерометра (швидка, «висока частота»): інтегруємо рух
    est_vz  += az_world * dt;          // прискорення -> швидкість
    est_alt += est_vz  * dt;           // швидкість  -> висота
    // 2) корекція барометром (повільна, «низька частота»): тягнемо оцінку до нього
    float k = dt / (tau + dt);         // вага барометра на цьому кроці
    est_alt += k * (baro_alt - est_alt);
    // невеликий відкат швидкості, щоб гасити повільний дрейф інтеграла
    est_vz  += (k * (baro_alt - est_alt)) / tau;
    return est_alt;
}
