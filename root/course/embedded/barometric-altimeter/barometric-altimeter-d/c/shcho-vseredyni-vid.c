// Спрощена компенсація в стилі MEMS-барометра: сирі коди -> Pa.
// coef_* — індивідуальні коефіцієнти чипа з його ПЗП (прочитані при старті).
// raw_t, raw_p — сирі 24-бітні коди температурного й тискового каналів.
float compensate_pressure(int32_t raw_t, int32_t raw_p, const cal_t *c) {
    // 1) температура кристала з температурного каналу (потрібна для кроку 2)
    float t = (raw_t - c->t_offset) * c->t_gain;      // °C
    // 2) тиск: базова лінійна частина + поправки на температуру й нелінійність
    float p = c->p0
            + c->p_gain * raw_p                        // основний нахил
            + c->p_t    * raw_p * t                    // температурний зсув нахилу
            + c->p_nl   * raw_p * raw_p;               // квадратична нелінійність
    return p;                                          // Pa
}
