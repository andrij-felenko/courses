import numpy as np

GRAVITY = 9.80665    # стандартне прискорення вільного падіння, м/с²

# Вертикальне (світове) прискорення РУХУ: обернути вектор тіла у світ,
# узяти Z-складову й відняти тяжіння. accel_body — вже зі знятим зсувом.
# R — матриця обертання «тіло -> світ» форми (3, 3) з оцінки орієнтації IMU.
def world_vertical_accel(R: np.ndarray, accel_body: np.ndarray) -> float:
    # третій рядок матриці = проєкція осей тіла на світову вертикаль
    az_world = R[2] @ accel_body
    return az_world - GRAVITY    # прибрати g -> лишається прискорення руху
