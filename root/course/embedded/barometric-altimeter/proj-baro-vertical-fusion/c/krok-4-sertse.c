typedef struct {
    float alt;      // оцінена висота над точкою старту (м)
    float vz;       // оцінена вертикальна швидкість, + вгору (м/с)
    float tau;      // стала часу злиття (с): більша -> більше довіри акселерометру
    int   started;  // 1 після ініціалізації стану
} vfusion_t;

// Один крок злиття.
//   az_world  — вертикальне прискорення РУХУ у світі, без g (м/с²) [крок 2]
//   baro_alt  — відносна барометрична висота (м) [крок 3]
//   dt        — крок часу від попереднього виклику (с)
//   have_baro — 1, якщо цього кроку прийшов НОВИЙ відлік барометра (див. крок 5)
void vfusion_update(vfusion_t *f, float az_world, float baro_alt,
                    float dt, int have_baro) {
    if (!f->started) {           // ініціалізація нуля станом барометра, не 0.0!
        f->alt = baro_alt;
        f->vz  = 0.0f;
        f->started = 1;
        return;
    }

    // 1) ПРОГНОЗ від акселерометра (високі частоти): інтегруємо рух.
    //    трапецієподібно по швидкості — трохи точніше за прямокутник.
    float vz_new = f->vz + az_world * dt;
    f->alt += 0.5f * (f->vz + vz_new) * dt;    // середня швидкість за крок
    f->vz   = vz_new;

    // 2) КОРЕКЦІЯ барометром (низькі частоти) — лише коли є новий відлік.
    if (have_baro) {
        float err = baro_alt - f->alt;          // куди тягне барометр
        float k1  = 2.0f / f->tau;              // корекція висоти  (1/с)
        float k2  = 1.0f / (f->tau * f->tau);   // корекція швидкості (1/с²)
        f->alt += k1 * err * dt;
        f->vz  += k2 * err * dt;
    }
}
