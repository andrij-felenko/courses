// Матриця обертання «тіло -> світ», 3×3 (з оцінки орієнтації IMU).
typedef struct { float m[3][3]; } mat3;   // m[рядок][стовпець]

#define GRAVITY 9.80665f    // стандартне прискорення вільного падіння, м/с²

// Вертикальне (світове) прискорення РУХУ: обернути вектор тіла у світ,
// узяти Z-складову й відняти тяжіння. accel_body — вже зі знятим зсувом.
float world_vertical_accel(const mat3 *R, vec3 accel_body) {
    // третій рядок матриці = проєкція осей тіла на світову вертикаль
    float az_world = R->m[2][0] * accel_body.x
                   + R->m[2][1] * accel_body.y
                   + R->m[2][2] * accel_body.z;
    return az_world - GRAVITY;    // прибрати g -> лишається прискорення руху
}
