// Плаваючі оцінки центру й розкиду похибки на «звичайному» рівні.
// α мале (напр. 0.001): оцінка забуває минуле дуже повільно.
static const float ALPHA = 0.001f;

static void update_threshold(float score)
{
    // Оновлюємо тільки на ТИХИХ вимірах — інакше сама аномалія «навчить»
    // поріг вважати себе нормою (і детектор осліпне на затяжний дефект).
    if (score < mu_err + K * sigma_err) {
        float d = score - mu_err;
        mu_err    += ALPHA * d;                    // центр повзе до нового рівня
        sigma_err += ALPHA * (fabsf(d) - sigma_err); // розкид теж підлаштовується
    }
}
