#include "stm32f4xx.h"
#include <stdbool.h>

/**
 * @brief Апаратний захисний інтервал перед виконанням небезпечної ініціалізації.
 * Дає налагоджувачу 2 секунди для перехоплення контролю над ядром.
 */
static void debug_startup_guard(void) {
    // Вмикаємо тактування порту кнопки (наприклад, PA0)
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOAEN;
    GPIOA->MODER &= ~(0x3U << (0 * 2)); // Вхід
    GPIOA->PUPDR |=  (0x2U << (0 * 2)); // Підтяжка вниз (Pull-down)

    // Якщо кнопка затиснута під час увімкнення — зависаємо в безпечному циклі
    if ((GPIOA->IDR & (1U << 0)) != 0) {
        while (true) {
            __NOP(); // Дозволяє відлагоджувачу підключитися в будь-який момент
        }
    }

    // Захисна затримка на 2000 мс при стандартній частоті тактування 16 МГц (HSI)
    for (volatile uint32_t i = 0; i < 2000000UL; ++i) {
        __NOP();
    }
}

int main(void) {
    // ВИКЛИКАТИ ПЕРШИМ РЯДКОМ У MAIN!
    debug_startup_guard();

    // Далі йде потенційно небезпечний код перепризначення виводів або переходу в сон:
    // enter_stop_mode();
    
    while (1) {
    }
}
