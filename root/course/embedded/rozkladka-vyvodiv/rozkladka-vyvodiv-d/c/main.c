#include "stm32f4xx.h"
#include <stdbool.h>

/**
 * @brief Безпечна ініціалізація виводів: захист SWD та оптимізація швидкості.
 */
void pinout_safe_init(void) {
    // 1. Увімкнути тактування портів GPIOA та GPIOB
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOAEN | RCC_AHB1ENR_GPIOBEN;

    // -------------------------------------------------------------
    // ЗАХИСТ ЛІНІЙ НАЛАГОДЖЕННЯ:
    // PA13 (SWDIO) та PA14 (SWCLK) за замовчуванням перебувають в AF0.
    // Заборонено змінювати MODER для ніжок 13 та 14 на виходи GPIO!
    // -------------------------------------------------------------

    // 2. Налаштування PA5 під тактовий сигнал SPI1 (SPI1_SCK, AF5)
    // Очистити поле MODER5 (2 біти) та встановити режим 0b10 (Alternate Function)
    GPIOA->MODER &= ~(0x3U << (5 * 2));
    GPIOA->MODER |=  (0x2U << (5 * 2));

    // Вихідний каскад: Push-Pull (0), без підтяжки (No Pull - 0b00)
    GPIOA->OTYPER &= ~(1U << 5);
    GPIOA->PUPDR  &= ~(0x3U << (5 * 2));

    // ВСТАНОВЛЕННЯ ОПТИМАЛЬНОЇ ШВИДКОСТІ (Slew Rate):
    // Замість надлишкового 0x3 (Very High Speed 100MHz) ставимо
    // 0x2 (High Speed 50MHz) або 0x1 (Medium Speed 25MHz) для боротьби з EMI.
    GPIOA->OSPEEDR &= ~(0x3U << (5 * 2));
    GPIOA->OSPEEDR |=  (0x2U << (5 * 2)); // 50 MHz достатньо для SPI 21 Мбіт/с

    // Вибір альтернативної функції AF5 (0x05) у регістрі AFRL (ніжка 5)
    GPIOA->AFR[0] &= ~(0xFU << (5 * 4));
    GPIOA->AFR[0] |=  (0x5U << (5 * 4));

    // 3. Налаштування PB6 під вивід статусного LED (Низькочастотний вихід)
    GPIOB->MODER &= ~(0x3U << (6 * 2));
    GPIOB->MODER |=  (0x1U << (6 * 2)); // Режим звичайного цифрового виходу

    // Для індикатора обов'язково обираємо Low Speed (0x0)
    GPIOB->OSPEEDR &= ~(0x3U << (6 * 2)); // Мінімум завад, чистий фронт 30 нс
}
