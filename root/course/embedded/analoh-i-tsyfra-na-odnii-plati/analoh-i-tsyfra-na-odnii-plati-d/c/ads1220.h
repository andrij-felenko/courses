/* ads1220.h — драйвер 24-бітного дельта-сигма АЦП TI ADS1220.
 *
 * Конфігурація зашита в драйвер і зумисне не виноситься назовні: у цій темі
 * важить одне ввімкнення — диференційний вхід AIN0/AIN1, підсилення 32,
 * зовнішня опора 3.300 В із чистого LDO аналогового домену, 20 вибірок за
 * секунду з одночасним придушенням 50 і 60 Гц.
 */
#ifndef ADS1220_H
#define ADS1220_H

#include <stdint.h>

/* Повна шкала диференційного 24-бітного доповняльного коду: 2^23 − 1. */
#define ADS1220_FULL_SCALE 8388607L

/* Опорна напруга в нановольтах. Саме та, що її формує окремий малошумний
 * LDO аналогового домену (розділ «Пост-стабілізація за допомогою LDO»). */
#define ADS1220_VREF_NV 3300000000LL

/* Підсилення вбудованого PGA. Разом з опорою дає діапазон входу
 * ±Vref/G = ±103.125 мВ — типовий розмах тензометричного мосту. */
#define ADS1220_GAIN 32

/* Скільки чекати на DRDY. При 20 SPS результат приходить кожні 50 мс;
 * 200 мс — це вже чотири пропущені перетворення, тобто збій. */
#define ADS1220_DRDY_TIMEOUT_MS 200u

typedef enum {
    ADS1220_OK = 0,
    ADS1220_ERR_SPI,        /* контролер SPI не завершив обмін */
    ADS1220_ERR_TIMEOUT,    /* DRDY мовчить: чип скинувся або втратив живлення */
    ADS1220_ERR_CONFIG,     /* прочитана назад конфігурація не збіглася із записаною */
    ADS1220_ERR_SATURATED   /* вхід вийшов за межі шкали, код недостовірний */
} ads1220_status_t;

/* Скидання, запис конфігурації і читання її назад для звірки. */
ads1220_status_t ads1220_init(void);

/* Запуск неперервних перетворень (команда START/SYNC). */
ads1220_status_t ads1220_start(void);

/* Чекає на DRDY, зчитує 24-бітний код і розширює знак.
 * При ADS1220_ERR_SATURATED значення в *code_out усе одно записане —
 * воно потрібне, щоб зрозуміти, у який бік поїхав вхід. */
ads1220_status_t ads1220_read(int32_t *code_out);

/* Код перетворювача у нановольти на вході (уже з урахуванням підсилення).
 * Молодший розряд при G = 32 важить близько 12.3 нВ, тож мікровольти тут
 * були б грубішими за сам перетворювач. */
int32_t ads1220_code_to_nanovolts(int32_t code);

const char *ads1220_strerror(ads1220_status_t status);

#endif /* ADS1220_H */
