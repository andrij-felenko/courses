/* filter.h — ковзне усереднення з відкиданням викидів.
 *
 * Завади від перемикання цифрових шин не схожі на «білий шум»: це рідкі
 * поодинокі стрибки в момент, коли мікроконтролер смикнув паралельну шину
 * або пішов пакет по SPI. Просте середнє такий стрибок не прибирає, а
 * розмазує по всьому вікну. Тому спершу судимо новий відлік за медіаною
 * вікна, і лише прийняті усереднюємо.
 */
#ifndef FILTER_H
#define FILTER_H

#include <stdbool.h>
#include <stdint.h>

#define FILTER_WINDOW 16u

typedef struct {
    int32_t window[FILTER_WINDOW]; /* кільцевий буфер прийнятих кодів */
    uint8_t head;
    uint8_t count;
    uint8_t streak;    /* скільки відліків поспіль визнано викидами */
    uint32_t accepted;
    uint32_t rejected;
} robust_filter_t;

void robust_filter_init(robust_filter_t *f);

/* Приймає новий сирий код. Повертає false, поки вікно ще наповнюється —
 * судити нема за чим і виводити нема чого. Далі завжди повертає true, а в
 * *out кладе відфільтроване значення: середнє по вікну, а при відкинутому
 * викиді — попереднє середнє, тобто утримує останній достовірний рівень. */
bool robust_filter_push(robust_filter_t *f, int32_t code, int32_t *out);

/* Розмах вікна «від краю до краю», у кодах перетворювача. Це та сама
 * величина, яку інженер бачить у терміналі як «молодші біти стрибають»,
 * і головний числовий вирок якості розведення плати. */
int32_t robust_filter_spread(const robust_filter_t *f);

/* Скільки розрядів із 24 несуть сигнал, а не шум: 24 − log2(розмах). */
uint8_t robust_filter_enob(const robust_filter_t *f);

#endif /* FILTER_H */
