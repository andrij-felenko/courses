// Те саме без HAL: PC13/14/15 як входи, підтяжка вимкнена — напряму в регістрах.
static void rev_straps_init_bare(void) {
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOCEN;   // такт на порт C

    // MODER: по 2 біти на пін; 00 = вхід. Чистимо поля 13,14,15 → вони стають входами.
    GPIOC->MODER &= ~((3u << (13*2)) | (3u << (14*2)) | (3u << (15*2)));

    // PUPDR: по 2 біти на пін; 00 = без підтяжки, 01 = pull-up, 10 = pull-down.
    // Чистимо поля 13,14,15 → 00 → жодної внутрішньої підтяжки.
    GPIOC->PUPDR &= ~((3u << (13*2)) | (3u << (14*2)) | (3u << (15*2)));
}
