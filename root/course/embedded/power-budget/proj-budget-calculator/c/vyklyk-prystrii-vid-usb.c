void check_usb_budget(void) {
    static const rail_t rails[] = {
        { 3300, 90 },   // 0: шина 3.3 В через buck, ККД 90 %
        { 5000, 100 },  // 1: шина 5 В напряму з входу (ККД 100 %)
    };
    static const load_t loads[] = {
        { 0, 300, 1000 },  // МК + радіо в TX:  300 мА на 3.3 В, завжди в піку
        { 0,  50, 1000 },  // давачі:            50 мА на 3.3 В
        { 1, 120, 1000 },  // дисплей з підсвіткою: 120 мА на 5 В
    };

    budget_t b = power_budget(rails, 2, loads, 3,
                              5000, 500,   // джерело: USB 5 В × 500 мА
                              80);         // запас 80 %

    // Очікувано: worst ≈ 1.88 Вт, стеля 2.50 Вт, межа 2.00 Вт → fits = true, 75 %.
    ESP_LOGI("pwr", "пік %llu мкВт / межа %llu мкВт → %s (%u %% стелі)",
             b.worst_uw, b.headroom_uw, b.fits ? "OK" : "ПЕРЕВАНТАЖЕННЯ",
             b.load_pct);
}
