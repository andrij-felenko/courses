#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

// Шина живлення: напруга й перетворювач, що її живить від спільного входу.
typedef struct {
    uint32_t mv;       // напруга шини, мВ           (3300 = 3.3 В)
    uint16_t eff_pct;  // ККД перетворювача, %       (90 = 90 %; 100 = напряму)
} rail_t;

// Споживач: на якій шині сидить, скільки бере в піку й яку частку часу.
typedef struct {
    uint8_t  rail;     // індекс у масиві шин
    uint32_t peak_ma;  // піковий струм, мА          (300 = 0.3 А)
    uint16_t duty_pm;  // робочий цикл, проміле      (1000 = завжди ON)
} load_t;
