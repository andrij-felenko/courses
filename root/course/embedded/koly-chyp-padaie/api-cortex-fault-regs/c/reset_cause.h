/* reset_cause.h — читання «липких» прапорців причини скидання (RCC->CSR).
 *
 * Прапорці переживають перезапуск ядра й накопичуються доти, доки їх не
 * зітруть записом RMVF. Тому порядок роботи завжди один: прочитати ОДИН раз
 * на старті, зберегти копію, негайно очистити — інакше наступне скидання
 * покаже суміш двох подій.
 */
#ifndef RESET_CAUSE_H
#define RESET_CAUSE_H

#include <stdint.h>
#include <stdbool.h>

/* Сирий знімок RCC->CSR. Читати до будь-якої іншої ініціалізації. */
uint32_t reset_cause_read(void);

/* Стерти всі прапорці *RSTF (RCC_CSR_RMVF). Викликати одразу після read. */
void reset_cause_clear(void);

/* Розшифрувати знімок у діагностичний вивід. */
void reset_cause_report(uint32_t csr);

/* Чи прийшли ми з-під сторожового таймера — тобто прошивка зависла.
 * Це єдиний прапорець, на який стартовий код зазвичай реагує логікою,
 * а не лише записом у журнал. */
bool reset_cause_is_watchdog(uint32_t csr);

/* Чи це «холодний» старт (подача живлення / BOR): попередній стан у RAM
 * після нього недійсний, бо живлення просідало. */
bool reset_cause_is_cold(uint32_t csr);

#endif /* RESET_CAUSE_H */
