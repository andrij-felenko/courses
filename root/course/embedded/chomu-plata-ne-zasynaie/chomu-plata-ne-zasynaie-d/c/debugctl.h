/* debugctl.h — гасіння налагоджувальної інфраструктури ядра перед сном.
 *
 * Поки в DBGMCU_CR стоять DBG_SLEEP/DBG_STOP/DBG_STANDBY, блок CoreSight
 * не дає зупинити генератори й стабілізатор ядра: WFI виконується, а струм
 * лишається активним (5–10 мА). Сюди ж — трасування (TRCENA, ITM, DWT, SWO)
 * і аналогові супервізори живлення (PVD, BOR).
 */
#ifndef DEBUGCTL_H
#define DEBUGCTL_H

#include <stdbool.h>

/* Чи приєднаний зонд просто зараз (біт C_DEBUGEN у DHCSR).
 * Вимір струму спокою при істині недостовірний навіть після всіх вимкнень:
 * лишаються підтяжки SWDIO/SWCLK у кристалі та в самому зонді. */
bool debug_probe_attached(void);

/* Знімає блокування сну блоком налагодження й глушить трасування. */
void debug_silence_core(void);

/* Переводить супервізори напруги в економний режим: PVD геть,
 * BOR — на імпульсне опитування замість безперервного порівняння. */
void debug_low_power_supervisors(void);

/* Зупиняє лічильник у налагоджувачі: без цього таймери периферії
 * заморожуються під час зупинки ядра й лишають блоки під тактом. */
void debug_unfreeze_peripherals(void);

#endif /* DEBUGCTL_H */
