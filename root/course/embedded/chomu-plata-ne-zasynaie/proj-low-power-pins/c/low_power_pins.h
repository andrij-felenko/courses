/* Ізоляція виводів і блоку налагодження на час сну.
 *
 * Правило просте: усе, що не мусить лишатися живим, іде в аналоговий режим
 * без підтяжок. Список винятків — короткий і явний, бо кожен зайвий виняток
 * у ньому це мікроампери, які потім шукають амперметром.
 */
#ifndef LOW_POWER_PINS_H
#define LOW_POWER_PINS_H

#include "mcu.h"

/* Готує виводи портів A, B, C і чистить DBGMCU_CR.
 * Викликається ПІСЛЯ того, як шини зупинені, а датчики знеструмлені. */
void lp_pins_enter_sleep(void);

/* Повертає збережену конфігурацію портів у зворотному порядку. */
void lp_pins_restore(void);

/* Чи збережена конфігурація дійсна (тобто чи ми справді спали). */
bool lp_pins_is_isolated(void);

#endif /* LOW_POWER_PINS_H */
