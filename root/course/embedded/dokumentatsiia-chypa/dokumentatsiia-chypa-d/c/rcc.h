/* rcc.h — крок 1 методики запуску периферії: подача тактового сигналу.
 *
 * До запису біта тактування периферійний блок мовчить: транзакція на шині
 * не отримує підтвердження й перетворюється на BusFault. Усі інші модулі
 * прошивки звертаються до RCC лише через ці три функції — щоб обхід еррати
 * «Delay after an RCC peripheral clock enabling» стояв в одному місці.
 */
#ifndef RCC_H
#define RCC_H

#include <stdint.h>

/* Увімкнути тактування блоків на шині AHB1 (маски RCC_AHB1ENR_*). */
void rcc_ahb1_enable(uint32_t mask);

/* Увімкнути тактування блоків на шині APB1 (маски RCC_APB1ENR_*). */
void rcc_apb1_enable(uint32_t mask);

/* Імпульс апаратного скидання блоку APB1: усі його регістри повертаються
 * до значень після скидання, кінцевий автомат — у початковий стан. */
void rcc_apb1_reset(uint32_t mask);

#endif /* RCC_H */
