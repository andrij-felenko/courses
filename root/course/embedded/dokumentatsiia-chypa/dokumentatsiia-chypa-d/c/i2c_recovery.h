/* i2c_recovery.h — обхід зависання шини I2C, описаного в Errata Sheet.
 *
 * Дефект: кінцевий автомат I2C зупиняється посеред кадру, прапорець BUSY
 * лишається піднятим назавжди, ведений пристрій тримає SDA притиснутою до
 * землі. Жоден запис у регістри блоку з цього стану не виводить.
 *
 * Обхід виробника: вимкнути блок, забрати ніжки в ручне керування, руками
 * видати такти на SCL, доки ведений не відпустить SDA, згенерувати STOP,
 * повернути ніжки в альтернативну функцію й перезапустити блок скиданням.
 */
#ifndef I2C_RECOVERY_H
#define I2C_RECOVERY_H

#include <stdbool.h>
#include <stdint.h>

typedef enum {
    I2C_OK = 0,
    I2C_ERR_BAD_CLOCK,      /* частота APB1 поза діапазоном поля FREQ      */
    I2C_ERR_SCL_STUCK_LOW,  /* SCL притиснута — це вже несправність плати  */
    I2C_ERR_SDA_STUCK_LOW,  /* дев'ять тактів не звільнили лінію           */
    I2C_ERR_STILL_BUSY,     /* блок перезапущено, а BUSY не впав           */
} i2c_status_t;

/* apb1_clock_hz — частота шини, до якої підключений блок (поле CR2_FREQ);
 * cpu_clock_hz  — частота ядра, потрібна для відліку затримок під час
 *                 ручного ногодрингу лініями. */
i2c_status_t i2c_init(uint32_t apb1_clock_hz, uint32_t cpu_clock_hz);

/* Прапорець BUSY регістра SR2 — тип доступу RO, ним керує лише кремній. */
bool i2c_bus_busy(void);

/* Повний обхід еррати. Повертає I2C_OK, коли шина знову вільна. */
i2c_status_t i2c_recover_bus(void);

#endif /* I2C_RECOVERY_H */
