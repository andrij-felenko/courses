/* Індекс = (prev_state << 2) | curr_state */
static const int8_t gray_encoder_lut[16] = {
     0, /* 00 -> 00: немає руху */
    -1, /* 00 -> 01: крок CCW */
     1, /* 00 -> 10: крок CW */
     0, /* 00 -> 11: ЗАБОРОНЕНО (брязкіт / пропуск) */

     1, /* 01 -> 00: крок CW */
     0, /* 01 -> 01: немає руху */
     0, /* 01 -> 10: ЗАБОРОНЕНО (брязкіт / пропуск) */
    -1, /* 01 -> 11: крок CCW */

    -1, /* 10 -> 00: крок CCW */
     0, /* 10 -> 01: ЗАБОРОНЕНО (брязкіт / пропуск) */
     0, /* 10 -> 10: немає руху */
     1, /* 10 -> 11: крок CW */

     0, /* 11 -> 00: ЗАБОРОНЕНО (брязкіт / пропуск) */
     1, /* 11 -> 01: крок CW */
    -1, /* 11 -> 10: крок CCW */
     0  /* 11 -> 11: немає руху */
};
