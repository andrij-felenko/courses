// геометричні множники підшипника — рахуються РАЗ, не залежать від оборотів
float Nb = 9.0f;
float Bd = 7.938f, Pd = 38.5f;
float cb = 1.0f;                 // cos(0°) для радіального підшипника
float r  = Bd / Pd;              // = 0.20618  — ключове відношення

float m_ftf  = 0.5f * (1.0f - r * cb);                 // = 0.39691
float m_bpfo = (Nb / 2.0f) * (1.0f - r * cb);          // = 3.5722
float m_bpfi = (Nb / 2.0f) * (1.0f + r * cb);          // = 5.4278
float m_bsf  = (Pd / (2.0f * Bd)) * (1.0f - r * r * cb * cb); // = 2.3219
