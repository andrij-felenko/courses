// mag[k] — магнітуди зі ШПФ (k = 0..N/2)
float fs = 4000.0f;
int   N  = 1024;
float fr = 3000.0f / 60.0f;          // = 50 Гц — частота обертання вала

int k1 = (int)(fr * N / fs + 0.5f);  // бін під 1×:  50·1024/4000 ≈ 12.8 → 13
float level_1x = mag[k1];            // висота піка дисбалансу

// підшипник: BPFO = 3.6× обертів (множник із даташита)
float f_bpfo = 3.6f * fr;            // = 180 Гц
int   k_bpfo = (int)(f_bpfo * N / fs + 0.5f);  // 180·1024/4000 ≈ 46
float level_bpfo = mag[k_bpfo];      // висота піка зовнішньої доріжки
