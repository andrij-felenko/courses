#ifndef PT100_H
#define PT100_H

/* Перетворення опору платинового датчика в температуру за рівнянням
   Каллендара-Ван Дюзена (характеристика DIN/IEC 60751). */

typedef enum {
    PT100_OK = 0,
    PT100_ERR_ARG,
    PT100_ERR_RANGE  /* опір поза паспортним діапазоном -200…850 °C */
} pt100_status_t;

/* Пряме рівняння: температура -> опір. Потрібне для ітерацій Ньютона
   й зручне, щоб перевірити тракт табличним значенням. */
float pt100_resistance_at(float t_celsius);

/* Обернена задача: опір -> температура. Вище нуля розв'язується
   аналітично, нижче нуля уточнюється методом Ньютона-Рафсона. */
pt100_status_t pt100_celsius_at(float r_ohms, float *t_celsius);

#endif /* PT100_H */
