/* chip_status.h — таксономія кодів повернення драйвера.
 *
 * Жодна функція драйвера не повертає «магічних» чисел: кожен код однозначно
 * називає причину збою, щоб викликач міг обрати різну реакцію (повторити,
 * скинути шину, зупинити задачу, підняти аварію).
 */
#ifndef CHIP_STATUS_H
#define CHIP_STATUS_H

typedef enum {
    CHIP_OK                = 0,  /* операція завершена успішно                       */
    CHIP_ERR_INVALID_PARAM = -1, /* нульовий покажчик або значення поза межами       */
    CHIP_ERR_COMM          = -2, /* апаратна помилка шини: NACK, зайнято, обрив      */
    CHIP_ERR_TIMEOUT       = -3, /* вичерпано квантований ліміт очікування           */
    CHIP_ERR_NOT_FOUND     = -4, /* WHO_AM_I не збігся з очікуваним ідентифікатором  */
    CHIP_ERR_NOT_INIT      = -5, /* робота з пристроєм до успішної ініціалізації     */
    CHIP_ERR_NO_DATA       = -6  /* нового відліку ще немає (DRDY = 0, FIFO порожній)*/
} chip_status_t;

/* Людиночитний опис коду — для журналу прошивки й діагностики на стенді. */
const char *chip_status_str(chip_status_t status);

#endif /* CHIP_STATUS_H */
