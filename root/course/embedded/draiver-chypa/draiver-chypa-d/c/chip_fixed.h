/* chip_fixed.h — перетворення сирих відліків без плаваючої коми.
 *
 * На Cortex-M0/M0+/M3 апаратного FPU немає: кожна операція над float — це
 * виклик бібліотечної функції, у 10–20 разів повільніший за цілочисельну
 * інструкцію, плюс сотні байтів коду. Для таких ядер драйвер дає цілий шлях:
 * мілігравітації та міліметри на секунду в квадраті.
 *
 * Проміжне множення завжди робиться в 64 бітах: 32767 · 732 · 980665 не
 * влазить у int32 і мовчки перетворилося б на сміття.
 */
#ifndef CHIP_FIXED_H
#define CHIP_FIXED_H

#include <stdint.h>

#include "chip_regs.h"

/* Ділення з округленням до найближчого, симетричне для від'ємних значень. */
int32_t chip_div_round(int64_t numerator, int64_t denominator);

/* Сирий код → мілігравітації (мг). */
int32_t chip_raw_to_mg(int16_t raw_code, chip_range_t range);

/* Сирий код → міліметри на секунду в квадраті (мм/с²), одиниці SI. */
int32_t chip_raw_to_mm_s2(int16_t raw_code, chip_range_t range);

/* Збирання 16-бітного слова з пари байтів у порядку little-endian:
 * молодший байт іде першим, старший зсувається вліво на 8 позицій. */
uint16_t chip_le16(const uint8_t *pair);

/* Розширення знака з урахуванням роздільності. Для 12-бітного відліку,
 * вирівняного по лівому краю, слово зсувається вправо на 4 позиції, а знак
 * добудовується вручну — покладатися на арифметичний зсув знакових типів
 * переносний драйвер не має права. */
int16_t chip_sign_extend(uint16_t word, chip_resolution_t resolution);

#endif /* CHIP_FIXED_H */
