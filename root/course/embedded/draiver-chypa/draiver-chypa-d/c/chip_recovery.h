/* chip_recovery.h — аварійне скидання завислої шини I2C (Bus Recovery).
 *
 * Ситуація: мікроконтролер перезавантажився сторожовим таймером посеред
 * транзакції читання, коли ведений чип тримав SDA притиснутою до землі.
 * Периферія I2C бачить постійний нуль на SDA й повертає Bus Busy назавжди.
 *
 * Ліки — віддати лінії GPIO й вручну дотактувати чип до кінця його байта.
 */
#ifndef CHIP_RECOVERY_H
#define CHIP_RECOVERY_H

#include "chip_bus.h"
#include "chip_status.h"

/* Виконує послідовність відновлення:
 *   1) відпускає SDA, дає до 9 тактів SCL — ведений по одному виштовхує
 *      залишок свого зсувного регістра, поки не відпустить SDA у «1»;
 *   2) формує умову STOP (перехід SDA 0→1 при високому SCL);
 *   3) повертає лінії периферії шини.
 *
 * CHIP_OK — SDA відпущено; CHIP_ERR_COMM — лінія лишилася в нулі після
 * дев'яти тактів (коротке замикання, мертвий чип, відсутня підтяжка).
 */
chip_status_t chip_bus_recover(const chip_gpio_ops_t *gpio, void *user_ctx);

#endif /* CHIP_RECOVERY_H */
