// перетворення Цензу у вікні 5×5: 24 сусіди → 24-бітний відбиток.
// (центр не кодуємо; беремо менше вікно, бо 9×9 дало б 80 біт — незручно)
static uint32_t census_5x5(const uint8_t img[H][W], int x, int y)
{
    uint8_t  c   = img[y][x];      // яскравість центрального пікселя
    uint32_t bits = 0;
    for (int j = -2; j <= 2; ++j) {
        for (int i = -2; i <= 2; ++i) {
            if (i == 0 && j == 0) continue;   // центр пропускаємо
            bits <<= 1;
            if (img[y + j][x + i] > c)         // сусід яскравіший за центр?
                bits |= 1u;
        }
    }
    return bits;                   // 24-бітний «відбиток» локального рельєфу
}

// вартість збігу = відстань Геммінга між відбитками (кількість різних бітів)
static inline uint32_t hamming(uint32_t a, uint32_t b)
{
    uint32_t x = a ^ b;            // біти, де відбитки розходяться
    // popcount: на Cortex-M часто є __builtin_popcount або інструкція;
    // тут — переносний варіант Кернігана (рахує лише встановлені біти)
    uint32_t n = 0;
    while (x) { x &= (x - 1); ++n; }
    return n;
}
