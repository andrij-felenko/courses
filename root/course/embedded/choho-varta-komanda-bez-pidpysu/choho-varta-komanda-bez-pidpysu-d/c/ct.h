#ifndef CT_H
#define CT_H

#include <stddef.h>
#include <stdint.h>

/*
 * Примітиви сталого часу для звіряння криптографічних тегів.
 *
 * Головна вимога: час виконання не залежить від ПОЗИЦІЇ першого незбігу.
 * Саме позиція незбігу — та єдина крихта, якої нападнику досить, щоб
 * підбирати тег байт за байтом замість перебору 2^256 варіантів.
 */

/* Звіряє len байтів за сталий час.
   Повертає 0, якщо буфери однакові, і -1 інакше.
   Читає ЗАВЖДИ всі len байтів обох буферів. */
int ct_verify(const uint8_t *a, const uint8_t *b, size_t len);

/* Затирає буфер нулями так, щоб оптимізатор не мав права викинути запис
   як «мертвий» (класична пастка: memset перед виходом із функції зникає
   на -O2, і сесійний ключ лишається лежати в стеку). */
void ct_wipe(void *buf, size_t len);

#endif /* CT_H */
