#include <stdint.h>

// Ініціалізуємо UART під ту саму швидкість, що й перетворювач/термінал на ПК.
// 115200 — найзвичніша для логів і налагодження.
void bridge_selftest_init(void) {
    uart_init(/*tx=*/1, /*rx=*/3, /*baud=*/115200);
}

// Усе, що прийшло з ПК через міст, одразу відправляємо назад.
// На екрані термінала набрані символи мають з'явитися — отже, обидва напрями працюють.
void bridge_selftest_poll(void) {
    if (uart_rx_ready()) {           // прийшов байт з RX (від моста)
        uint8_t b = uart_read();     // забрали його
        uart_write(b);               // штовхнули назад у TX (до моста)
    }
}
