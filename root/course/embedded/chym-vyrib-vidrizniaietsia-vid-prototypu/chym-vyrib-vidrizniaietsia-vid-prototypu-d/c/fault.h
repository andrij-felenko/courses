/* fault.h — єдина точка виходу з аварії.
 *
 * Порядок дій у ній не обговорюється: спершу знеструмити, потім записати,
 * і лише потім перезапускати. Зворотний порядок означає, що привід
 * ще секунду штовхає механізм, поки ми акуратно рахуємо контрольну суму. */
#ifndef FAULT_H
#define FAULT_H

#include "crash_log.h"

/* Аварійне завершення роботи прикладного рівня. Не повертається. */
__attribute__((noreturn)) void panic(panic_reason_t reason);

/* Перевірка інваріанта, яку не вимикають у релізі: у виробі краще
 * керований рестарт із діагностикою, ніж мовчазна робота на сміттєвих
 * даних. Умова обчислюється завжди. */
#define REQUIRE(cond)                          \
    do {                                       \
        if (!(cond)) {                         \
            panic(PANIC_ASSERTION);            \
        }                                      \
    } while (0)

#endif /* FAULT_H */
