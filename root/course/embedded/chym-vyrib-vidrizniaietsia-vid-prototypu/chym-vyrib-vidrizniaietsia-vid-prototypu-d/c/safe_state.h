/* safe_state.h — детермінований аварійний стан виконавчих органів.
 *
 * Безпечний стан — це не «зупинити керування», а фізично знеструмити те,
 * що може рухатися, нагрівати чи вмикати напругу. Він мусить наставати
 * і при аварії прошивки, і на кожному старті — до того, як почне
 * виконуватися хоч один рядок прикладної логіки.
 *
 * Два стани розрізняються навмисно:
 *   armed   — силове вимкнено, але це нормальний стан щойно завантаженої
 *             системи; вийти з нього можна;
 *   latched — силове вимкнено через аварію; вийти можна лише рестартом. */
#ifndef SAFE_STATE_H
#define SAFE_STATE_H

#include <stdbool.h>

/* Перше, що робить прошивка після скидання: переводить лінії керування
 * силовими ключами у вихід із рівнем «вимкнено». До цього виклику вони
 * лишаються входами, і зовнішні підтяжки на платі тримають драйвери
 * закритими — саме тому підтяжки в серійному виробі обов'язкові. */
void safe_state_arm_outputs(void);

/* Дозволити роботу силового каскаду. Повертає false, якщо систему вже
 * зафіксовано в аварійному стані. */
bool safe_state_enable_power(void);

/* Штатне вимкнення каскаду: сеанс керування скінчився. Аварії не оголошує
 * і фіксації не ставить — на відміну від safe_state_enter(). */
void safe_state_disable_power(void);

/* Аварійне знеструмлення із фіксацією. Ідемпотентна, придатна до виклику
 * з обробника винятку й із вимкненими перериваннями. */
void safe_state_enter(void);

/* true, якщо силова частина зараз знеструмлена (з будь-якої причини). */
bool safe_state_is_active(void);

/* true, якщо знеструмлення сталося через аварію й тримається до рестарту. */
bool safe_state_is_latched(void);

#endif /* SAFE_STATE_H */
