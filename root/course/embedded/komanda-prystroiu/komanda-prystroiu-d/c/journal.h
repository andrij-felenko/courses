#ifndef JOURNAL_H
#define JOURNAL_H

/* Журнал незавершеної транзакції в незалежній пам'яті (FRAM).
 *
 * Кільцевий буфер ідемпотентності живе в SRAM і гине разом із живленням.
 * Тому перед подачею струму на силовий ключ факт «токен пішов у залізо»
 * лягає у FRAM, а після завершення операції запис знімається. Якщо при
 * старті прошивка знайшла відкритий запис — операція обірвалася посеред
 * руху, і механізм у невизначеному стані. */

#include <stdint.h>
#include <stdbool.h>

/* Запис відкритої транзакції перед подачею струму. */
void journal_begin(uint64_t token, uint8_t type);

/* Зняття запису після будь-якого термінального стану. */
void journal_commit(void);

/* Чи є у FRAM відкрита транзакція (виклик на старті прошивки). */
bool journal_open_entry(uint64_t *token, uint8_t *type);

#endif /* JOURNAL_H */
