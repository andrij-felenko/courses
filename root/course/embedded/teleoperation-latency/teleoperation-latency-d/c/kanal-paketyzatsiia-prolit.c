// Затримка каналу з перевідправленнями (ARQ), мс
float t_one   = 8.0f;    // один проліт пакета
float p_loss  = 0.20f;   // ймовірність втрати одного пакета

// Середнє число спроб до успіху для незалежних втрат: 1/(1-p_loss)
float attempts_avg = 1.0f / (1.0f - p_loss);   // = 1.25 спроби
float t_channel_avg = attempts_avg * t_one;    // = 10 мс у середньому

// Гірший розумний випадок: скільки спроб покривають 99% доставок?
// P(усе ще не дійшло після k спроб) = p_loss^k. Треба p_loss^k < 0.01
// 0.2^1=0.2, 0.2^2=0.04, 0.2^3=0.008 < 0.01 → k = 3
int k99 = 3;
float t_channel_99 = k99 * t_one;   // = 24 мс — утричі за середнє!
