// Масив пасивний — керувати ним не можна. Але можна непрямо помітити
// неправильний/деградований захист за станом самого інтерфейсу:
// завелика ємність на лінії (не той масив) псує фронти й піднімає
// частоту помилок зв'язку. Прямого регістра масиву немає.
#define LINK_ERR_THRESHOLD   50u   // поріг помилок за вікно (емпіричний)

void check_link_health(uint32_t link_errors_per_window)
{
    if (link_errors_per_window > LINK_ERR_THRESHOLD) {
        // забагато помилок на захищеній лінії: серед причин —
        // невідповідний ESD-масив (завелика ємність) або
        // деградований захист після сильного розряду. Привід глянути
        // на фізику лінії та сам масив, а не лише на прошивку.
        log_fault(FAULT_LINK_DEGRADED);
    }
}
