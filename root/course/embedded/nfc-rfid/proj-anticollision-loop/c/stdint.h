#include <stdint.h>
#include <stdbool.h>
#include <string.h>

// ── Команди ISO 14443A ───────────────────────────────────────────────
#define CMD_REQA   0x26   // 7-бітний короткий кадр: «хто в полі, відгукніться»
#define CMD_WUPA   0x52   // 7-бітний: те саме, але будить і приспаних (HALT)
#define CMD_CT     0x88   // Cascade Tag — мітка «UID триває наступним каскадом»
#define CMD_HLTA   0x50   // Halt: приспати обрану картку (далі 0x00 + CRC_A)
#define SEL_CL1    0x93   // вибір каскаду 1
#define SEL_CL2    0x95   // вибір каскаду 2
#define SEL_CL3    0x97   // вибір каскаду 3

// ── Коди повернення ──────────────────────────────────────────────────
typedef enum {
    PCD_OK = 0,           // кадр пройшов, відповідь у буфері
    PCD_TIMEOUT,          // ніхто не відповів (порожнє поле)
    PCD_COLLISION,        // сталася колізія (кілька карток)
    PCD_ERR               // CRC/парність/інша помилка кадру
} pcd_status_t;

// Передати кадр і прийняти відповідь. Це — єдиний примітив фронтенда.
//   tx, tx_len       — кадр на передачу
//   tx_last_bits     — скільки біт ОСТАННЬОГО байта дійсні (0 = весь байт)
//   rx, rx_len (in/out) — буфер відповіді та його місткість/довжина
//   rx_align         — з якого біта складати перший прийнятий байт (для розрізу)
//   coll_pos (out)   — при колізії: позиція першого розбіжного біта (1..32)
// Реалізація — специфічна для мікросхеми (SPI-регістри); тут вона нам байдужа.
pcd_status_t pcd_transceive(const uint8_t *tx, uint8_t tx_len, uint8_t tx_last_bits,
                            uint8_t *rx, uint8_t *rx_len, uint8_t rx_align,
                            uint8_t *coll_pos);

// Порахувати CRC_A (поліном 0x1021, початкове 0x6363) над буфером.
// Пише 2 байти молодшим уперед у out[0], out[1]. Апаратно — регістр CRC фронтенда.
void pcd_crc_a(const uint8_t *data, uint8_t len, uint8_t *out);

// Увімкнути поле (несучу). Виклик один раз на старті циклу.
void pcd_field_on(void);
