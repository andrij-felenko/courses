// Викликається апаратно при кожному захопленні (фронт на вході).
void TIM_CC_IRQHandler(void)
{
    if (!(TIM->SR & TIM_SR_CC1IF))   // саме наш канал захоплення
        return;

    uint16_t cap = (uint16_t)TIM->CCR1;  // апаратний знімок лічильника (знімає й CC1IF)
    uint32_t ovf = g_ovf;                // поточний лічильник переповнень

    // Розв'язання гонки: переповнення вже сталося, але його ISR ще не відпрацював?
    // Ознака — зведений UIF разом із МАЛИМ захопленим значенням (фронт уже ПІСЛЯ
    // перевороту, тож належить новому оберту, який ще не врахований в ovf).
    if ((TIM->SR & TIM_SR_UIF) && cap < (TIMER_ARR / 2)) {
        ovf++;                            // дорахувати оберт, який UP_IRQ ще не встиг
    }

    // Повна 48-бітна позиція цього фронту.
    uint64_t now = ((uint64_t)ovf << 16) | cap;

    if (g_primed) {
        g_period = now - g_last_cap;      // різниця повних позицій — повний період
        g_seq++;                          // позначити, що є свіжий вимір
    }
    g_last_cap = now;
    g_primed   = true;
}
