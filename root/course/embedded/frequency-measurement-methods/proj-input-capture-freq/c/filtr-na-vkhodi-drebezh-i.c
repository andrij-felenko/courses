// Налаштування каналу 1 на захоплення по наростальному фронту з фільтром.
static void capture_setup_filtered(void)
{
    // IC1F = 0b1111: максимальний фільтр — фронт визнається лише після
    // 8 послідовних однакових вибірок на частоті f_DTS/32 (найповільніший,
    // найстійкіший до дребезгу варіант; для чистого сигналу беруть менше).
    TIM->CCMR1 &= ~TIM_CCMR1_IC1F_Msk;
    TIM->CCMR1 |=  (0xF << TIM_CCMR1_IC1F_Pos);   // CC1 як вхід, фільтр 0b1111

    TIM->CCER  &= ~(TIM_CCER_CC1P | TIM_CCER_CC1NP); // наростальний фронт
    TIM->CCER  |=  TIM_CCER_CC1E;                  // увімкнути захоплення на CC1

    TIM->DIER  |=  TIM_DIER_CC1IE | TIM_DIER_UIE;  // переривання захоплення + update
}
