uart_send_byte:
    ldr     r1, =0x40013800   ; Адреса регістру стану
    ldr     r2, [r1]          ; ЗЧИТУВАННЯ ВІДБУВАЄТЬСЯ ОДИН РАЗ ДО ЦИКЛУ!
    tst     r2, #128          ; Перевіряємо біт TXE
    bne     .L_ready          ; Якщо TXE був 1 — виходимо
