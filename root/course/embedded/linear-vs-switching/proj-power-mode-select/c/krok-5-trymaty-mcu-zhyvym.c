// Перекинути живлення MCU на тихий LDO (перед приспанням buck).
// make-before-break: нову опору підняли й переконались — тоді відпускаємо стару.
static bool mcu_switch_to_ldo(void)
{
    gpio_set_level(MCU_LDO_EN, 1);       // 1) увімкнути тиху опору
    esp_rom_delay_us(MCU_LDO_RISE_US);   // 2) дати LDO вийти на напругу
                                         //    (LDO швидкий; PGOOD зазвичай нема)
    // 3) Тепер MCU має ДВІ живі опори одночасно — момент, коли нічого не провисає.
    //    Аж тепер безпечно послабити buck (пропуск) чи згодом його вимкнути.
    return true;
}

// Повернути живлення MCU на ефективний buck (після прокидання).
// Дзеркально: спершу підняли й підтвердили buck, ТОДІ прибрали LDO.
static bool mcu_switch_to_buck(void)
{
    // Buck уже у PWM і його головна шина підтверджена PGOOD у power_enter_run().
    // Отже, обидві опори знову живі — можна відпускати тимчасову.
    gpio_set_level(MCU_LDO_EN, 0);       // прибрати LDO — MCU лишається на buck
    return true;
}
