# вхідні дані
rho = 1.2       # густина повітря, кг/м³
V   = 30.0      # швидкість, м/с
S   = 0.012     # площа керма за завісою, м²
c   = 0.04      # середня хорда керма, м
Ch  = 0.2       # коефіцієнт моменту на завісі (повне відхилення)

# 1) динамічний тиск q = ½·ρ·V²
q = 0.5 * rho * V * V                    # 0.5·1.2·900 = 540 Па

# 2) момент на завісі H = Ch·q·S·c
H = Ch * q * S * c                       # 0.2·540·0.012·0.04 = 0.0518 Н·м

# 3) передавальне відношення 1:1 → момент серво дорівнює H
M_servo = H * 1.0                        # r_кач/r_горн = 1

# 4) запас 2.5×
M_req = M_servo * 2.5                     # 0.0518·2.5 = 0.1296 Н·м

# 5) переклад у кг·см (1 кг·см ≈ 0.0981 Н·м)
kgcm = M_req / 0.0981                     # 0.1296/0.0981 ≈ 1.32 кг·см

print(f"q={q:.0f} Pa  H={H:.4f} N*m  M_req={M_req:.4f} N*m  = {kgcm:.2f} kg*cm")
