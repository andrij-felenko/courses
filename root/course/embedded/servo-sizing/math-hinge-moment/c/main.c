#include <stdio.h>

int main(void) {
    // вхідні дані
    float rho = 1.2f;       // густина повітря, кг/м³
    float V   = 30.0f;      // швидкість, м/с
    float S   = 0.012f;     // площа керма за завісою, м²
    float c   = 0.04f;      // середня хорда керма, м
    float Ch  = 0.2f;       // коефіцієнт моменту на завісі (повне відхилення)

    // 1) динамічний тиск q = ½·ρ·V²
    float q = 0.5f * rho * V * V;            // 0.5·1.2·900 = 540 Па

    // 2) момент на завісі H = Ch·q·S·c
    float H = Ch * q * S * c;                 // 0.2·540·0.012·0.04 = 0.0518 Н·м

    // 3) передавальне відношення 1:1 → момент серво дорівнює H
    float M_servo = H * 1.0f;                 // r_кач/r_горн = 1

    // 4) запас 2.5×
    float M_req = M_servo * 2.5f;             // 0.0518·2.5 = 0.1296 Н·м

    // 5) переклад у кг·см (1 кг·см ≈ 0.0981 Н·м)
    float kgcm = M_req / 0.0981f;             // 0.1296/0.0981 ≈ 1.32 кг·см

    printf("q=%.0f Pa  H=%.4f N*m  M_req=%.4f N*m  = %.2f kg*cm\n",
           q, H, M_req, kgcm);
    return 0;
}
