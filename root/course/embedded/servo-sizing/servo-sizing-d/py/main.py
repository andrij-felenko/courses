# момент зручно тримати в цілих мілі-ньютон-метрах (уникаємо float)
STALL_KGCM_X10 = 120   # 12.0 кг·см, помножено на 10
ARM_MM         = 15    # плече качалки 1.5 см = 15 мм

# 1 кг·см = 98.1 мН·м  →  момент у мН·м
stall_mNm = STALL_KGCM_X10 * 981 // 100   # 120 * 9.81 = 1177 мН·м

# сила на кінці плеча: F = M / r ;  r у метрах = ARM_MM / 1000
# F [Н] = M[мН·м] / r[м] / 1000 = stall_mNm / ARM_MM   (мН·м / мм = Н)
force_N = stall_mNm // ARM_MM              # 1177 / 15 ≈ 78 Н
