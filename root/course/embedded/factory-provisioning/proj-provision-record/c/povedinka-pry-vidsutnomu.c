// Гілка «стоп»: виріб без особистості НЕ МАЄ ПРАВА працювати.
void app_main_strict(void) {
    if (!prov_init()) {
        // Не провізіонована або запис побитий. Не працюємо — сигналимо й стоїмо.
        report_fault(FAULT_NOT_PROVISIONED);   // блимнути кодом, лог у діагностику
        enter_safe_halt();                     // безпечний стоп, не робочий режим
        // сюди керування не повертається
    }
    // Сюди дійшли ЛИШЕ з валідним записом — далі можна довіряти своїй особистості.
    normal_operation();
}
