// Комплементарний фільтр однієї осі нахилу.
//   angle    — попередня оцінка кута (рад), оновлюється на місці
//   gyro_rate — кутова швидкість цієї осі з гіроскопа (рад/с)
//   acc_angle — абсолютний кут цієї осі з акселерометра (рад)
//   dt        — крок часу від минулого виклику (с)
//   tau       — стала фільтра (с): більша → більше довіри гіроскопу
static float comp_filter(float angle, float gyro_rate,
                         float acc_angle, float dt, float tau)
{
    // коефіцієнт поділу: яку частку лишаємо за гіроскопом
    float a = tau / (tau + dt);
    // швидка частина (гіроскоп) + повільна корекція (акселерометр)
    return a * (angle + gyro_rate * dt) + (1.0f - a) * acc_angle;
}
