#ifndef CRC16_H
#define CRC16_H

#include <stddef.h>
#include <stdint.h>

// CRC-16-CCITT: G(x) = x^16 + x^12 + x^5 + 1 (0x1021), початкове значення 0xFFFF,
// без відображення бітів і без фінального XOR.
//
// Важлива властивість цього варіанта: якщо порахувати CRC над блоком РАЗОМ із
// дописаною до нього контрольною сумою (старший байт перший), результат дорівнює 0.
// Приймач саме так і перевіряє кадр — однією дією, без порівняння двох чисел.
uint16_t crc16_ccitt(const uint8_t *data, size_t len);

#endif // CRC16_H
