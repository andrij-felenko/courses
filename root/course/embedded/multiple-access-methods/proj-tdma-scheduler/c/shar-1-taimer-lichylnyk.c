#include <stdint.h>
#include <stdbool.h>

// ── Параметри кадру (однакові на ВСІХ вузлах) ─────────────────────────────
#define N_SLOTS     8          // вікон у кадрі
#define SLOT_US     2500u      // повна тривалість одного вікна, мкс
#define GUARD_US    300u       // захисний зазор у кінці вікна, мкс
#define FRAME_US    (N_SLOTS * SLOT_US)   // тривалість кадру, мкс = 20000

#define MY_SLOT     3          // це вікно належить нам (0..N_SLOTS-1)

// ── Монотонний годинник вузла: 1 тик = 1 мкс ─────────────────────────────
// Апаратний таймер налаштований рахувати вгору з кроком 1 мкс і
// викликати timer_overflow_isr() при переповненні; ми ведемо 64-бітний час.
static volatile uint64_t g_now_us = 0;        // поточний час вузла, мкс

uint64_t now_us(void) {
    // Атомарне читання 64-бітного лічильника з апаратного таймера + бази.
    // (на 32-бітному МК — захист від розриву читання half-words)
    uint64_t t;
    __disable_irq();
    t = g_now_us + timer_hw_counter();        // база + поточний відлік таймера
    __enable_irq();
    return t;
}
