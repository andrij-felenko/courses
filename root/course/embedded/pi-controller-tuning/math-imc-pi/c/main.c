// виведені lambda/IMC-коефіцієнти ПІ з удар-тесту печі
// модель об'єкта (з удар-тесту):  K, tau, theta — НЕ ваш вибір, а вимір
float K = 4.0f, tau = 80.0f, theta = 12.0f;

// ЄДИНА ручка людини: бажана стала часу замкненого контуру
float lambda = tau;                         // помірно стійко (можна 0.5*tau..3*tau)

// крок 1: скорочення полюса об'єкта нулем регулятора
float Ti = tau;                             // = 80 c   (нуль на -1/tau)

// кроки 2-3: повна повільність (lambda+theta) задає обидва підсилення
float denom = K * (lambda + theta);         // = 4*(80+12) = 368
float Kp = tau / denom;                     // = 0.217
float Ki = 1.0f / denom;                    // = 0.00272  (== Kp/Ti)

