#ifndef SETPOINT_H
#define SETPOINT_H

#include <stdbool.h>
#include <stdint.h>

#include "linalg.h"

/* ---------------------------------------------------------------------------
   Контракт між доменами. Усе, що повільне наведення каже швидкому регулятору,
   вміщується в цю структуру — і нічого більше через межу не проходить:
   ні координат NED, ні вейпойнтів, ні стану GNSS.
   --------------------------------------------------------------------------- */
typedef struct {
    uint64_t stamp_us;   /* коли уставку згенеровано (мікросекунди монотонного часу) */
    Quat     q_target;   /* цільова орієнтація корпуса */
    Vec3     rate_ff;    /* прямий зв'язок за кутовою швидкістю, рад/с (body) */
    float    thrust;     /* колективна тяга, 0.0 .. 1.0 */
} Setpoint;

/* ---------------------------------------------------------------------------
   Seqlock: єдиний письменник (наведення, 50 Гц), єдиний читач (регулятор, 1 кГц).
   Читач НІКОЛИ не блокується — переривання гіроскопа не має права чекати на
   м'ютекс, який тримає задача навігації. Непарний лічильник = запис триває.
   --------------------------------------------------------------------------- */
#define SP_READ_ATTEMPTS 4

typedef struct {
    _Atomic uint32_t seq;
    Setpoint data;
} SetpointMailbox;

void sp_mailbox_init(SetpointMailbox *mb);
void sp_publish(SetpointMailbox *mb, const Setpoint *sp);
/* true — вдалося зняти цілісну копію; false — розірване читання або даних ще нема. */
bool sp_consume(SetpointMailbox *mb, Setpoint *out);

/* ---------------------------------------------------------------------------
   Зворотний канал знизу вгору. Один біт, але без нього анти-вінд-ап неможливий:
   наведення мусить знати, що мотори вже вперлися у стелю.
   --------------------------------------------------------------------------- */
#define FB_SATURATED 0x1u   /* актуатори в насиченні */
#define FB_FALLBACK  0x2u   /* регулятор перейшов на утримання горизонту */

typedef struct {
    _Atomic uint32_t bits;
} ControlFeedback;

void fb_init(ControlFeedback *fb);
void fb_set_bit(ControlFeedback *fb, uint32_t bit, bool on);
bool fb_test(ControlFeedback *fb, uint32_t bit);

#endif /* SETPOINT_H */
