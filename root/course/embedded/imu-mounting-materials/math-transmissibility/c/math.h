#include <math.h>
float r = 6.0f;
// суха гума, ζ = 0.05
float z1 = 0.05f;
float T1 = sqrtf(1 + powf(2*z1*r,2)) / sqrtf(powf(1-r*r,2) + powf(2*z1*r,2));
// чисельник: √(1+(2·0.05·6)²)=√(1+0.36)=√1.36≈1.166
// знаменник: √((1−36)²+(0.36))=√(1225+0.36)=√1225.36≈35.0
// T1 ≈ 1.166/35.0 ≈ 0.0333   → доходить ~3.3 %

// в'язкий гель, ζ = 0.4
float z2 = 0.40f;
