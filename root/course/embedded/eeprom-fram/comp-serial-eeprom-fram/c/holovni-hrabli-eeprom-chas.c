// Записати один байт за адресою addr у I²C-EEPROM (7-бітна адреса dev).
// Після запису комірці потрібні мілісекунди — чекаємо не наосліп фіксованою
// паузою, а опитуванням ACK: поки чип зайнятий, він не підтверджує адресу.
void eeprom_write_byte(uint8_t dev, uint16_t addr, uint8_t data) {
    i2c_start();
    i2c_send(dev << 1);          // адреса чипа + біт запису (0)
    i2c_send(addr >> 8);         // старший байт адреси комірки
    i2c_send(addr & 0xFF);       // молодший байт адреси
    i2c_send(data);
    i2c_stop();                  // тут чип починає внутрішній цикл запису

    // ACK polling: шлемо лише адресу, поки чип знову не підтвердить ACK
    while (1) {
        i2c_start();
        uint8_t ack = i2c_send(dev << 1);   // зайнятий → NACK, готовий → ACK
        i2c_stop();
        if (ack == I2C_ACK) break;          // підтвердив → запис завершено
    }
}
