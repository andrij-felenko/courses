/* sf_ackset.h — множина квитованих номерів як кілька діапазонів.
 *
 * Навіщо взагалі множина, а не одне число «підтверджено до N».
 *
 * Вивантаження двоколійне. Свіжа телеметрія йде в ефір одразу, щойно
 * лягла у флеш, і квитується десь угорі нумерації. Історія тим часом
 * повзе від хвоста батчами. Тому квитанції приходять двома острівцями:
 * суцільний шматок біля хвоста (пакетний ACK) і суцільний шматок біля
 * голови (жива колія). Одним числом їх не описати.
 *
 * Острівців тримаємо чотири. Це не «на всяк випадок»: кожен розрив —
 * це один епізод розриву зв'язку, а після четвертого найдешевший
 * діапазон викидається, і ті кадри просто поїдуть удруге. Сервер
 * відкине дубль за номером; втратити дані така економія не може.
 *
 * ⚠ Діапазони НІКОЛИ не розширюються заради економії місця: об'єднати
 * [10..12] і [20..22] у [10..22] означало б збрехати, що 13..19 доїхали,
 * і тихо стерти сім кадрів.
 */
#ifndef SF_ACKSET_H
#define SF_ACKSET_H

#include <stdbool.h>
#include <stdint.h>

#define SF_ACK_RANGES 4u

typedef struct {
    uint32_t lo; /* включно */
    uint32_t hi; /* включно */
} sf_ackrange_t;

typedef struct {
    sf_ackrange_t r[SF_ACK_RANGES];
    uint8_t       count;
    uint32_t      dropped; /* скільки діапазонів витіснено -> повторні надсилання */
} sf_ackset_t;

void sf_ackset_reset(sf_ackset_t *s);

/* Позначити діапазон [lo..hi] квитованим. Сусідні й перекриті
 * діапазони зливаються. false — місця не було, найдешевший діапазон
 * викинуто (лічильник dropped зріс). */
bool sf_ackset_add_range(sf_ackset_t *s, uint32_t lo, uint32_t hi);

static inline bool sf_ackset_add(sf_ackset_t *s, uint32_t seq)
{
    return sf_ackset_add_range(s, seq, seq);
}

bool sf_ackset_contains(const sf_ackset_t *s, uint32_t seq);

/* Викинути все, що вже нижче за хвіст: ці номери більше ні про що
 * не свідчать, а місце в таблиці потрібне. */
void sf_ackset_prune_below(sf_ackset_t *s, uint32_t seq);

#endif /* SF_ACKSET_H */
