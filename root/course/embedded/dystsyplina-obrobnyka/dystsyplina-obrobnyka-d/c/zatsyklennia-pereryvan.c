/* НАДІЙНИЙ ВАРІАНТ: скидання на початку з бар'єром шини */
void TIM2_IRQHandler(void) {
    if (TIM2->SR & TIM_SR_UIF) {
        /* 1. Скидаємо прапорець першим кроком */
        TIM2->SR = ~TIM_SR_UIF;
        
        /* 2. Фіктивне читання змушує шину APB завершити транзакцію запису */
        (void)TIM2->SR;

        /* 3. Корисна дія */
        do_fast_action();
    }
}
