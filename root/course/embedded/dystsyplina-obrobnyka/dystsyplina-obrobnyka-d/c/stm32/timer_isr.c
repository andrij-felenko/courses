#include "timer_isr.h"

#include "stm32f4xx.h"
#include "stm32f4xx_ll_tim.h"
#include "stm32f4xx_ll_gpio.h"

static volatile uint32_t s_ms_ticks;
static volatile uint32_t s_spurious;

/* Корисна дія обробника: мілісекундна мітка часу й імпульс «я живий»
 * на ніжці PD12. Обидві операції — по одному запису в регістр, тобто
 * рівно те, що обробнику дозволено. */
static void do_fast_action(void)
{
    s_ms_ticks++;
    LL_GPIO_TogglePin(GPIOD, LL_GPIO_PIN_12);
}

/* ---------------------------------------------------------------------------
 * НАДІЙНИЙ ВАРІАНТ: прапорець знімаємо ПЕРШИМ рядком і закриваємо запис
 * бар'єром, аби до BX LR сигнал переривання встиг згаснути на шині APB.
 * ------------------------------------------------------------------------ */
void TIM2_IRQHandler(void)
{
    if (!LL_TIM_IsActiveFlag_UPDATE(TIM2)) {
        /* Ми тут, хоча прапорця немає. Це і є помилковий повторний вхід —
         * рахуємо його замість того, щоб мовчки вийти. */
        s_spurious++;
        return;
    }

    /* 1. Квитування першим кроком. Поки виконається корисна дія,
     *    запис устигне доїхати до периферії природним чином. */
    LL_TIM_ClearFlag_UPDATE(TIM2);

    /* 2. Корисна дія — вона ж і затримка, за яку шина завершує транзакцію. */
    do_fast_action();

    /* 3. Страховка на випадок, коли дія виявилась надто короткою:
     *    DSB зупиняє конвеєр, доки всі звернення до пам'яті не завершено.
     *    Одне читання того самого регістра дало б той самий ефект —
     *    зчитування не повертається, поки шина не відповість. */
    __DSB();
}

uint32_t timer_ms_ticks(void)
{
    return s_ms_ticks;
}

uint32_t timer_spurious_entries(void)
{
    return s_spurious;
}
