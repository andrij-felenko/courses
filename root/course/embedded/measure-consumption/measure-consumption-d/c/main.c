#include <stdint.h>

// Параметри тракту (визначаються схемою й калібруванням):
#define R_SHUNT_MOHM   100      // шунт 0.1 Ом = 100 мОм
#define ADC_VREF_UV    3300000  // опора АЦП, 3.3 В у мкВ
#define ADC_MAX        4095     // 12-біт АЦП
#define GAIN_CSA       50       // підсилення підсилювача струму (×50)
#define DT_US          1000     // крок інтегрування, 1 мс

// Накопичений заряд у пікокулонах (пКл): 64 біти, щоб не переповнити.
// 1 пКл = 10⁻¹² Кл; за годину піку 200 мА це ~7×10¹⁷ пКл — влазить у int64.
static int64_t charge_pC = 0;
static uint32_t samples   = 0;

// Один крок інтегрування — викликати рівно раз на DT_US мікросекунд.
void coulomb_step(uint16_t adc_code)
{
    // 1) код АЦП -> напруга на вході АЦП, мкВ
    //    V_adc = code / ADC_MAX * Vref
    int32_t v_adc_uv = (int32_t)((int64_t)adc_code * ADC_VREF_UV / ADC_MAX);

    // 2) напруга АЦП -> спад на шунті, нВ (ділимо на підсилення CSA)
    //    V_shunt = V_adc / GAIN; тримаємо в нановольтах для точності дна
    int32_t v_shunt_nv = (v_adc_uv * 1000) / GAIN_CSA;   // мкВ*1000 = нВ

    // 3) спад -> струм, наноампери: I = V_shunt / R_shunt
    //    R у мОм: I[нА] = V[нВ] / R[мОм]  (нВ/мОм = мкА... перевіримо одиниці)
    //    V[нВ]/R[мОм] = 10⁻⁹ В / 10⁻³ Ом = 10⁻⁶ А = мкА -> домножимо на 1000 -> нА
    int32_t i_nA = (v_shunt_nv * 1000) / R_SHUNT_MOHM;   // струм у нА

    // 4) заряд за крок: dQ = I * dt.  нА * мкс = 10⁻⁹·10⁻⁶ Кл = 10⁻¹⁵ Кл = фКл
    //    переводимо у пКл: /1000
    charge_pC += ((int64_t)i_nA * DT_US) / 1000;
    samples++;
}

// Середній струм за весь час спостереження, у наноамперах.
// I_сер = Q / T;  T = samples * DT_US.  Q у пКл, T у мкс.
// пКл/мкс = 10⁻¹²Кл / 10⁻⁶с = 10⁻⁶ А = мкА -> *1000 -> нА
int32_t average_current_nA(void)
{
    int64_t t_us = (int64_t)samples * DT_US;
    if (t_us == 0) return 0;
    return (int32_t)((charge_pC * 1000) / t_us);
}
