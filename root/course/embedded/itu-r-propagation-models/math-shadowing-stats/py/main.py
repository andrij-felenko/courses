import math

# Запас на затінення M (дБ) під задане покриття краю p (0..1).
# Наближення оберненої Q-функції (Acklam / раціональне) — для прикидок досить.
def shadow_margin_db(sigma_db, p_coverage):
    # z = Q^-1(1 - p) = Phi^-1(p): квантиль нормального розподілу
    # груба, але робоча апроксимація для p у межах 0.5..0.999:
    q = 1.0 - p_coverage                    # площа хвоста
    t = math.sqrt(-2.0 * math.log(q))       # проміжна
    z = t - (2.515517 + 0.802853*t + 0.010328*t*t) \
          / (1.0 + 1.432788*t + 0.189269*t*t + 0.001308*t*t*t)
    return z * sigma_db                      # запас = z · σ


m95 = shadow_margin_db(8.0, 0.95)
# m95 ≈ 1.645 * 8 ≈ 13.2 дБ
# тобто над «середнім» рівнем з формули треба ще ~13 дБ запасу,
# щоб зв'язок тримався у 95 зі 100 точок міста.
m90 = shadow_margin_db(8.0, 0.90)
# m90 ≈ 1.282 * 8 ≈ 10.3 дБ — на 90% вистачить ~10 дБ.
