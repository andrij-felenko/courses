/* crc16.h — CRC-16/CCITT-FALSE: поліном 0x1021, початкове значення 0xFFFF.
 *
 * Побітова версія без таблиці: 512 байтів таблиці у Flash дорожчі за 8 зсувів
 * на байт, а рахуємо ми 14 байтів кадру, а не потік телеметрії.
 */
#ifndef CRC16_H
#define CRC16_H

#include <stddef.h>
#include <stdint.h>

/* Рахує суму над len байтами. seed дозволяє продовжити рахунок по частинах
 * (заголовок окремо, тіло окремо) — потрібне драйверу скидання дампу в L2. */
uint16_t crc16_ccitt(const void *data, size_t len, uint16_t seed);

#endif /* CRC16_H */
