#include <stdint.h>

// Стан фільтра живе МІЖ блоками, тому статичний.
// bias — повільна оцінка постійного зсуву у форматі 16.16
// (фіксована кома: старші 16 біт — ціла частина, молодші — дробова).
static int32_t bias = 0;

void dc_block(int16_t *samples, int n) {
    for (int i = 0; i < n; i++) {
        int32_t x = (int32_t)samples[i] << 16;   // відлік у формат 16.16
        // повзуча середня: наздоганяємо зсув на 1/1024 різниці за крок
        bias += (x - bias) >> 10;
        int32_t y = x - bias;                     // лишаємо тільки коливання
        samples[i] = (int16_t)(y >> 16);          // назад у int16
    }
}
