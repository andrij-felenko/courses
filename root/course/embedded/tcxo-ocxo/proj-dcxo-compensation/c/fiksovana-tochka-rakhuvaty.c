#include <stdint.h>

/* Калібрувальні коефіцієнти з EEPROM.
 * Кожен коефіцієнт уже помасштабований стендом так, що результат
 * поліному виходить у Q16-форматі ppb (тобто ppb << 16).
 * Масштаб коефіцієнтів (Q-формат) підібрано під його степінь:
 *   c[0]: ppb          << 16
 *   c[1]: ppb/°C       << 16, але температура теж масштабована — див. нижче
 * Щоб не жонглювати різними Q на кожен степінь, ми тримаємо T
 * у фіксованій точці Q8 (T_q8 = round(T_degC * 256)), а коефіцієнти
 * стенд підбирає так, щоб горнерів прохід сходився в Q16 ppb. */
typedef struct {
    int32_t c0, c1, c2, c3;   /* з EEPROM, поекземплярно */
    int32_t t_min_q8, t_max_q8; /* межі валідності калібрування, Q8 */
} dcxo_cal_t;

/* Горнерів прохід у фіксованій точці.
 * T_q8 — температура в Q8 (°C * 256). Повертає Δf/f у Q16 ppb.
 * 64-бітний акумулятор acc тримає проміжки без переповнення. */
static int32_t dcxo_poly_q16(const dcxo_cal_t *cal, int32_t T_q8)
{
    /* Затиснути T у діапазон калібрування: за його межами поліном
     * екстраполює НАВМАННЯ і може дати дику поправку (кубіка розганяється).
     * Краще впертись у край, ніж підкрутити варикап у безодню. */
    if (T_q8 < cal->t_min_q8) T_q8 = cal->t_min_q8;
    if (T_q8 > cal->t_max_q8) T_q8 = cal->t_max_q8;

    int64_t acc = cal->c3;                 /* старший коефіцієнт */
    acc = (acc * T_q8 >> 8) + cal->c2;     /* ·T, тоді +c2; >>8 знімає Q8 множника */
    acc = (acc * T_q8 >> 8) + cal->c1;     /* ·T, +c1 */
    acc = (acc * T_q8 >> 8) + cal->c0;     /* ·T, +c0 → результат у Q16 ppb */
    return (int32_t)acc;
}
