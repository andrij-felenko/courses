// перцептивна яскравість (0..1000) -> код струму панелі (0..max_code)
// L_панелі = (perc/1000)^2.2  — обертаємо кубокореневе сприйняття ока
uint16_t perc_to_panel(uint16_t perc, uint16_t max_code) {
    if (perc == 0) return 0;
    float p = (float)perc / 1000.0f;
    // p^2.2 без math.h: p^2 * p^0.2, а p^0.2 ~ швидка апроксимація
    float p2  = p * p;
    // p^0.2 ≈ через два кроки Ньютона для кореня 5-го степеня — але простіше
    // й дешевше взяти готову таблицю; тут показуємо чесний степінь:
    float g   = p2 * powf(p, 0.2f);      // = p^2.2
    return (uint16_t)(g * max_code + 0.5f);
}
