// у скільки (0..256, де 256 = ×1.0) масштабувати синій, щоб вирівняти знос.
// щойно синій набіг переганяє середнє R/G — прибираємо трохи синього.
uint16_t wear_blue_scale(const disp_guard_t *g) {
    uint64_t rg = (g->wear_r + g->wear_g) / 2;      // опорний темп «здорових» каналів
    if (rg == 0) return 256;                        // ще нічого не набігло
    // наскільки синій попереду опорного, у 1/256-х
    if (g->wear_b <= rg) return 256;                // синій не попереду — не чіпаємо
    uint64_t excess = ((g->wear_b - rg) * 256) / rg; // відносне випередження
    if (excess > 40) excess = 40;                    // стеля −~16 %, щоб не позеленити картинку
    return (uint16_t)(256 - excess);
}
