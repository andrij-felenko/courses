#ifndef SAFETY_HAL_H
#define SAFETY_HAL_H

/* Контракт заліза для контролера безпеки.
   Усе, що нижче, — це виводи реального модуля: два тестові виходи T1/T2,
   два входи E-Stop, петля EDM з дзеркальних NC-контактів K1 і K2, котушки
   контакторів, контакти 3-позиційної кнопки дозволу, органи оператора
   та лампа з зумером контролю пильності. */

#include <stdbool.h>
#include <stdint.h>

enum {
    HAL_CH_A = 0,   /* канал 1: живиться від тестового виходу T1 */
    HAL_CH_B = 1    /* канал 2: живиться від тестового виходу T2 */
};

/* Тестовий вихід: high = +24 В, low = тестовий провал у нуль. */
void hal_set_test_output(uint8_t ch, bool high);

/* Вхід каналу E-Stop: true = на вході рівень логічної одиниці. */
bool hal_read_estop_input(uint8_t ch);

/* Петля EDM: послідовно з'єднані дзеркальні NC-контакти K1 і K2.
   true = обидва контактори відпущені (силові NO розімкнені). */
bool hal_read_edm_loop(void);

/* Котушки обох силових контакторів. false = знеструмлення (Категорія 0). */
void hal_set_contactors(bool energize);

/* Контакти 3-позиційної кнопки: два NO-кола дозволу (замкнені лише в
   Позиції 2) і NC-контакт паніки (розмикається в Позиції 3). */
void hal_read_enabling_contacts(bool *circuit_a, bool *circuit_b, bool *panic_nc);

bool hal_read_reset_button(void);   /* кнопка пуску після зняття аварії */
bool hal_read_ack_button(void);     /* кнопка підтвердження пильності */
bool hal_operator_active(void);     /* джойстик, штурвал, вибір швидкості */

void hal_set_lamp(bool on);         /* світлова фаза ескалації тривоги */
void hal_set_buzzer(bool on);       /* звукова фаза ескалації тривоги */

/* Затримка на час тестового імпульсу. Мікросекунди, без сну планувальника:
   провал мусить бути коротшим за час відпускання контактора. */
void hal_busy_wait_us(uint32_t us);

/* Вільно біжучий лічильник мілісекунд. Переповнення дозволене: різниця
   двох беззнакових значень лишається правильною. */
uint32_t hal_now_ms(void);

#endif /* SAFETY_HAL_H */
