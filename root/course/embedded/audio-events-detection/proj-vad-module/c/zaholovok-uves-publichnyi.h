#ifndef VAD_H
#define VAD_H

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

// ── Налаштування сторожа. Заповни під свій мікрофон і частоту, або візьми
//    типові з vad_config_default(). Пороги — МНОЖНИКИ над оцінкою фону,
//    а не абсолютні числа, тож переносяться між кімнатами без правок. ──
typedef struct {
    uint16_t frame_len;   // відліків у кадрі (N), напр. 256 при 16 кГц ≈ 16 мс
    uint16_t k_up;        // запас на ВХІД у подію  (поріг_ВГ = фон·k_up),  Q4-множник
    uint16_t k_down;      // запас на ВИХІД        (поріг_ВН = фон·k_down), Q4-множник
    uint16_t alpha_shift; // згладжування фону: крок = різниця >> alpha_shift
    uint16_t hang_frames; // хвіст утримання, кадрів (типово 100–300 мс)
    uint16_t zcr_high;    // поріг «висока ZCR» — страховка глухих звуків
    uint32_t noise_init;  // початкова груба оцінка фону (енергія кадру)
} vad_config_t;

// ── Контекст одного сторожа. Поля видно тут (щоб викликач міг покласти
//    структуру на стек чи в статику без malloc), але чіпати їх не можна —
//    лише через функції. На кожен мікрофон — свій окремий vad_t. ──
typedef struct {
    vad_config_t cfg;
    uint32_t     noise;    // поточна оцінка фону (енергія)
    bool         active;   // стан автомата: чи триває подія
    uint16_t     hang;     // лічильник хвоста, кадрів
} vad_t;

// Заповнити налаштування розумними типовими (16 кГц, кадр 256).
void vad_config_default(vad_config_t *cfg);

// Завести сторожа: скинути стан, узяти налаштування. Викликати ОДИН раз.
void vad_init(vad_t *v, const vad_config_t *cfg);

// Згодувати ОДИН кадр (N = cfg.frame_len відліків int16). Оновлює стан
// усередині; повертає поточний прапорець події (true = зараз подія).
bool vad_feed(vad_t *v, const int16_t *frame);

// Прочитати поточний прапорець, не годуючи (напр. з іншого місця циклу).
bool vad_poll(const vad_t *v);

#endif // VAD_H
