static void noise_update(vad_t *v, uint64_t e)
{
    // Різниця зі знаком: енергія може бути і нижчою за оцінку (фон просів).
    int64_t diff = (int64_t)e - (int64_t)v->noise;

    // Крок = diff / 2^shift через зсув. Для додатної різниці зсув округлює
    // ВНИЗ до нуля, тож при малій додатній різниці крок = 0 і оцінка
    // «застрягає» під ціллю. Гарантуємо крок хоча б на 1 у бік різниці,
    // поки різниця не нульова — інакше фон ніколи не дійде вгору.
    int64_t step = diff >> v->cfg.alpha_shift;   // арифм. зсув (sign-extend)
    if (step == 0 && diff != 0) step = (diff > 0) ? 1 : -1;

    int64_t nn = (int64_t)v->noise + step;
    if (nn < 0) nn = 0;                      // фон не буває від'ємним
    v->noise = (uint32_t)nn;
}
