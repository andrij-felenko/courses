// Дешевша енергія для крихітних МК: сума модулів (замість суми квадратів).
// Немає множень; накопичувач 32-бітний; міра — середній модуль, не RMS.
static uint32_t frame_absenergy(const int16_t *x, uint16_t n)
{
    uint32_t acc = 0;
    for (uint16_t i = 0; i < n; i++) {
        int32_t s = x[i];
        acc += (uint32_t)(s < 0 ? -s : s);
    }
    return acc;                              // ділити на n не треба — фон масштабується так само
}
