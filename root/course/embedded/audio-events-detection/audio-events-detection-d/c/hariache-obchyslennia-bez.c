#include <stdint.h>

// Середній квадрат кадру, повністю в цілих.
// Повертає MSE ≈ середню потужність; кореня не беремо — поріг теж тримаємо у квадраті.
uint32_t frame_power(const int16_t *frame, int N) {
    uint64_t acc = 0;                     // 38+ біт суми — тільки 64-бітний тип
    for (int i = 0; i < N; i++) {
        int32_t s = frame[i];             // РОЗШИРЕННЯ перед множенням — обов'язкове
        acc += (uint64_t)(s * s);         // s*s ≤ 2^30, у int32 влазить; копичимо в 64
    }
    return (uint32_t)(acc / (uint32_t)N); // MSE ≤ 2^30 — назад у 32 біти влазить
}
