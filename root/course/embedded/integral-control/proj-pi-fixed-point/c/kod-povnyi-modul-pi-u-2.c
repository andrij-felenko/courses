/* один такт ПІ-регулятора у фіксованій комі.
   setpoint, meas — у тих самих одиницях, що й вихід (цілі відліки);
   dt_q — виміряний крок часу, дроб у Q16 (секунди).
   Повертає вплив u в одиницях виконавчого органу.                       */
int32_t pi_fx_step(PI_fx *c, int32_t setpoint, int32_t meas, int32_t dt_q)
{
    int32_t e = setpoint - meas;                 /* помилка (ціла)          */

    /* 1. Накопичуємо ПОВНЕ e·dt у широкому слові — БЕЗ зсуву назад.
          Так дрібний доданок не округлюється в нуль (пастка «мертвого I»). */
    c->integ += (int64_t)e * dt_q;               /* масштаб: e · Q16        */

    /* 2. Складаємо вплив. Обидва члени зводимо до одного масштабу зсувом,
          який робимо ТІЛЬКИ тут, на виході — не в накопичувачі.
          P:  kp_q·e         має масштаб Q16 → >> Q
          I:  ki_q·integ     має масштаб Q16·(e·Q16)=Q32·e → >> 2Q          */
    int64_t up = ((int64_t)c->kp_q * e) >> Q;                 /* внесок P    */
    int64_t ui = ((int64_t)c->ki_q * c->integ) >> (2 * Q);   /* внесок I    */
    int64_t u_raw = up + ui;

    /* 3. Затискаємо вихід до меж виконавчого органу — у ШИРОКОМУ типі,
          і лише потім звужуємо в 32 біти (інакше переповнення спотворить
          число ще до перевірки меж). */
    int32_t u = (int32_t)clamp64(u_raw, c->u_min, c->u_max);

    /* 4. Антивіндап зворотним перерахунком. Надлишок (u_raw − u) — це друга
          «помилка» на вході інтегратора: помножений на Kt, він відмотує I.
          Та відмотувати треба ПО ЧАСУ — інтегруємо надлишок ТАК САМО, як e:
          через крок dt_q. Забути dt_q — і поправка стане в dt_q разів заквола
          (за dt = 0.001 с — у 66 разів!), а «антивіндап» — майже бутафорським. */
    int64_t excess = u_raw - u;                  /* > 0, якщо вперлись у стелю */
    if (excess != 0) {
        int64_t track = ((int64_t)c->kt_q * excess) >> Q;  /* Kt · надлишок     */
        c->integ -= track * dt_q;                          /* інтегруємо, як e  */
    }

    return u;
}
