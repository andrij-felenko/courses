/* pid.h — виробничий PID у стандартній формі (Kp, Ti, Td) */
#include <stdbool.h>

typedef struct {
    /* Настройки (можна міняти на льоту — безстрибково) */
    float Kp;        /* підсилення (спільне зверху над P, I, D) */
    float Ti;        /* стала часу інтегрування, с  (Ti = 0 → I вимкнено) */
    float Td;        /* стала часу диференціювання, с (Td = 0 → D вимкнено) */
    float N;         /* дільник фільтра похідної: τ_f = Td/N (типово 8..10) */
    float Tt;        /* стала часу відстеження (anti-windup): √(Ti·Td) */
    float out_min;   /* нижня межа виходу (насичення виконавчого органу) */
    float out_max;   /* верхня межа виходу */

    /* Внутрішній стан (між викликами) */
    double I_term;   /* інтегральний внесок У ОДИНИЦЯХ ВИХОДУ (не «гола» сума!) */
    float  D_term;   /* відфільтрована похідна (внесок у вихід) */
    float  y_prev;   /* попередній вимір (для похідної по виміру) */
    bool   manual;   /* true → ручний режим (вихід = man_out) */
    float  man_out;  /* вихід, заданий оператором у ручному */
    bool   initialized;
} pid_t;
