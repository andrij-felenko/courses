// Не керування конденсатором (він пасивний), а непряма перевірка:
// надмірна Y-ємність на землю інколи проявляється як завищений
// струм спокою / витоку, видний у самодіагностиці живлення.
// Поріг — з межі струму дотику класу приладу (тут клас II → 0.25 мА).
#define LEAKAGE_LIMIT_uA   250u     // межа струму на землю, мкА (клас II)

void check_earth_leakage(uint32_t measured_uA)
{
    if (measured_uA > LEAKAGE_LIMIT_uA) {
        // забагато струму на землю: ймовірно завелика сумарна Y-ємність
        // або витік ізоляції — далі не сертифікуєшся, шукай причину
        log_fault(FAULT_LEAKAGE_OVER_LIMIT);
    }
}
