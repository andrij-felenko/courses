static void on_step(uint32_t t)
{
    // Один раз по входу в ON: дати головному реально замкнутись, тоді
    // прибрати передзарядний (перекриття 4→5 із діаграми).
    if (contactor_pre_is_on() && (t - bms.t_enter > PRECHARGE_SETTLE_MS)) {
        contactor_pre(false);          // 5) передзарядний більше не потрібен
    }

    // Усталений режим: стережемо залиплий контактор (див. нижче) і безпеку
    // (безпеку вже перевірив bms_step() перед викликом).
    watch_stuck_contactor(t);
}
