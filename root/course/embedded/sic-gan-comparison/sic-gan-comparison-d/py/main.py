# втрати провідності: P = I*I * Rds_on
I = 20.0                     # струм через ключ, А

# кремнієвий 1200-В ключ: опір каналу великий
Rds_si = 0.200               # 200 мОм (типовий порядок для Si на 1200 В)
P_si = I * I * Rds_si        # = 400 * 0.2  = 80 Вт

# SiC-ключ тієї ж напруги: опір у рази менший
Rds_sic = 0.040             # 40 мОм
P_sic = I * I * Rds_sic      # = 400 * 0.04 = 16 Вт
