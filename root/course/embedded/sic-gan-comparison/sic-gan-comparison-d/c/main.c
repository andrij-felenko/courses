// втрати провідності: P = I*I * Rds_on
float I = 20.0f;             // струм через ключ, А

// кремнієвий 1200-В ключ: опір каналу великий
float Rds_si  = 0.200f;      // 200 мОм (типовий порядок для Si на 1200 В)
float P_si    = I * I * Rds_si;   // = 400 * 0.2  = 80 Вт

// SiC-ключ тієї ж напруги: опір у рази менший
float Rds_sic = 0.040f;      // 40 мОм
float P_sic   = I * I * Rds_sic;  // = 400 * 0.04 = 16 Вт
