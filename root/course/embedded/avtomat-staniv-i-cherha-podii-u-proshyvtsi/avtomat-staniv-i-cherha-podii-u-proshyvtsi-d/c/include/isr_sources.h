#ifndef EVSE_ISR_SOURCES_H
#define EVSE_ISR_SOURCES_H

#include <stdint.h>

/*
 * Джерела подій. Кожна функція — тіло обробника переривання: прив'яжіть її до
 * відповідного вектора свого мікроконтролера (EXTI, TIM, USART, COMP). Усі
 * вони дотримуються однієї дисципліни: прочитати апаратний регістр, скласти
 * запис події, покласти його в чергу й вийти. Жодних переходів автомата,
 * жодних звернень до дисплея, жодних циклів очікування.
 */

void isr_sources_init(void);

/* Системний таймер, 1 кГц. Веде лічильник мілісекунд, крутить програмні
 * таймери й кожні 10 мс кладе такт для повільних опитувань. */
void isr_systick_1ms(void);

/* Зовнішнє переривання по спаду з кнопки «Грибок». */
void isr_emergency_button(void);

/* Компаратор струму силової лінії; amperes — миттєве значення з АЦП. */
void isr_overcurrent(uint16_t amperes);

/* Трансформатор нульової послідовності; milliamps — диференційний струм. */
void isr_leakage(uint16_t milliamps);

/* Кнопка скидання аварії на лицьовій панелі. */
void isr_reset_button(void);

/* Приймач UART зчитувача RFID: один байт на виклик. */
void isr_rfid_rx_byte(uint8_t byte);

/*
 * Поштова скринька зчитувача: повний 32-бітний номер останньої прочитаної
 * картки. У подію влазять лише молодші 16 біт, тож автомат бере номер звідси.
 */
uint32_t isr_rfid_last_card(void);

#endif /* EVSE_ISR_SOURCES_H */
