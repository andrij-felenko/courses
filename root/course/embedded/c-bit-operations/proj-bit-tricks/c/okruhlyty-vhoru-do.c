#include <stdint.h>

uint32_t next_pow2(uint32_t x) {
    x--;                 // щоб точний степінь двійки лишився собою, а не подвоївся
    x |= x >> 1;
    x |= x >> 2;
    x |= x >> 4;
    x |= x >> 8;
    x |= x >> 16;        // тепер x = 0...0111...1 (усе під старшою 1 — одиниці)
    x++;                 // хвіст одиниць перекидається в наступний степінь двійки
    return x;
}
