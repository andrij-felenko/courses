#include <stdint.h>

#define N_CH  79                    // скільки каналів у смузі

// Перестановна таблиця: розкидає близькі входи по смузі (частина прикладу).
// Будується один раз; заповнюється так, щоб сусідні індекси йшли в далекі канали.
static const uint8_t chan_perm[N_CH] = {
    0, 27, 54, 12, 39, 66, 24, 51, 5, 32, 59, 17, 44, 71, 29, 56,
    /* ... решта 79 значень — перестановка чисел 0..78 ... */
};

// Відобразити слово LFSR у номер каналу, уникаючи повтору й сусіда попереднього.
// prev_ch — попередній канал (для першого стрибка передай, скажімо, 0xFF).
uint8_t word_to_channel(uint16_t *state, uint8_t prev_ch) {
    for (int guard = 0; guard < 8; guard++) {   // не більш як кілька спроб
        *state = lfsr16_step(*state);           // беремо наступне слово
        uint8_t ch = chan_perm[*state % N_CH];  // крізь перестановну таблицю
        // відкинути, якщо це той самий канал або впритул до попереднього
        if (prev_ch == 0xFF ||
            (ch != prev_ch && ch != prev_ch + 1 && ch + 1 != prev_ch)) {
            return ch;
        }
    }
    // якщо кілька спроб поспіль не дали чистого каналу — беремо як є
    return chan_perm[*state % N_CH];
}
