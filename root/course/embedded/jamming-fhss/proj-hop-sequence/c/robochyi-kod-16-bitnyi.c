#include <stdint.h>

// Маска відводів для 16-бітного МАКСИМАЛЬНОГО LFSR (відводи 16,14,13,11).
// Біти 15,13,12,10 → 1011 0100 0000 0000 = 0xB400 (зсув праворуч, форма Галуа).
// Обережно: поширена маска 0x8408 (поліном CRC-16-CCITT) НЕ максимальна —
// вона дає лише 32767 станів, половину циклу. Бери відводи з таблиці, не навмання.
#define LFSR16_POLY  0xB400u

// Один такт: зсув праворуч + умовний XOR маскою (форма Галуа).
// Повертає новий 16-бітний стан. state НІКОЛИ не має бути 0.
static inline uint16_t lfsr16_step(uint16_t state) {
    uint16_t lsb = state & 1u;      // біт, що випадає
    state >>= 1;                    // зсув праворуч
    if (lsb) state ^= LFSR16_POLY;  // якщо випав 1 — перевертаємо відводи
    return state;
}
