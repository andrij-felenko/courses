// Суматор на ОП: Vout = −Rf·Σ(Vn/Rn).
// Кожен вхід має свою «гучність» — менший Rn дає більший внесок.
float summing_out(const float v[], const float r[], int n, float r_f) {
    float acc = 0.0f;
    for (int i = 0; i < n; i++)
        acc += v[i] / r[i];           // струм кожного входу у вузол
    return -r_f * acc;                // Rf обертає суму струмів на напругу
}

// v = {1.0, 2.0, 0.5}, r = {10e3, 10e3, 10e3}, Rf = 10 кОм
// Σ(Vn/Rn) = (1 + 2 + 0.5)/10e3 = 0.00035 А
// Vout = −10e3 · 0.00035 = −3.5 В   (чиста сума зі знаком «мінус»)
