const size_t license_table_count = sizeof(license_table) / sizeof(license_table[0]);

static char lower_ascii(char c)
{
    return (c >= 'A' && c <= 'Z') ? (char)(c - 'A' + 'a') : c;
}

const license_entry_t *license_table_find(const char *prefix)
{
    if (prefix == NULL || *prefix == '\0') {
        return NULL;
    }

    for (size_t i = 0; i < license_table_count; ++i) {
        const char *name = license_table[i].name;
        const char *want = prefix;

        while (*want != '\0' && lower_ascii(*name) == lower_ascii(*want)) {
            ++name;
            ++want;
        }
        if (*want == '\0') {
            return &license_table[i];
        }
    }
    return NULL;
}
