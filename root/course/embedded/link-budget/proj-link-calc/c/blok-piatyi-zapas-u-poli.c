// Запас лінії з ВИМІРЯНОГО RSSI (дБм) — реальні втрати вже враховані виміром.
static float margin_from_rssi(float rssi_dbm, float s_rx_dbm) {
    return rssi_dbm - s_rx_dbm;
}

// Доступність лінії за запасом на завмирання M (дБ), плоский релеївський канал.
// Миттєва потужність розподілена експоненційно, тож частка часу [0..1], коли
// сигнал НЕ провалюється під поріг, ТОЧНО дорівнює exp(−10^(−M/10)) — для будь-
// якого M: додатного, нульового й від'ємного (мертва лінія → 0). Без спецвипадків.
static float availability_from_margin(float margin_db) {
    float ratio = powf(10.0f, -margin_db / 10.0f);  // γ_пор / γ_сер = 10^(−M/10)
    return expf(-ratio);
}
