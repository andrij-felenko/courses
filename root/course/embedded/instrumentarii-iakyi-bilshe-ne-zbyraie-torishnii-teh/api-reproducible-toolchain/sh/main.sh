# 1. Пошук випадкових хостових шляхів у ELF-файлі
# Очікуваний результат: порожній вивід. Будь-який знайдений шлях означає відсутність -ffile-prefix-map
strings build/firmware.elf | grep -E "/home/|/Users/|/workspace/src"

# 2. Аудит структури статичних архівів бібліотек
# Очікуваний результат: права rw-r--r--, UID 0, GID 0, мітка дати Jan 1 1970
ar tv build/libdrivers.a

# 3. Перевірка відсутності динамічних часових міток препроцесора
# Очікуваний результат: відсутність англомовних трибуквених назв місяців у двійковому образі
strings build/firmware.bin | grep -E "(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) [0-9]{1,2} [0-9]{4}"
