#ifndef DELAY_H
#define DELAY_H

#include <stdint.h>

/* Мікросекундні паузи для ручного тактування шини. Джерело часу — лічильник
   тактів ядра DWT: він не займає жодного таймера й не залежить від того,
   скільки циклів компілятор вирішив зробити з порожнього while. */
void delay_init(void);

/* Пауза не коротша за задану. Довша — можлива (переривання), і це безпечно:
   протокол I2C обмежує мінімальну тривалість рівнів, а не максимальну. */
void delay_us(uint32_t us);

#endif /* DELAY_H */
