#define KW_INDEX    3      // індекс нашого ключового слова у виході моделі
#define UNK_INDEX   6      // індекс класу «чуже» (нецільова мова + шум)
#define THRESHOLD   0.85f  // поріг спрацювання за ЗГЛАДЖЕНОЮ ймовірністю
#define ALPHA       0.35f  // інертність згладжування (стійкість ↔ швидкість)
#define REFRACTORY  20     // період спокою після спрацювання, у ПРОГОНАХ мережі

static float smooth   = 0.0f;   // згладжена ймовірність ключового слова
static int   cooldown = 0;      // лишок періоду спокою, у прогонах (0 = слухаю)

// Приймає свіжі ймовірності з kws_invoke, повертає true рівно раз на слово.
static bool kws_decide(const float probs[N_CLASS]) {
    // 1. Згладити ймовірність НАШОГО слова (експоненційне ковзне середнє).
    smooth += ALPHA * (probs[KW_INDEX] - smooth);

    // 2. Якщо в періоді спокою — доживаємо його й нічого не оголошуємо.
    if (cooldown > 0) { cooldown--; return false; }

    // 3. Ворота «чуже»: якщо модель певніша, що це НЕ команда, — навіть не думаємо.
    if (probs[UNK_INDEX] > probs[KW_INDEX]) return false;

    // 4. Рішення: згладжена ймовірність упевнено пробила поріг.
    if (smooth > THRESHOLD) {
        cooldown = REFRACTORY;   // блокуємо повтори на це слово
        smooth   = 0.0f;         // СКИДАННЯ: інакше хвіст згладжування спрацює ще раз
        return true;             // ← ключове слово розпізнано, рівно раз
    }
    return false;
}
