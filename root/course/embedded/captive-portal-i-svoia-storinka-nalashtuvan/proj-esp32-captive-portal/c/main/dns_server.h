#pragma once

#include <stdint.h>
#include "esp_err.h"

/*
 * Піднімає catch-all DNS: окреме завдання FreeRTOS слухає UDP-порт 53
 * і на будь-який запит типу A відповідає адресою answer_ip (у мережевому
 * порядку байтів — так, як її повертає esp_ip4addr_aton).
 *
 * Саме ця підміна й змушує телефон побачити «підозрілу» мережу: його зонд
 * стукає до відомого імені, отримує адресу мікроконтролера, бачить не той
 * вміст і показує сторінку входу.
 */
esp_err_t dns_server_start(uint32_t answer_ip);

/* Зупиняє завдання й закриває сокет. Повертається після виходу завдання. */
void dns_server_stop(void);
