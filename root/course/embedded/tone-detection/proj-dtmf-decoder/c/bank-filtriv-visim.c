#include <stdint.h>
#include <math.h>

#define N_BLOCK   205          // довжина блоку: 8 частот DTMF лягають у біни
#define FS        8000.0f      // частота дискретизації, Гц
#define N_TONES   8            // чотири рядкові + чотири стовпцеві

// вісім частот: спершу низькі (рядки), потім високі (стовпці)
static const float dtmf_freq[N_TONES] = {
    697.0f, 770.0f, 852.0f, 941.0f,        // [0..3] — рядки (низька група)
    1209.0f, 1336.0f, 1477.0f, 1633.0f     // [4..7] — стовпці (висока група)
};

// один резонатор Ґерцеля
typedef struct { float coeff, s1, s2; } goertzel_t;

// весь банк + спільний стан блоку
typedef struct {
    goertzel_t g[N_TONES];     // вісім фільтрів
    float      energy;         // сума квадратів відліків блоку (для відносного порога)
    uint16_t   n;              // скільки відліків блоку вже набрано
} dtmf_bank_t;
