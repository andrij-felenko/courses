// викликати на КОЖЕН новий відлік (напр. з ISR АЦП).
// Повертає 1, коли набрано повний блок (час рахувати рішення), інакше 0.
int dtmf_feed_sample(dtmf_bank_t *b, float x)
{
    // одна рекурсія Ґерцеля на кожен із восьми фільтрів
    for (int i = 0; i < N_TONES; ++i) {
        float s = x + b->g[i].coeff * b->g[i].s1 - b->g[i].s2;
        b->g[i].s2 = b->g[i].s1;
        b->g[i].s1 = s;
    }
    b->energy += x * x;        // енергія блоку — для відносного порога

    if (++b->n < N_BLOCK)
        return 0;              // блок ще не повний
    return 1;                  // повний блок — головний цикл рахує power
}
