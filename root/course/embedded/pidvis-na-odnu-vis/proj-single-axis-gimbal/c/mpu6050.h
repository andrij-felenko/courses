/* mpu6050.h — драйвер 6-осьового IMU MPU-6050 для однієї осі підвісу.
 *
 * Числа регістрів і масштабів — з паспорта InvenSense MPU-6000/6050
 * (Register Map, rev. 4.2). Нічого вигаданого тут бути не може: ці адреси
 * читає справжня мікросхема. */

#ifndef MPU6050_H
#define MPU6050_H

#include <stdint.h>
#include <stdbool.h>

#include "i2c.h"

/* AD0 на землі → 0x68; AD0 на живленні → 0x69. */
#define MPU6050_ADDR 0x68

/* Вісь обертання підвісу — X гіроскопа; нахил дає пара Y/Z акселерометра. */
typedef struct {
    float gyro_x_dps;   /* Кутова швидкість, °/с (сира, без калібрування) */
    float accel_y_g;    /* Проєкція прискорення, g */
    float accel_z_g;
} imu_sample_t;

/* Будить давач, вимикає сон, ставить смугу ФНЧ 44 Гц, діапазони
 * ±500 °/с і ±2 g, частоту вибірок 200 Гц. Перевіряє WHO_AM_I. */
i2c_status_t mpu6050_init(void);

/* Один пакетний обмін на 14 байтів: розривати його на три транзакції
 * означало б зшити кут із покази, знятих у різні миті. */
i2c_status_t mpu6050_read(imu_sample_t *out);

#endif /* MPU6050_H */
