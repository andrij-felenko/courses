/* uart.h — телеметрія стенда, 115200 8N1, передавання за перериванням.
 *
 * Рядок телеметрії — 30…40 символів. Віддати його блокуючим циклом
 * означає з'їсти ~3 мс із такту в 5 мс: контур почав би спізнюватися саме
 * тоді, коли ми його вимірюємо. Тому в такті ми лише кладемо байти в
 * кільце, а вивозить їх переривання спорожнілого регістра. */

#ifndef UART_H
#define UART_H

#include <stdint.h>

void uart_init(uint32_t baud);

/* Кладе рядок у кільце. Якщо місця немає — ТИХО відкидає: телеметрія
 * ніколи не має права затримати контур керування. */
void uart_write(const char *s);

/* Ціле зі знаком у десятковому вигляді. */
void uart_write_i32(int32_t v);

/* Скільки байтів телеметрії загублено через переповнення кільця.
 * Число росте — знижуй частоту виводу, інакше графік бреше. */
uint16_t uart_dropped(void);

#endif /* UART_H */
