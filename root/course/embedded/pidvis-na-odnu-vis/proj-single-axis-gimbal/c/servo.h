/* servo.h — імпульс RC-серво апаратним Timer1 (вивід OC1A, ніжка PB1).
 *
 * Формувати 1…2 мс програмою в такті контуру не можна: будь-яке
 * переривання зсуне фронт на десятки мікросекунд, і вал смикатиметься
 * від самого джитера. Порівнювач таймера ставить фронт із точністю
 * 0.5 мкс незалежно від того, чим зайнятий процесор. */

#ifndef SERVO_H
#define SERVO_H

#include <stdint.h>

/* Timer1 у режимі Fast PWM з вершиною в ICR1, дільник 8:
 * такт 0.5 мкс, період кадру 20 мс (50 Гц). */
void servo_init(void);

/* Тривалість імпульсу в мікросекундах; значення затискається
 * до безпечного ходу 1000…2000 мкс. */
void servo_write_us(uint16_t pulse_us);

#endif /* SERVO_H */
