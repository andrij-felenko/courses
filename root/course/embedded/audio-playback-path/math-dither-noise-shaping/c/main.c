/* TPDF-розмивання ±1 LSB: сума двох незалежних рівномірних по ±0.5 LSB.
   rand01() повертає рівномірне число в [0, 1). Додаємо ДО округлення. */
static inline float tpdf_lsb(void) {
    float u1 = rand01() - 0.5f;   /* рівномірне [−0.5, +0.5) LSB */
    float u2 = rand01() - 0.5f;   /* друге, незалежне           */
    return u1 + u2;               /* трикутне [−1, +1) LSB       */
}

/* застосування перед зменшенням розрядності (напр. 24 → 16 біт):
   x_hi — відлік у високій точності, у одиницях цільового LSB */
int16_t dither_to_16(float x_hi) {
    float y = x_hi + tpdf_lsb();          /* домішали трикутну крихту */
    long   q = lrintf(y);                 /* округлили до цілого LSB   */
    if (q >  32767) q =  32767;           /* захист від переповнення   */
    if (q < -32768) q = -32768;
    return (int16_t)q;
}
