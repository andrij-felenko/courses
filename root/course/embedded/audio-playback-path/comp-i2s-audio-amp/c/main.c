/* заповнити буфер синусоїдою 440 Гц (нота «ля»), стерео, 16 біт */
#include <math.h>
#define SR      44100
#define FREQ    440
#define AMPL    8000        /* нижче стелі 32767 — щоб не кліпувало */

int16_t buf[SR];            /* одна секунда моно-відліків */
for (int i = 0; i < SR; i++) {
    buf[i] = (int16_t)(AMPL * sinf(2.0f * M_PI * FREQ * i / SR));
}
