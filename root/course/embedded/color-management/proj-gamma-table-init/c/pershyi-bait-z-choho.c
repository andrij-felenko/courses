/* Діагностична сіра шкала: рівні кроки КОДУ по горизонталі.
   Якщо панель калібрована — яскравість росте візуально рівно;
   якщо тіні «злипаються» в чорне або світла вибілені — крива крива. */
void draw_gray_ramp(int x, int y, int w, int h) {
    for (int i = 0; i < w; i++) {
        uint8_t g = (uint8_t)(i * 255 / (w - 1));   /* 0..255 рівномірно */
        uint16_t c = ((g & 0xF8) << 8) |            /* R (5 біт) RGB565  */
                     ((g & 0xFC) << 3) |            /* G (6 біт)         */
                     (g >> 3);                       /* B (5 біт)         */
        fill_rect(x + i, y, 1, h, c);
    }
}
