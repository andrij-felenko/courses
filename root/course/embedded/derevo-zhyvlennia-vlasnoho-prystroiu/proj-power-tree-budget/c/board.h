/* board.h — апаратний контракт плати для секвенсера живлення.
 *
 * Секвенсер не знає ні про регістри GPIO, ні про конкретний мікроконтролер:
 * він бачить лише ці виклики. Реальна плата реалізує їх поверх свого HAL,
 * стенд заняття — поверх моделі (board_sim.c). */
#ifndef BOARD_H
#define BOARD_H

#include <stdbool.h>
#include <stdint.h>

/* --- керування рейками дерева живлення --- */

/* I ступінь: EN синхронного Buck 12 В -> 3.3 В (з нього живиться і LDO ядра). */
void board_core_rail_en(bool on);

/* II ступінь: EN LDO/Buck головної цифрової шини DVDD. */
void board_io_rail_en(bool on);

/* Силовий ключ (Load Switch) периферії та зовнішніх датчиків.
 * Ключ із керованим dV/dt: напруга наростає за одиниці мілісекунд. */
void board_periph_switch_en(bool on);

/* Апаратний NRST радіомодуля й зовнішнього контролера: true — тримаємо в скиданні. */
void board_reset_assert(bool asserted);

/* --- ізоляція сигнальних ліній --- */

/* Піни I2C/SPI у високоомний стан (GPIO_MODE_ANALOG) і підтяжки геть.
 * Обов'язково ДО зняття VCC периферії: інакше датчик живитиметься струмом
 * витоку через підтягувальні резистори та вхідні ESD-діоди. */
void board_bus_pins_isolate(void);

/* Повертає піни в робочий режим (альтернативна функція I2C/SPI).
 * Дозволено лише коли шина периферії вже під напругою. */
void board_bus_pins_activate(void);

/* --- зворотний зв'язок від живлення --- */

bool board_core_pgood(void);   /* PGOOD первинного перетворювача */
bool board_io_pgood(void);     /* PGOOD шини DVDD */
bool board_fault_irq(void);    /* лінія аварії ключа: перевантаження, КЗ, перегрів */
uint16_t board_vin_mv(void);   /* вхідна напруга шини, мВ (номінал 12000) */

#endif /* BOARD_H */
