// Типовий монолітний C51 на мікроконтролері Intel 8051
void main(void) {
    TMOD = 0x20;    // Таймер 1 у 8-бітному автоперезавантаженні
    TH1 = 0xFD;     // Швидкість 9600 бод при кварці 11.0592 МГц
    SCON = 0x50;    // Режим 1, 8-бітний UART, увімкнено прийом
    TR1 = 1;        // Запуск таймера 1
    
    while (1) {
        if (RI) {
            RI = 0;
            P1 = SBUF; // Прямий запис прийнятого байта в порт вводу-виводу
        }
    }
}
