/* hal/hal_time.h — час і сон. Три функції, які реалізує порт: на платі це
 * лічильник SysTick і команда WFI, на комп'ютері розробника — монотонний
 * годинник і коротка пауза потоку. Шар вище про різницю не здогадується. */
#ifndef HAL_TIME_H
#define HAL_TIME_H

#include <stdint.h>

/* Монотонні мілісекунди від старту. Переповнення через 49 діб штатне:
 * скрізь порівнюємо різницю (now - then), а не самі значення. */
uint32_t hal_time_now_ms(void);

/* Приспати ядро до найближчого переривання. Ніяких порожніх циклів. */
void hal_cpu_sleep(void);

/* Активне очікування. Дозволене лише всередині драйверів на короткі
 * апаратні затримки (скидання мікросхеми), ніколи — у шарі застосунку. */
void hal_time_delay_ms(uint32_t ms);

static inline uint32_t hal_time_elapsed_ms(uint32_t since_ms)
{
    return hal_time_now_ms() - since_ms;
}

#endif /* HAL_TIME_H */
