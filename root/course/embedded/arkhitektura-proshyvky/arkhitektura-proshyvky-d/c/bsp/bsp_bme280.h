/* bsp/bsp_bme280.h — драйвер давача мікроклімату BME280.
 * Драйвер приймає дескриптор шини, а не «знає» контролер I2C1: тій самій
 * мікросхемі байдуже, чи це апаратний контролер STM32, програмна шина на
 * ніжках, чи імітація в модульному тесті.
 *
 * Уся пам'ять статична: жодного malloc, як велить надійність вбудованої
 * системи, де купа фрагментується й падає через півроку роботи. */
#ifndef BSP_BME280_H
#define BSP_BME280_H

#include "hal/hal_i2c.h"

typedef struct bsp_bme280 bsp_bme280_t;

/* Дескриптор із калібрувальними коефіцієнтами мікросхеми. Розмір задано
 * з запасом; статичне твердження в bsp_bme280.c стежить за відповідністю. */
typedef struct {
    _Alignas(8) unsigned char bytes[96];
} bsp_bme280_storage_t;

/* Фізичні величини, а не коди АЦП: градуси, відсотки, гектопаскалі. */
typedef struct {
    float temperature_c;
    float humidity_rh;
    float pressure_hpa;
} bsp_bme280_readings_t;

/* Піднімає давач: перевіряє ідентифікатор, скидає його, вичитує
 * калібрувальну таблицю з ПЗП мікросхеми й ставить передискретизацію.
 * NULL — давача на шині немає або він відповів чужим ідентифікатором. */
bsp_bme280_t *bsp_bme280_init(bsp_bme280_storage_t *storage,
                              const hal_i2c_bus_t *bus,
                              uint8_t i2c_addr);

/* Одне вимірювання в режимі forced: давач прокидається, міряє, засинає.
 * Саме цей режим тримає споживання логера на рівні одиниць мікроампер.
 * false — шина мовчить або перетворення не завершилося вчасно. */
bool bsp_bme280_measure(bsp_bme280_t *dev, bsp_bme280_readings_t *out_readings);

hal_i2c_status_t bsp_bme280_last_error(const bsp_bme280_t *dev);

#endif /* BSP_BME280_H */
