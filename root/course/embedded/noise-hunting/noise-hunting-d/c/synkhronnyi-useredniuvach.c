#include <stdint.h>

#define BINS      200        // точок на один період 50 Гц (20 мс / 200 = 100 мкс/бін)
#define AVG_CYCLES 256       // скільки періодів мережі нагромадити

static int32_t  accum[BINS]; // сума відліків у кожній фазовій точці
static uint16_t bin   = 0;   // поточна фазова точка в межах періоду
static uint16_t cycle = 0;   // скільки періодів уже зібрано
static uint8_t  done  = 0;

// Викликається з детектора переходу мережі через нуль (раз на період):
// скидає фазу на початок періоду — це і є прив'язка тригера до 50 Гц.
void on_mains_zero_cross(void) {
    bin = 0;
    if (++cycle >= AVG_CYCLES) done = 1;
}

// Викликається таймером рівно BINS разів за період (тут кожні 100 мкс):
// кладе відлік у поточну фазову точку. Оскільки старт періоду щоразу
// вирівняно по переходу нуля, той самий bin завжди відповідає тій самій
// фазі мережі — синхронне (когерентне) нагромадження.
void on_sample_tick(uint16_t adc) {
    if (done || bin >= BINS) return;
    accum[bin] += adc;
    bin++;
}

// Коли done — дістаємо усереднену форму одного періоду:
// поділ суми на число періодів. Некогерентний шум упав як √AVG_CYCLES
// (256 → у 16 разів), а форма, синхронна з мережею, лишилась чистою.
void finish(uint16_t out[BINS]) {
    for (uint16_t i = 0; i < BINS; i++)
        out[i] = (uint16_t)(accum[i] / AVG_CYCLES);
}
