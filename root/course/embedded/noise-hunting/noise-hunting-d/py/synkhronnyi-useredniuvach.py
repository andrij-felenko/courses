BINS       = 200   # точок на один період 50 Гц (20 мс / 200 = 100 мкс/бін)
AVG_CYCLES = 256   # скільки періодів мережі нагромадити


class SyncAverager:
    def __init__(self):
        self.accum = [0] * BINS  # сума відліків у кожній фазовій точці
        self.bin   = 0           # поточна фазова точка в межах періоду
        self.cycle = 0           # скільки періодів уже зібрано
        self.done  = False

    # Викликається з детектора переходу мережі через нуль (раз на період):
    # скидає фазу на початок періоду — це і є прив'язка тригера до 50 Гц.
    def on_mains_zero_cross(self):
        self.bin = 0
        self.cycle += 1
        if self.cycle >= AVG_CYCLES:
            self.done = True

    # Викликається таймером рівно BINS разів за період (тут кожні 100 мкс):
    # кладе відлік у поточну фазову точку. Оскільки старт періоду щоразу
    # вирівняно по переходу нуля, той самий bin завжди відповідає тій самій
    # фазі мережі — синхронне (когерентне) нагромадження.
    def on_sample_tick(self, adc):
        if self.done or self.bin >= BINS:
            return
        self.accum[self.bin] += adc
        self.bin += 1

    # Коли done — дістаємо усереднену форму одного періоду:
    # поділ суми на число періодів. Некогерентний шум упав як √AVG_CYCLES
    # (256 → у 16 разів), а форма, синхронна з мережею, лишилась чистою.
    def finish(self):
        return [s // AVG_CYCLES for s in self.accum]
