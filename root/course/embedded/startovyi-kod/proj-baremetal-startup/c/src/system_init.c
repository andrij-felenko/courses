/* system_init.c — базове налаштування ядра між зануленням RAM і main().

   Тактування тут навмисно не чіпається: PLL, дільники й затримки Flash у
   кожного чипа свої, а стартовий код від чипа не залежить. Те, що робить цей
   модуль, справедливе для будь-якого ARMv7-M. */

#include <stdint.h>

#include "cortex_m.h"
#include "startup.h"

void SystemInit(void)
{
    /* 1. Векторна таблиця. Після скидання ядро читає вектори з адреси 0, тож
          прошивка, злита з початку Flash, працює й без цього запису. Але щойно
          образ переїде за завантажувач (0x08004000 і далі) або таблиця
          скопіюється в RAM задля швидкого перепризначення обробників — VTOR
          стає обов'язковим. Пишемо його завжди: рядок дешевий, а мовчазне
          «переривання пішло не туди» коштує вечора. */
    CM_REG32(SCB_VTOR) = (uint32_t)&g_pfnVectors[0];

    /* 2. Власні вектори для MemManage, BusFault і UsageFault. Доки біти не
          виставлені, ядро ескалює будь-який із цих збоїв у HardFault, і причину
          доводиться відновлювати за ознакою FORCED. З дозволом кожен збій
          приходить своїм вектором — і обробник одразу знає, що сталося. */
    CM_REG32(SCB_SHCSR) |= SCB_SHCSR_MEMFAULTENA |
                           SCB_SHCSR_BUSFAULTENA |
                           SCB_SHCSR_USGFAULTENA;

    /* 3. Пастка на ділення цілого на нуль. Без DIV_0_TRP інструкція udiv тихо
          віддає нуль, і помилка спливає за десять кроків від місця, де вона
          сталася. З пасткою — UsageFault з ознакою DIVBYZERO рівно на винній
          інструкції. */
    CM_REG32(SCB_CCR) |= SCB_CCR_DIV_0_TRP;

    /* Невирівняний доступ (UNALIGN_TRP) свідомо лишаємо дозволеним: ядро
       Cortex-M4 виконує його апаратно, а пастка поламала б пакування структур
       у чужих бібліотеках. */

    cm_dsb();
    cm_isb();
}
