/* startup.h — символи, які видає лінкер, і точки входу стартового коду.

   ⚠ Кожен символ звідси — це АДРЕСА, а не змінна. У таблиці символів ELF
   `_sdata` позначає межу секції; байтів під ним не існує. Тому в коді пишуть
   `&_sdata`, а не `_sdata`: без амперсанда компілятор згенерує читання пам'яті
   за цією адресою й візьме перше слово самої секції за її межу.

   Тип uint32_t обрано навмисно: усі межі вирівняні лінкером на 4 байти, тож
   копіювання й занулення йдуть машинними словами, а не байтами. */

#ifndef STARTUP_H
#define STARTUP_H

#include <stdint.h>

/* Межі секцій у RAM (VMA). */
extern uint32_t _sdata;   /* початок ініціалізованих даних   */
extern uint32_t _edata;   /* кінець ініціалізованих даних    */
extern uint32_t _sbss;    /* початок неініціалізованих даних */
extern uint32_t _ebss;    /* кінець неініціалізованих даних  */

/* Копія початкових значень .data у Flash (LMA). */
extern uint32_t _sidata;

/* Перший вільний байт за глобальними змінними — звідси росте купа. */
extern uint32_t _end;

/* Вершина стека й гарантований лінкером резерв під нього. Обидва — адреси:
   `&_Min_Stack_Size` дорівнює самому числу 0x400, бо символ не має секції. */
extern uint32_t _estack;
extern uint32_t _Min_Stack_Size;

/* Таблиці покажчиків на ініціалізатори. Оголошені масивами: так до них
   звертаються без зайвого взяття адреси, а розмір лінкер усе одно не знає. */
extern void (*__preinit_array_start[])(void);
extern void (*__preinit_array_end[])(void);
extern void (*__init_array_start[])(void);
extern void (*__init_array_end[])(void);

/* Точка входу після апаратного скидання. */
void Reset_Handler(void) __attribute__((noreturn));

/* Заглушка для векторів, які прошивка не перевизначила. */
void Default_Handler(void) __attribute__((noreturn));

/* Базове налаштування ядра. Викликається з Reset_Handler уже після того,
   як .data і .bss набули коректного стану, але ще до конструкторів. */
void SystemInit(void);

/* Векторна таблиця. Потрібна назовні одному місцю — SystemInit, який кладе
   її адресу у VTOR. */
extern void (*const g_pfnVectors[])(void);

#endif /* STARTUP_H */
