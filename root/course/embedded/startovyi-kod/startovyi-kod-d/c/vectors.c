#include "startup.h"

/* Таблиця мусить лежати за нульовим зсувом образу прошивки. Секцію туди
   кладе скрипт лінкера рядком KEEP(*(.isr_vector)), а `used` не дає
   компілятору викинути символ, на який ніхто не посилається з коду. */
#define MCU_VECTOR_ENTRY(name) name,

__attribute__((section(".isr_vector"), used, aligned(VECTOR_TABLE_ALIGN)))
const vector_handler_t g_pfnVectors[] = {
    /* 0x00: не функція, а початкове значення MSP — ядро читає його
       апаратно, ще до першої декодованої інструкції. */
    (vector_handler_t)(&_estack),
    Reset_Handler,      /* 0x04: точка входу стартового коду */
    NMI_Handler,        /* 0x08: збій кварцу, аварія живлення */
    HardFault_Handler,  /* 0x0C: критичний системний збій */
    MemManage_Handler,  /* 0x10: порушення правил MPU */
    BusFault_Handler,   /* 0x14: помилка шини */
    UsageFault_Handler, /* 0x18: недійсна інструкція, INVSTATE, ділення на 0 */
    0, 0, 0, 0,         /* 0x1C…0x28: зарезервовано архітектурою */
    SVC_Handler,        /* 0x2C: системний виклик */
    DebugMon_Handler,   /* 0x30: монітор налагодження */
    0,                  /* 0x34: зарезервовано архітектурою */
    PendSV_Handler,     /* 0x38: відкладене перемикання задач */
    SysTick_Handler,    /* 0x3C: системний таймер */

    /* 0x40 і далі: переривання периферії, позиції NVIC 0…42.
       Решта векторів STM32F407 (позиції 43…81) у прикладі не
       перелічена — жодне з тих переривань тут не вмикається, а NVIC
       читає запис лише для того переривання, яке справді дозволене. */
    MCU_IRQ_VECTORS(MCU_VECTOR_ENTRY)
};
