#include "startup.h"

/* Розгортання робочого простору змінних. Функція викликається до першого
   звертання до глобальних даних, тому сама їх не торкається: усе, чим
   вона користується, лежить на стеку або в регістрах. */
void startup_init_memory(void)
{
    const uint32_t *src = &_sidata;
    uint32_t *dst = &_sdata;

    /* Копіювання 32-бітними словами правильне лише за вирівняними межами
       секцій — їх дає `. = ALIGN(4);` у скрипті лінкера. Незарівняний
       кінець .data мовчки затер би перший байт сусідньої .bss, тому
       перевіряємо всі п'ять меж одразу. */
    const uintptr_t bounds = (uintptr_t)src | (uintptr_t)dst
                           | (uintptr_t)&_edata
                           | (uintptr_t)&_sbss | (uintptr_t)&_ebss;
    if ((bounds & 3U) != 0U) {
        startup_trap();
    }

    /* Прошивку, зібрану на виконання просто з Flash, копіювати не треба:
       у неї LMA збігається з VMA, джерело й ціль — та сама пам'ять. */
    if (src != dst) {
        while (dst < &_edata) {
            *dst++ = *src++;
        }
    }

    /* .bss у прошивці не займає жодного байта — нулі створюємо тут */
    for (uint32_t *bss = &_sbss; bss < &_ebss; ++bss) {
        *bss = 0U;
    }
}
