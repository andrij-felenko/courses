int tls_client_connect(const char *hostname) {
    // ★ зв'язати заповнений конфіг із цією сесією. Після setup конфіг НЕ
    //    можна змінювати — сесія тримає на нього вказівник, тож conf має
    //    жити доти, доки жива ssl.
    if (mbedtls_ssl_setup(&ssl, &conf) != 0)
        return -1;

    // ★ очікуване ім'я хоста. Це ДРУГА половина автентичності: перевірити не
    //    лише що ланцюг чинний, а що сертифікат виписаний САМЕ на цей сервер.
    //    Пропустиш — і чинний сертифікат ІНШОГО сервера пройде перевірку.
    if (mbedtls_ssl_set_hostname(&ssl, hostname) != 0)
        return -1;

    // прив'язати вже відкритий TCP-сокет (net_ctx) як транспорт для read/write.
    mbedtls_ssl_set_bio(&ssl, &net_ctx,
                        mbedtls_net_send, mbedtls_net_recv, NULL);

    // РУКОСТИСКАННЯ. Тут і живе вся дорожнеча: ECDHE, розбір сертифіката,
    // перевірка підпису. mbedtls_ssl_handshake крутить обмін, доки не завершить.
    int ret;
    while ((ret = mbedtls_ssl_handshake(&ssl)) != 0) {
        if (ret != MBEDTLS_ERR_SSL_WANT_READ &&
            ret != MBEDTLS_ERR_SSL_WANT_WRITE) {
            // будь-яка інша помилка = рукостискання провалилось.
            // напр. MBEDTLS_ERR_X509_CERT_VERIFY_FAILED: ланцюг не зійшовся —
            // САМЕ ТАК і має поводитись пристрій, коли підсунули чужий сертифікат:
            // з'єднання розірвано, назовні НЕ пішло НІ БАЙТА даних.
            return -1;
        }
    }

    // додаткова строгість: явно переконатися, що звірка сертифіката чиста.
    // (VERIFY_REQUIRED уже обірвав би при провалі, але явна перевірка —
    //  добра звичка, і дає точний прапор причини у flags.)
    uint32_t flags = mbedtls_ssl_get_verify_result(&ssl);
    if (flags != 0)
        return -1;   // щось у ланцюгу не так — не довіряємо

    return 0;   // канал захищений і співрозмовник звірений
}
