#ifndef KALMAN_H
#define KALMAN_H

#include <stdbool.h>

/* Фільтр Калмана на одну кутову вісь.
 *
 * Стан — [пеленг цілі, кутова швидкість цілі] у НЕРУХОМІЙ рамці: пеленг
 * відлічується не від осі апарата, а від напрямку, зафіксованого на старті.
 * Саме тому власне обертання апарата не сприймається як маневр цілі: гіроскоп
 * інтегрується окремо (поле body_angle), і кут візування в поточній рамці
 * тіла дістаємо відніманням.
 *
 * body_angle зростає без обмеження, поки триває супровід. За кутової швидкості
 * 1 рад/с і сеансу в кілька хвилин це сотні радіан — float тримає там крок
 * близько 3e-5 рад, що на порядок дрібніше за шум детектора. */
typedef struct {
    float bearing;      /* оцінка пеленга цілі в нерухомій рамці (рад) */
    float rate;         /* оцінка кутової швидкості цілі (рад/с) */
    float P[2][2];      /* коваріація похибки оцінки */
    float q_bearing;    /* шум процесу за кутом (рад²/с) */
    float q_rate;       /* шум процесу за швидкістю (рад²/с³) — маневр цілі */
    float r_meas;       /* дисперсія шуму детектора (рад²) */
    float gate2;        /* квадрат порога відбраковування, у сигмах */
    float body_angle;   /* інтегрований гіроскоп: поворот апарата (рад) */
    int   rejects;      /* скільки вимірювань поспіль відкинув гейт */
    bool  primed;       /* чи засіяно стан першим вимірюванням */
} KalmanAxis;

void  kalman_axis_init(KalmanAxis *k, float q_bearing, float q_rate, float r_meas);

/* Скидання оцінки цілі. Гіроскопний інтеграл НЕ чіпаємо: на нього посилається
 * історія курсу, за якою шукають ракурс на момент експозиції кадру. */
void  kalman_axis_acquire(KalmanAxis *k);

/* Фаза прогнозу: викликається з частотою контуру керування (100–250 Гц). */
void  kalman_axis_predict(KalmanAxis *k, float dt, float gyro_rate);

/* Фаза корекції: викликається асинхронно, коли детектор віддав кадр.
 * los_angle — кут візування в рамці тіла на момент ЕКСПОЗИЦІЇ,
 * body_at_capture — інтеграл гіроскопа на той самий момент,
 * latency_s — наскільки стан фільтра випередив момент експозиції.
 * Повертає false, коли вимірювання відкинув гейт інновації. */
bool  kalman_axis_update(KalmanAxis *k, float los_angle, float body_at_capture, float latency_s);

/* Фаза екстраполяції: кут візування в ПОТОЧНІЙ рамці тіла, з випередженням
 * lead_s на запізнення виконавчого контуру. */
float kalman_axis_extrapolate(const KalmanAxis *k, float lead_s);

float kalman_axis_body_angle(const KalmanAxis *k);
float kalman_axis_rate(const KalmanAxis *k);

#endif /* KALMAN_H */
