/* Коефіцієнти ПІ-корекції Mahony. Підбір — нижче в «пастках».
   twoKp/twoKi — подвоєні Kp/Ki: двійка зручно скорочується з ½ у q̇,
   тому в коді носять одразу подвоєні (так у класичній реалізації). */
#define twoKp  (2.0f * 0.5f)     /* пропорційна: 2·0.5 = 1.0  */
#define twoKi  (2.0f * 0.0f)     /* інтегральна: за умовч. 0, увімкнути обережно */

/* Оцінка зсуву нуля гіроскопа — стан, живе між тактами (рад/с). */
static float gbx = 0.0f, gby = 0.0f, gbz = 0.0f;

/* Один такт фільтра Mahony (лише гіро + акселерометр).
   gx,gy,gz — рад/с;  ax,ay,az — будь-які одиниці (нормуємо самі);  dt — с. */
void mahony_update_imu(float gx, float gy, float gz,
                       float ax, float ay, float az, float dt)
{
    /* ── КРОК «ВИПРАВ» застосовуємо, лише якщо акселерометр щось показує.
       Якщо ax=ay=az=0 (вільне падіння / збій) — напряму «низу» нема,
       корекцію пропускаємо, лишається чистий гіроскоп. ── */
    float an = sqrtf(ax * ax + ay * ay + az * az);
    if (an > 1e-6f) {
        float inv = 1.0f / an;            /* нормуємо вимір до одиничного */
        ax *= inv; ay *= inv; az *= inv;

        /* Очікуваний «низ» за поточним q — третій стовпчик R(q). */
        float vx = 2.0f * (q1 * q3 - q0 * q2);
        float vy = 2.0f * (q0 * q1 + q2 * q3);
        float vz = q0 * q0 - q1 * q1 - q2 * q2 + q3 * q3;

        /* Похибка = векторний добуток виміряного й очікуваного «низу». */
        float ex = ay * vz - az * vy;
        float ey = az * vx - ax * vz;
        float ez = ax * vy - ay * vx;

        /* ІНТЕГРАЛЬНА складова: накопичуємо похибку у зсув гіроскопа. */
        if (twoKi > 0.0f) {
            gbx += twoKi * ex * dt;       /* інтеграл похибки = оцінка дрейфу */
            gby += twoKi * ey * dt;
            gbz += twoKi * ez * dt;
        } else {
            gbx = gby = gbz = 0.0f;       /* інтеграл вимкнено — не накопичуємо */
        }
        gx -= gbx;  gy -= gby;  gz -= gbz;   /* прибрати оцінений зсув */

        /* ПРОПОРЦІЙНА складова: підправити швидкість прямо зараз. */
        gx += twoKp * ex;
        gy += twoKp * ey;
        gz += twoKp * ez;
    }

    /* ── КРОК «ПЕРЕДБАЧ»: проінтегрувати кватерніон виправленою швидкістю.
       gx,gy,gz уже містять корекцію (і мінус зсув). ── */
    float qDot0 = 0.5f * (-q1 * gx - q2 * gy - q3 * gz);
    float qDot1 = 0.5f * ( q0 * gx + q2 * gz - q3 * gy);
    float qDot2 = 0.5f * ( q0 * gy - q1 * gz + q3 * gx);
    float qDot3 = 0.5f * ( q0 * gz + q1 * gy - q2 * gx);

    q0 += qDot0 * dt;
    q1 += qDot1 * dt;
    q2 += qDot2 * dt;
    q3 += qDot3 * dt;

    quat_normalize();                    /* КОЖЕН такт — на одиничну сферу */
}
