/* Повернути кватерніон на одиничну сферу. Без цього він поволі «пливе»
   за довжиною, і орієнтація спотворюється. Робити КОЖЕН такт. */
static void quat_normalize(void)
{
    float n = sqrtf(q0*q0 + q1*q1 + q2*q2 + q3*q3);
    if (n > 1e-9f) {                 /* захист від ділення на нуль */
        float inv = 1.0f / n;
        q0 *= inv; q1 *= inv; q2 *= inv; q3 *= inv;
    }
}
