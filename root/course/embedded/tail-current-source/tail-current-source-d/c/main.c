// Хвіст I0 = 5 мкА, напруга Ерлі U_A = 100 В.
// Крутість біполярного транзистора: gm = I0 / U_T, де U_T ~ 0.026 В (тепловий потенціал).
float V_A   = 100.0f;
float U_T   = 0.026f;        // тепловий потенціал при кімнатній температурі, ~26 мВ
float i0    = 5.0e-6f;       // струм хвоста, А

float r0    = V_A / i0;                 // 100/5e-6 = 20 МОм — одиночний транзистор
float gm    = i0 / U_T;                 // 5e-6/0.026 ≈ 192 мкА/В
float gain  = gm * r0;                  // 192e-6 * 20e6 ≈ 3846 — "власне підсилення"
float r0_cascode = gain * r0;           // ≈ 3846 * 20e6 ≈ 7.7e10 Ом ≈ 77 ГОм (!)
