// Наймолодший біт — уперед: SPI переведено в LSB-first,
// або кожен байт слід прогнати через reverse8() перед send().

#define MLCD_WR   0x80    // «писати рядок»
#define MLCD_VCOM 0x40    // біт інверсії COM (програмний режим)
#define MLCD_CLR  0x20    // «очистити всю пам'ять»

void draw_row64(void) {
    cs_high();                       // SCS — активний ВИСОКИМ, тримаємо весь кадр

    spi_send(MLCD_WR | MLCD_VCOM);   // команда «писати» + черговий стан інверсії
    spi_send(64);                    // адреса рядка (рахунок із 1)

    spi_send(0xFF);                  // перші 8 пікселів увімкнено
    for (int i = 0; i < 15; i++)     // решта 120 пікселів (15 байтів) — вимкнено
        spi_send(0x00);

    spi_send(0x00);                  // фіктивний байт: кінець рядка
    spi_send(0x00);                  // два нулі: кінець кадру
    spi_send(0x00);

    cs_low();                        // опустити SCS — панель зафіксує запис
}
