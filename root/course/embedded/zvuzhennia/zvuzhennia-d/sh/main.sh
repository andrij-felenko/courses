# 1. Запуск процедури бісекції
git bisect start
git bisect bad                 # Поточна версія (v2.3) містить дефект
git bisect good v2.0            # Остання відома стабільна версія (v2.0)

# Git автоматично перемикає робоче дерево на середній коміт (крок 1 із 8)
# Компілюємо, прошиваємо плату, перевіряємо працездатність:
git bisect good                # Якщо дефекту немає (помилку внесено пізніше)
# або
git bisect bad                 # Якщо система падає (помилка вже є тут)

# Автоматизація через скрипт автоматичного тестування:
git bisect run ./scripts/automated_hil_test.sh
