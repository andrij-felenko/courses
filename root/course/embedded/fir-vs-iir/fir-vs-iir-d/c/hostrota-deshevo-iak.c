#include <math.h>
// Нормована частота вирізу: скільки радіан на відлік припадає на 50 Гц
float f0 = 50.0f, fs = 1000.0f;
float w0 = 2.0f * (float)M_PI * f0 / fs;   // = 0.3142 рад/відлік
float r  = 0.98f;                          // радіус полюса: чим ближче до 1, тим вужчий виріз

// Нулі — точно на колі (радіус 1) під кутом w0:  z = e^(±j·w0)
//   (1 − e^(jw0)·z⁻¹)(1 − e^(−jw0)·z⁻¹) = 1 − 2cos(w0)·z⁻¹ + z⁻²
float b0 = 1.0f;
float b1 = -2.0f * cosf(w0);               // = -1.902
float b2 = 1.0f;
// Полюси — той самий кут, але радіус r < 1 (трохи всередині кола)
//   знаменник: 1 − 2r·cos(w0)·z⁻¹ + r²·z⁻²
float a1 = -2.0f * r * cosf(w0);           // = -1.864
float a2 = r * r;                          // = 0.9604
// Нормування підсилення в смузі пропускання (щоб далеко від 50 Гц |H| ≈ 1)
float g  = (1.0f - 2.0f*r*cosf(w0) + r*r) / (2.0f - 2.0f*cosf(w0));
b0 *= g; b1 *= g; b2 *= g;
