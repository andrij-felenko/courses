// Один прохід циклу керування критичною функцією.
// Будь-який шлях, де ми втратили довіру до входу, веде в safe_state().
void safety_cycle(void) {
    float alt_m;

    // 1. Спроба отримати достовірне значення (тайм-аут + перевірка діапазону всередині).
    if (!altimeter_read(&alt_m)) {          // давач мовчить або бреше
        enter_safe_state(HAZARD_NO_ALT);    // не керуємо наосліп — у безпечний стан
        return;
    }

    // 2. Значення є й достовірне — керуємо нормально.
    update_control(alt_m);

    // 3. «Я живий» сторожовому таймеру: якщо цикл десь зависне,
    //    навіть цей рядок не виконається — і watchdog сам перезапустить систему.
    watchdog_feed();
}

// Безпечний стан — заздалегідь визначений і той самий для всіх причин відмови.
void enter_safe_state(hazard_t why) {
    motors_hold();          // зависання / керований спуск — двигуни в безпечний режим
    beacon_alarm(why);      // подати сигнал: людина має знати, що апарат у failsafe
    log_hazard(why);        // слід для розбору: що саме спрацювало
}
