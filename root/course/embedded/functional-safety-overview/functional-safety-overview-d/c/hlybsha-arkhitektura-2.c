// Викликається ОДИН раз при старті, до передачі керування.
// Мета — зловити ЛАТЕНТНІ відмови: ті, що мовчать у нормі й вилізуть
// аж тоді, коли знадобиться безпечний стан — тобто в найгірший момент.
bool power_on_self_test(void) {
    // 1. Перевірити ПАМ'ЯТЬ: марш-тест RAM, контрольна сума Flash.
    //    Збитий біт у критичній константі — латентна відмова, що чекає.
    if (!ram_march_test() || !flash_crc_ok())      return false;

    // 2. Перевірити сам МЕХАНІЗМ безпечного стану. Це найтонше:
    //    реле, що має знеструмити двигун, могло приваритися МІСЯЦЬ ТОМУ,
    //    і ми б не знали, бо в безпечний стан ще жодного разу не йшли.
    //    Тому навмисне смикаємо його й переконуємось, що воно розмикає.
    if (!safe_state_actuator_selftest())           return false;

    // 3. Перевірити, що ОБИДВА канали живі й дають узгоджене значення
    //    на відомому вході (інакше стартуємо вже з мертвим резервом —
    //    HFT насправді нульовий, хоч на папері одиниця).
    if (!both_channels_agree_on_reference())       return false;

    return true;   // усе живе — можна вмикати керування
}
