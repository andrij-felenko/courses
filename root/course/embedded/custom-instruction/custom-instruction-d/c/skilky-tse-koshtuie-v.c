/* Класична наївна версія: дивимось молодший біт, зсуваємо, повторюємо.
   Кожен біт слова — окрема ітерація: ≈32 проходи на одне слово. */
uint32_t popcount_sw(uint32_t x) {
    uint32_t n = 0;
    while (x) {          /* поки лишилися одиниці */
        n += x & 1u;     /* додати молодший біт */
        x >>= 1;         /* зсунути наступний на його місце */
    }
    return n;            /* десятки тактів ядра на одне слово */
}
