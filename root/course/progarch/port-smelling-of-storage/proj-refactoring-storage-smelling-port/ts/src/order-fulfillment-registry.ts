import { Order, OrderId } from './domain';

/**
 * Чистий рольовий контракт вихідного порту (Role-based Outgoing Port).
 * Спроєктований «зсередини назовні» виключно під потреби бізнес-сценарію комплектації:
 *
 * 1. Відсутність моделей ORM: оперує лише доменними сутностями Order та OrderId.
 * 2. Відсутність параметрів SQL-пагінації: метод виражає бізнес-намір (зарезервувати N замовлень),
 *    а не технічне зміщення курсора чи сторінки (offset/page).
 * 3. Відсутність прапорців блокування бази даних: конкурентність і блокування (SELECT FOR UPDATE)
 *    є суто внутрішньою справою вторинного адаптера сховища.
 * 4. Відсутність числових первинних ключів та колонок бази даних.
 */
export interface OrderFulfillmentRegistry {
  /**
   * Атомарно знаходить та резервує наступну партію замовлень, готових до комплектації.
   * Адаптер сховища зобов'язаний сам гарантувати ізоляцію від стану гонитви (race condition)
   * між паралельними екземплярами сервісу.
   *
   * @param batchSize Максимальна кількість замовлень у партії.
   */
  claimOrdersReadyForFulfillment(batchSize: number): Promise<Order[]>;

  /**
   * Фіксує результати збереження партії укомплектованих замовлень.
   *
   * @param orders Список укомплектованих доменних замовлень.
   */
  saveFulfilledOrders(orders: readonly Order[]): Promise<void>;

  /**
   * Пошук замовлення за його доменним ідентифікатором (OrderId).
   */
  findById(id: OrderId): Promise<Order | null>;
}
