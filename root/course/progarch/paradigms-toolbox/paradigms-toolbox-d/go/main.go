// Шов між прийомом (один продюсер) і правилами (пул воркерів).
// Канал місткістю 256 — це і є шов: він передає І тисне назад.
frames := make(chan Frame, 256)

// Продюсер: якщо буфер повний — блокується (зворотний тиск угору, до джерела)
func ingest(dev *Device) {
    for f := range dev.Stream() {
        frames <- f            // повно → чекаємо тут, а не топимо пам'ять
    }
}

// Пул: N воркерів тягнуть із того самого каналу
for i := 0; i < runtime.NumCPU(); i++ {
    go func() {
        for f := range frames { applyRules(f) }
    }()
}
