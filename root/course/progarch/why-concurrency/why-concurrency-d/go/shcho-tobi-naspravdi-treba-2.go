// CPU-bound: суцільна лічба, снів нема. Одне ядро на дві задачі = ≈ 2s.
// Порятунок — дозволити планувальнику розкласти їх на РІЗНІ ядра (справжній паралелізм).
runtime.GOMAXPROCS(2) // тепер двоє ядер справді рахують водночас → ≈ 1s

var wg sync.WaitGroup
for i := 0; i < 2; i++ {
    wg.Add(1)
    go func() {
        defer wg.Done()
        sum := 0
        for n := 0; n < 2_000_000_000; n++ { sum += n } // секунда чистої лічби
        _ = sum
    }()
}
wg.Wait() // GOMAXPROCS(1) → ≈ 2s; GOMAXPROCS(2) → ≈ 1s. Різницю дає лише кількість ядер.
