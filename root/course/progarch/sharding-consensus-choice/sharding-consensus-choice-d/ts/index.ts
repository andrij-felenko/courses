// Монотонна операція: додати помічений пристрій у множину дому.
// Порядок НЕ важить — будь-яка перестановка дає ту саму множину.
const seen = new Set<string>();
["lamp-3", "thermostat-1"].forEach(d => seen.add(d));   // вузол A
["thermostat-1", "lamp-3"].forEach(d => seen.add(d));   // вузол B, зворотний порядок
// два вузли сходяться в ТУ САМУ відповідь, не змовляючись між собою:
console.assert(seen.size === 2);                        // координація не потрібна → щабель 0

// Немонотонна операція: видати ОДИН глобально унікальний номер замовлення.
// Якщо два вузли вирішать незалежно — вони видадуть однакове число.
const nextId = 41;
const a = nextId + 1;    // вузол A: 42
const b = nextId + 1;    // вузол B, не бачачи A: теж 42  → колізія
console.assert(a === b); // «рівно один» неможливо БЕЗ згоди про порядок → щабель 2
