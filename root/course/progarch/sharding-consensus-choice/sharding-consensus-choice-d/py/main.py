# Монотонна операція: додати помічений пристрій у множину дому.
# Порядок НЕ важить — будь-яка перестановка дає ту саму множину.
seen = set()
seen |= {"lamp-3"};       seen |= {"thermostat-1"}   # вузол A у своєму порядку
seen |= {"thermostat-1"}; seen |= {"lamp-3"}         # вузол B у зворотному
# два вузли сходяться в ТУ САМУ відповідь, не змовляючись між собою:
assert seen == {"lamp-3", "thermostat-1"}            # координація не потрібна → щабель 0

# Немонотонна операція: видати ОДИН глобально унікальний номер замовлення.
# Якщо два вузли вирішать незалежно — вони видадуть однакове число.
next_id = 41
a = next_id + 1          # вузол A: 42
b = next_id + 1          # вузол B, не бачачи A: теж 42  → колізія
assert a == b            # «рівно один» неможливо БЕЗ спільної згоди про порядок → щабель 2
