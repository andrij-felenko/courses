@runtime_checkable
class Readable(Protocol):
    def read(self) -> float: ...

@runtime_checkable
class Switchable(Protocol):
    def turn_on(self) -> None: ...
    def turn_off(self) -> None: ...

class TempSensor:                # лише Readable
    def read(self) -> float: return self.celsius

class SmartSocket:               # Readable + Switchable
    def read(self) -> float: ...
    def turn_on(self): ...
    def turn_off(self): ...
