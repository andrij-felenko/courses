// Наївний клієнт: таймаут → повтор. Але таймаут НЕ означає «не сталося».
async function unlock(lockId: string): Promise<void> {
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      await hub.send({ cmd: "unlock", lockId }); // чекаємо підтвердження
      return;                                    // дійшло — виходимо
    } catch (err) {
      // err — це таймаут. Ми НЕ знаємо: замок не чіпали чи вже відчинили?
      // Якщо відчинили, а загубилось лише підтвердження — цей повтор
      // віддає команду ВДРУГЕ. Гонка проти того, хто чекав біля дверей.
    }
  }
  throw new Error("не вдалося за 3 спроби");
}
