/// Епоха Discord — 1 січня 2015, 00:00 UTC, у мілісекундах від епохи Unix.
const DISCORD_EPOCH: u64 = 1_420_070_400_000;
/// Ширина відра — 10 діб у мілісекундах (10·24·60·60·1000).
const BUCKET_MS: u64 = 10 * 24 * 60 * 60 * 1000; // = 864_000_000

/// Мілісекунди від епохи Discord: старші 42 біти Snowflake — це показ годинника.
fn ms_since_epoch(id: u64) -> u64 {
    id >> 22
}

/// Номер відра: у яке 10-денне вікно потрапляє повідомлення.
fn bucket_of(id: u64) -> u64 {
    ms_since_epoch(id) / BUCKET_MS
}

/// Календарний час (мс від епохи Unix) — лише щоб показати людині дату.
fn unix_ms(id: u64) -> u64 {
    ms_since_epoch(id) + DISCORD_EPOCH
}

fn main() {
    // Наскрізний приклад із розбору:
    let id: u64 = 181_193_932_800_000_000;
    assert_eq!(ms_since_epoch(id), 43_200_000_000);  // id >> 22
    assert_eq!(bucket_of(id), 50);                    // 43_200_000_000 / 864_000_000
    assert_eq!(unix_ms(id), 1_463_270_400_000);       // + епоха → десь травень 2016
}
