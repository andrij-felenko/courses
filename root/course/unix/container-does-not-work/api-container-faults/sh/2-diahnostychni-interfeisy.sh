# 1. Перевірка реальних, ефективних та файлових ідентифікаторів процесу
cat /proc/$PID/status | grep -E 'Uid|Gid'
# Вивід:
# Uid:   1000    1000    1000    1000   (real, effective, saved set, fs)
# Gid:   1000    1000    1000    1000

# 2. Перевірка таблиці відображення простору користувача (User Namespace)
cat /proc/$PID/uid_map
# Вивід для rootless podman:
#          0       1000          1      (UID 0 в контейнері -> UID 1000 на хості)
#          1     100000      65536      (UID 1..65536 в контейнері -> UID 100000..165535)

cat /proc/$PID/gid_map
# Вивід:
#          0       1000          1
#          1     100000      65536

# 3. Перевірка системних файлів підпорядкованих діапазонів на хості
cat /etc/subuid
# developer:100000:65536

cat /etc/subgid
# developer:100000:65536
