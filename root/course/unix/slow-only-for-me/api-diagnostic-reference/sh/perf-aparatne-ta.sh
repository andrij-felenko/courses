# Миттєвий інтерактивний огляд гарячих функцій процесу
perf top -p <PID>

# Запис стека викликів із частотою 99 Гц на 10 секунд
perf record -F 99 -g -p <PID> -- sleep 10

# Перегляд звіту з ієрархічним деревом викликів
perf report -g 'graph,0.5,caller'

# Збір апаратних лічильників PMU (інструкції, цикли, промахи кешу, IPC)
perf stat -p <PID> -- sleep 5
