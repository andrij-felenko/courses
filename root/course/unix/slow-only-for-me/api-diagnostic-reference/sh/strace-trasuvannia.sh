# Підрахунок та агрегація часу всіх викликів живого процесу
strace -c -p <PID>

# Фільтрація за типами викликів (мережа, файли, процеси)
strace -e trace=network,file,desc -p <PID>

# Друк точного часу початку кожного виклику з мікросекундами
strace -tt -T -p <PID>

# Відстеження нащадків (нових потоків та процесів)
strace -f -c -p <PID>
