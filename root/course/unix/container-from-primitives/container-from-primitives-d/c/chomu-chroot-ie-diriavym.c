/* Замикаємо процес у підкаталозі */
chroot("/tmp/jail");

/* Використовуємо відкритий дескриптор для виходу за межі кореня */
fchdir(fd);

/* Піднімаємося вгору по дереву хоста */
for (int i = 0; i < 50; i++) {
    chdir("..");
}
