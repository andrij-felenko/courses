# 1. Загальний стан, черги планувальника та пам'ять (аналіз колонок r, b, si, so, us, sy, wa)
vmstat 1 5

# 2. Розподіл процесорного часу по всіх логічних ядрах (пошук перекосу на softirq або одне ядро)
mpstat -P ALL 1 3

# 3. Дефіцит ресурсів та об'єктивний тиск на систему (PSI для CPU, Memory, I/O)
grep -H . /proc/pressure/{cpu,memory,io}

# 4. Стан блокових накопичувачів (аналіз %util, aqu-sz, r_await, w_await)
iostat -xz 1 3

# 5. Вільна, доступна та буферизована пам'ять (перевірка MemAvailable та Swap)
free -m

# 6. Мережева активність та переповнення черг інтерфейсів (rx_dropped, overruns)
sar -n DEV,EDEV 1 3

# 7. Стан сокетів, заповнення черг Send-Q та Recv-Q
ss -s; ss -tulpn | grep -E 'Recv-Q|Send-Q' | head -n 20

# 8. Топ процесів за процесорним часом, пам'яттю та станом виконання
top -b -n 1 | head -n 25

# 9. Системні логи, апаратні помилки ядра, скидання контролерів або спрацьовування OOM
dmesg -T --level=err,warn | tail -n 30
