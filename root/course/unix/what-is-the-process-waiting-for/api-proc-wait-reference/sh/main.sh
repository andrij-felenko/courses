# Вивести стек викликів усіх процесів, заблокованих у стані неперервного сну (D):
echo w > /proc/sysrq-trigger

# Вивести стек викликів взагалі всіх активних завдань і потоків у dmesg:
echo t > /proc/sysrq-trigger

# Вивести стан апаратних переривань та блокувань процесора:
echo q > /proc/sysrq-trigger

# Примусово скинути буфери файлових систем на накопичувачі:
echo s > /proc/sysrq-trigger
