# Пробуємо виклик до 3 разів, із паузою між спробами.
# Тактика купує ДОСТУПНІСТЬ (миттєвий збій не доходить до користувача),
# але платить ЗАТРИМКОЮ і навантаженням на сусіда.
def call_with_retry(req):
    max_tries = 3
    backoff = 0.05                            # секунди

    for attempt in range(1, max_tries + 1):
        try:
            return do_call(req)               # влучили — повертаємо відповідь одразу
        except (TimeoutError, BusyError):     # м'який збій — варто повторити
            if attempt == max_tries:
                raise                         # спроби вичерпано — віддаємо помилку вгору
        # «жорстка» помилка (немає прав, битий запит) сюди не долетить:
        # її except не ловить — виняток летить далі, повтор не поможе.

        time.sleep(backoff)                   # пауза перед наступною спробою
        backoff *= 2                          # 0.05 → 0.1 → 0.2: не добиваємо сусіда
