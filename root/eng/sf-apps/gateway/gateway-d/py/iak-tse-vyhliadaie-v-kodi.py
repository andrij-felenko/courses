# РЕАЛІЗАЦІЯ шлюзу: єдине місце, де програма знає мову чужого сервісу.
class HttpТарифШлюз(ТарифШлюз):
    def __init__(self, базовий_url: str, токен: str):
        self._url = базовий_url
        self._токен = токен

    async def тариф_для(self, напрямок: Напрямок) -> Тариф:
        # 1. переклад НАШОЇ мови → у мову чужого API
        url = f"{self._url}/rate?seg={напрямок.код}&v=3"
        відповідь = await http_get(url, token=self._токен)

        # 2. чужі коди помилок → НАШІ доменні помилки
        if відповідь.status == 406:
            raise ТарифНедоступний(напрямок)
        if відповідь.status == 419:
            raise ДоступПрострочено()
        if відповідь.status >= 400:
            raise ШлюзНедоступний(відповідь.status)

        # 3. чужа форма даних → НАШ доменний об'єкт (rate_bps — їхня назва)
        дані = відповідь.json()
        return Тариф(дані["rate_bps"] / 100)   # переклад завершено — далі рідне
