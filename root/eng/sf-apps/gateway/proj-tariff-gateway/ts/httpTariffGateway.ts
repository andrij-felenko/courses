// http/httpTariffGateway.ts — ЄДИНЕ місце, де програма знає мову чужого сервісу.
import { ТарифШлюз } from "../domain/tariffGateway";
import { Напрямок, Тариф, ТарифНедоступний, ДоступПрострочено, ШлюзНедоступний }
  from "../domain/tariff";
import { httpGet } from "./transport";
import { зПовтором } from "./retry";

export class HttpТарифШлюз implements ТарифШлюз {
  constructor(private базовийUrl: string, private токен: string) {}

  async тарифДля(напрямок: Напрямок): Promise<Тариф> {
    // ── ПЕРЕКЛАД 1: наш Напрямок → їхній URL ──
    const url = `${this.базовийUrl}/rate?seg=${напрямок.код}&v=3`;

    // мережевий крок — під захистом: обрив/таймаут повторяться з відкатом,
    // а доданий нижче переклад кодів у винятки повтор НЕ зачепить.
    const відповідь = await зПовтором(() => httpGet(url, this.токен));

    // ── ПЕРЕКЛАД 2: чужі коди → НАШІ доменні винятки ──
    if (відповідь.статус === 406) throw new ТарифНедоступний(напрямок);
    if (відповідь.статус === 419) throw new ДоступПрострочено();
    if (відповідь.статус >= 400)  throw new ШлюзНедоступний(`код ${відповідь.статус}`);

    // ── ПЕРЕКЛАД 3: чужий JSON → НАШ Тариф (rate_bps — їхня назва, не наша) ──
    const дані = await відповідь.тіло();
    return new Тариф(дані.rate_bps / 100);   // переклад завершено — далі рідне
  }
}
