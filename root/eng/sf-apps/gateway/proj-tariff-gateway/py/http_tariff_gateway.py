# http/http_tariff_gateway.py — ЄДИНЕ місце, де програма знає мову чужого сервісу.
from domain.tariff_gateway import ТарифШлюз
from domain.tariff import (Напрямок, Тариф, ТарифНедоступний,
                           ДоступПрострочено, ШлюзНедоступний)
from http.transport import http_get
from http.retry import з_повтором

class HttpТарифШлюз(ТарифШлюз):
    def __init__(self, базовий_url: str, токен: str):
        self._url = базовий_url
        self._токен = токен

    async def тариф_для(self, напрямок: Напрямок) -> Тариф:
        # ── ПЕРЕКЛАД 1: наш Напрямок → їхній URL ──
        url = f"{self._url}/rate?seg={напрямок.код}&v=3"

        # мережевий крок — під захистом: обрив/таймаут повторяться з відкатом,
        # а переклад кодів у винятки нижче повтор НЕ зачепить.
        відповідь = await з_повтором(lambda: http_get(url, self._токен))

        # ── ПЕРЕКЛАД 2: чужі коди → НАШІ доменні винятки ──
        if відповідь.статус == 406:
            raise ТарифНедоступний(напрямок)
        if відповідь.статус == 419:
            raise ДоступПрострочено()
        if відповідь.статус >= 400:
            raise ШлюзНедоступний(f"код {відповідь.статус}")

        # ── ПЕРЕКЛАД 3: чужий JSON → НАШ Тариф (rate_bps — їхня назва) ──
        дані = await відповідь.тіло()
        return Тариф(дані["rate_bps"] / 100)   # переклад завершено — далі рідне
