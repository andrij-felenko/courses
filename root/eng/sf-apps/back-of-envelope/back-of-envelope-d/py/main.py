import math

# Little's Law: L = λ·W — скільки запитів у польоті водночас
def in_flight(rate_per_s, latency_s):
    return rate_per_s * latency_s

L = in_flight(2000, 0.050)           # = 100 запитів у польоті

# Блокуючий сервер (потік на запит): треба ~100 потоків.
threads   = math.ceil(L)             # = 100
stack_mb  = threads * 1              # ~1 МБ стек на потік → ~100 МБ лише на стеки

# А якщо пул усього на 20 потоків? Тоді стеля пропускної здатності:
cap = 20 / 0.050                     # = 400 запитів/с — на 2000 захлинемось
