package main

import "fmt"

// Число пар (комунікаційних шляхів) у групі з n людей: n·(n−1)/2.
func paths(n int) int {
	return n * (n - 1) / 2
}

func main() {
	// Варіант A: один моноліт — усі 12 в одній групі, кожен з кожним.
	mono := paths(12)

	// Варіант B: три автономні команди по 4 людини.
	// Усередині кожної — густе спілкування (усі пари),
	// а МІЖ командами лишаємо один тонкий контракт (одна пара-зв'язок на межу).
	teams := []int{4, 4, 4}
	inside := 0
	for _, t := range teams { // пари всередині команд
		inside += paths(t)
	}
	between := 3 // 3 межі → 3 тонкі контракти

	fmt.Printf("Моноліт (12 в купі):        %d шляхів\n", mono)
	fmt.Printf("3 команди — усередині:      %d шляхів\n", inside)
	fmt.Printf("3 команди — між командами:  %d контракти\n", between)
	fmt.Printf("Разом при розбитті:         %d проти %d\n",
		inside+between, mono)
}
