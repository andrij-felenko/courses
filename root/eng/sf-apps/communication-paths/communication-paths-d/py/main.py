# Число пар (комунікаційних шляхів) у групі з n людей: n·(n−1)/2.
def paths(n):
    return n * (n - 1) // 2

# Варіант A: один моноліт — усі 12 в одній групі, кожен з кожним.
mono = paths(12)

# Варіант B: три автономні команди по 4 людини.
# Усередині кожної — густе спілкування (усі пари),
# а МІЖ командами лишаємо один тонкий контракт (одна пара-зв'язок на межу).
teams = [4, 4, 4]
inside = sum(paths(t) for t in teams)   # пари всередині команд
between = 3                              # 3 межі → 3 тонкі контракти

print(f"Моноліт (12 в купі):        {mono} шляхів")
print(f"3 команди — усередині:      {inside} шляхів")
print(f"3 команди — між командами:  {between} контракти")
print(f"Разом при розбитті:         {inside + between} проти {mono}")
