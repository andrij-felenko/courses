// Шлях 2: стоп — окремою лінією переривання, поза чергою й обробником.
// Витісняє все, спрацьовує за одиниці мікросекунд. Ціна — окремий шлях і
// прямий доступ до моторів з ISR (треба стерегтися станів гонки).

// Апаратне переривання від виділеного піна «аварійний стоп».
// Пріоритет ВИЩИЙ за цикл стабілізації — щоб витіснити навіть його.
void emergency_stop_isr(void) {
    motors_set_all(0);              // прямо в регістри ШІМ: 0 усім каналам, негайно
    g_flight_state = STATE_HALTED;  // ядро побачить прапорець і не крутитиме мотори далі
    // жодних черг, жодного очікування: команда виконана тут-таки
}

// Цикл стабілізації тепер щоразу звіряється з прапорцем: якщо аварія —
// не чіпає моторів, хай би що казав керувальний закон.
void stabilization_tick(void) {
    if (g_flight_state == STATE_HALTED) {
        motors_set_all(0);          // страхувальний бар'єр: мотори лишаються нульовими
        return;
    }
    // ... звичайний розрахунок стабілізації й запис ШІМ ...
}
