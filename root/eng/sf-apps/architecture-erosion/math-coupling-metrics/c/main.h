// D = |A + I − 1|,  де  I = Ce/(Ca+Ce),  A = абстрактні/усі типи

// Пакет "core": ядро-контракти. Ca=40 (усі спираються), Ce=0 (ні від кого),
//               з 10 типів 9 абстрактні.
double I_core = 0.0 / (40.0 + 0.0);      // = 0.00   стабільний
double A_core = 9.0 / 10.0;              // = 0.90   майже весь абстрактний
double D_core = fabs(A_core + I_core - 1.0);
                                         // = |0.90 + 0.00 − 1| = 0.10  ← майже ідеал

// Пакет "db_utils": конкретна утиліта, у яку вросли всі. Ca=25, Ce=3,
//                   з 12 типів 0 абстрактних — сирий код.
double I_db = 3.0 / (25.0 + 3.0);        // = 0.107  майже стабільний
double A_db = 0.0 / 12.0;                // = 0.00   зовсім конкретний
double D_db = fabs(A_db + I_db - 1.0);
                                         // = |0 + 0.107 − 1| = 0.893  ← ГЛИБОКО в зоні болю

// Пакет "ui": екранна конкретика на краю. Ca=1, Ce=15, з 8 типів 0 абстрактних.
double I_ui = 15.0 / (1.0 + 15.0);       // = 0.938  дуже нестабільний
double A_ui = 0.0 / 8.0;                 // = 0.00   конкретний — і це доречно
double D_ui = fabs(A_ui + I_ui - 1.0);
                                         // = |0 + 0.938 − 1| = 0.062  ← здоровий: конкретне листя
