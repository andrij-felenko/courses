from machine import UART

# Кістяк навмисне вбогий: один давач, один кадр, один шлях.
# Усе «доросле» (кілька давачів, черга, ретраї, CRC, база) — потім,
# коли ця нитка вже доводить, що стики між частинами тримають.

# --- Вузол 3: канал. Тут — уже реальний UART, а не заглушка. ---
# Саме стик «прошивка → канал» ми й хочемо перевірити на живому.
uart = UART(1, baudrate=115200)


# --- Вузол 1: давач. Поки що заглушка замість реального АЦП. ---
def sensor_read_temp_dc():
    # decidegrees: 235 = 23.5 °C. Справжній драйвер прийде пізніше —
    # зараз важливо, що ЧИСЛО пішло далі й дійшло, а не звідки воно.
    return 235


# --- Вузол 2: пакування кадру. Найпростіший формат, який лише можна. ---
# [0xAA | старший байт | молодший байт]. Big-endian — і ЦЕ рішення
# кістяк одразу виносить на стик: сервер мусить читати так само.
def frame_pack(value):
    # маркер 0xAA + два байти значення, старший першим
    return bytes((0xAA, (value >> 8) & 0xFF, value & 0xFF))


# --- Нитка: єдиний наскрізний прохід через усі три вузли. ---
def skeleton_tick():
    t = sensor_read_temp_dc()   # вузол 1
    frame = frame_pack(t)       # вузол 2
    uart.write(frame)           # вузол 3 → далі на сервер
