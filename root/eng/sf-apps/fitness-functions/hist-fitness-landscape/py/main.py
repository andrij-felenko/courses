# Голландів компас: фітнес-функцію ПИШЕ людина, бо середовища немає.
# Приклад — наскільки кандидат близький до цілі (більше збігів = вище).
target = "HELLO"

def fitness(candidate):
    # плавна оцінка: скільки літер уже стоять на місці (0..len)
    return sum(1 for c, t in zip(candidate, target) if c == t)

