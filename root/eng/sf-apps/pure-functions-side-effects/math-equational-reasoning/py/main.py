# f чиста → «порахувати раз» і «порахувати двічі» дають те саме
def pure(x): return x * x
pure(4) + pure(4)                     # 16 + 16 = 32
t = pure(4); t + t                    # 16 + 16 = 32   ← та сама відповідь, CSE законне

# g нечиста (прихований лічильник) → дві форми РОЗБІГАЮТЬСЯ
n = 0
def g():
    global n; n += 1; return n
g() + g()                             # 1 + 2 = 3
n = 0
t = g(); t + t                        # 1 + 1 = 2      ← інша! CSE тут ламає програму
