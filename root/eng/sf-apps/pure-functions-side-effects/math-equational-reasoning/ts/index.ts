// f чиста → «порахувати раз» і «порахувати двічі» дають те саме
const pure = (x: number) => x * x;
pure(4) + pure(4);                    // 16 + 16 = 32
{ const t = pure(4); t + t; }         // 16 + 16 = 32   ← та сама відповідь, CSE законне

// g нечиста (прихований лічильник) → дві форми РОЗБІГАЮТЬСЯ
let n = 0;
const g = () => ++n;
g() + g();                            // 1 + 2 = 3
n = 0;
{ const t = g(); t + t; }             // 1 + 1 = 2      ← інша! CSE тут ламає програму
