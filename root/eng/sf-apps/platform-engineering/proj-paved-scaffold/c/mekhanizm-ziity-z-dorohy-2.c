// Рідкісний випадок: надточний вимірювач з нестандартним стартом.
// Ця команда СВІДОМО сходить з дороги й бере всю відповідальність.
#include "platform.h"
#include "platform_internal.h"   // доступ до цеглинок платформи

// Явна, ГУЧНА позначка з'їзду — щоб і людина, і сторож (нижче)
// знали: тут дорогу обійшли навмисно, це не забута помилка.
PLATFORM_OFF_ROAD("hires-meter: custom clock tree, ADC-synced");

int main(void) {
    // Свій старт: беремо окремі цеглинки платформи, але складаємо
    // їх по-своєму. За коректність тепер відповідає ЦЯ команда.
    my_custom_clock_setup();     // особлива схема тактування під АЦП
    if (uart_log_init(115u)) {   // журнал усе одно беремо з платформи
        log_line("hires-meter: custom boot");
    }
    wdt_configure(500u);         // свій, коротший період watchdog

    app_run();
    return 0;
}
