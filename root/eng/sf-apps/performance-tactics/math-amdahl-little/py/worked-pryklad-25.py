# Частки роботи (виміряні профайлером на одному ядрі):
p = 0.75                 # паралельна частка (незалежне обчислення)
# послідовна частка = 1 − p = 0.25

# --- 8 ядер ---
s  = 8
Ts = (1.0 - p) + p / s              # = 0.25 + 0.75/8
                                    # = 0.25 + 0.09375
                                    # = 0.34375
S8 = 1.0 / Ts                       # = 1 / 0.34375
                                    # ≈ 2.909  → лише ~2.9×, не 8×!

# --- межа: s → ∞ ---
Smax = 1.0 / (1.0 - p)              # = 1 / 0.25
                                    # = 4.0   → стеля рівно 4×
