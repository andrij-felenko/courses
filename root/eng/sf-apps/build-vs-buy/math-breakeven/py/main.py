Sb, m = 60_000, 2_500      # своє:  вкладок на старті + супровід/міс
Sk, f =  2_500, 4_000      # чуже:  налаштування + плата/міс
r = 0.10 / 12              # місячна ставка дисконту (10%/рік)

# 1. Номінальний перелам — період окупності зайвого вкладка
t_star = (Sb - Sk) / (f - m)
print(f"номінальний перелам   t*  = {t_star:.1f} міс")

# 2. Коефіцієнт ануїтету: у скільки «сьогоднішніх» місяців
#    стискається t місяців майбутньої плати
def a(t):
    return (1 - (1 + r) ** -t) / r

# 3. Дисконтований перелам: той самий поріг, але для a(t), не для t
need    = (Sb - Sk) / (f - m)      # той самий 38.33 — тепер як ануїтет
ceiling = 1 / r                    # стеля ануїтету: далі стискати нема куди
if need >= ceiling:
    print("дисконтований перелам НЕ настає — чуже виграє на будь-якому горизонті")
else:
    lo, hi = 0.0, 1000.0           # двійковий пошук t, де a(t) = need
    for _ in range(60):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if a(mid) < need else (lo, mid)
    print(f"дисконтований перелам t_d = {hi:.1f} міс  (стеля ануїтету {ceiling:.0f})")

# 4. NPV кожного варіанта на конкретному горизонті
H = 60
npv_build = Sb + m * a(H)
npv_buy   = Sk + f * a(H)
print(f"NPV свого на {H} міс      = {npv_build:>10,.0f} $")
print(f"NPV чужого на {H} міс     = {npv_buy:>10,.0f} $")
print(f"перевага свого (дисконт.) = {npv_buy - npv_build:>10,.0f} $")

# 5. Реальний опціон шва — окремим доданком
p_change  = 0.40           # ймовірність, що доведеться міняти постачальника
avoided   = 120_000        # уникнута вартість виходу, якщо шов є
seam_cost =   8_000        # ціна поставити й тримати шов
option = p_change * avoided - seam_cost
print(f"цінність опціону шва     = {option:>10,.0f} $  ->",
      "ставити шов" if option > 0 else "шов зайвий")
