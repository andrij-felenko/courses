typedef struct {
    int64_t earliest; /* Найраніший момент фізичного часу */
    int64_t latest;   /* Найпізніший момент фізичного часу */
} tt_interval_t;

/* 1. Повертає поточний довірчий інтервал часу */
tt_interval_t tt_now(void);

/* 2. Перевіряє, чи момент t гарантовано минув у фізичному часі */
bool tt_after(int64_t t);

/* 3. Перевіряє, чи момент t гарантовано ще не настав */
bool tt_before(int64_t t);
