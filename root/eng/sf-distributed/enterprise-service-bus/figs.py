        p.append(arrow(xs[i], top_y + bh / 2 + 2, xs[i], cy2 - bus_h / 2 - 4, color=FIELD, sw=1.8))
        p.append(arrow(xs[i], cy2 - bus_h / 2 - 4, xs[i], top_y + bh / 2 + 2, color=MUTED, sw=1.4))

