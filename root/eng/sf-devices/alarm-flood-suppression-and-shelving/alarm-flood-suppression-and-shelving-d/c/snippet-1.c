#define MAX_ALARMS 32U

typedef uint32_t bitmask32_t;

// Матриця суміжності графу першопричин у Flash-пам'яті (const)
// DAG_Matrix[i] містить бітову маску тривог-наслідків, які пригнічуються тривогою i
static const bitmask32_t g_dag_adjacency_matrix[MAX_ALARMS] = {
    [0] = (1U << 1) | (1U << 2), // Тривога 0 (Першопричина) пригнічує тривоги 1 та 2
    [1] = (1U << 3),            // Тривога 1 пригнічує тривогу 3
    [2] = 0U,
    [3] = 0U
    // ... решта елементів ініціалізуються нулями
};

// Режимні маски FSM для різних станів системи (BOOT, RUN, SHUTDOWN)
static const bitmask32_t g_fsm_mode_masks[3] = {
    [0] = 0x00000003U, // BOOT: дозволені лише тривоги 0 та 1
    [1] = 0xFFFFFFFFU, // RUN: дозволені всі тривоги
    [2] = 0x0000000FU  // SHUTDOWN: дозволені тривоги 0..3
};
