word72 ecc_encode(uint64_t data) {
    word72 cw = 0;

    /* 1. Розкласти дані: біти 0..63 → не-контрольні позиції 1..71 за зростанням. */
    unsigned b = 0;
    for (unsigned p = 1; p <= HAM; ++p)
        if (!is_check(p)) {
            cw |= (word72)((data >> b) & 1) << p;
            ++b;                            /* рівно 64 таких позиції */
        }

    /* 2. Контрольні біти. Синдром слова з самих даних — це число t;
       його розряди — це рівно контрольні біти, кожен на своїй позиції 2^j.
       Виставивши їх, робимо синдром цілого слова нулем: t ⊕ t = 0. */
    unsigned t = syndrome(cw);
    for (unsigned j = 0; j < 7; ++j)
        if ((t >> j) & 1) cw |= (word72)1 << (1u << j);   /* позиція 2^j */

    /* 3. Біт загальної парності на позицію 0 — робить вагу всього слова парною. */
    cw |= (word72)parity(cw) << 0;
    return cw;
}
