// Дружній до кешу: рядок за рядком — сусідні адреси,
// кожен промах підтягує цілу лінію, далі суцільні влучання
for (int r = 0; r < N; r++)
    for (int c = 0; c < N; c++)
        sum += a[r][c];

// Ворожий до кешу: стовпець за стовпцем — стрибки на N елементів,
// майже кожен доступ промахується, кеш-лінія не довикористовується
for (int c = 0; c < N; c++)
    for (int r = 0; r < N; r++)
        sum += a[r][c];
