/* Шлях 1: нескінченна рекурсія — кадри множаться без кінця */
uint32_t sum_to(uint32_t n) {
    uint32_t partial = n;        /* локальна → кадр росте з кожним викликом */
    return partial + sum_to(n - 1);   /* нема базового випадку: n ніколи не 0 при беззнаковому відніманні */
}
/* n=1 → 0 → 0xFFFFFFFF → ... стек повзе вниз, доки не наїде на купу */

/* Шлях 2: один кадр більший за весь стек */
void parse_packet(void) {
    uint8_t scratch[8192];       /* 8 КБ локального масиву у 4-КБ стек — кадр не влазить одразу */
    memset(scratch, 0, sizeof scratch);   /* перший же доступ пише за межі стека */
}
