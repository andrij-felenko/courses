// Ідея quine у скелеті: масив ЧИСЕЛ несе весь текст програми.
// Спершу друкуємо самі числа (це — «дані»),
// потім друкуємо те, що ці числа означають (це — «код»).
char s[] = { /* тут числові коди КОЖНОГО символу цього ж файлу */ };

int main(void) {
    // Фаза 1: вивести масив s як послідовність чисел — відтворити «дані».
    for (int i = 0; s[i]; i++) print_as_number(s[i]);
    // Фаза 2: вивести s як текст — відтворити «код».
    for (int i = 0; s[i]; i++) putchar(s[i]);
    return 0;
}
