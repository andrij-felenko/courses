Регістрова машина (називає регістри — команди складніші):
    load  r1, a          ; r1 ← a
    load  r2, b          ; r2 ← b
    mul   r2, r2, 2      ; r2 ← b * 2
    add   r1, r1, r2     ; r1 ← a + (b*2)

Стекова машина (усе через верхівку — команди прості):
    PUSH a               ; стек: [a]
    PUSH b               ; стек: [a, b]
    PUSH 2               ; стек: [a, b, 2]
    MUL                  ; стек: [a, b*2]     (зняв 2 і b, поклав добуток)
    ADD                  ; стек: [a + b*2]    (зняв два, поклав суму)
