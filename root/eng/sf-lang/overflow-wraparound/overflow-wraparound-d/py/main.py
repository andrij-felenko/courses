import numpy as np
# У самого Python int безмежний — переповнення просто НЕ буває;
# фіксовану ширину (як у мікроконтролері) дають типи NumPy.

count = np.uint8(255)        # беззнаковий байт: межа 255
count = count + np.uint8(1)  # 256 не влазить → лишається 8 молодших бітів
print(count)                 # 0   (перевалює за модулем 2^8)

temp = np.int8(127)          # знаковий байт: межа +127
temp = temp + np.int8(1)     # старший біт перекидається → 10000000
print(temp)                  # -128  (NumPy ще й попередить RuntimeWarning)
