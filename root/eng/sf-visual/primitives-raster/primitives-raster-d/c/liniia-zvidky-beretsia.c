// ПРОМІЖНО: ще float, але вже «накопичена похибка проти півклітинки»
float err = 0.0f;
int y = y0;
for (int x = x0; x <= x1; x++) {
    set_pixel(x, y, color);
    err += m;                 // лінія піднялась на нахил
    if (err > 0.5f) {         // переросла півклітинки — рядок треба підняти
        y++;
        err -= 1.0f;          // і відняти цілу клітинку назад
    }
}
