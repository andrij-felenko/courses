// ЦІЛОЧИСЛОВО (полога лінія вправо-вгору): самі int, без множень у циклі
int e = 0;                    // = 2·dx·(дробова похибка)
int y = y0;
for (int x = x0; x <= x1; x++) {
    set_pixel(x, y, color);
    e += 2 * dy;              // 2·dy — константа, обчислена один раз
    if (e > dx) {            // поріг «півклітинки», помножений на 2·dx
        y++;
        e -= 2 * dx;
    }
}
