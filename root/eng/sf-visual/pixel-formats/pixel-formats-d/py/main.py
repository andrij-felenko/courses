W, H = 1280, 720
npix = W * H                      # 921600 пікселів

# RGB888: 3 байти на піксель, колір у кожному
rgb888 = npix * 3                 # 921600 * 3 = 2 764 800 Б  ≈ 2.64 МіБ

# YUYV (4:2:2): 2 байти на піксель (Y скрізь + півдолі кольору)
yuyv   = npix * 2                 # 921600 * 2 = 1 843 200 Б  ≈ 1.76 МіБ

# NV12 (4:2:0): Y повний (W*H) + кольору вчетверо менше * 2 канали
nv12   = npix + (npix // 4) * 2   # 921600 + 230400*2 = 1 382 400 Б ≈ 1.32 МіБ
