# hist  — гістограма з кроку 1
# n     — кількість пікселів (та сама, що рахували)
# повертає: таблиця замін із 256 значень 0…255
def build_lut(hist, n):
    if n == 0:                                 # порожній кадр — нема що ділити
        return list(range(256))                # тотожна таблиця

    lut = [0] * 256
    acc = 0                                    # накопичена сума лічильників = CDF·n
    for v in range(256):
        acc += hist[v]                         # тепер acc = h(0)+…+h(v)
        # нове = round( (acc/n) · 255 ) = (acc·255 + n//2) // n   — цілочисельно
        lut[v] = (acc * 255 + n // 2) // n     # 0…255 гарантовано: acc ≤ n
    return lut
