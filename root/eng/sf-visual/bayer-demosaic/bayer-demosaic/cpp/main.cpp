// raw[H][W] — сира мозаїка, 1 байт/піксель; out[H][W] — повний RGB.
// Беремо ВНУТРІШНІЙ червоний піксель: y, x — парні, 0 < x,y < межа.
uint8_t Rv = raw[y][x];                    // червоне виміряно прямо

// зелене: 4 зелені сусіди по боках (хрест)
int Gv = ( raw[y-1][x] + raw[y+1][x]
         + raw[y][x-1] + raw[y][x+1] + 2 ) / 4;   // +2 — округлення

// синє: 4 сині сусіди по діагоналях
int Bv = ( raw[y-1][x-1] + raw[y-1][x+1]
         + raw[y+1][x-1] + raw[y+1][x+1] + 2 ) / 4;

out[y][x].r = Rv;
out[y][x].g = (uint8_t)Gv;
out[y][x].b = (uint8_t)Bv;
