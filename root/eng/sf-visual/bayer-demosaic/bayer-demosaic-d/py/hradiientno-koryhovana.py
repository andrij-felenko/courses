# Внутрішній червоний піксель (y,x парні). raw — сира RGGB-мозаїка (2D-масив uint8).
# Повертає оцінку зеленого, зважену вздовж напрямку з меншим перепадом.
def green_at_red(raw, y, x):
    gl, gr = int(raw[y][x-1]), int(raw[y][x+1])   # зелені ліворуч / праворуч
    gu, gd = int(raw[y-1][x]), int(raw[y+1][x])   # зелені зверху / знизу

    dH = abs(gl - gr)                              # перепад по горизонталі
    dV = abs(gu - gd)                              # перепад по вертикалі

    wH = 1 + dV        # вага горизонталі БІЛЬША, коли вертикальний перепад великий
    wV = 1 + dH        # (тобто межа вертикальна → інтерполюємо вздовж неї, по горизонталі)

    hAvg = (gl + gr + 1) // 2                       # середнє вздовж горизонталі
    vAvg = (gu + gd + 1) // 2                       # середнє вздовж вертикалі

    g = (wH * hAvg + wV * vAvg + (wH + wV) // 2) // (wH + wV)
    return g & 0xFF
