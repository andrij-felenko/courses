#include <stdint.h>

#define W   320
#define H   240            /* 16 біт/піксель → кожен піксель = один uint16_t */

/* кадровий буфер = звичайний масив у RAM; його розмір і є W×H×бпп÷8 */
static uint16_t fb[W * H];          /* 320 * 240 * 2 = 153600 байтів ≈ 150 КБ */

/* «постав піксель»: порахуй зсув рядок-за-рядком і поклади колір у комірку */
static inline void set_pixel(int x, int y, uint16_t color)
{
    if ((unsigned)x >= W || (unsigned)y >= H)   /* за межами — мовчки вийти */
        return;                                 /* інакше — запис у чужу памʼять */
    fb[y * W + x] = color;                      /* зсув = y·W + x (в одиницях пікселя) */
}
