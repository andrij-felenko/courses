W = 320
H = 240                              # 16 біт/піксель → кожен піксель = один uint16

# кадровий буфер = звичайний масив у RAM; його розмір і є W×H×бпп÷8
fb = bytearray(W * H * 2)            # 320 * 240 * 2 = 153600 байтів ≈ 150 КБ

# «постав піксель»: порахуй зсув рядок-за-рядком і поклади колір у комірку
def set_pixel(x, y, color):
    if not (0 <= x < W and 0 <= y < H):   # за межами — мовчки вийти
        return                            # інакше — запис у чужу памʼять
    off = (y * W + x) * 2                 # зсув = (y·W + x)·бпп (у байтах)
    fb[off]     = color & 0xFF            # little-endian: молодший байт
    fb[off + 1] = (color >> 8) & 0xFF     # старший байт
