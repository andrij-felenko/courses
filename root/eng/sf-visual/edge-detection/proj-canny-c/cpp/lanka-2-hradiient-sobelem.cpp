// Собелеві ядра.  Gx — вертикальні межі, Gy — горизонтальні.
static const int SOBEL_X[3][3] = {{-1,0,1},{-2,0,2},{-1,0,1}};
static const int SOBEL_Y[3][3] = {{-1,-2,-1},{0,0,0},{1,2,1}};

// mag[] — сила градієнта (int), dir[] — сектор напряму 0..3.
// Сектор — це ВІСЬ ГРАДІЄНТА (впоперек межі); двох сусідів уздовж неї й порівнює NMS.
// 0 = ліво/право (межа вертикальна);           2 = верх/низ (межа горизонтальна);
// 1 = ~45°: градієнт на діагоналі \ (межа /);  3 = ~135°: градієнт на діагоналі / (межа \).
static void sobel_grad(int H, int W, const uint8_t *in, int *mag, uint8_t *dir) {
    for (int y = 1; y < H - 1; y++) {
        for (int x = 1; x < W - 1; x++) {
            int gx = 0, gy = 0;
            for (int ky = -1; ky <= 1; ky++)
                for (int kx = -1; kx <= 1; kx++) {
                    int v = in[IDX(y + ky, x + kx)];
                    gx += SOBEL_X[ky + 1][kx + 1] * v;
                    gy += SOBEL_Y[ky + 1][kx + 1] * v;
                }
            // сила: округлене евклідове; для МК можна |gx|+|gy| (дешевше, трохи грубіше)
            mag[IDX(y, x)] = (int)(sqrt((double)gx * gx + (double)gy * gy) + 0.5);

            // напрям → один із 4 секторів (кут за модулем 180°)
            double ang = atan2((double)gy, (double)gx) * 180.0 / M_PI; // -180..180
            if (ang < 0) ang += 180.0;                                  // 0..180
            uint8_t s;
            if      (ang < 22.5  || ang >= 157.5) s = 0;  // ~0°   → сусіди ліво/право
            else if (ang < 67.5)                  s = 1;  // ~45°  → сусіди по діагоналі \ (↖↘)
            else if (ang < 112.5)                 s = 2;  // ~90°  → сусіди верх/низ
            else                                  s = 3;  // ~135° → сусіди по діагоналі / (↙↗)
            dir[IDX(y, x)] = s;
        }
    }
}
