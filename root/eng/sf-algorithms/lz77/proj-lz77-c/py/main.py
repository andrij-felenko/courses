WINDOW  = 4096   # буфер пошуку: як далеко назад дивимось (offset < 4096)
MAX_LEN = 18     # буфер попереду: найдовший збіг, який кодуємо
MIN_LEN = 3      # коротші збіги не кодуємо посиланням (невигідно)

# Один елемент виходу. offset/length задають збіг у вже бачених даних;
# next — свіжий символ за збігом (як у класичному LZ77) або None у самому кінці.
class Triple(NamedTuple):
    offset: int          # на скільки байтів назад (0, якщо збігу нема)
    length: int          # скільки байтів копіювати (0, якщо збігу нема)
    next: int | None     # наступний свіжий байт; None — свіжого байта нема
