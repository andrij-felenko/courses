#include <stdint.h>
#include <stddef.h>

#define WINDOW   4096   // буфер пошуку: як далеко назад дивимось (offset < 4096)
#define MAX_LEN   18     // буфер попереду: найдовший збіг, який кодуємо
#define MIN_LEN    3     // коротші збіги не кодуємо посиланням (невигідно)

// Один елемент виходу. offset/length задають збіг у вже бачених даних;
// next — свіжий символ, що йде відразу за збігом (як у класичному LZ77).
typedef struct {
    uint16_t offset;   // на скільки байтів назад (0, якщо збігу нема)
    uint16_t length;   // скільки байтів копіювати (0, якщо збігу нема)
    uint8_t  next;     // наступний свіжий байт
    uint8_t  has_next; // чи є цей свіжий байт (на самому кінці може не бути)
} Triple;
