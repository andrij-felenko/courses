#include <stddef.h>
#include <stdbool.h>

/*
 * Базове сортування масиву цілих чисел типу int за зростанням.
 * Виконує повний подвійний цикл без перевірки проміжного стану.
 *
 * @param arr Покажчик на початок масиву. Мусить бути валідним і не-NULL при n > 0.
 * @param n   Кількість елементів у масиві.
 */
void bubble_sort_int_naive(int *arr, size_t n);

/*
 * Адаптивне сортування масиву int із прапорцем swapped.
 * Завершує роботу за один прохід (O(N)), якщо масив уже впорядкований.
 *
 * @param arr Покажчик на початок масиву.
 * @param n   Кількість елементів у масиві.
 */
void bubble_sort_int_adaptive(int *arr, size_t n);

/*
 * Оптимізоване сортування бульбашкою зі звуженням меж за індексом останнього обміну.
 * Ефективно перестрибує вже впорядковані кінцеві сегменти масиву.
 *
 * @param arr Покажчик на початок масиву.
 * @param n   Кількість елементів у масиві.
 */
void bubble_sort_int_last_swap(int *arr, size_t n);

/*
 * Двонаправлене сортування перемішуванням (Cocktail Shaker Sort).
 * Чергує прямі та зворотні проходи, усуваючи затримку «черепах».
 *
 * @param arr Покажчик на початок масиву.
 * @param n   Кількість елементів у масиві.
 */
void cocktail_shaker_sort_int(int *arr, size_t n);

/*
 * Універсальне сортування буфера довільного типу за аналогією з qsort() зі stdlib.h.
 *
 * @param base Покажчик на перший байт неструктурованого буфера.
 * @param num  Кількість елементів у буфері.
 * @param size Розмір одного елемента в байтах (sizeof(T)).
 * @param cmp  Функція-компаратор: повертає >0 якщо a > b, <=0 якщо a <= b.
 */
void bubble_sort_generic(void *base, size_t num, size_t size,
                         int (*cmp)(const void *a, const void *b));
