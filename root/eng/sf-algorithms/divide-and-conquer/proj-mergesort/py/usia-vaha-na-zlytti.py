def merge(a, buf, lo, mid, hi):
    """Зливає дві відсортовані частини a[lo:mid] і a[mid:hi] через buf,
       тоді переносить злите назад у a[lo:hi].
       Півінтервали: ліва [lo, mid), права [mid, hi) — межа mid належить ПРАВІЙ."""
    i, j, k = lo, mid, lo               # i — по лівій, j — по правій, k — по buf
    while i < mid and j < hi:
        if a[i] <= a[j]:                # ≤, а не < — на рівних беремо з ЛІВОЇ (стійкість)
            buf[k] = a[i]; i += 1
        else:
            buf[k] = a[j]; j += 1
        k += 1
    while i < mid:                      # долити лівий хвіст (правий уже вичерпано)
        buf[k] = a[i]; i += 1; k += 1
    while j < hi:                       # або правий хвіст (вичерпано лівий)
        buf[k] = a[j]; j += 1; k += 1
    a[lo:hi] = buf[lo:hi]              # перенести злите на місце
