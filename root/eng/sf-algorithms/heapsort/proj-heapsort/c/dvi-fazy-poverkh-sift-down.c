void heapsort(int a[], int n) {
    /* Фаза 1 — побудова купи знизу-вгору. Останній батько — індекс n/2-1. */
    for (int i = n / 2 - 1; i >= 0; i--)
        sift_down(a, i, n);

    /* Фаза 2 — (n-1) разів зняти корінь-максимум у хвіст і полагодити купу. */
    for (int end = n - 1; end > 0; end--) {
        int t = a[0]; a[0] = a[end]; a[end] = t;   /* максимум → на лівий край хвоста */
        sift_down(a, 0, end);                       /* купа тепер коротша: розмір = end */
    }
}
