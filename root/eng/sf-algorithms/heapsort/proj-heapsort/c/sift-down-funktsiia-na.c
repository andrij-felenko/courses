/* Просіяти a[i] вниз по max-купі, що займає a[0 .. n-1].
   Після виходу піддерево з коренем i — знову коректна купа. */
static void sift_down(int a[], int i, int n) {
    for (;;) {
        int l   = 2 * i + 1;         /* ліва дитина  */
        int r   = 2 * i + 2;         /* права дитина */
        int max = i;                 /* поки що найбільший — сам батько */

        if (l < n && a[l] > a[max]) max = l;
        if (r < n && a[r] > a[max]) max = r;   /* r < n: правої дитини може й не бути */

        if (max == i) return;        /* батько не менший за обох — тут купа ціла */

        int t = a[i]; a[i] = a[max]; a[max] = t;   /* міняємось із БІЛЬШОЮ дитиною */
        i = max;                     /* спускаємось на її місце — і по колу знову */
    }
}
