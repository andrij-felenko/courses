# Втрата Губера: квадрат для малих помилок, модуль — для великих
def huber(pred, truth, delta):
    e = pred - truth
    a = abs(e)
    if a <= delta:
        return 0.5 * e * e                  # гладка квадратична серцевина
    else:
        return delta * (a - 0.5 * delta)    # лінійні «хвости» проти викидів

# малий промах e=0.4, δ=1 → 0.5·0.16 = 0.08 (як MSE)
# викид     e=10,  δ=1 → 1·(10 − 0.5) = 9.5 (як MAE, а не 100!)
