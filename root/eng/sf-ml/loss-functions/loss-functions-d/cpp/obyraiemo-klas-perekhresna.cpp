#include <math.h>
// Перехресна ентропія для одного прикладу: штраф лише за впевненість
// у ПРАВИЛЬНОМУ класі (решта не рахуються — їхня «істина» = 0)
float cross_entropy(const float *p, int correct) {
    float pc = p[correct];
    if (pc < 1e-7f) pc = 1e-7f;   // захист від log(0) → -∞
    return -logf(pc);
}
// p = {0.7, 0.2, 0.1}, правильний клас 0 → pc = 0.7
// штраф = -ln(0.7) ≈ 0.357  (вагалась, але вгадала — помірний штраф)
//
// якби модель дала правильному класу 0.02 (упевнене «ні»):
// штраф = -ln(0.02) ≈ 3.91  — удесятеро більший за самовпевненість
