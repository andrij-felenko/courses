// Один крок L1-регуляризації: штовхаємо вагу до нуля на СТАЛУ величину
// (нахил |w| не залежить від розміру ваги). Це «м'яке порогування».
void l1_step(float *w, int n, float eta, float lambda) {
    float step = eta * lambda;              // однаковий крок для всіх
    for (int i = 0; i < n; i++) {
        if (w[i] >  step)      w[i] -= step; // додатну підсуваємо вниз
        else if (w[i] < -step) w[i] += step; // від'ємну — вгору
        else                   w[i] = 0.0f;  // якщо ближче за крок — ЗАНУЛЯЄМО
    }
}
// w = {2.0, 0.05, -3.0}, eta=0.1, lambda=0.1 -> step = 0.01
// w -> {1.99, 0.04, -2.99}; а вага 0.008 (< step) впала б рівно в 0
