// Один крок L2-регуляризації (weight decay) для масиву ваг.
// Кожну вагу зсуваємо проти градієнта штрафу 2*lambda*w.
void l2_step(float *w, int n, float eta, float lambda) {
    for (int i = 0; i < n; i++)
        w[i] -= eta * (2.0f * lambda * w[i]);   // = w[i] * (1 - 2*eta*lambda)
}

// w = {2.0, 0.5, -3.0}, eta = 0.1, lambda = 0.1
// множник згасання = 1 - 2*0.1*0.1 = 0.98
// w -> {1.96, 0.49, -2.94}   — усі притиснулись до нуля на 2%,
//                              велика (-3.0) втратила найбільше в абсолюті
