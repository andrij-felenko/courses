#include <stdint.h>

// заздалегідь, офлайн: M0 = round(M * 2^n)
// M = 0.15, n = 20 → 2^20 = 1048576
// M0 = round(0.15 * 1048576) = round(157286.4) = 157286
const int32_t M0 = 157286;
const int     n  = 20;
const int32_t zy = -5;

int8_t requantize(int32_t acc) {
    // 64-бітний проміжний, щоб acc*M0 не переповнило int32
    int64_t t = (int64_t)acc * M0;   // 1000000 * 157286 = 157 286 000 000
    int32_t r = (int32_t)(t >> n);   // >> 20  →  157286000000 / 1048576 ≈ 149999
    r += zy;                          // 149999 + (-5) = 149994
    // clamp у діапазон int8 (див. нижче) — тут число велике, обріжеться до 127
    if (r < -128) r = -128;
    if (r >  127) r =  127;
    return (int8_t)r;                 // 127
}
