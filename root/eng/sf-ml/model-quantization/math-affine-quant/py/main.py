# заздалегідь, офлайн: M0 = round(M * 2^n)
# M = 0.15, n = 20 → 2^20 = 1048576
# M0 = round(0.15 * 1048576) = round(157286.4) = 157286
M0 = 157286
n  = 20
zy = -5

def requantize(acc: int) -> int:
    # цілі Python необмежені, тож acc*M0 не переповнить — «широкий проміжний» безплатний
    t = acc * M0             # 1000000 * 157286 = 157 286 000 000
    r = t >> n               # >> 20  →  157286000000 / 1048576 ≈ 149999
    r += zy                  # 149999 + (-5) = 149994
    # clamp у діапазон int8 (див. нижче) — тут число велике, обріжеться до 127
    if r < -128: r = -128
    if r >  127: r =  127
    return r                 # 127
