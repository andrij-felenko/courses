/* t = округл(a · b · 2 / 2^32): множимо два Q31, беремо старші 32 біти,
   з подвоєнням і округленням до найближчого. Сатурація — лише на єдиному
   поганому випадку a = b = INT32_MIN (де точний результат +2^31 не влазить). */
static inline int32_t sat_round_dbl_high(int32_t a, int32_t b)
{
    if (a == INT32_MIN && b == INT32_MIN) return INT32_MAX;   /* єдине переповнення */
    int64_t ab = (int64_t)a * (int64_t)b;                     /* точний 64-біт добуток */
    /* «підштовх» на округлення: +2^30 як знаки збігаються, інакше −(2^30−1) */
    int32_t nudge = (a ^ b) >= 0 ? (1 << 30) : -((1 << 30) - 1);
    return (int32_t)((ab + nudge) / (int64_t)(1LL << 31));     /* /2^31 = старші 32 біти ×2 */
}
