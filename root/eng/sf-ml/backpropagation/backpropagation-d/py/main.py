import math

# ── дано ──
x, w1, w2, target = 1.0, 0.8, 1.5, 2.0

# ── ПРОХІД УПЕРЕД (дорогою запам'ятовуємо проміжні числа) ──
z   = w1 * x                # вхід прихованого нейрона
h   = math.tanh(z)          # його вихід після активації
out = w2 * h                # вихід мережі
err = out - target          # «сира» різниця
E   = 0.5 * err * err       # похибка (1/2 — щоб похідна була чистою)

# ── ПРОХІД НАЗАД (кожен крок = помножити те, що прийшло, на локальне) ──
dE_dout = err               # ∂E/∂out : похідна 1/2·err² по out = err
dE_dw2  = dE_dout * h       # out = w2·h ⇒ локальне ∂out/∂w2 = h

dE_dh = dE_dout * w2        # несемо провину в прихований шар: ∂out/∂h = w2
dtanh = 1.0 - h * h         # локальна похідна tanh: 1 − tanh²(z)
dE_dz = dE_dh * dtanh       # дельта прихованого нейрона
dE_dw1 = dE_dz * x          # z = w1·x ⇒ локальне ∂z/∂w1 = x

print(f"out={out:.4f}  E={E:.4f}")   # out=0.9961  E=0.5040
print(f"dE/dw2={dE_dw2:.4f}")        # -0.6667
print(f"dE/dw1={dE_dw1:.4f}")        # -0.8419
