/* Константне умовне віднімання без розгалужень */
static inline uint64_t ct_sub_if_gte(uint64_t t, uint64_t n) {
    /* d = t - n (у разі t < n виникає переповнення/запозичення) */
    uint64_t d = t - n;
    
    /* Отримуємо маску запозичення: 
       якщо t >= n, запозичення немає, старший біт 0 -> маска 0x0000000000000000
       якщо t < n, запозичення є, старший біт 1 -> маска 0xFFFFFFFFFFFFFFFF */
    uint64_t has_borrow = (t < n) ? 1 : 0;
    uint64_t mask = -has_borrow;
    
    /* Мультиплексування без умовного переходу:
       якщо t >= n (mask = 0), повертається d = t - n
       якщо t < n (mask = ~0), повертається t */
    return (t & mask) | (d & ~mask);
}
