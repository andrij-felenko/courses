// портативно: жодного типу, ширшого за u64. Вимагає m < 2⁶³,
// щоб проміжні суми a+a та r+a не переповнили саме слово.
u64 mulmod_slow(u64 a, u64 b, u64 m) {
    u64 r = 0;  a %= m;
    while (b) {
        if (b & 1) r = (r + a) % m;   // додаємо a, якщо біт стоїть
        a = (a + a) % m;              // подвоюємо a за модулем
        b >>= 1;
    }
    return r;
}
