def powmod(a: int, k: int, n: int) -> int:
    """a^k mod n — «ланцюг квадратів плюс вибірка за бітами»."""
    r = 1                      # накопичувач: тут росте відповідь
    a %= n
    while k:
        if k & 1:              # цей степінь двійки є в розкладі k?
            r = r * a % n      # так → вкручуємо поточну ланку
        a = a * a % n          # наступна ланка: a, a², a⁴, a⁸, …
        k >>= 1                # перейшли до наступного біта показника
    return r

assert powmod(13, 27, 55) == 7          # той самий приклад, що й на папері
assert powmod(13, 27, 55) == pow(13, 27, 55)
