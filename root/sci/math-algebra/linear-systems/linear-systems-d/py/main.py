# Розв'язати  a11*x + a12*y = b1
#             a21*x + a22*y = b2
# Повертає (x, y); None — якщо розв'язок не єдиний.
def solve2x2(a11, a12, b1, a21, a22, b2):
    det = a11 * a22 - a12 * a21    # визначник: 0 ⇒ прямі паралельні
    if det == 0.0:
        return None                # нема єдиного розв'язку

    x = (b1 * a22 - a12 * b2) / det
    y = (a11 * b2 - b1 * a21) / det
    return x, y
