/* G = x³+x+1 = 0b1011 (4 біти, разом зі старшим x³).
   Степінь G = 3, тож лишок займає 3 біти. */
uint8_t crc3(uint8_t msg, int nbits) {   /* msg = 0b1010, nbits = 4 */
    uint8_t rem = msg << 3;              /* M·x³  → 1010000 (дописані 3 нулі) */
    for (int i = nbits + 3 - 1; i >= 3; i--) {   /* від старшого біта до x³ */
        if (rem & (1u << i))            /* старший біт проміжку = 1? */
            rem ^= 0b1011u << (i - 3);  /* так → відняти (XOR) G, підведений під цей біт */
    }                                    /* ні → нічого, просто крок далі */
    return rem & 0b111u;                 /* лишок — 3 молодші біти */
}
