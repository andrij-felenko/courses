# G = x³+x+1 = 0b1011 (4 біти, разом зі старшим x³).
# Степінь G = 3, тож лишок займає 3 біти.
def crc3(msg, nbits):                     # msg = 0b1010, nbits = 4
    rem = msg << 3                        # M·x³  → 1010000 (дописані 3 нулі)
    for i in range(nbits + 3 - 1, 2, -1): # від старшого біта до x³
        if rem & (1 << i):               # старший біт проміжку = 1?
            rem ^= 0b1011 << (i - 3)      # так → відняти (XOR) G, підведений під цей біт
                                          # ні → нічого, просто крок далі
    return rem & 0b111                   # лишок — 3 молодші біти
# крок i=6: 1010000 ^ 1011000 = 0001000   (старша 1 згасла)
# крок i=5,4: старший біт 0 → пропуск
# крок i=3: 0001000 ^ 0001011 = 0000011   → лишок 011
