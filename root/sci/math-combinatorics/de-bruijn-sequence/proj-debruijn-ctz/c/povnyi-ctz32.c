#include <stdint.h>

static const uint8_t deBruijn32[32] = {
     0,  1, 28,  2, 29, 14, 24,  3, 30, 22, 20, 15, 25, 17,  4,  8,
    31, 27, 13, 23, 21, 19, 16,  7, 26, 12, 18,  6, 11,  5, 10,  9,
};

// Позиція наймолодшого встановленого біта (0…31). Передумова: x ≠ 0.
int ctz32(uint32_t x) {
    uint32_t isolated = x & -x;                  // 2^p: лишити єдину наймолодшу 1
    return deBruijn32[(isolated * 0x077CB531u) >> 27];
}
