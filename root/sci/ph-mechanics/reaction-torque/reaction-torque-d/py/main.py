# Реактивний момент гвинта ∝ (оберти)². База — момент при зависанні.
Q0 = 0.06          # Н·м на один гвинт у режимі зависання

# Дві діагональні пари крутяться в протилежні боки.
# Пара A: +10 % обертів  → момент × 1.10²
# Пара B: −10 % обертів  → момент × 0.90²
up_a = 1.10 ** 2   # = 1.21
dn_b = 0.90 ** 2   # = 0.81

# Кожна пара — з двох гвинтів. Реактивні моменти пар напрямлені
# у протилежні боки, тож чистий момент рискання — їхня різниця:
yaw = 2.0 * Q0 * up_a  -  2.0 * Q0 * dn_b
#   = 2·0.06·1.21  −  2·0.06·0.81
#   = 0.1452       −  0.0972
#   = 0.0480  (Н·м)
