Omega, R, m = 7.29e-5, 6.378e6, 70.0
g_екв, g_пол = 9.7803, 9.8322          # виміряні (враховують і форму, і відцентрову)

dg_cf = Omega**2 * R                    # послаблення суто від відцентрової, на екваторі
print(f"лише відцентрова:  Δg = {dg_cf:.4f} м/с² = {100*dg_cf/g_екв:.3f}% "
      f"→ 70 кг легшають на {m*dg_cf/9.81:.3f} кгс")

dg_tot = g_пол - g_екв                  # повна різниця полюс−екватор
print(f"повна (з формою):  Δg = {dg_tot:.4f} м/с² = {100*dg_tot/g_екв:.3f}% "
      f"→ 70 кг легшають на {m*dg_tot/9.81:.3f} кгс")

# перевірка теоремою Клеро: (g_пол − g_екв)/g_екв = 5/2·m − f
m_ratio = Omega**2 * R / g_екв          # відцентрова-до-тяжіння на екваторі
f_flat  = 1/298.257                     # сплюснутість Землі
print(f"теорема Клеро 5/2·m − f = {100*(2.5*m_ratio - f_flat):.3f}%")
