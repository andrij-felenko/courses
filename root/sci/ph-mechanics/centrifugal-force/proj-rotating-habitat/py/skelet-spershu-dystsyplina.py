"""Калькулятор обертової станції зі штучним тяжінням. Лише стандартна бібліотека."""
import math
from dataclasses import dataclass

G_EARTH = 9.81                 # м/с² — земне тяжіння, еталон для «частки g»

# ── переклад між людською мовою (об/хв) і фізичною (рад/с) ──
def rpm_to_rad(rpm):  return rpm * 2.0 * math.pi / 60.0     # об/хв → рад/с
def rad_to_rpm(w):    return w * 60.0 / (2.0 * math.pi)     # рад/с → об/хв

# ── межі комфорту (синтез досліджень; джерела вище) ──
RPM_OK    = 2.0    # об/хв — «оптимальний комфорт» (Gilruth, 1968)
RPM_TOL   = 6.0    # об/хв — терпима стеля з адаптацією (Gilruth; Gordon & Gervais)
V_RIM_MIN = 6.0    # м/с   — щоб хода не міняла вагу помітно (Hill & Schnitzer, ~20 фут/с)
GRAD_MAX  = 0.15   # частка — голова-ноги ≤ 15 % на зріст (Gilruth; Gordon & Gervais)
G_LO, G_HI = 0.30, 1.00   # частка g — комфортний коридор тяжіння
