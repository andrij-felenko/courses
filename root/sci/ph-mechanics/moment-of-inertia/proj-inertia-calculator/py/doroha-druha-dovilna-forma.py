import math

def disc_inertia_grid(R, M, n):
    """Момент інерції однорідного диска (вісь ⟂ через центр) — чисельно.
    Накриваємо диск сіткою n×n по описаному квадрату 2R×2R; клітинка,
    чий центр упав у диск, — елемент маси Δm на відстані r від осі.
    Контроль: результат мусить збігтися з ½·M·R²."""
    step = 2 * R / n                   # сторона клітинки
    s = 0.0                            # Σ r² по клітинках усередині
    inside = 0
    for i in range(n):
        x = -R + (i + 0.5) * step      # центр клітинки по x
        for j in range(n):
            y = -R + (j + 0.5) * step
            if x*x + y*y <= R*R:       # клітинка всередині диска?
                s += x*x + y*y         # r² = x² + y²
                inside += 1
    dm = M / inside                    # рівна маса на клітинку: Σ Δm = M точно
    return s * dm                      # J = Σ r²·Δm
