def inertia_about_axis(parts):
    """parts — послідовність (m, J_cm, d):
        m    — маса частини, кг
        J_cm — момент інерції навколо ВЛАСНОЇ осі через центр мас,
               паралельної до цільової осі, кг·м²
        d    — відстань від центра мас частини до цільової осі, м
    Повертає момент інерції всього тіла навколо цільової осі, кг·м²."""
    return sum(J_cm + m * d*d for m, J_cm, d in parts)
