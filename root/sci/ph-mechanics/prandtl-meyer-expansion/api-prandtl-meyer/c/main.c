typedef struct {
    double M;           /* Місцеве число Маха */
    double nu_rad;      /* Значення функції Прандтля — Майєра (рад) */
    double nu_deg;      /* Значення функції Прандтля — Майєра (град) */
    double mu_rad;      /* Кут Маха μ = arcsin(1/M) (рад) */
    double mu_deg;      /* Кут Маха μ (град) */
    double p_p0;        /* Відношення статичного тиску до повного p/p0 */
    double T_T0;        /* Відношення статичної температури до повної T/T0 */
    double rho_rho0;    /* Відношення густини до повної rho/rho0 */
    double v_aSt;       /* Безрозмірна швидкість v / a* (параметр Лаваля λ) */
} pm_state_t;
