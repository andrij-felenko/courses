struct FlowState {
    double M{1.0};            // Місцеве число Маха
    double nu_rad{0.0};       // Значення функції Прандтля — Майєра (рад)
    double nu_deg{0.0};       // Значення функції Прандтля — Майєра (град)
    double mu_rad{0.0};       // Кут Маха μ = arcsin(1/M) (рад)
    double mu_deg{0.0};       // Кут Маха μ (град)
    double p_p0{1.0};         // Відношення статичного тиску до повного p/p0
    double T_T0{1.0};         // Відношення статичної температури до повної T/T0
    double rho_rho0{1.0};     // Відношення густини до повної rho/rho0
    double v_aSt{1.0};        // Безрозмірна швидкість v / a* (параметр Лаваля λ)
};
