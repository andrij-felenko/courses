import numpy as np

# --- тіло: телефон як прямокутна коробка (товщина × ширина × висота) ---
m = 0.170                        # маса, кг
t, w, h = 0.008, 0.070, 0.150    # м

# головні моменти інерції коробки (осі крізь центр мас)
I1 = m/12 * (t**2 + w**2)        # довга вісь («свердло»)   — НАЙМЕНШИЙ
I2 = m/12 * (t**2 + h**2)        # вісь ширини («перекид»)  — ПРОМІЖНИЙ
I3 = m/12 * (w**2 + h**2)        # вісь товщини («тарілка») — НАЙБІЛЬШИЙ
I = np.array([I1, I2, I3])       # → [7.03e-5, 3.20e-4, 3.88e-4] кг·м², I1 < I2 < I3

def euler_rhs(o):                # праві частини рівнянь Ейлера (o = ω)
    o1, o2, o3 = o
    return np.array([
        (I[1] - I[2]) * o2 * o3 / I[0],
        (I[2] - I[0]) * o3 * o1 / I[1],
        (I[0] - I[1]) * o1 * o2 / I[2],
    ])

def rk4(o, dt):                  # один крок Рунге-Кутта 4-го порядку
    k1 = euler_rhs(o)
    k2 = euler_rhs(o + 0.5*dt*k1)
    k3 = euler_rhs(o + 0.5*dt*k2)
    k4 = euler_rhs(o + dt*k3)
    return o + dt/6 * (k1 + 2*k2 + 2*k3 + k4)

def L_mag(o):  return np.linalg.norm(I * o)   # |L| у системі тіла: |(I₁ω₁, I₂ω₂, I₃ω₃)|
def two_T(o):  return I @ (o * o)             # 2·кінетична енергія: Σ Iₖ·ωₖ²
