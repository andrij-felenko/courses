import math

Omega = 7.29e-5          # кутова швидкість Землі, рад/с
phi   = 50               # широта, градуси
v     = 800              # горизонтальна швидкість снаряда, м/с
t     = 50               # час польоту, с

# параметр Коріоліса: яка частка обертання крутить місцевий горизонт
f = 2 * Omega * math.sin(math.radians(phi))
#  = 2 · 7.29e-5 · 0.766 = 1.117e-4   (1/с)

# бічне прискорення від сили Коріоліса (на одиницю маси)
a = f * v
#  = 1.117e-4 · 800 = 0.0894   (м/с²)

# рівноприскорений знос убік за час польоту
d = 0.5 * a * t**2
#  = 0.5 · 0.0894 · 2500 ≈ 112   (м)
