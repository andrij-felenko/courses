import math

# --- система (СІ) ---
m, k  = 1.0, 100.0      # маса (кг), жорсткість пружини (Н/м)
g     = 9.8
mu_s  = 0.5             # тертя спокою
mu_k  = 0.3             # тертя ковзання
V     = 0.02            # швидкість тяги вільного кінця пружини (м/с)
dt, T = 1e-4, 8.0

N  = m * g              # нормальна сила = вага бруска
Fs = mu_s * N           # поріг зриву
Fk = mu_k * N           # рівень тертя ковзання

x = v = t = 0.0
stuck = True            # режим: прилип чи ковзає
log = []

while t < T:
    F = k * (V * t - x)                 # сила пружини: жорсткість × розтяг
    if stuck:
        if F >= Fs:                     # напруга перевищила поріг —
            stuck = False               #   ЗРИВ
    else:
        fric = Fk if v >= 0 else -Fk    # кінетичне тертя — завжди проти руху
        a = (F - fric) / m              # другий закон Ньютона
        v += a * dt                     # напівнеявний Ейлер: спершу швидкість…
        x += v * dt                     # …тоді положення вже новою v
        if v <= 0.0:                    # швидкість упала до нуля —
            v, stuck = 0.0, True        #   ПРИЛИП знову
    log.append((t, x, v, F, stuck))
    t += dt

# --- зняти характеристики пилки з журналу ---
breaks = [log[i][0] for i in range(1, len(log))
          if log[i-1][4] and not log[i][4]]         # миті зриву
period = breaks[1] - breaks[0]
vpk = max(r[2] for r in log)
print(f"поріг зриву μ_s·N = {Fs:.2f} Н,  рівень ковзання μ_k·N = {Fk:.2f} Н")
print(f"стрибок сили на зриві = {2*(mu_s-mu_k)*N:.2f} Н")
print(f"період stick-slip ≈ {period:.2f} с  (частота {1/period:.2f} Гц)")
print(f"тривалість ковзання ≈ {math.pi*math.sqrt(m/k):.3f} с")
print(f"пік швидкості кидка = {vpk:.3f} м/с  (≈ {vpk/V:.0f}·V)")
