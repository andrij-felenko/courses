import numpy as np

# ── Спектр AM1.5G як число ──────────────────────────────────────────
# b(E) = q·φ(E) — спектральна густина фотоструму, мА·см⁻²·еВ⁻¹:
# «скільки струму дала б кожна вузька смужка спектра при повному зборі».
# Груба згладжена копія AM1.5G (без реальних водяних провалів — див. пастки).
E_tab = np.array([0.50,0.70,0.90,1.10,1.30,1.45,1.60,1.75,1.90,2.10,2.30,2.60,3.00,3.50,4.00])
b_tab = np.array([  30,  31,  32,  36,  42,  40,  34,  29,  24,  19,  15,  10, 5.0, 2.2, 0.3])

def b(E):
    "Спектральна густина фотоструму b(E), мА·см⁻²·еВ⁻¹."
    return np.interp(E, E_tab, b_tab, left=0.0, right=0.0)

def photocurrent(lo, hi, n=2000):
    "Фотострум смуги [lo, hi) — інтеграл b(E) dE за енергією, мА/см²."
    E = np.linspace(lo, hi, n)
    return np.trapz(b(E), E) if hi > lo else 0.0
