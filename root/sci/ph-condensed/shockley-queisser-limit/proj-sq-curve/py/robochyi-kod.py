# -*- coding: utf-8 -*-
"""Крива межі одного переходу з першопринципів: інтегруємо планківський
потік фотонів, проганяємо детальний баланс по всіх порогах Eg, шукаємо пік.
Чиста стандартна бібліотека — жодних залежностей."""
import math

# ── фізичні сталі (SI) ──────────────────────────────────────────────
h  = 6.62607015e-34    # стала Планка, Дж·с
c  = 2.99792458e8      # швидкість світла, м/с
kB = 1.380649e-23      # стала Больцмана, Дж/К
q  = 1.602176634e-19   # заряд електрона, Кл

T_sun  = 5800.0        # температура фотосфери Сонця, К
T_cell = 300.0         # температура елемента, К

# Сонце — маленький диск (кутовий радіус 0.2665°), а не ціла півсфера.
# Тілесний кут цього диска «розводить» яскравий планківський потік
# до земного рівня ~одне сонце.
theta     = math.radians(0.2665)
OMEGA_SUN = 2*math.pi*(1 - math.cos(theta))     # ≈ 6.8e-5 ср

# ── планківський потік фотонів ──────────────────────────────────────
def photon_flux(E_eV, T):
    """Спектральна густина потоку фотонів чорного тіла за T:
    фотони за секунду на м², на стерадіан, на еВ."""
    x = E_eV*q / (kB*T)
    if x <= 0.0 or x > 700.0:        # захист від переповнення exp (див. пастки)
        return 0.0
    E = E_eV*q
    return (2.0/(h**3 * c**2)) * E*E / (math.exp(x) - 1.0) * q   # ×q: на еВ, не на Дж

# ── сітка енергій для інтегрування ──────────────────────────────────
DE = 0.002                                        # крок, еВ (див. пастку про збіжність)
EMIN, EMAX = 0.05, 6.0
GRID = [EMIN + DE*i for i in range(int((EMAX-EMIN)/DE) + 1)]

def integrate(f):
    """Сума прямокутників по сітці. Для гладкого планківського спектра
    цього досить: метод трапецій дав би те саме до четвертого знака."""
    return sum(f(E) for E in GRID) * DE

# падна потужність: інтеграл ЕНЕРГІЇ планківського потоку × тілесний кут диска
P_IN = OMEGA_SUN * integrate(lambda E: (E*q) * photon_flux(E, T_sun))

def photons_above(Eg, T):
    """Фотони за секунду на м² на стерадіан з енергією E ≥ Eg."""
    return sum(photon_flux(E, T) for E in GRID if E >= Eg) * DE

# ── детальний баланс для одного порога ──────────────────────────────
def efficiency(Eg):
    N_gen  = OMEGA_SUN * photons_above(Eg, T_sun)   # надпорогові фотони Сонця
    N_emit = math.pi   * photons_above(Eg, T_cell)  # власне світіння у півсферу
    Jsc = q * N_gen                                 # короткий струм
    J0  = q * N_emit                                # темновий струм насичення
    Voc = (kB*T_cell/q) * math.log(Jsc/J0 + 1.0)

    Pmax = Vmp = 0.0                                 # робоча точка макс. потужності
    STEPS = 1000
    for i in range(1, STEPS):
        V = Voc * i/STEPS
        J = Jsc - J0*(math.exp(q*V/(kB*T_cell)) - 1.0)
        if J < 0:                                    # за Voc струм уже від'ємний
            break
        if J*V > Pmax:
            Pmax, Vmp = J*V, V
    return dict(Eg=Eg, Jsc=Jsc, Voc=Voc, Pmax=Pmax,
                eta=Pmax/P_IN, FF=Pmax/(Jsc*Voc))

# ── крива η(Eg), пік і матеріали ────────────────────────────────────
if __name__ == "__main__":
    print("Падна потужність (чорне тіло %.0f K × Ω) = %.0f Вт/м²" % (T_sun, P_IN))

    gaps  = [0.40 + 0.01*i for i in range(261)]      # 0.40 … 3.00 еВ
    curve = [(Eg, efficiency(Eg)['eta']) for Eg in gaps]
    Eg_pk, eta_pk = max(curve, key=lambda p: p[1])
    print("Пік: Eg = %.2f еВ,  η = %.1f%%" % (Eg_pk, eta_pk*100))

    for name, Eg in [("Si", 1.12), ("GaAs", 1.42)]:
        m = efficiency(Eg)
        print("  %-4s Eg=%.2f еВ  η=%.1f%%  Voc=%.3f В  Jsc=%.0f А/м²  FF=%.2f"
              % (name, Eg, m['eta']*100, m['Voc'], m['Jsc'], m['FF']))
