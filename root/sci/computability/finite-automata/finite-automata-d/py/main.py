# Стани кодуємо числами 0..3 — це індекс у таблиці δ.
# NEXT[state][bit] — наступний стан; точно як таблиця вище.
NEXT = (
    #    bit=0  bit=1
    (     0,     1  ),   # S0
    (     2,     1  ),   # S1
    (     0,     3  ),   # S2
    (     2,     1  ),   # S3
)

def has_101(bits):
    s = 0                          # q0 = S0
    for b in bits:
        s = NEXT[s][b & 1]         # один перехід на символ: δ(s, біт)
        if s == 3:                 # S3 ∈ F — підрядок знайдено
            return True
    return False
