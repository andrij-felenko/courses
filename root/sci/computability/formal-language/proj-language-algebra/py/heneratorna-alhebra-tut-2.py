def upto(L, n):
    """Усі слова мови L завдовжки ≤ n — скінченний список у шортлекс-порядку.
    Спиняється ЛИШЕ на шортлекс-потоці: перше ж слово, довше за n, означає,
    що довших уже не буде, — і читати далі нема сенсу."""
    out = []
    for w in L():
        if len(w) > n:
            break                    # ← ось ця межа й робить нескінченне скінченним
        out.append(w)
    return out
