def diagonal_language(langs, rank):
    """langs[n](w) → чи належить слово w до мови Lₙ (мови занумеровані від 0).
    rank(w)       → номер слова w у шортлекс-переліку Σ*.
    Повертає предикат мови D, якої НЕМАЄ серед langs."""
    def D(w):
        n = rank(w)
        return not langs[n](w)          # клітинка (n, n), перевернута
    return D

