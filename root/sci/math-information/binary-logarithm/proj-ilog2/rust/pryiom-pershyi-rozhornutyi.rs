/// ⌊log₂n⌋ для n > 0 — двійковий пошук по позиції старшого біта
fn floor_log2_unrolled(mut n: u64) -> u32 {
    let mut k = 0;
    if n >= 1 << 32 { n >>= 32; k += 32; }
    if n >= 1 << 16 { n >>= 16; k += 16; }
    if n >= 1 << 8  { n >>= 8;  k += 8;  }
    if n >= 1 << 4  { n >>= 4;  k += 4;  }
    if n >= 1 << 2  { n >>= 2;  k += 2;  }
    if n >= 1 << 1  {           k += 1;  }
    k
}
