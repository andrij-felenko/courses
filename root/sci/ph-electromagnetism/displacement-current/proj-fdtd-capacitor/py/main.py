import math
import numpy as np

def run_fdtd_simulation():
    # Параметри простору й часу
    nx = 200             # Кількість просторових вузлів сітки
    max_steps = 400      # Кількість часових кроків моделювання
    c0 = 299792458.0     # Швидкість світла у вакуумі (м/с)
    dx = 1e-3            # Простокрок сітки Δx = 1 мм
    dt = dx / (2.0 * c0) # Часовий крок Δt за критерієм Куранта (S = 0.5)

    # Масиви діелектричних властивостей середовища (eps_r)
    eps_r = np.ones(nx)
    # Розміщуємо діелектрик конденсатора між вузлами 80 та 120
    eps_r[80:120] = 4.0   # ε_r = 4.0 (кераміка)

    eps0 = 8.854187817e-12
    mu0 = 4.0 * math.pi * 1e-7

    # Поля Ez та Hy
    Ez = np.zeros(nx)
    Hy = np.zeros(nx - 1)

    # Постійні коефіцієнти оновлення полів
    ch = dt / (mu0 * dx)
    ce = dt / (eps0 * eps_r * dx)

    print(f"Запуск симуляції FDTD (Python): dx={dx*1e3:.1f}мм, dt={dt*1e12:.2f}пс, кроків={max_steps}")

    # Головний часовий цикл
    for t_step in range(max_steps):
        # 1. Оновлення магнітного поля H_y
        Hy += ch * (Ez[1:] - Ez[:-1])

        # 2. Оновлення електричного поля E_z (струм зміщення)
        Ez[1:-1] += ce[1:-1] * (Hy[1:] - Hy[:-1])

        # 3. Гауссів імпульсний генератор у вузлі 30
        pulse = math.exp(-((t_step - 40.0) / 12.0) ** 2)
        Ez[30] += pulse

    max_ez_in_cap = np.max(np.abs(Ez[80:120]))
    print(f"Симуляцію успішно завершено. Макс. амплітуда Ez у конденсаторі: {max_ez_in_cap:.4f} В/м")

if __name__ == "__main__":
    run_fdtd_simulation()
