static uint64_t acc = 0;      // накопичувач суми квадратів (широкий!)
static uint32_t n   = 0;

void on_sample(int32_t v) {           // періодично, з таймера/ISR
    int32_t x = v - offset;           // прибрати зсув АЦП (середину шкали / DC)
    acc += (int64_t)x * x;            // ← єдине множення на відлік
    if (++n == N) {                   // вікно набралось (ціле число періодів!)
        Vrms = sqrtf((float)acc / N);
        acc = 0;  n = 0;              // почати нове вікно
    }
}
