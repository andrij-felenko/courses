acc = 0                       # накопичувач суми квадратів
n   = 0

def on_sample(v):                     # періодично, з таймера/ISR
    global acc, n, Vrms
    x    = v - offset                 # прибрати зсув АЦП (середину шкали / DC)
    acc += x * x                      # ← єдине множення на відлік
    n   += 1
    if n == N:                        # вікно набралось (ціле число періодів!)
        Vrms = math.sqrt(acc / N)
        acc = 0;  n = 0               # почати нове вікно
