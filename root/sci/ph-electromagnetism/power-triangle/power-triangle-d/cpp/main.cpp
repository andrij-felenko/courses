#include <cmath>

float U  = 230.0f;        // діюча напруга, В
float P  = 1500.0f;       // активна потужність, Вт
float pf = 0.75f;         // коефіцієнт потужності cos φ

// повна потужність: S = P / cos φ
float S = P / pf;
//        = 1500 / 0.75
//        = 2000.0 В·А

// реактивна: Q = sqrt(S² − P²)   (катет із Піфагора)
float Q = std::sqrt(S * S - P * P);
//        = sqrt(2000² − 1500²)
//        = sqrt(4000000 − 2250000)
//        = sqrt(1750000)
//        ≈ 1322.9 вар

// діючий струм у проводах визначає ПОВНА потужність, не активна
float I = S / U;
//        = 2000 / 230
//        ≈ 8.70 A

// якщо підняти cos φ до 0.95, повна потужність за тієї ж P:
float S2 = P / 0.95f;     // = 1578.9 В·А
float I2 = S2 / U;        // = 6.86 A
// струм падає з 8.70 до 6.86 A — на ~21 %
