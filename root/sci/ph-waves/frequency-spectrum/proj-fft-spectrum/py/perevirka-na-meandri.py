fs, f0, N = 48000, 100.0, 4800             # 0.1 с — рівно 10 періодів
t = np.arange(N) / fs
x = np.where((f0*t) % 1.0 < 0.5, 1.0, -1.0)   # півперіоду +1, півперіоду −1

f, a = spectrum(x, fs)
k0 = round(f0 / (fs/N))                    # бін основної частоти
for n in range(1, 10):
    k = n * k0
    print("%2d·f0 = %5.0f Гц   амплітуда %.4f   від основної %.4f"
          % (n, f[k], a[k], a[k]/a[k0]))
