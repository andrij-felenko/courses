#include <stdint.h>

/* Змішати дві доріжки в одну — саме це audio-callback робить на КОЖЕН буфер.
   Відлік — int16 у межах [-32768, 32767]. Сума двох може вилізти за край,
   тож накопичуємо ширше (int32) і обрізаємо — інакше буде різкий «клац». */
void mix(const int16_t *a, const int16_t *b, int16_t *out, int n)
{
    for (int i = 0; i < n; i++) {
        int32_t s = (int32_t)a[i] + b[i];   /* сума відлік за відліком */
        if (s >  32767) s =  32767;         /* насичення згори */
        if (s < -32768) s = -32768;         /* і знизу */
        out[i] = (int16_t)s;
    }
}
