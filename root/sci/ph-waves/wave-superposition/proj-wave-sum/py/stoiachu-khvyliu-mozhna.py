import numpy as np

A   = 1.0
lam = 1.0
k   = 2*np.pi/lam                 # хвильове число (2π на довжину хвилі)
f   = 2.0
w   = 2*np.pi*f                   # кутова частота
x   = np.linspace(0, 3*lam, 600)  # три довжини хвилі вздовж струни

def snapshot(t):
    right = A*np.sin(k*x - w*t)   # хвиля, що біжить праворуч
    left  = A*np.sin(k*x + w*t)   # відбита, біжить ліворуч
    return right + left           # сума = 2A·sin(kx)·cos(wt)

# вузли — там, де sin(kx) = 0; сума там нульова В БУДЬ-ЯКУ мить:
nodes = x[np.isclose(np.sin(k*x), 0.0, atol=1e-3)]
